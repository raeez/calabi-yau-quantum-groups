def virasoro_central_charge(k: int, N: int = 2):
    """Central charge of W_N at level k.

    For W_2 = Virasoro at level k (from sl_2 WZW):
        c = 1 - 6(p - q)^2 / (p * q)
    where p = k + 2, q = k + 1 ... (this is for minimal models).

    For generic W_N at level k (DS reduction of V_k(sl_N)):
        c = (N-1)(1 - N(N+1)/(k+N))

    At large k: c -> (N-1) (the rank).
    At k = 1: c = (N-1)(1 - N(N+1)/(N+1)) = (N-1)(1-N) = -(N-1)^2.
    """
    c = symbols("c")
    # Generic formula
    kk = Symbol("k")
    c_generic = (N - 1) * (1 - Rational(N * (N + 1), 1) / (kk + N))
    c_at_k = c_generic.subs(kk, k) if isinstance(k, int) else c_generic
    return {
        "N": N,
        "k": k,
        "c_formula": f"(N-1)(1 - N(N+1)/(k+N))",
        "c_value": c_at_k,
        "c_symbolic": c_generic,
    }


def shapovalov_form_level1(h, c):
    """Shapovalov form (= Gram matrix) at level 1 of the Virasoro Verma module.

    At level 1, the single state is L_{-1}|h>.
    The Shapovalov form is:
        S_1 = <h| L_1 L_{-1} |h> = <h| [L_1, L_{-1}] |h> = <h| 2 L_0 |h> = 2h.

    The Verma module M_h is reducible iff S_1 = 0, i.e., h = 0.
    """
    return {"level": 1, "basis": ["L_{-1}|h>"], "gram_matrix": Matrix([[2 * h]]),
            "det": 2 * h, "singular_iff": "h = 0"}


def shapovalov_form_level2(h, c):
    """Shapovalov form at level 2 of the Virasoro Verma module.

    Basis: {L_{-2}|h>, L_{-1}^2|h>}.

    Gram matrix entries:
        <h|L_2 L_{-2}|h> = <h|[L_2, L_{-2}]|h> = <h|(4L_0 + c/2)|h> = 4h + c/2
        <h|L_1^2 L_{-2}|h> = <h|L_1 [L_1, L_{-2}]|h> = <h|L_1 * 3L_{-1}|h>
            = 3 <h|[L_1, L_{-1}]|h> = 3 * 2h = 6h
        <h|L_2 L_{-1}^2|h> = same by hermiticity = 6h
        <h|L_1^2 L_{-1}^2|h> = <h|L_1 [L_1, L_{-1}^2]|h>
            = <h|L_1 (2L_0 L_{-1} + L_{-1} 2L_0)|h> ... let me be careful.

    [L_1, L_{-1}^2] = L_1 L_{-1} L_{-1} - L_{-1}^2 L_1
        = (L_{-1} L_1 + 2L_0) L_{-1} - L_{-1}^2 L_1
        = L_{-1} L_1 L_{-1} + 2L_0 L_{-1} - L_{-1}^2 L_1
        = L_{-1}(L_{-1} L_1 + 2L_0) + 2L_0 L_{-1} - L_{-1}^2 L_1
        = L_{-1}^2 L_1 + 2 L_{-1} L_0 + 2L_0 L_{-1} - L_{-1}^2 L_1
        = 2 L_{-1} L_0 + 2 L_0 L_{-1}
        = 2 L_{-1}(h+1) + 2(h+1) L_{-1}  ... NO, L_0 has eigenvalue h on |h>,
          but on L_{-1}|h> it has eigenvalue h+1.

    Actually, just compute directly using Virasoro commutation relations:
    [L_m, L_n] = (m-n) L_{m+n} + c/12 m(m^2-1) delta_{m+n,0}.

    <h|L_1^2 L_{-1}^2|h>:
    L_1 L_{-1} = L_{-1} L_1 + [L_1, L_{-1}] = L_{-1} L_1 + 2 L_0
    So L_1^2 L_{-1}^2 = L_1 (L_{-1} L_1 + 2L_0) L_{-1}
        = L_1 L_{-1} L_1 L_{-1} + 2 L_1 L_0 L_{-1}
        = (L_{-1} L_1 + 2L_0)(L_{-1} L_1 + 2L_0) + 2 L_1 L_0 L_{-1}
          ... this gets complicated. Use the standard result.

    The Shapovalov determinant at level 2 (Kac determinant formula):
        det S_2 = 2h * (16h^3 - (10 - 2c)h^2 + (c-1)h + c/2 ... )

    Actually, the known Gram matrix at level 2 is:
        S_2 = [[4h + c/2,  6h],
               [6h,        4h(2h+1)]]

    det S_2 = (4h + c/2)(4h(2h+1)) - (6h)^2
            = (4h + c/2)(8h^2 + 4h) - 36h^2
            = 32h^3 + 16h^2 + 4ch^2 + 2ch - 36h^2
            = 32h^3 + (4c - 20)h^2 + 2ch

    By Kac formula: det S_2 proportional to h * (h - h_{1,2})(h - h_{2,1})
    where h_{r,s} = ((r alpha_+ + s alpha_-)^2 - (alpha_+ + alpha_-)^2) / 4
    with alpha_+^2 = 2/p, alpha_-^2 = -2/q and p,q from c.
    """
    S = Matrix([
        [4 * h + c / 2, 6 * h],
        [6 * h, 4 * h * (2 * h + 1)],
    ])
    det = expand(S.det())
    return {
        "level": 2,
        "basis": ["L_{-2}|h>", "L_{-1}^2|h>"],
        "gram_matrix": S,
        "det": det,
        "det_expanded": expand(det),
    }


def shapovalov_inverse_level2(h, c):
    """Inverse Shapovalov form at level 2 (needed for R-matrix computation).

    S^{-1} projects onto the dual basis, required for inserting complete
    sets of states in the conformal block expansion of the R-matrix.
    """
    S = shapovalov_form_level2(h, c)["gram_matrix"]
    det = S.det()
    # S^{-1} = adj(S) / det(S)
    S_inv = S.adjugate() / det
    return {
        "level": 2,
        "S_inv": S_inv.applyfunc(cancel),
        "det": expand(det),
    }


