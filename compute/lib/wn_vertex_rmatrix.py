def universal_r_matrix_expansion(h1, h2, h3=None, order=3):
    """Universal R-matrix for W_{1+infinity} = Y(gl_hat_1) in power series.

    The Yangian Y(gl_hat_1) has a universal R-matrix:

        R(u) = 1 + hbar * Omega / u + hbar^2 * Omega^{(2)} / u^2 + ...

    where:
        hbar = sigma_3 = h1 * h2 * h3  (the "Planck constant")
        Omega = sum_n psi_n tensor psi_{-n}  (Casimir element)
        Omega^{(2)} = (Omega^2 - Omega_2) / 2  (second-order correction)
            with Omega_2 = sum_n psi_n psi_{-n} tensor 1 + 1 tensor sum_n psi_n psi_{-n}

    In the free-field realization on Fock modules, psi_n = a_n (boson modes),
    and the Casimir is:
        Omega = sum_{n > 0} (a_n tensor a_{-n} + a_{-n} tensor a_n) + a_0 tensor a_0

    The EXPONENTIAL form of the universal R-matrix:
        R(u) = exp(hbar * Omega / u + O(1/u^2))
             = 1 + hbar * Omega/u + hbar^2 * Omega^2 / (2u^2) + ...

    But the TRUE universal R-matrix is NOT simply exp(Omega/u) due to
    the noncocommutativity of the Yangian coproduct. The correct formula
    involves the KHOROSHKIN-TOLSTOY factorization:

        R(u) = R^+(u) * R^0(u) * R^-(u)

    where R^+, R^0, R^- correspond to the positive, zero, negative root
    spaces of the Yangian. For Y(gl_hat_1) (rank 1):

        R^+(u) = exp(sum_{n>0} hbar * e_n tensor f_{-n} / u)  (up to ordering)
        R^0(u) = prod_{n >= 0} g(u + n*hbar)^{psi_n tensor psi_{-n}}
        R^-(u) = exp(sum_{n>0} hbar * f_n tensor e_{-n} / u)

    This MATCHES the structure function g(u) from drinfeld_center_yangian.py:
    the diagonal part of the universal R-matrix on Fock modules IS g(u).
    """
    if h3 is None:
        h3 = -(h1 + h2)

    u = Symbol("u")
    hbar = h1 * h2 * h3  # = sigma_3

    # Perturbative expansion: R(u) = sum_n R_n / u^n
    R_coeffs = {}
    R_coeffs[0] = "Id tensor Id"
    R_coeffs[1] = f"hbar * Omega = {hbar} * sum_n (psi_n tensor psi_{{-n}})"

    if order >= 2:
        R_coeffs[2] = (
            f"hbar^2 * [Omega^2/2 + correction] = {hbar**2} * "
            f"(second Casimir + coproduct correction)"
        )

    if order >= 3:
        R_coeffs[3] = (
            f"hbar^3 * [Omega^3/6 + ...] = {hbar**3} * "
            f"(third order, involves triple Casimir + KT corrections)"
        )

    # On Fock modules at charge 1, the universal R-matrix evaluates to:
    # R(u)|box_1> tensor |box_2> = g(u) |box_1> tensor |box_2>
    # where g(u) = (u-h1)(u-h2)(u-h3) / ((u+h1)(u+h2)(u+h3))
    #            = 1 - 2(h1+h2+h3)/u + ... = 1 - 0/u + 2*sigma_2/u^2 - ...
    # (since h1+h2+h3 = 0 by CY condition).

    # So R(u) on charge 1 x charge 1:
    g_expansion_coeffs = []
    g_expansion_coeffs.append(("u^0", Rational(1)))
    g_expansion_coeffs.append(("u^{-1}", Rational(0)))  # CY condition kills this
    sigma2 = h1 * h2 + h1 * h3 + h2 * h3
    g_expansion_coeffs.append(("u^{-2}", 2 * sigma2))

    return {
        "universal_R_expansion": R_coeffs,
        "hbar": hbar,
        "KT_factorization": "R = R^+ * R^0 * R^-  (Khoroshkin-Tolstoy)",
        "diagonal_on_fock": "R^0 = prod g(u + n*hbar)^{...} = structure function",
        "g_expansion": g_expansion_coeffs,
        "key_identity": (
            "The universal R-matrix of Y(gl_hat_1) evaluated on charge-1 "
            "Fock modules gives g(u) = (u-h1)(u-h2)(u-h3)/((u+h1)(u+h2)(u+h3)). "
            "This is the SAME g(u) as in drinfeld_center_yangian.py. "
            "The universal formula R = 1 + hbar*Omega/u + ... is the algebraic "
            "source; g(u) is its representation-theoretic shadow."
        ),
    }


