    # (c/3) * 1 * 0 * (-3) / 120 = 0   (the central extension vanishes at m=1)
    # + 2(1) L_0 = 2h
    # + nonlinear correction from Lambda_0 = :L_0^2: + ...
    #
    # The full result for [W_1, W_{-1}] on a highest-weight state:
    # = 2h + (16/(22+5c)) * (something involving h^2 + corrections)
    #
