r"""Quantum vertex R-matrix for W_N algebras (type A, class M).

MATHEMATICAL CONTENT
====================

The W_N algebra at level k is the quantum Drinfeld-Sokolov reduction:
    W_k(sl_N) = H^0_{DS}(V_k(sl_N))

For N=2: W_2 = Virasoro with c = 1 - 6(k-1)^2/k = 13 - 6k - 6/k.
For N=3: W_3 has generators T(z) (spin 2) and W(z) (spin 3).
For N -> infinity: W_{1+infinity} = Y(gl_hat_1) (Prochazka-Rapcak).

The R-matrix acts on tensor products of Verma modules, NOT Fock spaces.
A Verma module M_h for Virasoro (or M_{h,w} for W_3) is infinite-
dimensional, generated by L_{-n_1}...L_{-n_k}|h> (and W_{-m_j}|h,w>
for W_3). The R-matrix must be computed level by level.

RELATION TO EXISTING ENGINES
==============================

drinfeld_center_yangian.py: R-matrix for Y(gl_hat_1) on FOCK modules.
    Fock = free boson representation. R(u) = g(u) at charge 1.
    This is the W_{1+infinity} R-matrix in the FREE FIELD realization.

e3_two_parameter_rmatrix.py: two-parameter extension G_ch(u,v) for C^3.

THIS MODULE: R-matrix on VERMA modules (interacting, not free field).
    The Verma module R-matrix involves the FULL OPE, not just free fields.
    At level 0 (highest weight states only): R(z) is a scalar phase.
    At level 1: R(z) involves the two-point function <T T> or <W W>.
    At higher levels: the full Shapovalov form enters.

EXPLICIT FORMULAS
==================

1. VIRASORO (W_2) R-MATRIX ON M_h1 tensor M_h2:

   The R-matrix is the BRAIDING of the vertex tensor category of Virasoro
   modules (Huang-Lepowsky-Zhang theory). On highest-weight states:

       R(z)|h1> tensor |h2> = z^{h1+h2-h_{12}} B(h1,h2,h_{12}) |...>

   where h_{12} runs over the fusion spectrum and B encodes 6j-symbols
   (Racah-Wigner coefficients). For generic c (non-degenerate), the
   fusion rules are trivial (M_h1 x M_h2 = integral over M_h), and
   the R-matrix reduces to the VERTEX OPERATOR ALGEBRA braiding:

       R(z) = e^{z L_{-1}} z^{L_0}  (transport operator)

   On the level-graded components M_h = oplus_n M_h[n]:

       R(z)_{n,m} = sum_{k} z^{h1+h2+k-n-m} C^k_{nm}(h1,h2,c)

   where C^k_{nm} are the CONFORMAL BLOCK COEFFICIENTS, computable from
   the Virasoro algebra relations and the Shapovalov form.

2. W_3 R-MATRIX: additional W_0 eigenvalue w produces a MATRIX structure
   even at level 0 (from the W_3 Casimir). The R-matrix has the form:

       R(z) = R^{Vir}(z) * (1 + sum_n a_n(h,w,c)/z^n * W-corrections)

   The W-corrections involve the spin-3 current's contribution to the
   braiding, controlled by the W_3 structure constants C_{33}^3(c).

3. UNIVERSAL R-MATRIX for W_{1+infinity}:
   In the Yangian realization Y(gl_hat_1), the universal R is:

       R(u) = 1 + hbar * Omega / u + hbar^2 * Omega^{(2)} / u^2 + ...

   where Omega = sum_n (psi_n tensor psi_{-n}) is the Casimir of
   Y(gl_hat_1), with psi_n the generating currents (modes of W-fields).

CONVENTIONS:
    c = central charge of W_N algebra
    h = L_0 eigenvalue (conformal weight)
    w = W_0 eigenvalue (W_3 charge, only for N >= 3)
    z = spectral parameter (position on the Riemann surface)
    hbar = 1/(k + N) = inverse shifted level

REFERENCES:
    Feigin-Fuchs, "Representations of the Virasoro algebra" (1984)
    Huang-Lepowsky-Zhang, "Logarithmic tensor category theory" (2010+)
    Frenkel-Ben-Zvi, "Vertex Algebras and Algebraic Curves" (2004)
    Prochazka-Rapcak, arXiv:1910.07997 (W_{1+inf} = Y(gl_hat_1))
    Zamolodchikov, "Infinite additional symmetries in 2D CFT" (1985)
    Fateev-Lukyanov, arXiv:hep-th/0612308 (W_3 structure constants)
    Bowcock-Watts, "On the classification of quantum W-algebras" (1992)
    Maulik-Okounkov, arXiv:1211.1287 (quantum groups, R-matrices)
"""

