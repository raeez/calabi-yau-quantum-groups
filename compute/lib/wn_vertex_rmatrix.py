def virasoro_ybe_level0_verify(h1, h2, h3, c, z1, z2, z3):
    """Verify the Yang-Baxter equation at level 0 for Virasoro.

    YBE: R_{12}(z12) R_{13}(z13) R_{23}(z23) = R_{23}(z23) R_{13}(z13) R_{12}(z12)

    At level 0, in a fixed intermediate channel, each R is a SCALAR
    (= z^{Delta}). So YBE reduces to commutativity of scalars, which
    is trivially satisfied.

    The NONTRIVIAL Yang-Baxter equation involves the FULL R-matrix
    (all levels), and reduces to the CROSSING SYMMETRY of conformal
    blocks (Moore-Seiberg). This is:

        sum_{h_s} F_{h_s}[h1,h2,h3,h4] * F_{h_s}[...] = ...

    which is the PENTAGON IDENTITY for the fusion matrices (= 6j-symbols).

    At level 0, the verification is:
        z12^{a} * z13^{b} * z23^{c} = z23^{c} * z13^{b} * z12^{a}

    which holds since the z's are commuting variables.
    """
    h12 = Symbol("h_{12}")
    h13 = Symbol("h_{13}")
    h23 = Symbol("h_{23}")

    z12 = z1 - z2
    z13 = z1 - z3
    z23 = z2 - z3

    Delta_12 = h12 - h1 - h2
    Delta_13 = h13 - h1 - h3
    Delta_23 = h23 - h2 - h3

    lhs = z12 ** Delta_12 * z13 ** Delta_13 * z23 ** Delta_23
    rhs = z23 ** Delta_23 * z13 ** Delta_13 * z12 ** Delta_12

    # These are identical as expressions (commutativity of multiplication)
    return {
        "ybe_level_0": True,
        "reason": "Scalar R-matrices commute. YBE at level 0 is trivial.",
        "nontrivial_ybe": (
            "The NONTRIVIAL YBE is the PENTAGON IDENTITY for fusion matrices: "
            "sum_s F_{pq}^{rs}[h_s] F_{qr}^{st}[h_u] = sum_t F_{pr}^{st}[h_v] "
            "F_{pq}^{vt}[h_w] F_{qr}^{tw}[h_x]. "
            "This is EQUIVALENT to the consistency of the vertex tensor category "
            "(Huang-Lepowsky). Verification requires the FULL Virasoro 6j-symbols "
            "(Racah-Wigner coefficients), which are given by the Virasoro "
            "CROSSING KERNEL / fusion matrix."
        ),
        "crossing_kernel": (
            "The Virasoro crossing kernel (Ponsot-Teschner 2000) is: "
            "F_{h_s}[h1,h2,h3,h4] = "
            "integral S_b(h_s +/- h1 +/- h2) S_b(h_s +/- h3 +/- h4) / (...) "
            "where S_b is the double sine function and b^2 is related to c by "
            "c = 1 + 6(b + 1/b)^2. "
            "This SATISFIES the pentagon identity (proved by Teschner 2003)."
        ),
    }


def virasoro_ybe_level1_verify(h1, h2, h3_ext, c):
    """Verify YBE at level 1 for the Virasoro R-matrix.

    At level 1, the conformal block coefficient is:
        F_1 = (h12 + h1 - h2)(h12 - h1 + h2) / (2 h12)

    The YBE at level 1 is a FUNCTIONAL EQUATION for F_1 as a function
    of the intermediate weights. It states:

        sum_s F_1(h1,h2|h_s) F_1(h_s,h3|h_t) = sum_u F_1(h2,h3|h_u) F_1(h1,h_u|h_t)

    This is the FIRST NONTRIVIAL crossing relation.

    For the Virasoro algebra at generic c, this is verified by the
    ANALYTIC CONTINUATION of the conformal block (the monodromy
    representation of the braid group).

    We verify the CONSISTENCY CHECK: for h1 = h2 (identical modules),
    the R-matrix eigenvalues must be +/- 1 (bosonic/fermionic sectors)
    in the h12 -> 0 and h12 -> 2h1 limits.
    """
    h12 = Symbol("h_{12}")
    z = Symbol("z")

    F1_12 = (h12 + h1 - h2) * (h12 - h1 + h2) / (2 * h12)

    # For h1 = h2 (identical modules):
