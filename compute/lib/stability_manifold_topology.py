r"""Topology of Bridgeland stability manifolds Stab(D^b(X)) for CY3s.

THESIS
======

The stability manifold Stab(D^b(X)) is a complex manifold whose topology
controls the global structure of the E_1 chiral algebra A_X.  The key
observation: the hocolim A_X = hocolim_{Stab} CoHA is the UNIVERSAL COVER
construction -- the E_1 algebra that trivializes the monodromy
representation rho: pi_1(Stab) -> Aut_{E_1}(A_X).

THE FUNDAMENTAL GROUP pi_1(Stab)
================================

The fundamental group of Stab governs the monodromy of the E_1 algebra
as we transport around loops in the stability manifold.  For each loop
gamma in pi_1(Stab), parallel transport of the CoHA algebra along gamma
produces an autoequivalence of A_X.

Bridgeland's conjecture (proved for K3 by Bridgeland-K3):
    pi_0(Stab) is connected and the covering map
        Stab -> Hom(K_0, C)
    has fiber equal to Aut(D^b(X)).

So the short exact sequence is:
    1 -> pi_1(Hom(K_0, C)) -> pi_1(Stab) -> Aut(D^b(X)) -> 1

Since Hom(K_0, C) ~ C^r is contractible, this gives:
    pi_1(Stab) contains Aut(D^b(X)) as a quotient.

The autoequivalences act on Stab by DECK TRANSFORMATIONS of the
universal cover.

SIX STANDARD EXAMPLES
=====================

(1) C^3 (equivariant):
    Stab = C^3 / CY constraint ~ C^2.
    Simply connected, pi_1 = 0.
    No monodromy, A_X has Hall positive-half shadow CoHA = Y^+(gl_hat_1);
    W_{1+inf} appears after Drinfeld double/center and Fock evaluation.

(2) Resolved conifold:
    Stab ~ C x H (H = upper half-plane, after suitable quotient).
    Both factors contractible, pi_1 = 0.
    The FLOP autoequivalence acts as deck transformation,
    but on the simply-connected cover.

(3) Local P^2:
    Stab has Z/3 monodromy from the Seiberg duality cycle.
    The 3 mutations form a Z/3-orbit of the exceptional collection.
    pi_1(Stab / Aut_0) contains Z/3 (the cyclic mutation group).

(4) K3 surface:
    Bridgeland's theorem: Stab(K3) is connected, and
    pi_1(Stab(K3)) = Aut(D^b(K3)).
    Aut(D^b(K3)) contains:
      - Shift [1] (generates Z)
      - Line bundle twists O(L) for L in Pic(K3)
      - Spherical twists T_E for spherical objects E
      - The full group is an extension of the Mukai lattice isometries.

(5) K3 x E:
    By Kuenneth: Stab(K3 x E) contains Stab(K3) x Stab(E).
    pi_1 contains pi_1(Stab(K3)) x pi_1(Stab(E)).
    Stab(E) ~ C x H / SL_2(Z) with pi_1(Stab(E)) ~ SL_2(Z).
    So pi_1(Stab(K3 x E)) contains Aut(D^b(K3)) x SL_2(Z).

(6) Quintic CY3:
    pi_1(Stab) includes monodromy around:
      - Conifold points (local monodromy = Dehn twist = Picard-Lefschetz)
      - Gepner point (Z/5 monodromy from the LG orbifold)
      - Large complex structure limit (maximally unipotent monodromy)
    The monodromy group is generated by these, and is an arithmetic
    subgroup of Sp(4, Z) acting on H^3(X, Z) ~ Z^4.

THE MONODROMY REPRESENTATION
==============================

rho: pi_1(Stab) -> Aut_{E_1}(A_X)

For each generator g of pi_1(Stab):
  rho(g) is an E_1 automorphism of the global algebra A_X.

For the conifold: the flop autoequivalence F acts as
  rho(F): CoHA_I -> CoHA_II  (exchange of the two chambers).

For local P^2: the Seiberg duality cycle sigma (order 3) acts as
  rho(sigma): CoHA_0 -> CoHA_1 -> CoHA_2 -> CoHA_0.

THE UNIVERSAL COVER CONSTRUCTION
==================================

The hocolim A_X = hocolim_{Stab} CoHA is the E_1 algebra on the
UNIVERSAL COVER of Stab.  By definition, a diagram D: Stab -> E_1-Alg
on the universal cover has trivial monodromy (all loops are contractible),
so the hocolim descends to a well-defined global algebra.

The deck transformations pi_1(Stab) act on A_X, giving the monodromy
representation.  This is the E_1 analog of the classical fact that
sections of a local system on X are the same as equivariant functions
on the universal cover.

HIGHER HOMOTOPY GROUPS
========================

For CY3, Stab is a complex manifold of real dimension 2r (r = rk K_0).
  - pi_2(Stab) measures the failure of the covering space
    Stab -> Hom(K_0, C) to be a trivial bundle.
  - For K3: pi_2(Stab(K3)) = 0 (Bridgeland, proved case).
  - For CY3: pi_n(Stab) = 0 for n >= 2 is expected (aspherical).
    This is the content of the "Stab is a K(pi,1)" conjecture.

CHAMBER GROWTH RATE
=====================

For compact CY3, the chamber structure of Stab is infinite.
The growth rate of chambers (as a function of distance from a basepoint)
is controlled by the BPS spectrum:

  N(R) ~ exp(c * R)  (exponential growth)

where c depends on the density of BPS states.  For the quintic:
  c ~ 2*pi*sqrt(2*kappa)  (from the Cardy formula applied to BPS counting).

The exponential growth means the universal cover is "hyperbolic" in nature.

BRAID GROUP AND QUANTUM GROUP ACTION
======================================

The braid group Br_n appears as:
  - pi_1(Conf_n(C)) = Br_n (Artin's theorem)
  - pi_1(Stab_reg) maps to braid groups via the FN monodromy

For local P^2 with 3 exceptional objects:
  pi_1(Stab_reg) -> Br_3  (the 3-strand braid group)
  Br_3 acts on Rep(U_q(sl_3)) by the quantum R-matrix.
  This gives the braided structure on the E_2 enhancement.

CONVENTIONS
===========

  - Exact arithmetic via fractions.Fraction throughout.
  - Cohomological grading: |d| = +1.
  - Autoequivalence = exact self-equivalence of D^b(X).
  - Spherical twist T_E = cone(E -> RHom(E,-) tensor E -> id)[-1].
  - Euler form: skew-symmetric chi(E,F) = sum (-1)^i dim Ext^i(E,F).
  - pi_1 computed combinatorially from the chamber graph.
  - K(pi,1) = aspherical space: pi_n = 0 for n >= 2.

CAUTIONS (Beilinson)
====================

  AP-CY6: A_X does NOT exist for CY3 in general.  The universal cover
           construction gives A_X ONLY IF the hocolim converges, which
           requires the E_1 descent to terminate.  For CY3 with infinite
           chamber structure, this is nontrivial.

  AP42: "Stab is a K(pi,1)" is a CONJECTURE, not a theorem.
        Proved for K3 (Bridgeland 2008), open for CY3.

  AP-CY4: The covering space structure of Stab involves BOTH the
           autoequivalence group AND the contractibility of
           Hom(K_0, C).  Do not conflate the two.

  AP43: The "braid group action on A_X" requires A_X to exist.
        For CY3 where A_X is conditional (AP-CY6), the braid
        group action is similarly conditional.

REFERENCES
==========

  Bridgeland, "Stability conditions on triangulated categories" (2007)
  Bridgeland, "Stability conditions on K3 surfaces" (2008)
  Bayer-Macri, "The space of stability conditions on abelian threefolds"
  Kontsevich-Soibelman, "Stability structures" (2008)
  Seidel-Thomas, "Braid group actions on derived categories" (2001)
  Toda, "Stability conditions and crepant small resolutions" (2008)
  Bayer-Bridgeland, "Derived automorphism groups of K3 surfaces" (2017)
  Lurie, "Higher Algebra" (2017)
  Lorgat, Vol I: bar complex, shadow obstruction tower
  Lorgat, Vol III: stability_atlas_nerve, e1_hocolim_cy3
"""

