class FundamentalGroupData(NamedTuple):
    """Computed fundamental group data for Stab(D^b(X)).

    Attributes:
        cy_name: identifier (C3, conifold, local_P2, K3, K3xE, quintic)
        pi1_description: human-readable description of pi_1
        pi1_generators: list of named generators
        pi1_relations: list of relations among generators
        pi1_order: order of pi_1 (0 for infinite)
        pi1_abelianization: description of pi_1^ab = H_1(Stab; Z)
        is_simply_connected: whether pi_1 = 0
        is_finite_pi1: whether pi_1 is finite
        higher_homotopy: dict {n: description of pi_n}
        deck_transformations: description of the deck group
        monodromy_generators: list of E_1 automorphisms from pi_1
    """
    cy_name: str
    pi1_description: str
    pi1_generators: List[str]
    pi1_relations: List[str]
    pi1_order: int  # 0 = infinite
    pi1_abelianization: str
    is_simply_connected: bool
    is_finite_pi1: bool
    higher_homotopy: Dict[int, str]
    deck_transformations: str
    monodromy_generators: List[str]


# =========================================================================
# 2. MONODROMY REPRESENTATION
# =========================================================================

class MonodromyAction(NamedTuple):
    """A single monodromy automorphism rho(g) in Aut_{E_1}(A_X).

    Attributes:
        generator_name: name of the pi_1 generator g
        action_on_charges: how g permutes BPS charges
        matrix: the monodromy matrix on the charge lattice
        order: order of the automorphism (0 = infinite)
        is_identity: whether rho(g) = id
        eigenvalues: eigenvalues of the monodromy matrix (as rationals or roots of unity)
    """
    generator_name: str
    action_on_charges: Dict[Tuple[int, ...], Tuple[int, ...]]
    matrix: List[List[Fraction]]
    order: int
    is_identity: bool
    eigenvalues: List[str]


class MonodromyRepresentation(NamedTuple):
    """The full monodromy representation rho: pi_1(Stab) -> Aut_{E_1}(A_X).

    Attributes:
        cy_name: identifier
        lattice_rank: rank of the charge lattice
        generators: list of MonodromyAction
        is_faithful: whether rho is injective
        image_description: description of the image of rho
        kernel_description: description of ker(rho)
        preserves_euler_form: whether rho preserves the Euler form
    """
    cy_name: str
    lattice_rank: int
    generators: List[MonodromyAction]
    is_faithful: bool
    image_description: str
    kernel_description: str
    preserves_euler_form: bool


