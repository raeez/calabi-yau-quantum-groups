def run_full_topology_verification() -> Dict[str, Any]:
    r"""Run all verification checks.

    Multi-path verification:
      Path 1: Matrix computations (determinants, orders, nilpotency)
      Path 2: Dimension consistency (dim Stab = rk K_0)
      Path 3: Euler form preservation
      Path 4: Fundamental group structure (generators, relations)
      Path 5: Higher homotopy (K(pi,1) checks)
    """
    gepner = verify_gepner_order()
    conifold_mono = verify_conifold_monodromy()
    lcsl = verify_lcsl_monodromy()
    relation = verify_monodromy_relation_quintic()
    euler = verify_euler_form_preservation()
    seiberg = verify_seiberg_cycle_euler_form()

    # Dimension consistency
    dim_table = stab_dimension_table()
    dim_consistent = all(
        entry['dim_stab'] == entry['rank_k0']
        for entry in dim_table.values()
    )

    # Collect all topologies
    topologies = {
        'C^3': topology_c3(),
        'conifold': topology_conifold(),
        'local_P^2': topology_local_p2(),
        'K3': topology_k3(),
        'K3 x E': topology_k3xe(),
        'quintic': topology_quintic(),
    }

    return {
        'gepner_order_5': gepner,
        'conifold_monodromy': conifold_mono,
        'lcsl_monodromy': lcsl,
        'monodromy_relation': relation,
        'euler_form_preservation': euler,
        'seiberg_euler_form': seiberg,
        'dimension_table': dim_table,
        'dimension_consistent': dim_consistent,
        'topologies': {
            name: {
                'dim_stab': t.dim_stab,
                'pi1_simply_connected': t.pi1.is_simply_connected,
                'hocolim_well_defined': t.universal_cover.hocolim_well_defined,
            }
            for name, t in topologies.items()
        },
        'all_checks_pass': (
            gepner['G^5_is_identity']
            and conifold_mono['is_unipotent']
            and lcsl['is_maximally_unipotent']
            and euler['all_preserve_volume']
            and seiberg['euler_form_preserved']
            and dim_consistent
        ),
    }
