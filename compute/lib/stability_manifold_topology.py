def _gcd(a: int, b: int) -> int:
    """Greatest common divisor."""
    a, b = abs(a), abs(b)
    while b:
        a, b = b, a % b
    return a


def _matrix_rank_Q(mat: List[List[Fraction]]) -> int:
    """Rank of a matrix over Q via Gaussian elimination."""
    if not mat or not mat[0]:
        return 0
    m, n = len(mat), len(mat[0])
    M = [row[:] for row in mat]
    rank = 0
    for col in range(n):
        pivot = None
        for row in range(rank, m):
            if M[row][col] != 0:
                pivot = row
                break
        if pivot is None:
            continue
        M[rank], M[pivot] = M[pivot], M[rank]
        scale = M[rank][col]
        for j in range(n):
            M[rank][j] /= scale
        for row in range(m):
            if row == rank:
                continue
            if M[row][col] != 0:
                factor = M[row][col]
                for j in range(n):
                    M[row][j] -= factor * M[rank][j]
        rank += 1
    return rank


