def verify_seiberg_cycle_euler_form() -> Dict[str, Any]:
    r"""Verify that the Seiberg cycle preserves the Euler form.

    The Euler form on local P^2 with basis {[O], [O(1)], [O(2)]}:
      chi(O, O)     = 1,  chi(O, O(1))   = 3,  chi(O, O(2))   = 6
      chi(O(1),O)   = 0,  chi(O(1),O(1)) = 1,  chi(O(1),O(2)) = 3
      chi(O(2),O)   = 0,  chi(O(2),O(1)) = 0,  chi(O(2),O(2)) = 1

    The ANTISYMMETRIC (skew) Euler form is:
      <e_i, e_j> = chi(e_i, e_j) - chi(e_j, e_i)

      <e_0, e_1> = 3 - 0 = 3
      <e_0, e_2> = 6 - 0 = 6
      <e_1, e_2> = 3 - 0 = 3

    Under sigma: e_i -> e_{i+1 mod 3}:
      <sigma(e_0), sigma(e_1)> = <e_1, e_2> = 3  (should = <e_0, e_1> = 3) checkmark
      <sigma(e_0), sigma(e_2)> = <e_1, e_0> = -3 (should = <e_0, e_2> = 6) FAIL

    So the naive cyclic permutation does NOT preserve the Euler form!

    RESOLUTION: The Seiberg duality is NOT a simple permutation.
    It acts as a MUTATION, which DOES preserve the antisymmetric form
    but in a more subtle way (the charges transform nontrivially).

    For the McKay quiver of Z_3 (which is the SAME as local P^2 by
    the McKay correspondence), the 3 cyclic rotations of the Z_3
    representations give isomorphic quivers, and the Euler form
    IS preserved by the McKay rotation because the Euler form
    of the McKay quiver has full cyclic symmetry:
      <rho_i, rho_j> depends only on i-j mod 3.

    For the McKay quiver: chi(rho_i, rho_j) = delta_{ij} + contribution from arrows.
    The McKay quiver of Z_3 acting on C^3 has 3 arrows from each vertex to
    the next (from the 3 coordinates of C^3), so:
      chi(rho_i, rho_{i+1}) = 3  (3 arrows from i to i+1)
      chi(rho_i, rho_{i+2}) = 0  (no direct arrows)
      chi(rho_i, rho_i)     = 1  (identity)

    Antisymmetric:
      <rho_0, rho_1> = 3 - 0 = 3
      <rho_0, rho_2> = 0 - 3 = -3  (since chi(rho_2, rho_0) = 3)
      <rho_1, rho_2> = 3 - 0 = 3

    Under cyclic sigma: rho_i -> rho_{i+1 mod 3}:
      <sigma(rho_0), sigma(rho_1)> = <rho_1, rho_2> = 3 = <rho_0, rho_1> checkmark
      <sigma(rho_0), sigma(rho_2)> = <rho_1, rho_0> = -3 = <rho_0, rho_2> checkmark
      <sigma(rho_1), sigma(rho_2)> = <rho_2, rho_0> = 3 = <rho_1, rho_2> checkmark

    VERIFIED: The cyclic permutation preserves the McKay Euler form.
    """
    # McKay Euler form (antisymmetric)
    euler_mckay = {
        (0, 0): 0, (0, 1): 3, (0, 2): -3,
        (1, 0): -3, (1, 1): 0, (1, 2): 3,
        (2, 0): 3, (2, 1): -3, (2, 2): 0,
    }

    # Check cyclic invariance
    preserved = True
    checks = []
    for i in range(3):
        for j in range(3):
            original = euler_mckay[(i, j)]
            permuted = euler_mckay[((i + 1) % 3, (j + 1) % 3)]
            ok = original == permuted
            if not ok:
                preserved = False
            checks.append({
                'pair': (i, j),
                'original': original,
                'permuted': permuted,
                'match': ok,
            })

    return {
        'euler_form_preserved': preserved,
        'euler_form': euler_mckay,
        'checks': checks,
        'conclusion': (
            "The cyclic permutation sigma: rho_i -> rho_{i+1 mod 3} "
            "preserves the antisymmetric McKay Euler form on Z^3."
        ),
    }


