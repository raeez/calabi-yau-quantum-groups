def _mat_mul(A: List[List[Fraction]], B: List[List[Fraction]]) -> List[List[Fraction]]:
    """Multiply two matrices over Q."""
    n = len(A)
    m = len(B[0])
    p = len(B)
    result = [[Fraction(0)] * m for _ in range(n)]
    for i in range(n):
        for j in range(m):
            for k in range(p):
                result[i][j] += A[i][k] * B[k][j]
    return result


def _mat_pow(A: List[List[Fraction]], k: int) -> List[List[Fraction]]:
    """Compute A^k for a square matrix over Q."""
    n = len(A)
    result = [[Fraction(1) if i == j else Fraction(0) for j in range(n)] for i in range(n)]
    if k == 0:
        return result
    base = [row[:] for row in A]
    while k > 0:
        if k % 2 == 1:
            result = _mat_mul(result, base)
        base = _mat_mul(base, base)
        k //= 2
    return result


def _mat_is_identity(A: List[List[Fraction]]) -> bool:
    """Check if A is the identity matrix."""
    n = len(A)
    for i in range(n):
        for j in range(n):
            expected = Fraction(1) if i == j else Fraction(0)
            if A[i][j] != expected:
                return False
    return True


def _mat_trace(A: List[List[Fraction]]) -> Fraction:
    """Trace of a square matrix."""
    return sum(A[i][i] for i in range(len(A)))


def _mat_det_2x2(A: List[List[Fraction]]) -> Fraction:
    """Determinant of a 2x2 matrix."""
    return A[0][0] * A[1][1] - A[0][1] * A[1][0]


def _mat_det_nxn(A: List[List[Fraction]]) -> Fraction:
    """Determinant via Gaussian elimination."""
    n = len(A)
    M = [row[:] for row in A]
    det = Fraction(1)
    for col in range(n):
        pivot = None
        for row in range(col, n):
            if M[row][col] != 0:
                pivot = row
                break
        if pivot is None:
            return Fraction(0)
        if pivot != col:
            M[col], M[pivot] = M[pivot], M[col]
            det *= Fraction(-1)
        det *= M[col][col]
        scale = M[col][col]
        for j in range(n):
            M[col][j] /= scale
        for row in range(n):
            if row == col:
                continue
            if M[row][col] != 0:
                factor = M[row][col]
                for j in range(n):
                    M[row][j] -= factor * M[col][j]
    return det


def _char_poly_4x4(A: List[List[Fraction]]) -> List[Fraction]:
    r"""Characteristic polynomial of a 4x4 matrix.

    p(t) = det(tI - A) = t^4 - tr(A)*t^3 + ... + det(A)

    Uses the Newton identities / Faddeev-LeVerrier algorithm:
      c_0 = 1
      c_1 = -tr(A)
      c_2 = -(1/2)(c_1*tr(A) + tr(A^2))
      c_3 = -(1/3)(c_2*tr(A) + c_1*tr(A^2) + tr(A^3))
      c_4 = -(1/4)(c_3*tr(A) + c_2*tr(A^2) + c_1*tr(A^3) + tr(A^4))
    """
    n = 4
    # Compute traces of powers of A
    traces = [Fraction(0)] * (n + 1)
    traces[0] = Fraction(n)  # tr(I) = n
    A_pow = [row[:] for row in A]
    traces[1] = _mat_trace(A)
    for k in range(2, n + 1):
        A_pow = _mat_mul(A_pow, A)
        traces[k] = _mat_trace(A_pow)

    # Faddeev-LeVerrier
    c = [Fraction(0)] * (n + 1)
    c[0] = Fraction(1)
    for k in range(1, n + 1):
        s = Fraction(0)
        for j in range(1, k + 1):
            s += c[k - j] * traces[j]
        c[k] = -s / Fraction(k)

    # p(t) = c[0]*t^n + c[1]*t^{n-1} + ... + c[n]
    # Return coefficients [c_n, c_{n-1}, ..., c_0] (low to high degree)
    return list(reversed(c))


