def conf_space_real_dim(n: int, ambient_complex_dim: int = 3) -> int:
    """Real dimension of Conf_n(C^d).

    Conf_n(C^d) is an open submanifold of (C^d)^n = R^{2dn},
    so dim_R Conf_n(C^d) = 2*d*n.
    """
    return 2 * ambient_complex_dim * n


def linking_sphere_dim(ambient_complex_dim: int = 3) -> int:
    """Dimension of the linking sphere S^{2d-1} of the diagonal in C^d.

    The diagonal Delta_{ij} in C^d x C^d has real codimension 2d.
    The linking sphere is S^{2d-1}.

    For C^1 (d=1): S^1, giving degree-1 generators (Arnold relations)
    For C^2 (d=2): S^3, giving degree-3 generators
    For C^3 (d=3): S^5, giving degree-5 generators
    """
    return 2 * ambient_complex_dim - 1


def fundamental_group_conf2(ambient_complex_dim: int = 3) -> str:
    """Fundamental group of Conf_2(C^d).

    Conf_2(C^d) ~ C^d x (C^d - {0}) ~ C^d x S^{2d-1} x R+.
    pi_1(Conf_2(C^d)) = pi_1(S^{2d-1}):
      d=1: pi_1(S^1) = Z (braid group, nontrivial braiding)
      d=2: pi_1(S^3) = 0 (trivial)
      d=3: pi_1(S^5) = 0 (trivial)
    """
    sphere_dim = linking_sphere_dim(ambient_complex_dim)
    if sphere_dim == 1:
        return "Z"
    else:
        return "0"


def conf_space_betti_numbers(n: int, ambient_complex_dim: int = 3,
                              max_degree: int = 20) -> List[int]:
    """Betti numbers of Conf_n(C^d) in low degrees.

    By the Arnold-Cohen theorem (complex case), H*(Conf_n(C^d); Q) is
    generated by classes omega_{ij} of degree (2d-1) subject to:
      - omega_{ij} = (-1)^{2d} omega_{ji} = omega_{ji} (for d >= 1, even sign)
      - Arnold relation: omega_{ij} omega_{jk} + omega_{jk} omega_{ki}
                         + omega_{ki} omega_{ij} = 0

    For d=1: omega_{ij} in H^1, giving the Arnol'd presentation.
    For d=3: omega_{ij} in H^5.

    For n=2: H*(Conf_2(C^d)) = H*(S^{2d-1}), so
      Betti: b_0 = 1, b_{2d-1} = 1, all others 0.

    For general n: the Poincare polynomial is given by the formula
      P(Conf_n(C^d); t) = prod_{k=0}^{n-1} (1 + k*t^{2d-1})
    (Cohen 1976, Totaro 1996).

    Parameters
    ----------
    n : int
        Number of points.
    ambient_complex_dim : int
        Complex dimension d of the ambient space C^d.
    max_degree : int
        Compute Betti numbers up to this degree.

    Returns
    -------
    list of int
        Betti numbers b_0, b_1, ..., b_{max_degree}.
    """
    deg = 2 * ambient_complex_dim - 1  # degree of generators omega_{ij}

    # Poincare polynomial: prod_{k=0}^{n-1} (1 + k * t^deg)
    # Note: k=0 factor is (1 + 0) = 1, contributing nothing.
    # Effective product: prod_{k=1}^{n-1} (1 + k * t^deg)
    betti = [0] * (max_degree + 1)
    betti[0] = 1

    for k in range(1, n):
        # Multiply current polynomial by (1 + k * t^deg)
        new_betti = list(betti)
        for j in range(max_degree + 1):
            if betti[j] != 0 and j + deg <= max_degree:
                new_betti[j + deg] += k * betti[j]
        betti = new_betti

    return betti


def conf_space_euler_char(n: int, ambient_complex_dim: int = 3) -> int:
    """Euler characteristic of Conf_n(C^d).

    chi(Conf_n(C^d)) = n! for d >= 2 (a consequence of the product formula
    for the Poincare polynomial, evaluated at t = -1).

    For d=1: chi(Conf_n(C)) = n! as well (Arnold).

    Proof: P(t) = prod_{k=1}^{n-1} (1 + k*t^{2d-1}).
    At t=-1: product = prod_{k=1}^{n-1} (1 + k*(-1)^{2d-1})
                     = prod_{k=1}^{n-1} (1 - k)  if 2d-1 is odd (d >= 1)
    Wait: 2d-1 is always odd. So (-1)^{2d-1} = -1.
    product = prod_{k=1}^{n-1} (1 - k) = (1-1)(1-2)...(1-(n-1))
            = 0 * (-1) * ... * (2-n) = 0 for n >= 2.

    This is WRONG for chi. The Euler characteristic is:
    chi = prod_{k=0}^{n-1} (1 + k*(-1)^{2d-1}) = prod (1-k) = 0 for n >= 2.

    Correction: the formula above counts the UNORDERED configuration space.
    For the ORDERED configuration space Conf_n(C^d) (as an open algebraic
    variety), chi = n! by inclusion-exclusion on the arrangement complement.

    Actually: Conf_n(C^d) is the complement of a hyperplane arrangement
    (the diagonal arrangement) in C^{dn}. The Euler characteristic of
    a complex hyperplane complement is always a signed count related to
    the Mobius function of the intersection lattice.

    For the braid arrangement in C^n: chi(Conf_n(C)) = (-1)^n * n!
    (the Mobius function of the partition lattice).
    For C^d with d >= 2: chi(Conf_n(C^d)) = 0 for n >= 2 because the
    cohomology generators have odd degree (2d-1 is odd for d >= 1)
    and the product formula gives chi = prod_{k=1}^{n-1}(1-k) which
    vanishes at k=1.

    Returns chi(Conf_n(C^d)).
    """
    if n <= 1:
        return 1
    # For d >= 1: chi = prod_{k=0}^{n-1} (1 + k * (-1)^{2d-1})
    # = prod_{k=0}^{n-1} (1 - k) = 0 for n >= 2 (k=1 term is 0).
    return 0


def conf_space_total_betti(n: int, ambient_complex_dim: int = 3) -> int:
    """Total Betti number sum_{k} b_k(Conf_n(C^d)).

    For d >= 2: P(1) = prod_{k=1}^{n-1} (1+k) = n!.
    """
    if n <= 1:
        return 1
    result = 1
    for k in range(1, n):
        result *= (1 + k)
    return result  # = n!


