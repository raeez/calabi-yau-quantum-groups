# 8. FM compactification and boundary strata
# =========================================================================

def fm_compactification_strata(n: int,
                                ambient_complex_dim: int = 3) -> Dict:
    """Boundary strata of the Fulton-MacPherson compactification FM_n(C^d).

    FM_n(C^d) is a smooth manifold with corners, compactifying Conf_n(C^d).
    The boundary strata are indexed by nested subsets S = {S_1, ..., S_k}
    of {1, ..., n} (screens).

    The codimension-1 strata correspond to subsets S of size >= 2:
    the stratum where all points in S collide simultaneously.

    The number of codimension-1 strata is sum_{k=2}^{n} C(n,k) = 2^n - n - 1.

    Each stratum is a fiber bundle:
      FM_S x Conf_n/S(C^d) -> FM^{codim 1}
    where FM_S is the FM compactification of the colliding points
    and Conf_n/S is the configuration of the remaining points plus
    the collision point.

    For C^3: each codimension-1 stratum has (real) codimension 1 in FM_n.
    The forms omega_{ij} extend to FM_n and restrict to the strata
    as products of lower-arity forms.
    """
    num_codim1 = 2**n - n - 1
    # Number of all strata (indexed by nested partitions)
    # For the purpose of this engine, we enumerate only codim-1.

    strata = []
    for size in range(2, n + 1):
        count = math.comb(n, size)
        strata.append({
            "subset_size": size,
            "num_strata": count,
            "fiber": f"FM_{size} x Conf_{n-size+1}(C^{ambient_complex_dim})",
        })

    return {
        "n": n,
        "ambient_dim": ambient_complex_dim,
        "num_codim1_strata": num_codim1,
        "strata_by_size": strata,
        "smooth_with_corners": True,
        "extends_omega_ij": True,
        "formality": "Kriz 1994",
    }


