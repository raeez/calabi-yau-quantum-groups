# 9. The perturbative partition function sum
# =========================================================================

def perturbative_partition_function(
    max_n: int,
    h1: complex, h2: complex,
    h3: Optional[complex] = None,
    coupling: complex = 1.0,
) -> Dict:
    """Perturbative partition function of 6d hCS on C^3.

    Z_pert = 1 + sum_{n>=2} (coupling^n / n!) * I_n

    where I_n is the n-point Feynman integral on Conf_n(C^3).

    For gl_1 (abelian), only tree-level and one-loop diagrams contribute
    (no cubic vertex at the abelian level). The cubic vertex appears
    at the non-abelian level (gl_N for N >= 2).

    At abelian level:
      I_n^{tree} = prod_{k=1}^{n-1} g(u_k - u_{k+1})
      I_n^{1-loop} = prod_{k=1}^{n} g(u_k - u_{k+1 mod n})

    For n=2:
      I_2^{tree} = g(u_1 - u_2) (single propagator)
      I_2^{1-loop} = g(u_1-u_2)*g(u_2-u_1) = 1 (CY inversion)

    Returns a summary with perturbative contributions through order max_n.
    """
    if h3 is None:
        h3 = -(h1 + h2)

    contributions = {}
    z_total = 1.0 + 0j

    for n in range(2, max_n + 1):
        params = [3.7 + 1.1 * k for k in range(n)]
        tree = tree_integral_n_points(n, h1, h2, h3, params)
        loop = one_loop_integral_n_points(n, h1, h2, h3, params)
        weight = coupling**n / math.factorial(n)

        contributions[n] = {
            "tree": tree,
            "one_loop": loop,
            "weight": weight,
            "tree_weighted": tree * weight,
            "loop_weighted": loop * weight,
        }
        z_total += (tree + loop) * weight

    return {
        "max_order": max_n,
        "h1": h1, "h2": h2, "h3": h3,
        "sigma3": h1 * h2 * h3,
        "coupling": coupling,
        "Z_pert": z_total,
        "contributions": contributions,
    }


