def _g_rational(z: complex, h1: complex, h2: complex,
                h3: Optional[complex] = None) -> complex:
    """Rational structure function g(z) = prod(z-h_i)/prod(z+h_i).

    This is the one-parameter (Yangian) propagator kernel.
    Poles at z = -h_i, zeros at z = h_i.

    The spectral parameter z is a YANGIAN spectral parameter (AP-CY31),
    NOT a worldsheet coordinate.
    """
    if h3 is None:
        h3 = -(h1 + h2)
    numer = (z - h1) * (z - h2) * (z - h3)
    denom = (z + h1) * (z + h2) * (z + h3)
    if abs(denom) < 1e-30:
        raise ZeroDivisionError(f"g(z) pole at z={z}")
    return numer / denom


def _g_two_param(u: complex, v: complex, h1: complex, h2: complex,
                 h3: Optional[complex] = None) -> complex:
    """Two-parameter structure function g_ch(u,v) = g(u)*g(v)*g(u-v).

    The Zamolodchikov factorization: three factors from the three
    spectral parameter combinations in the E_3 braiding.

    Factor 1: g(u) = direction-1 braiding
    Factor 2: g(v) = direction-2 braiding
    Factor 3: g(u-v) = crossing factor (Miki kernel)
    """
    if h3 is None:
        h3 = -(h1 + h2)
    return (_g_rational(u, h1, h2, h3) *
            _g_rational(v, h1, h2, h3) *
            _g_rational(u - v, h1, h2, h3))


def propagator_heisenberg(z_ij: complex, omega_ab: complex = 1.0) -> complex:
    """Free-field (Heisenberg) propagator on C^3.

    P(z_i, z_j) = omega^{ab} / (z_i - z_j)^2

    For the rank-1 Heisenberg, omega^{ab} is the scalar CY pairing.
    The power 2 is from the holomorphic Green function on C^3 in the
    direction transverse to the Wilson line.

    Parameters
    ----------
    z_ij : complex
        Spectral parameter difference z_i - z_j.
    omega_ab : complex
        CY pairing coefficient.
    """
    if abs(z_ij) < 1e-30:
        raise ZeroDivisionError("Propagator at coincident points")
    return omega_ab / z_ij**2


def propagator_yangian(z_ij: complex, h1: complex, h2: complex,
                       h3: Optional[complex] = None) -> complex:
    """Yangian (one-loop deformed) propagator on C^3.

    P(z_i, z_j) = g(z_i - z_j)

    where g is the rational structure function. The poles at
    z_ij = +/- h_k encode the Omega-background deformation.
    """
    if h3 is None:
        h3 = -(h1 + h2)
    return _g_rational(z_ij, h1, h2, h3)


def propagator_toroidal(u_ij: complex, v_ij: complex,
                        h1: complex, h2: complex,
                        h3: Optional[complex] = None) -> complex:
    """Quantum toroidal (two-parameter) propagator on C^3.

    P(z_i, z_j) = g_ch(u_i - u_j, v_i - v_j)

    Two spectral parameters (u, v) from the two transverse directions
    beyond the Wilson line in C^3. The Zamolodchikov factorization
    R_ch(u,v) = R_1(u) * R_2(v) * R_12(u-v) is encoded in g_ch.

    The spectral parameters (u, v) arise from the Omega-background
    (epsilon_1, epsilon_2), NOT from the normal bundle grading
    directly (AP-CY20).
    """
    if h3 is None:
        h3 = -(h1 + h2)
    return _g_two_param(u_ij, v_ij, h1, h2, h3)


