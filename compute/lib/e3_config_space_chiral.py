def tree_integral_n_points(
    n: int, h1: complex, h2: complex,
    h3: Optional[complex] = None,
    spectral_params: Optional[List[complex]] = None,
) -> complex:
    """Tree-level (E_1) Feynman integral on Conf_n(C^3).

    The tree-level diagram is a line graph: propagators connect
    consecutive points (1,2), (2,3), ..., (n-1,n).

    I_n^{tree} = prod_{k=1}^{n-1} g(u_k - u_{k+1})

    This is the labeled-ordered (E_1) contribution: the product
    over consecutively ordered pairs.

    Parameters
    ----------
    n : int
        Number of points.
    h1, h2 : complex
        Omega-background parameters.
    spectral_params : list of complex, optional
        Spectral parameters u_1, ..., u_n. If None, uses default
        evenly spaced values avoiding poles (AP-CY28).

    Returns
    -------
    complex
        Tree-level integral value.
    """
    if h3 is None:
        h3 = -(h1 + h2)
    if n <= 1:
        return 1.0

    if spectral_params is None:
        # Default: evenly spaced, far from poles at +/- h_i (AP-CY28)
        spectral_params = [3.7 + 1.1 * k for k in range(n)]

    assert len(spectral_params) == n, \
        f"Need {n} spectral params, got {len(spectral_params)}"

    result = 1.0
    for k in range(n - 1):
        z_diff = spectral_params[k] - spectral_params[k + 1]
        result *= _g_rational(z_diff, h1, h2, h3)
    return result


def one_loop_integral_n_points(
    n: int, h1: complex, h2: complex,
    h3: Optional[complex] = None,
    spectral_params: Optional[List[complex]] = None,
) -> complex:
    """One-loop (E_2) Feynman integral on Conf_n(C^3).

    The one-loop diagram is a cycle: propagators connect
    (1,2), (2,3), ..., (n-1,n), (n,1).

    I_n^{1-loop} = prod_{k=1}^{n} g(u_k - u_{k+1 mod n})

    This is the braided (E_2) contribution: the product around the
    full cycle, encoding the Yang-Baxter structure.

    For n=2: I_2 = g(u_1-u_2) * g(u_2-u_1) = g(z)*g(-z) = 1
    by the CY inversion identity.

    Returns
    -------
    complex
        One-loop integral value.
    """
    if h3 is None:
        h3 = -(h1 + h2)
    if n <= 1:
        return 1.0

    if spectral_params is None:
        spectral_params = [3.7 + 1.1 * k for k in range(n)]

    result = 1.0
    for k in range(n):
        z_diff = spectral_params[k] - spectral_params[(k + 1) % n]
        result *= _g_rational(z_diff, h1, h2, h3)
    return result


def two_loop_e3_integral(
    h1: complex, h2: complex,
    h3: Optional[complex] = None,
    spectral_params: Optional[List[complex]] = None,
) -> complex:
    """Two-loop (E_3) Feynman integral on Conf_3(C^3).

    The two-loop contribution for 3 points uses the Zamolodchikov
    factorization: all 3 pairwise propagators.

    I_3^{E_3} = prod_{1<=i<j<=3} g_ch(u_i - u_j, v_i - v_j)

    For the single-parameter (E_2) case, this reduces to
    prod g(u_i - u_j) which is the standard Yangian 3-point function.

    The E_3 CORRECTION to the pairwise product is the ZTE obstruction
    (Theorem thm:zte-failure): the factored S_{ijk} = R_{ij}R_{ik}R_{jk}
    fails the tetrahedron equation at O(kappa^2). AP-CY30: factored !=
    solved for higher coherence.

    Here we compute the FACTORED (pairwise) version. The genuine E_3
    correction requires the ZTE correction engine.
    """
    if h3 is None:
        h3 = -(h1 + h2)

    if spectral_params is None:
        spectral_params = [3.7, 4.8, 6.1]

    assert len(spectral_params) == 3

    u = spectral_params
    result = 1.0
    for i in range(3):
        for j in range(i + 1, 3):
            result *= _g_rational(u[i] - u[j], h1, h2, h3)
    return result


def two_loop_e3_integral_two_param(
    h1: complex, h2: complex,
    h3: Optional[complex] = None,
    u_params: Optional[List[complex]] = None,
    v_params: Optional[List[complex]] = None,
) -> complex:
    """Two-loop E_3 integral with two spectral parameters.

    Uses the two-parameter structure function g_ch(u, v) for each pair.
    This is the C^3 analogue with both transverse directions active.

    I_3^{E_3,2-param} = prod_{i<j} g_ch(u_i - u_j, v_i - v_j)
    """
    if h3 is None:
        h3 = -(h1 + h2)

    if u_params is None:
        u_params = [3.7, 4.8, 6.1]
    if v_params is None:
        v_params = [2.3, 3.5, 5.2]

    assert len(u_params) == 3
    assert len(v_params) == 3

    result = 1.0
    for i in range(3):
        for j in range(i + 1, 3):
            du = u_params[i] - u_params[j]
            dv = v_params[i] - v_params[j]
            result *= _g_two_param(du, dv, h1, h2, h3)
    return result


