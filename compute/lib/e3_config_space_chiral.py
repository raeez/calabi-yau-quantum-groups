# 10. E_3 factorization homology integrals
# =========================================================================

def factorization_homology_c3_tree_level(
    h1: complex, h2: complex,
    h3: Optional[complex] = None,
    max_charge: int = 4,
) -> Dict:
    """Factorization homology int_{C^3} F at tree level (sigma_3 = 0 limit).

    At the self-dual point sigma_3 = 0, the E_3 structure reduces to
    E_inf (commutative). The factorization homology is:

      int_{C^3} F = F tensor H_*(C^3; k) = F

    (since H_*(C^3; k) = k, concentrated in degree 0). The tree-level
    partition function on C^3 is just the vacuum (no nontrivial topology).

    The nontrivial content emerges at one-loop (sigma_3 != 0):
    the Omega-background breaks E_inf to E_3, and the factorization
    homology integral gains perturbative corrections.

    For the Fock space at charge q: the plethystic logarithm of the
    partition function gives the single-particle spectrum.

    At tree level:
      Z_q = prod_{n=1}^{inf} 1/(1-q^n)^n  (MacMahon function)
    counting 3D partitions (plane partitions).

    This matches the C^3 DT partition function (MNOP 2006).
    """
    if h3 is None:
        h3 = -(h1 + h2)
    sigma3 = h1 * h2 * h3

    # MacMahon coefficients: number of plane partitions of n
    macmahon = [1]  # pp(0) = 1
    for n in range(1, max_charge + 1):
        macmahon.append(_plane_partition_count(n))

    return {
        "h1": h1, "h2": h2, "h3": h3,
        "sigma3": sigma3,
        "tree_level": abs(sigma3) < 1e-12,
        "E_n_level": "E_inf" if abs(sigma3) < 1e-12 else "E_3",
        "partition_function_type": "MacMahon (plane partitions)",
        "macmahon_coefficients": macmahon,
        "dt_identification": "Z_{DT}(C^3) = M(q) (MacMahon)",
        "plethystic_log": "q/(1-q)^2 (single-particle: bosonic, 2-param)",
    }


@lru_cache(maxsize=128)
def _plane_partition_count(n: int) -> int:
    """Count plane partitions of n (3D partitions).

    Uses the recursion from the generating function
    M(q) = prod_{k>=1} 1/(1-q^k)^k.

    First few values: 1, 1, 3, 6, 13, 24, 48, 86, 160, 282, 500.

    # VERIFIED: [DC] direct computation, [LT] OEIS A000219
    """
    if n == 0:
        return 1
    if n < 0:
        return 0

    # Use the recursion: n * pp(n) = sum_{k=1}^{n} sigma_2(k) * pp(n-k)
    # where sigma_2(k) = sum_{d|k} d^2 is the sum of squares of divisors.
    total = 0
    for k in range(1, n + 1):
        s2 = sum(d * d for d in range(1, k + 1) if k % d == 0)
        total += s2 * _plane_partition_count(n - k)
    return total // n


