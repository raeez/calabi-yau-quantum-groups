def cohomology_algebra_generators(n: int,
                                   ambient_complex_dim: int = 3) -> Dict:
    """Generators and relations of H*(Conf_n(C^d); Q).

    Generators: omega_{ij} for 1 <= i < j <= n, of degree 2d-1.
    Number of generators: C(n, 2) = n(n-1)/2.

    Relations:
      (1) omega_{ij}^2 = 0 (graded commutativity, since deg is odd)
      (2) Arnold relation: omega_{ij} omega_{jk} + omega_{jk} omega_{ki}
                           + omega_{ki} omega_{ij} = 0
          for all distinct i, j, k.
      (3) omega_{ij} omega_{kl} = (-1)^{(2d-1)^2} omega_{kl} omega_{ij}
                                = -omega_{kl} omega_{ij}  (since (2d-1)^2 is odd)

    The FORMALITY statement (Kriz 1994, Totaro 1996):
      C*(Conf_n(C^d); Q) is formal, i.e., quasi-isomorphic to its
      cohomology as a CDGA (commutative differential graded algebra).

    For C^3 specifically:
      - Generators in degree 5
      - Arnold relations in degree 10
      - The E_3 operad action on the CDGA is via the formality
        quasi-isomorphism from C*(E_3; Q) to H*(E_3; Q)
      - OVER Q: E_3 collapses to E_2 (formality kills the chain-level
        content). AP-CY33: the physical content (Miki, ZTE, etc.) lives
        at the chain level.
    """
    deg = 2 * ambient_complex_dim - 1
    num_generators = n * (n - 1) // 2
    # Arnold relations: one per unordered triple
    num_arnold = n * (n - 1) * (n - 2) // 6  # = C(n, 3)

    generators = []
    for i in range(1, n + 1):
        for j in range(i + 1, n + 1):
            generators.append(f"omega_{{{i}{j}}}")

    return {
        "n": n,
        "ambient_dim": ambient_complex_dim,
        "generator_degree": deg,
        "num_generators": num_generators,
        "generators": generators,
        "num_arnold_relations": num_arnold,
        "is_formal": True,  # Kriz 1994
        "formality_source": "Kriz 1994 (complex algebraic varieties)",
        "chain_level_E3_nontrivial": True,  # AP-CY33
        "rational_E3_collapses_to_E2": True,  # AP-CY33
    }


