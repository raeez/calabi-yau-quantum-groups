# 7. CY inversion and functional identities
# =========================================================================

def verify_cy_inversion(h1: complex, h2: complex,
                        h3: Optional[complex] = None,
                        n_points: int = 32,
                        tol: float = 1e-9) -> Tuple[bool, float]:
    """Verify g(z)*g(-z) = 1 (CY inversion identity).

    This is the fundamental identity of the CY structure function,
    following from h_1 + h_2 + h_3 = 0.

    Proof: g(z)*g(-z) = prod_i (z-h_i)/prod_i (z+h_i)
                        * prod_i (-z-h_i)/prod_i (-z+h_i)
                      = prod_i (z-h_i)(-z-h_i) / prod_i (z+h_i)(-z+h_i)
                      = prod_i (h_i^2 - z^2) / prod_i (h_i^2 - z^2) = 1.
    """
    if h3 is None:
        h3 = -(h1 + h2)

    max_res = 0.0
    for j in range(n_points):
        # Test points far from poles (AP-CY28)
        z = 3.7 + 1.3 * np.exp(2j * math.pi * (j + 0.37) / n_points)
        try:
            val = _g_rational(z, h1, h2, h3) * _g_rational(-z, h1, h2, h3)
            res = abs(val - 1.0)
            max_res = max(max_res, res)
        except ZeroDivisionError:
            continue

    return max_res < tol, max_res


def verify_two_param_inversion(h1: complex, h2: complex,
                               h3: Optional[complex] = None,
                               n_points: int = 32,
                               tol: float = 1e-9) -> Tuple[bool, float]:
    """Verify g_ch(u,v)*g_ch(-u,-v) = 1 (two-parameter CY inversion).

    Proof: g_ch(u,v) = g(u)*g(v)*g(u-v).
    g_ch(u,v)*g_ch(-u,-v) = g(u)g(-u) * g(v)g(-v) * g(u-v)g(-(u-v)) = 1*1*1 = 1.
    """
    if h3 is None:
        h3 = -(h1 + h2)

    max_res = 0.0
    for j in range(n_points):
        u = 3.7 + 1.1 * np.exp(2j * math.pi * (j + 0.23) / n_points)
        v = 5.2 + 0.9 * np.exp(2j * math.pi * (j + 0.61) / n_points)
        try:
            g_fwd = _g_two_param(u, v, h1, h2, h3)
            g_inv = _g_two_param(-u, -v, h1, h2, h3)
            res = abs(g_fwd * g_inv - 1.0)
            max_res = max(max_res, res)
        except ZeroDivisionError:
            continue

    return max_res < tol, max_res


def verify_one_loop_trivial(h1: complex, h2: complex,
                            h3: Optional[complex] = None,
                            tol: float = 1e-9) -> Tuple[bool, float]:
    """Verify the one-loop integral at n=2 is trivial.

    I_2^{1-loop} = g(u_1-u_2)*g(u_2-u_1) = g(z)*g(-z) = 1.

    This is the statement that the double braiding is trivial for
    the CY structure function (the S-matrix at charge 1 is 1).
    """
    if h3 is None:
        h3 = -(h1 + h2)

    z = 3.7 + 1.1j  # Far from poles (AP-CY28)
    val = one_loop_integral_n_points(
        2, h1, h2, h3,
        spectral_params=[0.0, -(3.7 + 1.1j)]
    )
    # Actually: we need z and -z
    val = _g_rational(z, h1, h2, h3) * _g_rational(-z, h1, h2, h3)
    res = abs(val - 1.0)
    return res < tol, res


def verify_tree_factorization(h1: complex, h2: complex,
                              h3: Optional[complex] = None,
                              n: int = 4,
                              tol: float = 1e-9) -> Tuple[bool, float]:
    """Verify tree integral factorizes: I_n^{tree} = prod g(u_k - u_{k+1}).

    This is the E_1 (labeled-ordered) property: the tree integral is
    a product over consecutive pairs, independent of the "internal"
    structure. The factorization is the content of E_1 coassociativity
    (automatic for the cofree tensor coalgebra T^c).
    """
    if h3 is None:
        h3 = -(h1 + h2)

    # Compute via the engine
    params = [3.7 + 1.1 * k for k in range(n)]
    I_tree = tree_integral_n_points(n, h1, h2, h3, params)

    # Compute by hand: product of consecutive g-values
    manual = 1.0
    for k in range(n - 1):
        manual *= _g_rational(params[k] - params[k + 1], h1, h2, h3)

    res = abs(I_tree - manual)
    return res < tol, res


