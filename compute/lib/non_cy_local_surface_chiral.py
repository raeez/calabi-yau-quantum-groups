def euler_characteristic_localization(a: int, b: int) -> int:
    """Equivariant Euler characteristic via Atiyah-Bott localization.

    For X_{a,b} = Tot(O(a)+O(b) -> P^1) with T^2 fiber action:

    Fixed locus = P^1 (zero section).
    chi(X) = chi(P^1) = 2.

    This is independent of (a, b).
    """
    return 2


def chi_compact_support(a: int, b: int) -> int:
    """Euler characteristic with compact support.

    For a rank-2 vector bundle over P^1:
    chi_c(Tot(E)) = chi(P^1) * chi(C^2) = 2 * 1 = 2.

    (The fiber C^2 has chi_c = 1 by contractibility.)
    """
    return 2


