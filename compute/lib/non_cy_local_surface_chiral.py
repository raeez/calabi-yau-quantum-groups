def h0_p1(n: int) -> int:
    """dim H^0(P^1, O(n)) = max(n + 1, 0)."""
    return max(n + 1, 0)


def h1_p1(n: int) -> int:
    """dim H^1(P^1, O(n)) = max(-n - 1, 0)."""
    return max(-n - 1, 0)


