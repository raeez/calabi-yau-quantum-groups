        # Verification for delta = 12: kappa = 1 + 1 = 2.
        # Verification for delta = -12: kappa = 1 - 1 = 0.
        #
        # BUT: is delta/12 the right formula?
        # The one-loop anomaly from a background field in O(n) on P^1:
        # The field has chi(O(n)) = n+1 modes.
