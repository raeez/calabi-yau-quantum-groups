class ChernData(NamedTuple):
    """Chern class data for X_{a,b} = Tot(O(a)+O(b) -> P^1).

    c(T_X) = c(T_{P^1}) * c(O(a)) * c(O(b))
           = (1 + 2H)(1 + aH)(1 + bH)
    on P^1, where H^2 = 0.

    c_1 = (2 + a + b)H = delta * H
    c_2 = (2a + 2b + ab)H^2 = 0   (since H^2 = 0 on P^1)
    c_3 = 2ab H^3 = 0
    """
    c1_degree: int     # coefficient of H in c_1
    c2_zero: bool      # whether c_2 = 0 (always True on P^1)
    c3_zero: bool      # whether c_3 = 0 (always True on P^1)
    c1_equals_delta: bool   # whether c_1 = delta * H
    todd_integral: Fraction  # integral of Todd_1 over P^1


def compute_chern_data(X: LocalSurfaceData) -> ChernData:
    """Compute the Chern class data for X_{a,b}."""
    a, b = X.a, X.b
    delta = X.delta

    # c_1(T_X) = (2 + a + b) H = delta H
    c1_deg = 2 + a + b  # = delta

    # Todd_1 = c_1/2, so integral_{P^1} Todd_1 = delta/2
    todd_int = Fraction(delta, 2)

    return ChernData(
        c1_degree=c1_deg,
        c2_zero=True,
        c3_zero=True,
        c1_equals_delta=(c1_deg == delta),
        todd_integral=todd_int,
    )


