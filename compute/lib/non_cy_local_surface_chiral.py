class HochschildData(NamedTuple):
    """Hochschild cohomology of the weight-0 polyvector fields.

    HH^k measures infinitesimal deformations (k=2) and obstructions (k=3).
    """
    dims: Dict[int, int]  # k -> dim HH^k
    euler: int            # alternating sum
    deformation_dim: int  # dim HH^2 (deformation space)
    obstruction_dim: int  # dim HH^3 (obstruction space)


def compute_hochschild(X: LocalSurfaceData) -> HochschildData:
    """Compute the Hochschild cohomology of PV^*(X_{a,b}).

    For the GL(2)-invariant sector on Tot(O(a)+O(b) -> P^1):

    The differential on PV^* is the de Rham differential d (or rather,
    its dual, the divergence operator div: PV^p -> PV^{p-1}).

    For the invariant sector:
    - The differential is TRIVIAL (div = 0 on GL(2)-invariant polyvectors)
      when the Poisson structure is nondegenerate.
    - HH^k_{inv} = PV^k_{inv} / (exact).

    For a local surface over P^1:
    - HH^0 = C (the constant)
    - HH^1 depends on (a,b): fiber Euler fields give dim >= 2
    - HH^2 is the key: controls deformations
    - HH^3 controls obstructions; vanishes iff BTT holds

    For the CY case (delta=0): BTT theorem gives HH^3 = 0 (unobstructed).
    For non-CY: HH^3 may be nonzero (obstructed).
    """
    pv = compute_pv_decomposition(X)
    a, b = X.a, X.b
    delta = X.delta

    # For the GL(2)-invariant sector, the differential on PV^* comes
    # from the divergence operator.  In the weight-0 fiber sector,
    # the divergence with respect to the holomorphic volume form is:
    #   div(alpha) = iota_Omega(d alpha)
    # where Omega is the (possibly non-existent) volume form.

    # For CY (delta=0): Omega exists, div is well-defined, and BTT gives
    # HH^3 = 0 (the complex is exact at PV^3).

    # For non-CY: Omega does not exist globally, but the complex
    # PV^0 -> PV^1 -> PV^2 -> PV^3 still makes sense with d = SN bracket
    # with the Poisson bivector pi = E_a /\\ E_b.

    # The differentials:
    # d_pi: PV^k -> PV^{k+1}, alpha -> [pi, alpha]_{SN}
    # where pi = E_a /\\ E_b (the Poisson bivector).

    # For the GL(2)-invariant sector:
    # d_pi(1) = [E_a /\\ E_b, 1] = 0  (constants are central)
    # d_pi(E_a) = [E_a /\\ E_b, E_a] = [E_a, E_a] /\\ E_b = 0
    # d_pi(E_b) = [E_a /\\ E_b, E_b] = E_a /\\ [E_b, E_b] = 0
    # d_pi(E_a /\\ E_b) = [E_a /\\ E_b, E_a /\\ E_b] = 0

    # So for the GL(2)-invariant sector, d_pi = 0 and HH = PV.

    gl2 = pv.gl2_inv_dims

    # The HH of the GL(2)-inv sector = PV GL(2)-inv (since d_pi = 0)
    hh = dict(gl2)

    # For the FULL (not GL(2)-inv) sector, the HH is more interesting.
    # The deformation space HH^2 has:
    # - The fiber part E_a /\\ E_b (GL(2)-inv): 1 dim
    # - Additional base-fiber parts (not GL(2)-inv)

    deformation_dim = hh.get(2, 0)
    obstruction_dim = hh.get(3, 0)
    euler = sum((-1)**k * v for k, v in hh.items())

    return HochschildData(
        dims=hh,
        euler=euler,
        deformation_dim=deformation_dim,
        obstruction_dim=obstruction_dim,
    )


