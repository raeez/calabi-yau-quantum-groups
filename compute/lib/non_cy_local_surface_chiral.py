def matches_conifold(a: int, b: int) -> bool:
    """Check if X_{a,b} reproduces the resolved conifold data."""
    return (a, b) == (-1, -1) or (a + b == -2 and a == b)


def is_cy_splitting(a: int, b: int) -> bool:
    """Check if (a,b) gives a CY3."""
    return a + b == -2


def all_cy_splittings(max_abs: int = 10) -> List[Tuple[int, int]]:
    """List all CY splittings (a, b) with a+b=-2, |a|, |b| <= max_abs."""
    splittings = []
    for a in range(-max_abs, max_abs + 1):
        b = -2 - a
        if abs(b) <= max_abs:
            splittings.append((a, b))
    return splittings


def pv_euler_characteristic(pv: PVDecomposition) -> int:
    """Alternating sum of PV dimensions: sum (-1)^p dim PV^p."""
    return sum((-1)**p * d for p, d in pv.dims.items())


def pv_gl2_euler(pv: PVDecomposition) -> int:
    """Alternating sum of GL(2)-invariant PV dimensions."""
    return sum((-1)**p * d for p, d in pv.gl2_inv_dims.items())


