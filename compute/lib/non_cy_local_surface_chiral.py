def fiber_symmetry_group(a: int, b: int) -> str:
    """The symmetry group of the fiber O(a) + O(b).

    - a = b: GL(2) (can interchange the two copies)
    - a != b: GL(1) x GL(1) (separate scaling of each factor)
    """
    if a == b:
        return "GL(2)"
    else:
        return "GL(1)xGL(1)"


def total_symmetry(a: int, b: int) -> str:
    """Total symmetry of the local surface.

    Combines the base Aut(P^1) = PGL(2) with the fiber symmetry.
    """
    fiber = fiber_symmetry_group(a, b)
    return f"PGL(2) x {fiber}"


