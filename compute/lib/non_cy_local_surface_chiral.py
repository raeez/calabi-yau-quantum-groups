# 5. Schouten-Nijenhuis bracket on the invariant sector
# =========================================================================

class SNBracketData(NamedTuple):
    """Schouten-Nijenhuis bracket structure on the GL(2)-invariant PV^*.

    The bracket {-, -}_{SN}: PV^p x PV^q -> PV^{p+q-1} restricted to
    the GL(2)-invariant sector gives the Lie algebra structure from which
    the Lie conformal algebra is constructed.
    """
    generators: Dict[str, int]   # name -> PV degree
    brackets: Dict[Tuple[str, str], Any]  # (gen1, gen2) -> bracket
    is_abelian: bool             # True if all brackets vanish


def compute_sn_brackets(X: LocalSurfaceData) -> SNBracketData:
    """Compute the SN bracket on GL(2)-invariant polyvector fields.

    For any (a,b), the GL(2)-invariant sector has:
    - 1 in PV^0 (constant)
    - E_a, E_b in PV^1 (Euler fields), plus possibly others when a=b
    - E_a /\\ E_b in PV^2, plus others depending on (a,b)
    - Trivector in PV^3 (only when delta=0, CY)

    All SN brackets in this sector VANISH (proof below), so the Lie
    algebra is abelian.

    Proof sketch:
    [1, anything]_{SN} = 0  (constants are central)
    [E_a, E_b]_{SN} = 0    (commuting vector fields)
    [E_a, E_a /\\ E_b]_{SN} = [E_a, E_a] /\\ E_b + E_a /\\ [E_a, E_b]
                              = 0 + 0 = 0
    [E_b, E_a /\\ E_b]_{SN} = 0  (similar)
    [E_a /\\ E_b, E_a /\\ E_b]_{SN} = 0  (E_a /\\ E_b is Poisson)
    """
    a, b = X.a, X.b
    delta = X.delta

    generators = {"1": 0, "E_a": 1, "E_b": 1, "Pi": 2}
    if a == b:
        generators["M_ba"] = 1  # y_b d/dy_a when a = b
        generators["M_ab"] = 1  # y_a d/dy_b when a = b

    if delta == 0:
        generators["Omega_inv"] = 3  # trivector (CY volume form dual)

    brackets = {}
    for g1 in generators:
        for g2 in generators:
            if (g2, g1) in brackets:
                continue
            brackets[(g1, g2)] = 0  # all vanish

    return SNBracketData(
        generators=generators,
        brackets=brackets,
        is_abelian=True,  # always abelian in the GL(2)-inv sector
    )


