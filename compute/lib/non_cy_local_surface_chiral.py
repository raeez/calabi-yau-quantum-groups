def landscape_table() -> str:
    """Generate a formatted table of the landscape data."""
    results = compute_landscape()
    lines = [
        f"{'Name':<25} {'(a,b)':<10} {'delta':<6} {'CY':<4} "
        f"{'kappa':<8} {'c':<6} {'BRST^2':<8} {'PV dims':<20} {'GL2 dims':<20}"
    ]
    lines.append("-" * 120)

    for r in results:
        pv_str = str({k: v for k, v in sorted(r["pv_dims"].items())})
        gl2_str = str({k: v for k, v in sorted(r["gl2_inv_dims"].items())})
        lines.append(
            f"{r['name']:<25} ({r['a']},{r['b']}){'':>4} "
            f"{r['delta']:<6} {'Y' if r['is_cy'] else 'N':<4} "
            f"{str(r['kappa']):<8} {str(r['c']):<6} "
            f"{str(r['brst_anomaly']):<8} {pv_str:<20} {gl2_str:<20}"
        )
    return "\n".join(lines)
