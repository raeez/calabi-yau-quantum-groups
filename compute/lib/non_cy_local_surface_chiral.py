# 3. Polyvector field decomposition (weight-0 sector on P^1)
# =========================================================================

class PVDecomposition(NamedTuple):
    """Weight-0 polyvector fields on X_{a,b}, decomposed by exterior degree.

    PV^p_{wt=0} consists of p-vector fields on X that are weight 0 under
    the C^*-action scaling the fiber coordinates.

    Attributes:
        dims: dict mapping p -> dim PV^p_{wt=0}
        gl2_inv_dims: dict mapping p -> dim PV^p_{wt=0, GL(2)-inv}
        detail: detailed decomposition data
    """
    dims: Dict[int, int]
    gl2_inv_dims: Dict[int, int]
    detail: Dict[str, Any]


def compute_pv_decomposition(X: LocalSurfaceData) -> PVDecomposition:
    """Compute the weight-0 polyvector field decomposition.

    For X = Tot(O(a)+O(b) -> P^1):

    PV^0_{wt=0}: Functions on P^1 of fiber weight 0.
        = O_{P^1}, so dim = h^0(P^1, O) = 1.

    PV^1_{wt=0}: Weight-0 vector fields on X.
        Components:
        (a) Base vector fields: d/dz, sections of T_{P^1} = O(2). dim = 3.
        (b) Fiber Euler fields:
            - E_a = y_a d/dy_a: section of O(0). dim = 1.
            - E_b = y_b d/dy_b: section of O(0). dim = 1.
        (c) Mixed fiber fields:
            - y_b d/dy_a: section of O(b-a). dim = h^0(O(b-a)).
            - y_a d/dy_b: section of O(a-b). dim = h^0(O(a-b)).

    PV^2_{wt=0}: Weight-0 bivector fields.
        Components:
        (a) Base /\\ base: /\\^2 T_{P^1} = O(2) (det of tangent). dim = 3.
            Wait: /\\^2 of a rank-2 bundle has rank 1. /\\^2 T_{P^1} is
            not well-defined since T_{P^1} has rank 1 (P^1 is 1-dim!).
            Actually T_{P^1} has rank 1, so /\\^2 T_{P^1} = 0.

            We must be more careful. X is a 3-fold, so T_X has rank 3.
            The weight-0 part of T_X has the components listed in PV^1.
            /\\^2 of the weight-0 tangent has components:

        (a) base /\\ E_a: d/dz /\\ y_a d/dy_a, section of O(2). dim = 3.
        (b) base /\\ E_b: d/dz /\\ y_b d/dy_b, section of O(2). dim = 3.
        (c) base /\\ (y_b d/dy_a): section of O(2+b-a). dim = h^0(O(2+b-a)).
        (d) base /\\ (y_a d/dy_b): section of O(2+a-b). dim = h^0(O(2+a-b)).
        (e) E_a /\\ E_b: y_a d/dy_a /\\ y_b d/dy_b, section of O(0). dim = 1.
        (f) E_a /\\ (y_b d/dy_a): y_a d/dy_a /\\ y_b d/dy_a = 0 (wedge of parallel).
            Actually: d/dy_a /\\ d/dy_a = 0, so y_a d/dy_a /\\ y_b d/dy_a = 0. -> 0.
        (g) E_a /\\ (y_a d/dy_b): y_a d/dy_a /\\ y_a d/dy_b, section of O(2a) * antisym.
            = y_a^2 d/dy_a /\\ d/dy_b, section of O(2a). dim = h^0(O(2a)).
        (h) E_b /\\ (y_b d/dy_a): y_b^2 d/dy_b /\\ d/dy_a, section of O(2b). dim = h^0(O(2b)).
        (i) E_b /\\ (y_a d/dy_b): y_b d/dy_b /\\ y_a d/dy_b = 0.  -> 0.
        (j) (y_b d/dy_a) /\\ (y_a d/dy_b): y_a y_b d/dy_a /\\ d/dy_b.
            Section of O(a+b).  dim = h^0(O(a+b)).
        (k) Same fiber crossing: y_a d/dy_b /\\ y_b d/dy_a is the SAME as (j)
            up to sign (it's the negative).

    This is getting complicated. Let me compute it more systematically.

    PV^3_{wt=0}: Weight-0 trivector fields.
        The top exterior power /\\^3 T_X at weight 0 = K_X^{-1}|_{wt=0}.
        K_X = p^* K_{P^1} tensor p^* det(O(a)+O(b))^{-1}
            = O(-2) tensor O(-a-b)
            = O(-a-b-2) = O(-delta)
        K_X^{-1} = O(delta).
        PV^3_{wt=0} = H^0(P^1, O(delta)).  dim = h^0(O(delta)).
    """
    a, b = X.a, X.b
    delta = X.delta

    # PV^0
    dim_pv0 = 1  # H^0(P^1, O) = C

    # PV^1
    dim_base = 3  # H^0(P^1, O(2)) = C^3 (sl_2 on P^1)
    dim_euler_a = 1  # y_a d/dy_a: O(0)
    dim_euler_b = 1  # y_b d/dy_b: O(0)
    dim_cross_ba = h0_p1(b - a)  # y_b d/dy_a: O(b-a)
    dim_cross_ab = h0_p1(a - b)  # y_a d/dy_b: O(a-b)
    dim_pv1 = dim_base + dim_euler_a + dim_euler_b + dim_cross_ba + dim_cross_ab

    # PV^2: we need to compute /\\^2 of the weight-0 tangent bundle
    # The tangent at weight 0 is T_{P^1} + (fiber directions at weight 0)
    # Since T_{P^1} has rank 1 on P^1, the wedge product structure is:
    #   /\\^2 T_wt0 = (T_{P^1} /\\ fiber_wt0) + /\\^2(fiber_wt0)

    # T_{P^1} /\\ E_a: O(2), dim 3
    # T_{P^1} /\\ E_b: O(2), dim 3
    # T_{P^1} /\\ (y_b d/dy_a): O(2+b-a), dim h^0(O(2+b-a))
    # T_{P^1} /\\ (y_a d/dy_b): O(2+a-b), dim h^0(O(2+a-b))
    dim_pv2_base_fiber = (3 + 3 + h0_p1(2 + b - a) + h0_p1(2 + a - b))

    # /\\^2(fiber_wt0): the fiber weight-0 space has basis:
    #   E_a = y_a d/dy_a, E_b = y_b d/dy_b,
    #   y_b d/dy_a (if h^0(O(b-a)) > 0), y_a d/dy_b (if h^0(O(a-b)) > 0)
    # /\\^2 of these:
    # E_a /\\ E_b: O(0), dim 1
    # E_a /\\ (y_a d/dy_b): really y_a^2 d/dy_a /\\ d/dy_b: O(2a), dim h^0(O(2a))
    # E_b /\\ (y_b d/dy_a): really y_b^2 d/dy_b /\\ d/dy_a: O(2b), dim h^0(O(2b))
    # (y_a d/dy_b) /\\ (y_b d/dy_a) = y_a y_b d/dy_b /\\ d/dy_a: O(a+b), dim h^0(O(a+b))
    # E_a /\\ (y_b d/dy_a) = y_a y_b d/dy_a /\\ d/dy_a = 0
    # E_b /\\ (y_a d/dy_b) = y_a y_b d/dy_b /\\ d/dy_b = 0
    dim_pv2_fiber = (
        1  # E_a /\\ E_b
        + h0_p1(2 * a)  # y_a^2 d/dy_a /\\ d/dy_b
        + h0_p1(2 * b)  # y_b^2 d/dy_b /\\ d/dy_a
        + h0_p1(a + b)  # y_a y_b d/dy_a /\\ d/dy_b (distinct from previous)
    )

    dim_pv2 = dim_pv2_base_fiber + dim_pv2_fiber

    # PV^3
    dim_pv3 = h0_p1(delta)  # H^0(P^1, O(delta)) = anti-canonical sections

    dims = {0: dim_pv0, 1: dim_pv1, 2: dim_pv2, 3: dim_pv3}

    # GL(2)-invariant sector
    # GL(2) = Aut(P^1) with Lie algebra sl_2.
    # SL(2)-invariants in H^0(P^1, O(n)) = Sym^n(C^2):
    #   dim = 1 if n = 0, else 0.
    gl2_pv0 = 1  # constant function
    gl2_pv1 = 0 + 1 + 1 + (1 if a == b else 0) + (1 if a == b else 0)
    # Base: SL2-inv in O(2) = Sym^2(C^2): dim 0 (no SL2-invariant).
    # E_a: O(0): dim 1. E_b: O(0): dim 1.
    # y_b d/dy_a: O(b-a): SL2-inv only if b-a=0, dim 1.
    # y_a d/dy_b: O(a-b): SL2-inv only if a-b=0, dim 1.

    if a == b:
        gl2_pv1 = 4  # E_a, E_b, y_b d/dy_a, y_a d/dy_b (all in O(0))
    else:
        gl2_pv1 = 2  # just E_a, E_b

    # GL(2)-inv of PV^2:
    # base /\\ fiber: SL2 in O(2) = 0, so base /\\ anything = 0 in GL2-inv
    # fiber only:
    # E_a /\\ E_b: O(0), SL2-inv: 1
    # y_a^2 d/dy_a /\\ d/dy_b: O(2a), SL2-inv: 1 if a=0, else 0
    # y_b^2 d/dy_b /\\ d/dy_a: O(2b), SL2-inv: 1 if b=0, else 0
    # y_a y_b d/dy_a /\\ d/dy_b: O(a+b), SL2-inv: 1 if a+b=0, else 0
    gl2_pv2 = (
        1  # E_a /\\ E_b always
        + (1 if a == 0 else 0)
        + (1 if b == 0 else 0)
        + (1 if a + b == 0 else 0)
    )

    # GL(2)-inv of PV^3: O(delta), SL2-inv: 1 if delta=0, else 0
    gl2_pv3 = 1 if delta == 0 else 0

    gl2_inv_dims = {0: gl2_pv0, 1: gl2_pv1, 2: gl2_pv2, 3: gl2_pv3}

    detail = {
        "pv1_base": dim_base,
        "pv1_euler": 2,
        "pv1_cross_ba": dim_cross_ba,
        "pv1_cross_ab": dim_cross_ab,
        "pv2_base_fiber": dim_pv2_base_fiber,
        "pv2_fiber": dim_pv2_fiber,
        "pv3_anticanonical": dim_pv3,
        "anticanonical_degree": delta,
    }

    return PVDecomposition(dims=dims, gl2_inv_dims=gl2_inv_dims, detail=detail)


