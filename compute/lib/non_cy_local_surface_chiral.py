        # for reference (see kappa_anomaly_shifted below).
        kappa_ch = Fraction(1)

        # Is the theory conformal?
        # For delta > 0: there are global sections of O(delta) that can
        # serve as background fields.  The theory can be DEFORMED to a
        # CFT (but the deformation is not unique: dim H^0(O(delta)) = delta+1).
        # For delta < 0: no global sections, and the anomaly cannot be
        # cancelled by a background field.  The theory is NOT conformal
        # in any deformation.
        is_conf = (delta == 0)

        # Shadow depth: for non-CY, the shadow tower is obstructed
        # at the level of the BRST anomaly.
        if delta > 0:
            shadow_d = None  # obstructed, but may have a deformed tower
        else:
            shadow_d = None  # strongly obstructed

        return ChiralAlgebraResult(
            central_charge=c_free,
            kappa=kappa_ch,
            algebra_type="betagamma_anomalous" if delta != 0 else "betagamma",
            is_conformal=is_conf,
            is_anomalous=(delta != 0),
            brst_anomaly=brst_anom,
            shadow_depth=shadow_d,
            name=f"A_{{{a},{b}}}",
        )


