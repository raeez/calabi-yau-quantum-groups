# =========================================================================
# 2. Local surface data
# =========================================================================

class LocalSurfaceData(NamedTuple):
    """Data of a local surface Tot(O(a) + O(b) -> P^1).

    Attributes:
        a: degree of first line bundle
        b: degree of second line bundle
        delta: CY defect a + b + 2
        is_cy: whether delta = 0
    """
    a: int
    b: int

    @property
    def delta(self) -> int:
        """CY defect: a + b + 2.  Zero iff CY."""
        return self.a + self.b + 2

    @property
    def is_cy(self) -> bool:
        """True iff this is a Calabi-Yau threefold."""
        return self.delta == 0

    @property
    def name(self) -> str:
        return f"O({self.a})+O({self.b})->P^1"

    @property
    def anticanonical_degree(self) -> int:
        """Degree of K_X^{-1} restricted to zero section = O(delta)."""
        return self.delta

    @property
    def euler_characteristic(self) -> int:
        """Topological Euler characteristic chi_top(X_{a,b}).

        By equivariant localization on P^1 with T^2-action on fibers:
            chi_top = 2 for ALL (a, b).

        Proof: the fixed locus of the T^2 action on the fibers is P^1
        itself (the zero section).  The Euler characteristic of the
        zero section is chi(P^1) = 2.  By localization, chi(X) = chi(P^1) = 2.
        """
        return 2


def local_surface(a: int, b: int) -> LocalSurfaceData:
    """Create a local surface Tot(O(a) + O(b) -> P^1)."""
    return LocalSurfaceData(a=a, b=b)


