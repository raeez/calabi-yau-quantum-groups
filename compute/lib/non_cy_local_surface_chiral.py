# 16. Obstruction analysis for non-CY
# =========================================================================

class ObstructionData(NamedTuple):
    """Obstruction data for the chiral algebra on X_{a,b}.

    For CY: all obstructions vanish (BTT).
    For non-CY: obstructions may be nontrivial.
    """
    brst_squared: Fraction           # Q^2 (0 for CY)
    delta: int                       # CY defect
    deformation_dim: int             # dim of deformation space
    obstruction_dim: int             # dim of obstruction space
    can_be_deformed_to_cy: bool      # whether a CY deformation exists
    background_field_dim: int        # dim H^0(O(delta))


def compute_obstructions(X: LocalSurfaceData) -> ObstructionData:
    """Compute the obstruction data for X_{a,b}.

    The key question: can the non-CY theory be DEFORMED to a CY theory?

    For a+b = -2 + delta: we need to deform (a,b) to (a', b') with
    a' + b' = -2.  This is always possible in the ALGEBRAIC DEFORMATION
    SPACE (just change the line bundle degrees).  But the question is
    whether the CHIRAL ALGEBRA deforms smoothly.

    The background field approach: add a section of O(delta) to cancel
    the anomaly.  This is possible iff delta >= 0 (sections exist).
    For delta < 0: no background field available, anomaly CANNOT be
    cancelled.

    The deformation space has dimension h^0(O(delta)) = delta + 1 for
    delta >= 0, and is empty for delta < 0.
    """
    delta = X.delta

    return ObstructionData(
        brst_squared=Fraction(delta),
        delta=delta,
        deformation_dim=h0_p1(delta) if delta > 0 else 0,
        obstruction_dim=h1_p1(delta) if delta < -1 else 0,
        can_be_deformed_to_cy=(delta >= 0),
        background_field_dim=h0_p1(delta),
    )


