        # The free-field kappa is 1 for ALL (a,b).
        # The formula kappa = 1 + delta/12 is a CONJECTURAL anomaly-shifted
        # value that requires independent verification.  Until verified,
        # we use the honest free-field value kappa = 1.
        #
