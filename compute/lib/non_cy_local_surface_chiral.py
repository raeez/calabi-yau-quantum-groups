# 17. The anomaly function f(delta)
# =========================================================================

def anomaly_function(delta: int) -> Fraction:
    """The anomaly function f(delta) measuring the CY defect's effect.

    For the chiral algebra on X_{a,b} with CY defect delta:

    kappa(A_{a,b}) = kappa_CY + f(delta)

    where kappa_CY = 1 (the CY value) and f(0) = 0.

    The function f(delta) is:
        f(delta) = 0  for all delta

    This is because kappa is determined by the FREE FIELD content
    (which is always one betagamma pair), and the CY defect affects
    only the INTERACTIONS (BRST structure), not the free-field kappa.

    The physical content of the non-CY anomaly lives in:
    - The BRST anomaly Q^2 = delta * (operator)
    - The background field deformation space
    - The obstruction to the shadow tower

    These are DIFFERENT invariants from kappa.
    """
    return Fraction(0)


def kappa_with_anomaly(a: int, b: int) -> Fraction:
    """Effective kappa including the anomaly contribution.

    kappa_ch = kappa_CY + f(delta) = 1 + 0 = 1.
    """
    delta = cy_defect(a, b)
    return Fraction(1) + anomaly_function(delta)


def kappa_anomaly_shifted_conjectural(a: int, b: int) -> Fraction:
    """CONJECTURAL anomaly-shifted kappa: 1 + delta/12.

    This is NOT the intrinsic free-field kappa (which is always 1).
    It is the CONJECTURAL effective kappa when a background field
    in O(delta) is added to cancel the BRST anomaly.

    The formula kappa_shifted = 1 + delta/12 comes from:
    - The background field has chi(O(delta)) = delta + 1 modes
    - Each mode contributes 1/12 to the Casimir energy
    - The zero mode is already in kappa_free
    - Net shift: delta/12

    STATUS: CONJECTURAL. Not verified by independent computation.
    Use kappa_local_surface() for the proved free-field value.
    """
    delta = cy_defect(a, b)
    return Fraction(1) + Fraction(delta, 12)


