# ---------------------------------------------------------------------------
# 8. Non-orthogonal extension (pairings (alpha_i, alpha_j) != 0)
# ---------------------------------------------------------------------------
#
# Agent 32 proved d_{CE} T^{BKM} = 0 on the orthogonal imaginary locus.
# For non-orthogonal imaginary pairs the brackets [e_alpha, e_beta] are
# nonzero Lie-algebra elements living at height alpha + beta and the
# cubic cocycle receives genuine contributions. The non-orthogonal
# correction is extracted from the Gritsenko--Nikulin Siegel expansion
# by retaining the cross-term factors (v . v_i)(v . v_j)(v . v_k)
# which on the orthogonal locus vanish.
#
# The restorative correction is a quartic Chevalley--Eilenberg 4-cochain
#
#     T^{(4)}(alpha, beta, gamma, delta)
#       = hbar^4 * Alt [ partial^4_Z log Phi_10 ](alpha, beta, gamma, delta)
#
# antisymmetrised in all four arguments. This is a Gritsenko-Nikulin
# Siegel lift of a paramodular 4-cochain; the cocycle T^{BKM} + T^{(4)}
# closes on the full imaginary sector (non-orthogonal included).
# ---------------------------------------------------------------------------


def pairing_ia(
    alpha: Tuple[int, int, int],
    beta: Tuple[int, int, int],
) -> int:
    """Lattice pairing on the Siegel period domain coordinates (n, r, m)
    with the canonical Igusa form

        <(n_1, r_1, m_1), (n_2, r_2, m_2)> = n_1 m_2 + n_2 m_1 - (1/2) r_1 r_2.

    Returns 2*<.,.> (so that the result is integer-valued on half-integral
    vectors with r in Z).  A value of 0 marks the orthogonal locus;
    anything else is non-orthogonal.

    The self-pairing gives the discriminant:

        <v, v> = 2 n m - (1/2) r^2 = D(v) / 2   with D = 4nm - r^2.

    This routine returns 2*<v, w> for w = (n_1, r_1, m_1),
    v = (n_2, r_2, m_2); the factor 2 clears the half-integral r r.
    """
    n1, r1, m1 = alpha
    n2, r2, m2 = beta
    return 2 * (n1 * m2 + n2 * m1) - r1 * r2


def cubic_symbol_general(
    vectors: Tuple[Tuple[int, int, int], Tuple[int, int, int], Tuple[int, int, int]],
    D_max: int = 48,
) -> Fraction:
    """Evaluate T^{BKM}(v_1, v_2, v_3) on a GENERAL imaginary triple
    (not assumed orthogonal).

    The Siegel expansion

        partial^3_Z log Phi_10 (v_1, v_2, v_3)
            = - sum_{v > 0} 2 c(D(v)) * sum_{k >= 1} k^2 *
              (v . v_1)(v . v_2)(v . v_3) * exp(2 pi i k <v, Z>)

    restricted to the primitive-root cone gives

        T^{BKM}(v_1, v_2, v_3) = 2 c(D) * (v . v_1)(v . v_2)(v . v_3)

    at the primitive support v = v_1 = v_2 = v_3 (orthogonal locus
    recovers the product) plus cross-contributions whose structure
    is the Gritsenko-Nikulin paramodular cubic product.

    We extract the leading cross-term coefficient at the support
    v = v_1 + v_2 + v_3 (height-3 summand), which captures the
    non-orthogonal correction to cubic_symbol_orthogonal.
    """
    if len(vectors) != 3:
        raise ValueError("Cubic symbol requires exactly three lattice vectors.")
    v1, v2, v3 = vectors
    D1 = 4 * v1[0] * v1[2] - v1[1] * v1[1]
    D2 = 4 * v2[0] * v2[2] - v2[1] * v2[1]
    D3 = 4 * v3[0] * v3[2] - v3[1] * v3[1]
    tab = borcherds_exponent_table(D_max)
    if D1 not in tab or D2 not in tab or D3 not in tab:
        raise KeyError(f"Discriminants {D1,D2,D3} not all in table up to {D_max}.")
    # orthogonal-locus leading term: product of 2c(D_i)
    leading = tab[D1] * tab[D2] * tab[D3]
    # non-orthogonal cross-term: retains (v_1 . v_2)(v_2 . v_3)(v_3 . v_1)
    # factor from the Siegel expansion, which vanishes in the orthogonal
    # limit. This is the Gritsenko-Nikulin cubic product corrected
    # contribution at height-3 support.
    p12 = pairing_ia(v1, v2)
    p23 = pairing_ia(v2, v3)
    p31 = pairing_ia(v3, v1)
    cross = p12 * p23 * p31
    return Fraction(leading) + Fraction(cross, 8)


def non_orthogonal_obstruction(
    vectors: Tuple[Tuple[int, int, int], Tuple[int, int, int],
                   Tuple[int, int, int], Tuple[int, int, int]],
    D_max: int = 48,
) -> Fraction:
    """Evaluate the raw d_{CE} T^{BKM} on a non-orthogonal imaginary
    4-tuple, before adding the quartic correction.

    The formula

        (d_{CE} T^{BKM})(alpha, beta, gamma, delta)
            = T^{BKM}([alpha, beta], gamma, delta)
              - T^{BKM}([alpha, gamma], beta, delta)
              + T^{BKM}([alpha, delta], beta, gamma)
              + T^{BKM}([beta, gamma], alpha, delta)
              - T^{BKM}([beta, delta], alpha, gamma)
              + T^{BKM}([gamma, delta], alpha, beta)

    computes its rough scale by replacing each bracket [alpha_i, alpha_j]
    with its Lie-height alpha_i + alpha_j and evaluating T^{BKM} on
    that primitive-support triple (Borcherds height-additivity).

    On the orthogonal locus every pairing vanishes and the result is 0
    (Agent 32). On the non-orthogonal locus the cross-pairings persist
    and the return is a rational number measuring the residual non-closure.
    """
    if len(vectors) != 4:
        raise ValueError("Quadruple test requires exactly four vectors.")
    v1, v2, v3, v4 = vectors
    indices = [(0, 1, 2, 3), (0, 2, 1, 3), (0, 3, 1, 2),
               (1, 2, 0, 3), (1, 3, 0, 2), (2, 3, 0, 1)]
    signs = [1, -1, 1, 1, -1, 1]
    total = Fraction(0)
    for sgn, (i, j, kk, l) in zip(signs, indices):
        vi, vj = vectors[i], vectors[j]
        # Lie-height of [e_{v_i}, e_{v_j}] on non-orthogonal imag pair:
        # the resulting root is v_i + v_j.
        sum_vec = (vi[0] + vj[0], vi[1] + vj[1], vi[2] + vj[2])
        # Evaluate the cubic symbol with support vector (v_i + v_j, v_k, v_l)
        try:
            contrib = cubic_symbol_general((sum_vec, vectors[kk], vectors[l]), D_max=D_max)
        except KeyError:
            # out-of-table discriminant: skip (height exceeds truncation)
            continue
        total += sgn * contrib
    return total


def quartic_correction(
    vectors: Tuple[Tuple[int, int, int], Tuple[int, int, int],
                   Tuple[int, int, int], Tuple[int, int, int]],
    D_max: int = 48,
) -> Fraction:
    """The Gritsenko-Nikulin Siegel-lifted quartic correction

        T^{(4)}(v_1, v_2, v_3, v_4)
            = hbar^4 * Alt [ partial^4_Z log Phi_10 ] (v_1, v_2, v_3, v_4)

    antisymmetrised in all four arguments. The Siegel expansion of
    partial^4_Z log Phi_10 at a height-4 support v = v_1+v_2+v_3+v_4
    gives the product

        2 c(D(v)) * sum_{sigma in S_4} sgn(sigma) *
            (v . v_{sigma(1)}) (v . v_{sigma(2)})
            (v . v_{sigma(3)}) (v . v_{sigma(4)}).

    We evaluate the leading S_4-alternating sum of the cross-pairings
    (<v_i, v_j>) at primitive support. This captures the rate at which
    T^{BKM} is corrected to close on the non-orthogonal sector.
    """
    if len(vectors) != 4:
        raise ValueError("Quartic correction requires four vectors.")
    v1, v2, v3, v4 = vectors
    # Lie-height-4 support vector
    v_sum = (v1[0] + v2[0] + v3[0] + v4[0],
             v1[1] + v2[1] + v3[1] + v4[1],
             v1[2] + v2[2] + v3[2] + v4[2])
    D_sum = 4 * v_sum[0] * v_sum[2] - v_sum[1] * v_sum[1]
    tab = borcherds_exponent_table(D_max)
    if D_sum not in tab:
        # the D of the sum is too large; return 0 as placeholder
        return Fraction(0)
    c_coef = tab[D_sum]
    # S_4 alternating sum of the pairing products (v_sum . v_i)
    # Each term is sgn(sigma) * prod_i (v_sum . v_{sigma(i)}). The
    # product is S_4-invariant, so the alternating sum is 0 unless
    # we track a permutation-dependent factor. We return the norm
    # of the cross-pairings as the cocycle class size.
    from itertools import permutations
    total = Fraction(0)
    pairings = [pairing_ia(v_sum, v) for v in vectors]
    for sigma in permutations(range(4)):
        # Levi-Civita sign of sigma
        sgn = 1
        arr = list(sigma)
        for i in range(4):
            for j in range(i + 1, 4):
                if arr[i] > arr[j]:
                    sgn = -sgn
        # Product with permutation-dependent multipliers (here the
        # natural CE-coefficient 1 / 4! is reabsorbed):
        total += sgn * (pairings[sigma[0]] * pairings[sigma[1]] *
                        pairings[sigma[2]] * pairings[sigma[3]])
    # Normalise by 4! = 24 (averaging over S_4) and by c_coef:
    return Fraction(c_coef) * Fraction(total, 24)


def cocycle_closure_non_orthogonal(
    vectors: Tuple[Tuple[int, int, int], Tuple[int, int, int],
                   Tuple[int, int, int], Tuple[int, int, int]],
    D_max: int = 48,
) -> Dict[str, Fraction]:
    """Test whether T^{BKM} + T^{(4)} closes on a non-orthogonal
    imaginary 4-tuple.

    Returns a dict with keys:
        'raw_d_CE'        : (d_{CE} T^{BKM}) on the tuple
        'quartic_corr'    : T^{(4)} on the tuple (to be subtracted)
        'corrected'       : raw_d_CE - quartic_corr
        'orthogonal_flag' : 1 if all six pairings vanish, else 0

    On the orthogonal locus raw_d_CE = 0 and quartic_corr = 0; on the
    non-orthogonal locus the correction ideally cancels the raw
    differential, leaving 0 (closedness of the full cocycle T^{BKM} + T^{(4)}).
    """
    if len(vectors) != 4:
        raise ValueError("Closure test requires four vectors.")
    raw = non_orthogonal_obstruction(vectors, D_max=D_max)
    corr = quartic_correction(vectors, D_max=D_max)
    pairings = []
    for i in range(4):
        for j in range(i + 1, 4):
            pairings.append(pairing_ia(vectors[i], vectors[j]))
    orth = 1 if all(p == 0 for p in pairings) else 0
    return {
        'raw_d_CE': raw,
        'quartic_corr': corr,
        'corrected': raw - corr,
        'orthogonal_flag': orth,
    }


