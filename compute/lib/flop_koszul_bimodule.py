# 11. Chain of flops and Coxeter group
# ============================================================================

def chain_of_flops_group(
    B: List[List[int]],
    name: str = 'conifold',
    max_elements: int = 50,
) -> Dict[str, Any]:
    r"""Compute the group generated by flops acting on the E_1 algebra.

    For a CY3 with multiple flop walls, the composition of flops
    generates a group G acting on the space of E_1 algebras (or
    equivalently, on the exchange graph of quivers).

    THEOREM (Fomin-Zelevinsky):
    The exchange graph of a quiver Q is:
    - Finite iff Q is of finite type (ADE classification)
    - In finite type: the group is the corresponding Weyl group W
    - The Coxeter generators are the individual mutations

    For the conifold (A_1): exchange graph has 1 edge, group = Z/2Z.
    For local P^2 (A_2 seed): 5 vertices, group = S_3 (symmetric group).
    For D_4: 6 vertices, group = W(D_4).

    For affine/wild type: the group is infinite. The exchange graph is
    an infinite but locally finite tree.

    We compute the exchange graph using BFS and extract the group structure.
    """
    n = len(B)

    # Use the exchange graph computation from mutation_e1_equivalence
    graph = exchange_graph(B, max_vertices=max_elements)

    # Determine the type
    num_vertices = graph['n_vertices']
    is_finite = graph.get('is_finite', num_vertices < max_elements)

    # For finite type: extract the Coxeter group
    if is_finite:
        # The number of vertices in the exchange graph determines the type
        # A_1: 1 edge (2 vertices), W = Z/2Z, |W| = 2
        # A_2: 5 vertices, W = S_3, |W| = 6
        # A_3: 14 vertices, W = S_4, |W| = 24
        # B_2: 6 vertices, W = W(B_2), |W| = 8
        # D_4: 6 vertices (for the seed), W = W(D_4), |W| = 192

        group_data = _identify_coxeter_group(n, num_vertices, name)
    else:
        group_data = {
            'type': 'infinite',
            'truncated_at': max_elements,
            'description': f'Infinite exchange graph, explored {num_vertices} vertices',
        }

    # Compute the action on kappa
    # Kappa is gauge-invariant under all mutations (= flops), so:
    kappa_action = 'trivial (kappa is invariant under all flops)'

    return {
        'name': name,
        'exchange_matrix': B,
        'num_exchange_graph_vertices': num_vertices,
        'exchange_graph_finite': is_finite,
        'coxeter_group': group_data,
        'kappa_action': kappa_action,
        'n_independent_flops': n,  # One mutation per vertex
    }


def _identify_coxeter_group(rank: int, num_vertices: int,
                             name: str) -> Dict[str, Any]:
    """Identify the Coxeter group from the exchange graph size."""
    # Known finite type exchange graph sizes (number of clusters = Cat(n+1))
    # A_n: Cat(n+1) = (2n+2)!/((n+1)!(n+2)!)
    # But exchange graph vertices = number of clusters.
    known_groups = {
        (2, 2): {'type': 'A_1', 'group': 'Z/2Z', 'order': 2},
        (2, 5): {'type': 'A_2', 'group': 'S_3', 'order': 6},
        (3, 14): {'type': 'A_3', 'group': 'S_4', 'order': 24},
        (2, 6): {'type': 'B_2', 'group': 'W(B_2)', 'order': 8},
        (4, 6): {'type': 'D_4', 'group': 'W(D_4)', 'order': 192},
        (3, 6): {'type': 'A_2 or B_2 variant', 'group': 'varies', 'order': 'varies'},
    }

    key = (rank, num_vertices)
    if key in known_groups:
        return known_groups[key]

    return {
        'type': f'unknown (rank={rank}, |exchange graph|={num_vertices})',
        'group': 'not identified',
        'order': num_vertices,
        'name': name,
    }


