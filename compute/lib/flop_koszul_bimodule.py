# 4. KS automorphism roundtrip verification (Path 3)
# ============================================================================

def ks_roundtrip_verification(max_height: int = 10) -> Dict[str, Any]:
    r"""Verify flop-flop = id via KS automorphism roundtrip.

    For the conifold, the flop corresponds to the wall-crossing at
    gamma = (1,1). The KS automorphism K_{(1,1)} is the gluing map
    between chambers I and II.

    The roundtrip K_{(1,1)} o K_{(1,1)}^{-1} = id verifies that
    the transition from I to II and back is the identity.

    This is an INDEPENDENT verification of flop-flop = id, using the
    KS automorphism formalism instead of the bimodule tensor product.
    """
    K = KSWallAutomorphism((1, 1), omega=1, max_height=max_height,
                           quiver='A1')
    K_inv = K.inverse()

    # Compose: K o K^{-1} on each generator
    composition = ComposedKSAutomorphism([K, K_inv])

    test_charges = [(a, b) for a in range(1, max_height)
                    for b in range(1, max_height - a + 1)
                    if a + b <= max_height]

    all_identity = True
    results = {}
    for beta in test_charges:
        composed = composition.act_on_generator(beta)
        expected = CoHAElement.generator(beta, max_height, quiver='A1')
        is_id = (composed == expected)
        if not is_id:
            all_identity = False
            results[str(beta)] = {
                'composed': str(composed),
                'expected': str(expected),
            }

    return {
        'is_identity': all_identity,
        'num_tested': len(test_charges),
        'failures': results,
        'path': 'KS automorphism roundtrip (Path 3)',
    }


