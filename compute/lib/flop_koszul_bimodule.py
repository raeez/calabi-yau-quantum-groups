def conifold_flop_bimodule(max_height: int = 12) -> FlopBimodule:
    r"""The flop bimodule for the Atiyah flop (conifold).

    Conifold: 2 vertices, exchange matrix B = ((0,2),(-2,0)).
    Mutation at vertex 0.

    The mutation matrix E_0^+ acts on charges:
        E_0^+(e_0) = -e_0
        E_0^+(e_1) = e_1 + 2*e_0   (since B[1][0] = -2, max(0, -2) = 0... hmm)

    Wait: the tropical mutation matrix is:
        E_k^+_{ii} = 1 (i != k)
        E_k^+_{kk} = -1
        E_k^+_{ik} = max(0, B_{ik}) for i != k

    For k=0:
        E_0^+_{00} = -1
        E_0^+_{11} = 1
        E_0^+_{10} = max(0, B[1][0]) = max(0, -2) = 0

    So E_0^+ = [[-1, 0], [0, 1]].

    This means mu_0(e_0) = -e_0, mu_0(e_1) = e_1.

    That cannot be right for an involution to work as a flop.
    The issue: the conifold exchange matrix has B = ((0,2),(-2,0)),
    so mutation at vertex 0 gives:
        E_0^+_{10} = max(0, B[1][0]) = max(0, -2) = 0

    But at vertex 1:
        E_1^+_{01} = max(0, B[0][1]) = max(0, 2) = 2
        E_1^+_{11} = -1
        E_1^+_{00} = 1

    So E_1^+ = [[1, 2], [0, -1]].

    Check involution: E_1'^+ for the mutated matrix.
    B' = mu_1(B) = exchange_matrix_mutate(B, 1):
        B'_{ij} = -B_{ij} if i=1 or j=1
                = B_{ij} + (|B_{i1}|*B_{1j} + B_{i1}*|B_{1j}|)/2 otherwise
    For 2x2: B'_{00} = 0 (diagonal). B'_{01} = -B_{01} = -2.
    B'_{10} = -B_{10} = 2. B'_{11} = 0.
    So B' = ((0,-2),(2,0)) = -B.

    E_1'^+ for B' at vertex 1:
        E_1'^+_{01} = max(0, B'[0][1]) = max(0, -2) = 0
        E_1'^+_{11} = -1
        E_1'^+_{00} = 1

    Product E_1'^+ * E_1^+ = [[1,0],[0,-1]] * [[1,2],[0,-1]]
        = [[1, 2], [0, 1]]. NOT identity.

    The issue: for the conifold, the mutation on CHARGES uses E_k^+ or E_k^-
    depending on the sign of the charge components. The standard tropical
    mutation formula handles this:
        mu_k(gamma)_k = -gamma_k + max(0, sum_{j} B_{jk}*gamma_j) for gamma_k >= 0.

    For the conifold flop, which EXCHANGES the two simples, the correct
    charge transformation is simply the permutation (a,b) <-> (b,a).
    This corresponds to the RELABELING of vertices, NOT the tropical mutation.

    The flop as a relabeling:
    Chamber I has simples S_0 = (1,0) and S_1 = (0,1).
    Chamber II (flopped) has simples S_0' = S_1 and S_1' = S_0.
    The charge map is the permutation matrix: F = [[0,1],[1,0]].
    F^2 = Id (involution).

    This is the CORRECT charge transformation for the conifold flop.
    The tropical mutation gives a DIFFERENT transformation (involving
    negatives), which works at the level of the seed but not at the
    level of positive charges/dimension vectors.

    For the bimodule, we use the permutation matrix as the charge map.
    """
    B = [[0, 2], [-2, 0]]
    # The conifold flop permutes the two vertices
    F = [[0, 1], [1, 0]]  # Permutation matrix
    F_inv = [[0, 1], [1, 0]]  # F = F^{-1} (involution)

    return FlopBimodule(
        name='conifold_flop',
        exchange_matrix=B,
        mutation_vertex=1,
        mutation_matrix=F,
        inverse_mutation_matrix=F_inv,
        max_height=max_height,
    )


def pagoda_flop_bimodule(max_height: int = 12) -> FlopBimodule:
    r"""The flop bimodule for the Pagoda flop (local P^1 x P^1).

    Local P^1 x P^1 has exchange matrix (SPP-type quiver with 3 vertices):
        B = ((0, 1, -1), (-1, 0, 1), (1, -1, 0))

    This is the A_2 exchange matrix. Mutation at vertex 0 gives the flop
    of the first P^1.

    The charge map for the flop: reflection at vertex 0.
    """
    B = [[0, 1, -1], [-1, 0, 1], [1, -1, 0]]
    k = 0

    E_plus = tropical_mutation_matrix(k, B, sign=1)
    Bp = exchange_matrix_mutate(B, k)
    E_plus_prime = tropical_mutation_matrix(k, Bp, sign=1)

    # Compute inverse: E_plus_prime should be the inverse of E_plus
    # when applied to dimension vectors in the positive cone.
    # For seeds: the inverse uses the opposite sign convention.
    # For the bimodule, we need F and F^{-1} on the charge lattice.

    # Direct computation:
    # E_0^+ for B = ((0,1,-1),(-1,0,1),(1,-1,0)):
    #   E_{00} = -1
    #   E_{10} = max(0, B[1][0]) = max(0, -1) = 0
    #   E_{20} = max(0, B[2][0]) = max(0, 1) = 1
    #   Other diagonal = 1
    # So E_0^+ = [[-1, 0, 0], [0, 1, 0], [1, 0, 1]]

    return FlopBimodule(
        name='pagoda_flop',
        exchange_matrix=B,
        mutation_vertex=k,
        mutation_matrix=E_plus,
        inverse_mutation_matrix=E_plus_prime,
        max_height=max_height,
    )


