# 10. Koszul wall in the stability manifold
# ============================================================================

def koszul_wall_detection(
    B: List[List[int]],
    name: str = 'conifold',
    max_mutations: int = 20,
) -> Dict[str, Any]:
    r"""Detect Koszul walls in the stability manifold.

    CONJECTURE (AP43 applies: this is NOT proved):
    In the Bridgeland stability manifold Stab(D^b(X)), there exists a
    distinguished wall W_K (the KOSZUL WALL) where:
    - The E_1 algebra A_t undergoes Koszul duality
    - Crossing W_K: A_t -> A_t^! (Koszul dual)
    - This is NOT a standard wall-crossing

    CRITERION: A Koszul wall would appear where the mutation sequence
    produces an exchange matrix B' satisfying:
        B' = -B (negation of the original)
    because the Koszul dual of a quiver algebra for B is related to
    the algebra for -B (reversed arrows).

    For the conifold: B = ((0,2),(-2,0)), B' = mu_1(B) = ((0,-2),(2,0)) = -B.
    So the conifold HAS a Koszul wall at the first mutation!

    For local P^2: B = ((0,3,-3),(-3,0,3),(3,-3,0)).
    Does any single or composed mutation produce -B?

    For the quintic: no quiver model exists (non-toric), so the Koszul
    wall question is open.
    """
    n = len(B)

    # Check if single mutations produce -B
    neg_B = [[-B[i][j] for j in range(n)] for i in range(n)]

    single_mutation_koszul = {}
    for k in range(n):
        Bp = exchange_matrix_mutate(B, k)
        is_neg = (Bp == neg_B)
        single_mutation_koszul[k] = {
            'Bp': Bp,
            'is_neg_B': is_neg,
        }

    has_single_koszul_wall = any(
        v['is_neg_B'] for v in single_mutation_koszul.values()
    )

    # Check composed mutations (BFS on the exchange graph)
    # Look for any mutation sequence producing -B
    visited: Set[str] = set()
    queue: List[Tuple[List[List[int]], List[int]]] = [(B, [])]
    visited.add(str(B))
    found_neg_B = has_single_koszul_wall
    neg_B_path: Optional[List[int]] = None

    if has_single_koszul_wall:
        for k, v in single_mutation_koszul.items():
            if v['is_neg_B']:
                neg_B_path = [k]
                break

    steps = 0
    while queue and steps < max_mutations and not found_neg_B:
        current_B, path = queue.pop(0)
        for k in range(n):
            Bp = exchange_matrix_mutate(current_B, k)
            key = str(Bp)
            if key not in visited:
                visited.add(key)
                new_path = path + [k]
                if Bp == neg_B:
                    found_neg_B = True
                    neg_B_path = new_path
                    break
                queue.append((Bp, new_path))
        steps += 1

    # Koszul wall for the quintic: OPEN QUESTION
    # The quintic CY3 has no toric model and no quiver with potential.
    # The existence of a Koszul wall is unknown.
    quintic_status = 'open'
    if name == 'quintic':
        quintic_status = (
            'No quiver model exists for the quintic CY3. '
            'The Koszul wall question is open (AP43).'
        )

    return {
        'name': name,
        'exchange_matrix': B,
        'neg_B': neg_B,
        'single_mutation_koszul': single_mutation_koszul,
        'has_single_koszul_wall': has_single_koszul_wall,
        'found_neg_B_in_exchange_graph': found_neg_B,
        'neg_B_mutation_path': neg_B_path,
        'num_matrices_explored': len(visited),
        'max_mutations': max_mutations,
        'quintic_status': quintic_status if name == 'quintic' else 'N/A',
        'claim_status': 'conjecture (AP43)',
    }


