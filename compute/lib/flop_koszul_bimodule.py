# 0. Bimodule element
# ============================================================================

class BimoduleElement:
    r"""Element of an A-B bimodule M in the charge-graded basis.

    A bimodule element is a formal linear combination of generators
    m_gamma for gamma in the charge lattice, truncated to max_height.

    The left A-action and right B-action are encoded as:
        e^A_alpha . m_gamma = sum_delta c^L_{alpha,gamma,delta} m_delta
        m_gamma . e^B_beta  = sum_delta c^R_{gamma,beta,delta} m_delta

    For the flop bimodule, the left and right actions are determined
    by the wall-crossing automorphism K_W.
    """

    def __init__(self, coeffs: Dict[Tuple[int, ...], Fraction],
                 max_height: int, rank: int = 2):
        self.max_height = max_height
        self.rank = rank
        self.coeffs: Dict[Tuple[int, ...], Fraction] = {
            k: v for k, v in coeffs.items()
            if v != 0 and charge_height(k) <= max_height
        }

    @classmethod
    def zero(cls, max_height: int, rank: int = 2) -> 'BimoduleElement':
        return cls({}, max_height, rank)

    @classmethod
    def generator(cls, gamma: Tuple[int, ...], max_height: int,
                  coeff: Fraction = Fraction(1)) -> 'BimoduleElement':
        return cls({gamma: coeff}, max_height, len(gamma))

    def __add__(self, other: 'BimoduleElement') -> 'BimoduleElement':
        result = dict(self.coeffs)
        for k, v in other.coeffs.items():
            result[k] = result.get(k, Fraction(0)) + v
            if k in result and result[k] == 0:
                del result[k]
        return BimoduleElement(result, self.max_height, self.rank)

    def __sub__(self, other: 'BimoduleElement') -> 'BimoduleElement':
        result = dict(self.coeffs)
        for k, v in other.coeffs.items():
            result[k] = result.get(k, Fraction(0)) - v
            if k in result and result[k] == 0:
                del result[k]
        return BimoduleElement(result, self.max_height, self.rank)

    def __neg__(self) -> 'BimoduleElement':
        return BimoduleElement({k: -v for k, v in self.coeffs.items()},
                               self.max_height, self.rank)

    def scale(self, c: Fraction) -> 'BimoduleElement':
        if c == 0:
            return BimoduleElement.zero(self.max_height, self.rank)
        return BimoduleElement({k: c * v for k, v in self.coeffs.items()},
                               self.max_height, self.rank)

    def is_zero(self) -> bool:
        return not self.coeffs

    def get(self, gamma: Tuple[int, ...]) -> Fraction:
        return self.coeffs.get(gamma, Fraction(0))

    def charges(self) -> List[Tuple[int, ...]]:
        return sorted(self.coeffs.keys(), key=lambda g: (charge_height(g), g))

    def __eq__(self, other: object) -> bool:
        if not isinstance(other, BimoduleElement):
            return NotImplemented
        return self.coeffs == other.coeffs

    def __repr__(self) -> str:
        if not self.coeffs:
            return '0'
        terms = []
        for g in self.charges():
            terms.append(f'{self.coeffs[g]}*m_{g}')
        return ' + '.join(terms)


