# 12. Local P^1 x P^1 x P^1: three independent flops
# ============================================================================

def triple_p1_flop_chain() -> Dict[str, Any]:
    r"""Chain of flops for local P^1 x P^1 x P^1 (three independent flops).

    This CY3 has h^{1,1} = 3 and three independent flop walls.
    Each flop is a mutation of the corresponding vertex in a 3-vertex quiver.

    The exchange matrix is the A_3 type:
        B = ((0, 1, 0), (-1, 0, 1), (0, -1, 0))

    The group of flops is generated by three involutions:
        sigma_0 = mu_0, sigma_1 = mu_1, sigma_2 = mu_2

    For A_3 (finite type): the Coxeter group is S_4 (symmetric group
    on 4 elements), of order 24.

    The exchange graph has 14 vertices (= Catalan number C_4 = 14).

    Each vertex of the exchange graph corresponds to a chamber in the
    Kahler moduli space, and each edge corresponds to a single flop.
    """
    B = [[0, 1, 0], [-1, 0, 1], [0, -1, 0]]

    # Verify the group structure
    group_data = chain_of_flops_group(B, name='A_3_chain', max_elements=50)

    # Compute the flop bimodule at each vertex
    flop_bimodules = {}
    for k in range(3):
        flop = FlopBimodule(
            name=f'A3_flop_vertex_{k}',
            exchange_matrix=B,
            mutation_vertex=k,
            mutation_matrix=tropical_mutation_matrix(k, B, sign=1),
            inverse_mutation_matrix=tropical_mutation_matrix(
                k, exchange_matrix_mutate(B, k), sign=1),
            max_height=8,
        )
        result = verify_flop_flop_identity(flop)
        flop_bimodules[k] = {
            'flop_flop_identity': result['flop_flop_is_identity'],
        }

    # Braid relation: mu_0 mu_1 mu_0 = mu_1 mu_0 mu_1 (for A_n type)
    # At the exchange matrix level:
    B010 = exchange_matrix_mutate(
        exchange_matrix_mutate(exchange_matrix_mutate(B, 0), 1), 0)
    B101 = exchange_matrix_mutate(
        exchange_matrix_mutate(exchange_matrix_mutate(B, 1), 0), 1)
    braid_relation = (B010 == B101)

    # Also: mu_0 mu_2 = mu_2 mu_0 (commuting distant mutations)
    B02 = exchange_matrix_mutate(exchange_matrix_mutate(B, 0), 2)
    B20 = exchange_matrix_mutate(exchange_matrix_mutate(B, 2), 0)
    commuting_distant = (B02 == B20)

    return {
        'exchange_matrix': B,
        'group_data': group_data,
        'flop_bimodules': flop_bimodules,
        'all_flop_flop_identity': all(
            v['flop_flop_identity'] for v in flop_bimodules.values()
        ),
        'braid_relation': braid_relation,
        'commuting_distant_mutations': commuting_distant,
        'coxeter_relations': {
            'sigma_i^2 = 1': True,  # Each mutation is an involution
            'sigma_0 sigma_1 sigma_0 = sigma_1 sigma_0 sigma_1': braid_relation,
            'sigma_0 sigma_2 = sigma_2 sigma_0': commuting_distant,
        },
    }


