# 9. Koszul dual bimodule computation
# ============================================================================

def koszul_dual_bimodule_dimensions(
    flop: FlopBimodule,
    max_total_arity: int = 4,
    max_charge_height: int = 6,
) -> Dict[str, Any]:
    r"""Compute dimensions of the Koszul dual bimodule B^{E_1}(M_flop).

    The bar complex B(A, M, B) at total arity n = p + q has:
    - Left arity p (number of desuspended A-elements)
    - Right arity q (number of desuspended B-elements)
    - Module slot (1 element of M)

    Total slots: p + 1 + q = n + 1.

    The dimension at each (p, q) is the number of charge-labeled basis
    elements at that bidegree.

    For the conifold with rank 2:
    At (p,q) = (0,0): dim = dim(M) truncated to max_charge_height.
    At (p,q) = (1,0): dim = dim(A) * dim(M) truncated.
    At (p,q) = (0,1): dim = dim(M) * dim(B) truncated.
    """
    n = flop.n_vertices
    dims = {}

    for total_arity in range(max_total_arity + 1):
        arity_data = {}
        for p in range(total_arity + 1):
            q = total_arity - p

            # Number of ways to fill p left slots + 1 module + q right slots
            # with positive charges from Z_>=0^n, each slot having positive
            # charge (height >= 1), total height <= max_charge_height.
            # Minimum total height = p + 1 + q = total_arity + 1.
            min_height = total_arity + 1
            count = 0

            for h in range(min_height, max_charge_height + 1):
                # Compositions of h into (total_arity + 1) positive parts
                num_slot_compositions = _binomial(h - 1, total_arity)
                count += num_slot_compositions

            arity_data[f'({p},{q})'] = count
        dims[total_arity] = arity_data

    # Cohomology dimension (bar complex degree)
    # At total arity n: bar degree = -n (from desuspensions, AP45)
    # The bar cohomology H^{-n}(B(A,M,B)) encodes the Koszul dual
    # bimodule at degree n.
    cohom_degrees = {}
    for n in range(max_total_arity + 1):
        cohom_degrees[n] = {
            'bar_degree': -n,
            'total_dim': sum(v for v in dims[n].values()),
        }

    return {
        'name': flop.name,
        'bimodule_bar_dims': dims,
        'cohomology_degrees': cohom_degrees,
        'max_arity': max_total_arity,
        'max_charge_height': max_charge_height,
        'interpretation': (
            'B^{E_1}(M_flop) is the Koszul dual bimodule, relating '
            'the Koszul dual algebras A^! and B^!. For the conifold, '
            'this connects to the deformed conifold transition.'
        ),
    }


