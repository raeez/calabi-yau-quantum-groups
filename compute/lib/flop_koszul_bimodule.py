# 2. Opposite bimodule: M_flop^{op} (for the reverse flop)
# ============================================================================

@dataclass
class OppositeFlop:
    r"""The opposite bimodule M_flop^{op} for the reverse flop X^+ -> X.

    If M_flop is an A-B-bimodule, then M_flop^{op} is a B-A-bimodule
    obtained by reversing the roles of left and right actions.

    For the conifold: the reverse flop is the SAME mutation (mu_k^2 = id),
    so M_flop^{op} has the same underlying vector space but with:
    - LEFT action by B = CoHA(Q', W')
    - RIGHT action by A = CoHA(Q, W)
    """
    flop: FlopBimodule

    def left_action(self, beta: Tuple[int, ...],
                    m_gamma: Tuple[int, ...]) -> Tuple[int, ...]:
        """Left B-action on the opposite bimodule."""
        # The mutation maps B-charges to A-charges
        mu_beta = apply_matrix(self.flop.mutation_matrix, beta)
        return charge_add(mu_beta, m_gamma)

    def right_action(self, m_gamma: Tuple[int, ...],
                     alpha: Tuple[int, ...]) -> Tuple[int, ...]:
        """Right A-action on the opposite bimodule."""
        return charge_add(m_gamma, alpha)


