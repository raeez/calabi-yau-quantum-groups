# 1. Flop bimodule: the E_1 bimodule encoding a single flop
# ============================================================================

@dataclass
class FlopBimodule:
    r"""The E_1 bimodule M_flop for a CY3 flop.

    For a flop X -> X^+ corresponding to mutation mu_k of (Q,W):
    - A = CoHA(Q, W)      (left algebra)
    - B = CoHA(Q', W')    (right algebra, mutated)
    - M = A-B-bimodule encoding the transition functor

    The bimodule is generated by elements m_gamma for gamma in the
    positive cone of the charge lattice. The left and right actions
    are determined by the mutation:

    LEFT ACTION: e^A_alpha . m_gamma = m_{alpha + gamma}
        (the left CoHA acts by extension from the left)

    RIGHT ACTION: m_gamma . e^B_beta = m_{gamma + mu_k^{-1}(beta)}
        (the right CoHA acts through the mutation inverse)

    The bimodule M_flop has a GENERATOR m_0 (the unit element),
    and all other elements are obtained by left/right action on m_0.

    CRITICAL SUBTLETY (AP42): The tropical mutation on charge vectors
    is PIECEWISE LINEAR, not linear. The matrix E_k^+ applies when
    d_k >= 0, and E_k^- when d_k < 0. For the bimodule structure,
    we work entirely with POSITIVE dimension vectors (the CoHA is
    graded by the positive cone N^{Q_0}), so left and right actions
    are simply charge addition. The mutation enters as the RELABELING
    of generators between the two CoHAs.

    At the level of the classical CoHA (q=1), both left and right
    actions are charge addition:
        e^A_alpha . m_gamma = m_{alpha + gamma}
        m_gamma . e^B_beta  = m_{gamma + beta}
    The bimodule is a free rank-1 module over A tensor B^{op}.
    """
    name: str
    exchange_matrix: List[List[int]]
    mutation_vertex: int
    mutation_matrix: List[List[int]] = field(default_factory=list)
    inverse_mutation_matrix: List[List[int]] = field(default_factory=list)
    max_height: int = 12

    @property
    def n_vertices(self) -> int:
        return len(self.exchange_matrix)

    @property
    def mutated_exchange_matrix(self) -> List[List[int]]:
        """Exchange matrix of the mutated quiver."""
        return exchange_matrix_mutate(self.exchange_matrix, self.mutation_vertex)

    def left_action(self, alpha: Tuple[int, ...],
                    m_gamma: Tuple[int, ...]) -> Tuple[int, ...]:
        """Left A-action: e^A_alpha . m_gamma = m_{alpha + gamma}."""
        return charge_add(alpha, m_gamma)

    def right_action(self, m_gamma: Tuple[int, ...],
                     beta: Tuple[int, ...]) -> Tuple[int, ...]:
        """Right B-action: m_gamma . e^B_beta = m_{gamma + beta}.

        Both A and B act by charge addition. The distinction between
        A and B is encoded in the EXCHANGE MATRIX (which determines
        the E_1 product structure), not in the charge-level action.
        """
        return charge_add(m_gamma, beta)

    def left_action_element(self, alpha: Tuple[int, ...],
                            m: BimoduleElement) -> BimoduleElement:
        """Apply left action of e^A_alpha on a bimodule element m."""
        result: Dict[Tuple[int, ...], Fraction] = {}
        for gamma, coeff in m.coeffs.items():
            target = self.left_action(alpha, gamma)
            if charge_height(target) <= self.max_height:
                result[target] = result.get(target, Fraction(0)) + coeff
        return BimoduleElement(
            {k: v for k, v in result.items() if v != 0},
            self.max_height, self.n_vertices
        )

    def right_action_element(self, m: BimoduleElement,
                             beta: Tuple[int, ...]) -> BimoduleElement:
        """Apply right action of e^B_beta on a bimodule element m."""
        result: Dict[Tuple[int, ...], Fraction] = {}
        for gamma, coeff in m.coeffs.items():
            target = self.right_action(gamma, beta)
            if charge_height(target) <= self.max_height:
                result[target] = result.get(target, Fraction(0)) + coeff
        return BimoduleElement(
            {k: v for k, v in result.items() if v != 0},
            self.max_height, self.n_vertices
        )


