def verify_flop_flop_identity(flop: FlopBimodule) -> Dict[str, Any]:
    r"""Verify flop-flop = identity for a given flop bimodule.

    This runs the tensor product computation to check that
    M_flop tensor_{B} M_flop^{op} ~ identity bimodule.

    Multi-path verification:
    Path 1: Bimodule tensor product (algebraic)
    Path 2: Charge vector composition
    Path 5: Exchange matrix involution mu_k^2 = id
    Path 6: Euler form preservation
    """
    results: Dict[str, Any] = {'name': flop.name}

    # Path 1 + 2: Tensor product computation
    tensor_result = compute_tensor_product_image(flop, flop.max_height)
    results['path_1_2_tensor'] = {
        'is_identity': tensor_result['tensor_is_identity_bimodule'],
        'charges_tested': tensor_result['charges_tested'],
        'mutation_involution': tensor_result['mutation_involution_on_B'],
        'charge_involution': tensor_result['charge_involution'],
    }

    # Path 5: Exchange matrix involution
    B = flop.exchange_matrix
    k = flop.mutation_vertex
    Bp = exchange_matrix_mutate(B, k)
    Bpp = exchange_matrix_mutate(Bp, k)
    results['path_5_exchange_involution'] = {
        'mu_k_squared_is_id': (Bpp == B),
        'B': B,
        'Bp': Bp,
        'Bpp': Bpp,
    }

    # Path 6: Euler form preservation
    euler_result = euler_form_preservation(B, k)
    results['path_6_euler'] = {
        'preserved': euler_result['euler_form_preserved'],
    }

    # Overall verdict
    results['flop_flop_is_identity'] = (
        tensor_result['tensor_is_identity_bimodule']
        and (Bpp == B)
        and euler_result['euler_form_preserved']
    )

    return results


def all_standard_flops_verification() -> Dict[str, Any]:
    r"""Verify flop-flop = identity for all standard flop types.

    Standard flops:
    1. Atiyah flop (conifold): simplest, 2-vertex quiver
    2. Pagoda flop (local P^1 x P^1): 3-vertex, A_2 exchange matrix
    3. Mukai flop (K3 fibration): 2-vertex, A_1 exchange matrix
    4. Reid fantasy flop: 4-vertex, D_4 exchange matrix
    """
    flops = {
        'atiyah': conifold_flop_bimodule(max_height=8),
        'pagoda': pagoda_flop_bimodule(max_height=8),
        'mukai': mukai_flop_bimodule(max_height=8),
        'reid': reid_flop_bimodule(max_height=8),
    }

    results = {}
    all_pass = True
    for name, flop in flops.items():
        result = verify_flop_flop_identity(flop)
        results[name] = result
        if not result['flop_flop_is_identity']:
            all_pass = False

    return {
        'flops': results,
        'all_pass': all_pass,
        'num_flops_tested': len(flops),
        'theorem': 'flop-flop = identity for all standard CY3 flops',
    }


