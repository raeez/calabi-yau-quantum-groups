# 5. Euler form preservation under bimodule transfer (Path 6)
# ============================================================================

def euler_form_preservation(B: List[List[int]], k: int) -> Dict[str, Any]:
    r"""Verify the Euler form is preserved under the bimodule transfer.

    The antisymmetric Euler form chi(g1, g2) = sum_{ij} B_{ij} g1_i g2_j
    should be preserved under mutation:
        chi'(mu_k(g1), mu_k(g2)) = chi(g1, g2)

    where chi' uses the mutated exchange matrix B' = mu_k(B).

    This is the key property ensuring that the bimodule M_flop
    intertwines the E_1 products of the two CoHAs.
    """
    n = len(B)
    Bp = exchange_matrix_mutate(B, k)
    E_plus = tropical_mutation_matrix(k, B, sign=1)

    preserved = True
    checks = {}

    # Test on all pairs of simple dimension vectors
    for i in range(n):
        for j in range(n):
            ei = tuple(1 if l == i else 0 for l in range(n))
            ej = tuple(1 if l == j else 0 for l in range(n))

            # Original Euler form
            chi_orig = sum(B[a][b] * ei[a] * ej[b]
                           for a in range(n) for b in range(n))

            # Mutated charges
            mu_ei = apply_matrix(E_plus, ei)
            mu_ej = apply_matrix(E_plus, ej)

            # Mutated Euler form
            chi_mut = sum(Bp[a][b] * mu_ei[a] * mu_ej[b]
                          for a in range(n) for b in range(n))

            match = (chi_orig == chi_mut)
            if not match:
                preserved = False
            checks[f'({i},{j})'] = {
                'chi_orig': chi_orig,
                'chi_mut': chi_mut,
                'match': match,
            }

    return {
        'euler_form_preserved': preserved,
        'checks': checks,
        'path': 'Euler form preservation (Path 6)',
    }


