# 4. CASIMIR ELEMENTS OF Y^+(gl_hat_1)
# ============================================================================

def yangian_casimir_eigenvalue(k: int, n: int,
                               h1: Rational, h2: Rational,
                               h3: Optional[Rational] = None) -> Dict[str, Any]:
    """Compute the k-th Casimir element eigenvalue spectrum of Y^+(gl_hat_1).

    The center of Y^+(gl_hat_1) is generated by central elements C_k
    constructed from the psi generating series:

      psi(z) = 1 + sigma_3 * sum psi_i z^{-i-1}

    The Casimir elements are the coefficients of the central series:
      C(z) = sum_k C_k z^{-k}
    obtained from the generating function of the center.

    On the charge-n Fock module, C_k acts as the k-th power-sum
    of box contents (up to normalization), hence:
      C_k |pi> = E_k(pi) |pi>

    where E_k(pi) = sum_{box in pi} content(box)^k.

    The first Casimirs:
      C_1 = psi_0 (charge operator) with eigenvalue n * (something)
      C_2 relates to the Virasoro L_0 (energy)
      C_3 is the cubic Casimir (genuinely 3D, first nonvanishing for CY3)

    Returns eigenvalue spectrum with multiplicities.
    """
    if h3 is None:
        h3 = -(h1 + h2)

    # The Casimir eigenvalues coincide with the CM eigenvalues by the
    # Schiffmann-Vasserot isomorphism CoHA = Y^+(gl_hat_1).
    # The power-sum Casimirs C_k have eigenvalue E_k(pi) on |pi>.
    return cm_hamiltonian_from_yangian(k, n, h1, h2, h3)


def first_casimirs(n: int, num_casimirs: int,
                   h1: Rational, h2: Rational,
                   h3: Optional[Rational] = None) -> Dict[int, Dict[str, Any]]:
    """Compute the first `num_casimirs` Casimir element spectra at charge n.

    Returns dict {k: casimir_data} for k = 1, ..., num_casimirs.
    """
    if h3 is None:
        h3 = -(h1 + h2)
    result = {}
    for k in range(1, num_casimirs + 1):
        result[k] = yangian_casimir_eigenvalue(k, n, h1, h2, h3)
    return result


