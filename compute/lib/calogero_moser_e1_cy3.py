# 5. CUBIC CM HAMILTONIAN (GENUINELY 3D PHENOMENON)
# ============================================================================

def cubic_hamiltonian_eigenvalues(n: int,
                                  h1: Rational, h2: Rational,
                                  h3: Optional[Rational] = None) -> Dict[str, Any]:
    """Compute the cubic CM Hamiltonian H_3 eigenvalues.

    H_3 is the genuinely 3D Hamiltonian:
      E_3(pi) = sum_{(i,j,l) in pi} (h1*i + h2*j + h3*l)^3

    This vanishes identically for 2D partitions (l=0 only) when
    restricted to the h3-direction, making it a genuinely 3D probe.

    The cubic Hamiltonian is controlled by the phi_3 = -2*sigma_3
    structure constant of the affine Yangian, confirming that H_3
    measures the cubic Casimir of the CY3 geometry.

    Key properties:
    1. E_3(pi) depends on all three parameters h1, h2, h3 in a
       non-trivial way.
    2. For pi a 2D partition (all boxes at l=0), E_3 reduces to the
       2D cubic Hamiltonian sum (h1*i + h2*j)^3.
    3. For pi the "column partition" (all boxes at i=j=0), E_3 =
       sum_{l=0}^{n-1} (h3*l)^3 = h3^3 * sum l^3 = h3^3 * [n(n-1)/2]^2.

    Returns spectrum of H_3 with analysis.
    """
    if h3 is None:
        h3 = -(h1 + h2)

    pps = enumerate_plane_partitions(n)
    spectrum = []
    for pp in pps:
        ev = cm_eigenvalue(pp, 3, h1, h2, h3)
        spectrum.append(ev)

    # Identify 2D partitions (those with max height 1 everywhere)
    two_d_evs = []
    three_d_evs = []
    for pp, ev in zip(pps, spectrum):
        max_height = max((max(row) for row in pp), default=0)
        if max_height <= 1:
            two_d_evs.append(ev)
        else:
            three_d_evs.append(ev)

    # Column partition: [[n]] = single column of height n
    col_pp = [[n]]
    col_ev = cm_eigenvalue(col_pp, 3, h1, h2, h3)
    # Expected: h3^3 * [n(n-1)/2]^2 (sum of cubes formula)
    col_expected = h3 ** 3 * Rational(n * (n - 1), 2) ** 2
    # Actually: sum_{l=0}^{n-1} (h3*l)^3 = h3^3 * sum l^3 = h3^3 * [n(n-1)/2]^2
    # by the identity sum_{l=0}^{m} l^3 = [m(m+1)/2]^2

    # Row partition: [[1,1,...,1]] (n ones) = all at height 1, layer 0
    row_pp = [[1] * n]
    row_ev = cm_eigenvalue(row_pp, 3, h1, h2, h3)
    # Expected: sum_{j=0}^{n-1} (h2*j)^3 = h2^3 * [n(n-1)/2]^2

    return {
        "n": n,
        "h_params": (h1, h2, h3),
        "dimension": len(pps),
        "spectrum": spectrum,
        "num_distinct": len(set(spectrum)),
        "num_2d_partitions": len(two_d_evs),
        "num_3d_partitions": len(three_d_evs),
        "column_eigenvalue": col_ev,
        "column_expected": col_expected,
        "column_match": expand(col_ev - col_expected) == 0,
        "row_eigenvalue": row_ev,
        "description": (
            f"Cubic CM Hamiltonian H_3 at charge {n}: "
            f"{len(set(spectrum))} distinct eigenvalues. "
            f"Column partition check: {expand(col_ev - col_expected) == 0}."
        ),
    }


