# 8. CONIFOLD: TWO-CENTER CM PROBLEM
# ============================================================================

def conifold_cm_eigenvalue(pp1: List[List[int]], pp2: List[List[int]],
                            k: int,
                            h1: Rational, h2: Rational,
                            h3: Optional[Rational] = None,
                            separation: Optional[Rational] = None) -> Rational:
    """CM eigenvalue for the conifold (2-center problem).

    The conifold has two torus-fixed charts, each contributing a local
    CM system. The global CM Hamiltonian is:

      H_k^{global} = H_k^{(1)} + H_k^{(2)} + Delta_k^{interaction}

    For separated centers (well-separated in the CY moduli):
      H_k^{(1)} = sum_{box in pi_1} content_1(box)^k
      H_k^{(2)} = sum_{box in pi_2} (content_2(box) + Delta)^k

    where Delta = separation between centers (Kahler modulus).

    The interaction energy Delta_k^{interaction} encodes the correction
    from wall-crossing: it measures how the global spectrum differs from
    the sum of local spectra.

    For the resolved conifold with Kahler parameter t:
      Delta = t (= FI parameter in the GLSM description)

    At the wall t = 0: the two centers merge, and the CM system is
    maximally interacting.

    Returns the total eigenvalue H_k^{(1)} + H_k^{(2)}(shifted).
    The interaction energy is the difference from the naive sum.
    """
    if h3 is None:
        h3 = -(h1 + h2)
    if separation is None:
        separation = Rational(0)

    # Local eigenvalues at each center
    ev1 = cm_eigenvalue(pp1, k, h1, h2, h3)

    # Second center: shift all contents by the separation
    ev2 = Rational(0)
    boxes2 = plane_partition_boxes(pp2)
    for (i, j, l) in boxes2:
        c = box_content(i, j, l, h1, h2, h3) + separation
        ev2 += c ** k

    return ev1 + ev2


def conifold_interaction_energy(pp1: List[List[int]], pp2: List[List[int]],
                                 k: int,
                                 h1: Rational, h2: Rational,
                                 h3: Optional[Rational] = None,
                                 separation: Optional[Rational] = None) -> Rational:
    """Interaction energy between the two conifold centers.

    Delta_k = E_k^{global}(sep) - E_k^{global}(sep=0)

    More precisely:
      Delta_k = H_k^{total}(sep) - [H_k^{(1)} + H_k^{(2,unshifted)}]

    This measures the wall-crossing correction to the CM spectrum.
    """
    if h3 is None:
        h3 = -(h1 + h2)
    if separation is None:
        separation = Rational(0)

    # Naive sum (no interaction)
    ev_naive = cm_eigenvalue(pp1, k, h1, h2, h3) + cm_eigenvalue(pp2, k, h1, h2, h3)

    # Full eigenvalue with separation
    ev_full = conifold_cm_eigenvalue(pp1, pp2, k, h1, h2, h3, separation)

    return ev_full - ev_naive


def conifold_cm_full_spectrum(n1: int, n2: int, max_k: int,
                               h1: Rational, h2: Rational,
                               h3: Optional[Rational] = None,
                               separation: Optional[Rational] = None) -> Dict[str, Any]:
    """Full CM spectrum for the conifold at charges (n1, n2).

    Enumerate all pairs (pi_1, pi_2) with |pi_1| = n1, |pi_2| = n2,
    compute the global CM eigenvalues, and analyze the interaction.

    Returns dict with full spectrum and interaction analysis.
    """
    if h3 is None:
        h3 = -(h1 + h2)
    if separation is None:
        separation = Rational(0)

    pps1 = enumerate_plane_partitions(n1)
    pps2 = enumerate_plane_partitions(n2)

    states = []
    for pp1 in pps1:
        for pp2 in pps2:
            evs = {}
            interactions = {}
            for k in range(1, max_k + 1):
                ev_full = conifold_cm_eigenvalue(pp1, pp2, k, h1, h2, h3, separation)
                ev_interaction = conifold_interaction_energy(pp1, pp2, k, h1, h2, h3, separation)
                evs[k] = ev_full
                interactions[k] = ev_interaction

            states.append({
                "pp1": pp1,
                "pp2": pp2,
                "n1": n1,
                "n2": n2,
                "eigenvalues": evs,
                "interactions": interactions,
            })

    # Analyze: at sep=0, interaction should vanish for k=1 (center of mass)
    # but not for k >= 2 in general.
    return {
        "n1": n1,
        "n2": n2,
        "separation": separation,
        "h_params": (h1, h2, h3),
        "num_states": len(states),
        "states": states,
    }


