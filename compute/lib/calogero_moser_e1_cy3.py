# 6. EIGENSTATES = BPS STATES
# ============================================================================

def bps_eigenstate_table(max_n: int,
                         h1: Rational, h2: Rational,
                         h3: Optional[Rational] = None,
                         max_k: int = 5) -> Dict[int, List[Dict[str, Any]]]:
    """Complete BPS eigenstate table for all |pi| <= max_n.

    For each plane partition pi with |pi| <= max_n, compute:
      E_k(pi) = sum_{box in pi} content(box)^k  for k = 1, ..., max_k

    The result is organized by charge n = |pi|.

    Returns dict {n: [{"partition": pi, "eigenvalues": {k: E_k}, ...}]}.
    """
    if h3 is None:
        h3 = -(h1 + h2)

    result = {}
    for n in range(max_n + 1):
        pps = enumerate_plane_partitions(n)
        states = []
        for pp in pps:
            evs = cm_eigenvalues_all(pp, max_k, h1, h2, h3)
            boxes = plane_partition_boxes(pp)
            contents = [box_content(i, j, l, h1, h2, h3) for (i, j, l) in boxes]
            states.append({
                "partition": pp,
                "n_boxes": n,
                "eigenvalues": evs,
                "contents": sorted(contents),
            })
        result[n] = states

    return result


def chern_number_eigenvalues(pp: List[List[int]], k: int,
                              h1: Rational, h2: Rational,
                              h3: Optional[Rational] = None) -> Rational:
    """k-th Chern number of the ideal sheaf I_pi.

    For the ideal sheaf I_pi corresponding to plane partition pi in
    Hilb^n(C^3), the k-th equivariant Chern number is:

      ch_k(I_pi) = sum_{box in pi} content(box)^k / k!

    This is the NORMALIZED version: ch_k = E_k / k!

    The ch_k are the natural Chern characters of the tautological
    bundle on Hilb^n. The CM eigenvalue E_k is the UN-normalized version.
    """
    if h3 is None:
        h3 = -(h1 + h2)
    ev = cm_eigenvalue(pp, k, h1, h2, h3)
    factorial = Rational(1)
    for i in range(1, k + 1):
        factorial *= i
    return ev / factorial


