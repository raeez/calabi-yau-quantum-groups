def enumerate_plane_partitions(n: int) -> List[List[List[int]]]:
    """Enumerate all plane partitions of n.

    A plane partition pi of n is a 2D array pi[i][j] of nonneg integers s.t.:
      pi[i][j] >= pi[i+1][j], pi[i][j] >= pi[i][j+1], sum = n.

    Returns list of plane partitions, each as a list of rows.
    WARNING: exponential growth. Only practical for n <= ~10.
    """
    if n == 0:
        return [[]]

    results: List[List[List[int]]] = []

    def _generate(remaining: int, max_shape: Optional[List[int]],
                  current: List[List[int]]):
        if remaining == 0:
            results.append([row[:] for row in current])
            return
        if max_shape is not None and all(v == 0 for v in max_shape):
            return

        max_first = remaining
        max_cols = remaining
        if max_shape is not None:
            max_first = min(max_first, max_shape[0])
            max_cols = len(max_shape)

        def _gen_row(pos: int, rem: int, prev_val: int, row: List[int]):
            if rem == 0 or pos >= max_cols:
                if sum(row) > 0:
                    new_shape = row[:]
                    current.append(new_shape)
                    _generate(rem, new_shape, current)
                    current.pop()
                return
            upper = min(prev_val, rem)
            if max_shape is not None and pos < len(max_shape):
                upper = min(upper, max_shape[pos])
            for v in range(upper, 0, -1):
                row.append(v)
                _gen_row(pos + 1, rem - v, v, row)
                row.pop()
            if sum(row) > 0:
                new_shape = row[:]
                current.append(new_shape)
                _generate(rem, new_shape, current)
                current.pop()

        _gen_row(0, remaining, max_first, [])

    _generate(n, None, [])
    return results


def plane_partition_volume(pp: List[List[int]]) -> int:
    """Total number of boxes in a plane partition."""
    return sum(sum(row) for row in pp)


def plane_partition_boxes(pp: List[List[int]]) -> List[Tuple[int, int, int]]:
    """List all box coordinates (i, j, l) in a plane partition.

    pp[i][j] = height of column at position (i, j).
    Box at (i, j, l) exists for 0 <= l < pp[i][j].
    """
    boxes = []
    for i, row in enumerate(pp):
        for j, height in enumerate(row):
            for l in range(height):
                boxes.append((i, j, l))
    return boxes


@lru_cache(maxsize=64)
def _plane_partition_counts(N: int) -> Tuple[int, ...]:
    """Plane partition counts pp(0), ..., pp(N-1). OEIS A000219."""
    c = [Fraction(0)] * N
    c[0] = Fraction(1)
    for k in range(1, N):
        for _ in range(k):
            for m in range(k, N):
                c[m] += c[m - k]
    return tuple(int(x) for x in c)


