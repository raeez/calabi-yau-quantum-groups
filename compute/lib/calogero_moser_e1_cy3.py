# 11. SUMMARY AND COMPREHENSIVE COMPUTATION
# ============================================================================

def cm_comprehensive_computation(max_n: int = 5,
                                  h1: Rational = Rational(1),
                                  h2: Rational = Rational(2),
                                  h3: Optional[Rational] = None,
                                  max_k: int = 5) -> Dict[str, Any]:
    """Run the comprehensive CM computation for all |pi| <= max_n.

    Computes:
    1. All eigenvalues E_k(pi) for k = 1, ..., max_k and |pi| <= max_n.
    2. Commutativity verification at each charge level.
    3. 2D reduction check.
    4. Cubic Hamiltonian analysis.
    5. Multi-path eigenvalue verification.

    Returns dict with full analysis.
    """
    if h3 is None:
        h3 = -(h1 + h2)

    results = {
        "h_params": (h1, h2, h3),
        "sigma_2": h1 * h2 + h1 * h3 + h2 * h3,
        "sigma_3": h1 * h2 * h3,
        "max_n": max_n,
        "max_k": max_k,
    }

    # BPS eigenstate table
    results["bps_table"] = bps_eigenstate_table(max_n, h1, h2, h3, max_k)

    # Integrability verification
    integrability = {}
    for n_val in range(1, max_n + 1):
        integrability[n_val] = verify_cm_commutativity(n_val, max_k, h1, h2, h3)
    results["integrability"] = integrability

    # Cubic Hamiltonian
    cubic = {}
    for n_val in range(1, max_n + 1):
        cubic[n_val] = cubic_hamiltonian_eigenvalues(n_val, h1, h2, h3)
    results["cubic"] = cubic

    # 2D reduction
    reduction = {}
    for n_val in range(1, min(max_n + 1, 6)):
        for k_val in range(1, min(max_k + 1, 4)):
            reduction[(n_val, k_val)] = verify_2d_reduction(n_val, k_val, h1, h2)
    results["reduction_2d"] = reduction

    return results
