# 9. W_{1+infinity} AT c=N: CM FROM W-ALGEBRA
# ============================================================================

def w_algebra_cm_eigenvalue(partition: Tuple[int, ...], k: int,
                             N: int) -> Rational:
    """CM eigenvalue from the W_{1+infinity}[N] algebra.

    At c = N, the W_{1+infinity} algebra has:
      h1 = 1, h2 = -N, h3 = N - 1  (Schiffmann-Vasserot parametrization)

    The CM Hamiltonians are the zero-modes W^{(k)}_0 of the W-algebra
    generators. On the Fock space with N colors, these are:

    For a COLORED partition (partition of n with N colors), the eigenvalue
    of W^{(k)}_0 is the k-th power-sum of box contents.

    For N = 1 (single color = ordinary partition), this reduces to:
      E_k = sum_{box in lambda} content(box)^k
    with content(i,j) = j - i (the standard content for 2D partitions).

    For the Schiffmann-Vasserot parametrization at level N:
      h1 = 1, h2 = -N, h3 = N - 1
      content(i, j) = h1*i + h2*j = i - N*j  (for 2D partitions with l=0)
    """
    h1 = Rational(1)
    h2 = Rational(-N)
    h3 = Rational(N - 1)

    # Build plane partition from 2D partition: height 1 everywhere
    pp = [[1] * part for part in partition]
    return cm_eigenvalue(pp, k, h1, h2, h3)


def w_algebra_virasoro_eigenvalue(partition: Tuple[int, ...],
                                   N: int) -> Dict[str, Rational]:
    """Virasoro L_0 eigenvalue from the W_{1+infinity}[N] algebra.

    L_0 = W^{(2)}_0 corresponds to the CM Hamiltonian H_2.
    The eigenvalue is:
      h_lambda = E_2(lambda) = sum_{box in lambda} content(box)^2

    For the Schiffmann-Vasserot parametrization at level N:
      h1 = 1, h2 = -N, h3 = N - 1
      L_0 eigenvalue = sum_{(i,j) in lambda} (i - N*j)^2

    The central charge of W_{1+infinity}[N] is:
      c = N

    For N=1: c=1, and the Fock space is the c=1 free boson.
    """
    h1 = Rational(1)
    h2 = Rational(-N)
    h3 = Rational(N - 1)

    pp = [[1] * part for part in partition]
    L0 = cm_eigenvalue(pp, 2, h1, h2, h3)
    # E_1 is the U(1) charge
    E1 = cm_eigenvalue(pp, 1, h1, h2, h3)

    return {
        "partition": partition,
        "N": N,
        "L_0": L0,
        "E_1": E1,
        "central_charge": Rational(N),
        "h_params": (h1, h2, h3),
    }


