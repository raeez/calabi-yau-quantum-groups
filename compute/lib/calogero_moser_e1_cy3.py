# 7. JACK POLYNOMIALS AND 2D LIMIT
# ============================================================================

def jack_eigenvalue_2d(partition: Tuple[int, ...], k: int,
                       beta: Rational) -> Rational:
    """k-th CM eigenvalue in the 2D limit (Jack polynomial eigenvalue).

    For a partition lambda = (lambda_1, ..., lambda_l) and coupling beta,
    the 2D CM eigenvalue is:

      E_k^{2D}(lambda) = sum_{(i,j) in lambda} (j - beta*i)^k

    where the sum is over all boxes (i,j) with 0-indexed coordinates:
      i = row index, j = column index, for 0 <= j < lambda_i.

    At beta = 1 (free fermion): E_k = sum (j - i)^k = content polynomial.
    At beta = 2: E_k gives the Sutherland model eigenvalues.

    The Jack polynomial J_lambda^{(1/beta)} is the eigenstate of the
    2D CM system with these eigenvalues.
    """
    total = Rational(0)
    for i, lam_i in enumerate(partition):
        for j in range(lam_i):
            content = Rational(j) - beta * Rational(i)
            total += content ** k
    return total


def verify_2d_reduction(n: int, k: int,
                         h1: Rational, h2: Rational) -> Dict[str, Any]:
    """Verify that the CY3 CM eigenvalues reduce to 2D (Jack) eigenvalues.

    When all boxes lie in the (i,j) plane (l=0), the 3D CM eigenvalue
    E_k^{3D}(pi) reduces to the 2D Jack polynomial eigenvalue E_k^{2D}(lambda)
    with beta = h1/h2 (ratio of equivariant parameters).

    For a 2D partition lambda = (lambda_1, ..., lambda_l) viewed as a plane
    partition pi with pi[i][j] = 1 if j < lambda_i else 0:

      E_k^{3D}(pi) = sum_{i,j} (h1*i + h2*j)^k = h2^k * sum (j + beta*i)^k

    and this should match E_k^{2D}(lambda, beta) with beta = -h1/h2
    (sign from content convention).

    Actually, let's be precise. With content = h1*i + h2*j (h3 irrelevant
    since l=0), we get:
      E_k = sum_{(i,j) in lambda} (h1*i + h2*j)^k

    The 2D Jack eigenvalue with content = j - beta*i uses beta = -h1/h2:
      E_k^{2D} = sum (j - beta*i)^k = (1/h2^k) * sum (h2*j + h1*i)^k

    Hence E_k^{3D} = h2^k * E_k^{2D} with beta = -h1/h2.
    """
    h3 = -(h1 + h2)
    beta = -h1 / h2

    # Enumerate ordinary (2D) partitions of n
    partitions_2d = _enumerate_partitions(n)

    results = []
    for lam in partitions_2d:
        # 2D eigenvalue
        ev_2d = jack_eigenvalue_2d(lam, k, beta)

        # 3D eigenvalue: build plane partition with height 1
        # pp[i] = [1, 1, ..., 1] with lam[i] ones
        pp = [[1] * part for part in lam]
        ev_3d = cm_eigenvalue(pp, k, h1, h2, h3)

        # Check: E_3d = h2^k * E_2d
        ev_expected = h2 ** k * ev_2d
        match = expand(ev_3d - ev_expected) == 0

        results.append({
            "partition": lam,
            "E_2d": ev_2d,
            "E_3d": ev_3d,
            "E_expected": ev_expected,
            "match": match,
        })

    all_match = all(r["match"] for r in results)

    return {
        "n": n,
        "k": k,
        "h_params": (h1, h2, h3),
        "beta": beta,
        "num_partitions": len(partitions_2d),
        "all_match": all_match,
        "details": results,
        "description": (
            f"2D reduction check at n={n}, k={k}: "
            f"{'all match' if all_match else 'MISMATCH FOUND'} "
            f"for {len(partitions_2d)} partitions."
        ),
    }


def _enumerate_partitions(n: int) -> List[Tuple[int, ...]]:
    """Enumerate all ordinary (2D) partitions of n as weakly decreasing tuples."""
    if n == 0:
        return [()]
    results: List[Tuple[int, ...]] = []

    def _gen(remaining: int, max_part: int, current: List[int]):
        if remaining == 0:
            results.append(tuple(current))
            return
        for p in range(min(remaining, max_part), 0, -1):
            current.append(p)
            _gen(remaining - p, p, current)
            current.pop()

    _gen(n, n, [])
    return results


