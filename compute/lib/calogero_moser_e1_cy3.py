# 2. CM HAMILTONIANS AS ELEMENTS OF Y^+(gl_hat_1)
# ============================================================================

def cm_hamiltonian_from_yangian(k: int, n: int,
                                h1: Rational, h2: Rational,
                                h3: Optional[Rational] = None) -> Dict[str, Any]:
    """Compute the k-th CM Hamiltonian as an element of Y^+(gl_hat_1).

    The CM Hamiltonians H_k live in the center of Y^+(gl_hat_1).
    On the charge-n Fock module, H_k acts diagonally on the basis
    of plane partitions |pi> with eigenvalue E_k(pi).

    This function computes the spectrum {E_k(pi) : |pi| = n} and
    verifies that H_k is well-defined (all eigenvalues computable).

    The Yangian generators act on plane partitions:
      e_m: adds a box (creation at mode m)
      f_m: removes a box (annihilation at mode m)
      psi_m: diagonal (Cartan, counting)

    The CM Hamiltonians are DIAGONAL in the plane partition basis,
    hence they lie in the span of the psi generators (Cartan subalgebra),
    equivalently in the center.

    Returns dict with eigenvalue spectrum and metadata.
    """
    if h3 is None:
        h3 = -(h1 + h2)

    pps = enumerate_plane_partitions(n)
    spectrum = []
    for pp in pps:
        ev = cm_eigenvalue(pp, k, h1, h2, h3)
        spectrum.append(ev)

    # Distinct eigenvalues and multiplicities
    ev_counts: Dict[Rational, int] = defaultdict(int)
    for ev in spectrum:
        ev_counts[ev] += 1

    return {
        "k": k,
        "n": n,
        "h_params": (h1, h2, h3),
        "dimension": len(pps),
        "spectrum": sorted(set(spectrum)),
        "multiplicities": dict(ev_counts),
        "all_eigenvalues": spectrum,
        "description": (
            f"H_{k} on charge-{n} Fock module of Y^+(gl_hat_1): "
            f"{len(pps)} states, {len(set(spectrum))} distinct eigenvalues"
        ),
    }


def cm_hamiltonian_matrix(k: int, n: int,
                          h1: Rational, h2: Rational,
                          h3: Optional[Rational] = None) -> List[List[Rational]]:
    """The CM Hamiltonian H_k as a matrix in the plane partition basis.

    Since H_k is diagonal in the plane partition basis, this returns
    a diagonal matrix: H_k = diag(E_k(pi_1), E_k(pi_2), ...).

    The plane partitions are in the canonical enumeration order.
    """
    if h3 is None:
        h3 = -(h1 + h2)

    pps = enumerate_plane_partitions(n)
    dim = len(pps)
    matrix = [[Rational(0)] * dim for _ in range(dim)]
    for idx, pp in enumerate(pps):
        ev = cm_eigenvalue(pp, k, h1, h2, h3)
        matrix[idx][idx] = ev
    return matrix


