def box_content(i: int, j: int, l: int,
                h1: Rational, h2: Rational,
                h3: Optional[Rational] = None) -> Rational:
    """Content of a box at position (i, j, l) in a 3D partition.

    content(i, j, l) = h1 * i + h2 * j + h3 * l

    where h1 + h2 + h3 = 0 (CY condition).
    For the CM system, this is the "position" of the box-particle.
    """
    if h3 is None:
        h3 = -(h1 + h2)
    return h1 * i + h2 * j + h3 * l


def cm_eigenvalue(pp: List[List[int]], k: int,
                  h1: Rational, h2: Rational,
                  h3: Optional[Rational] = None) -> Rational:
    """k-th CM Hamiltonian eigenvalue on a plane partition pi.

    E_k(pi) = sum_{(i,j,l) in pi} content(i,j,l)^k
            = sum_{(i,j,l) in pi} (h1*i + h2*j + h3*l)^k

    This is the k-th power-sum of the box contents.

    Physical meaning:
      k=1: total content (center-of-mass momentum analogue)
      k=2: CM Hamiltonian eigenvalue (energy)
      k=3: cubic Casimir (genuinely 3D; vanishes for 2D partitions)
    """
    if h3 is None:
        h3 = -(h1 + h2)
    total = Rational(0)
    boxes = plane_partition_boxes(pp)
    for (i, j, l) in boxes:
        c = box_content(i, j, l, h1, h2, h3)
        total += c ** k
    return total


def cm_eigenvalues_all(pp: List[List[int]], max_k: int,
                       h1: Rational, h2: Rational,
                       h3: Optional[Rational] = None) -> Dict[int, Rational]:
    """All CM eigenvalues E_1, ..., E_{max_k} for a plane partition.

    Returns dict {k: E_k(pi)}.
    """
    if h3 is None:
        h3 = -(h1 + h2)
    result = {}
    boxes = plane_partition_boxes(pp)
    for k in range(1, max_k + 1):
        total = Rational(0)
        for (i, j, l) in boxes:
            c = box_content(i, j, l, h1, h2, h3)
            total += c ** k
        result[k] = total
    return result


