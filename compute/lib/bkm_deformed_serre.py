# 5. Imaginary-real mixing (adjoint action)
# =========================================================================

def imaginary_real_mixing(D: int) -> Dict[str, Any]:
    r"""Compute the imaginary-real mixing OPE (adjoint action).

    For a real simple root delta_i (Cartan generator h_i(z)) and an
    imaginary root alpha at discriminant D:

        h_i(z) V_eps(alpha, w) ~ (delta_i, alpha) / (z - w) * V_eps(alpha, w)

    This is the ADJOINT ACTION: h_i acts on V_eps(alpha) by the inner
    product (delta_i, alpha). The Omega deformation PRESERVES this at
    leading order.

    In mode form:
        [h_{i,0}, e_D^{(a)}_n] = (delta_i, alpha_a) * e_D^{(a)}_n

    The deformation does NOT break the Cartan-imaginary commutation
    relation, because the spectral flow shifts conformal weights but
    does not change the Cartan eigenvalues (root labels).

    For II_{2,1} with Gram matrix A = ((2,-2,-2),(-2,2,-2),(-2,-2,2)):
    the inner product (delta_i, alpha) depends on the specific imaginary
    root alpha. For a root alpha = (n, l, m) in the lattice II_{2,1}
    (using the standard Siegel upper half-plane coordinates):

        (delta_1, alpha) = 2n - 2l - 2m
        (delta_2, alpha) = -2n + 2l - 2m
        (delta_3, alpha) = -2n - 2l + 2m

    The root eigenvalues are INTEGERS (lattice inner products), so
    the Cartan action is always well-defined.

    Parameters
    ----------
    D : int
        Discriminant of the imaginary root sector.

    Returns
    -------
    dict with adjoint action data.
    """
    bkm_bar = _import_bkm_bar()
    table = bkm_bar.c_table_from_phi01(max(D + 10, 30))
    c_val = table.get(D, 0)

    if c_val == 0:
        return {
            'discriminant': D,
            'has_mixing': False,
            'note': f'No imaginary generators at D={D}.',
            'status': STATUS,
        }

    mult = abs(c_val)
    parity = 'bosonic' if c_val > 0 else 'fermionic'

    return {
        'discriminant': D,
        'c_value': c_val,
        'multiplicity': mult,
        'parity': parity,
        'has_mixing': True,
        'ope_formula': (
            'h_i(z) V_eps(alpha, w) ~ (delta_i, alpha) / (z - w) * V_eps(alpha, w)'
        ),
        'mode_commutator': (
            '[h_{i,0}, e_D^{(a)}_n] = (delta_i, alpha_a) * e_D^{(a)}_n'
        ),
        'cartan_eigenvalue_type': 'integer (lattice inner product)',
        'deformation_stability': (
            'The Cartan-imaginary OPE is PRESERVED by the Omega deformation '
            'at leading order. The spectral flow shifts conformal weights '
            'but does not change root eigenvalues.'
        ),
        'adjoint_decomposition': (
            f'The {mult}-dimensional imaginary root space at D={D} '
            f'decomposes into Cartan eigenspaces under the 3 real '
            f'Cartan generators h_1, h_2, h_3. Each eigenspace is '
            f'a weight space of the Weyl group S_3.'
        ),
        'status': STATUS,
    }


