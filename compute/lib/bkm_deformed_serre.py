class OPESingularity(NamedTuple):
    """Classification of the OPE singularity at a given (D1, D2, eps).

    The singularity type determines the Serre relation:
    - 'regular': P > 0, Serre bracket vanishes, generators commute.
    - 'marginal': P = 0, logarithmic correction possible, requires O(eps^2).
    - 'pole': P < 0, nontrivial bracket with |P| independent terms.
    """
    D1: int
    D2: int
    ope_type: str                  # 'self' or 'cross'
    exponent: float                # P(D1, D2, eps)
    singularity_type: str          # 'regular', 'marginal', 'pole'
    pole_order: int                # max(0, -floor(P)) -- number of singular terms
    serre_type: str                # description of the Serre relation
    inner_product: int             # (alpha, beta) used


def classify_ope_singularity(D1: int, D2: int, epsilon: float = 1.0,
                             inner_product: Optional[int] = None
                             ) -> OPESingularity:
    r"""Classify the OPE singularity between roots at discriminants D1, D2.

    This determines the Serre relation type:
    - Regular (P > 0): trivial Serre (generators commute)
    - Marginal (P = 0): logarithmic, requires higher-order analysis
    - Pole (P < 0): nontrivial Serre with |P| independent constraints

    Parameters
    ----------
    D1, D2 : int
        Discriminants.
    epsilon : float
        Deformation parameter.
    inner_product : int or None
        Override lattice inner product. If None, uses 0 for cross-OPE
        and the self-OPE formula for D1 == D2.

    Returns
    -------
    OPESingularity
    """
    if D1 == D2 and inner_product is None:
        # Self-OPE
        P = deformed_ope_exponent_self(D1, epsilon)
        ip = -2 * D1  # (alpha, alpha) = -2D
        ope_type = 'self'
    else:
        # Cross-OPE
        ip = inner_product if inner_product is not None else 0
        P = deformed_ope_exponent_cross(D1, D2, epsilon, ip)
        ope_type = 'cross' if D1 != D2 else 'cross-within-sector'

    # Classify
    if P > 1e-10:
        sing_type = 'regular'
        pole_ord = 0
        serre = (
            f'Trivial Serre: bracket vanishes at leading order. '
            f'P = {P:.1f} > 0 gives (z-w)^{{{P:.0f}}} with no pole.'
        )
    elif abs(P) < 1e-10:
        sing_type = 'marginal'
        pole_ord = 0
        serre = (
            f'Marginal Serre: P = 0 gives (z-w)^0 = 1. '
            f'Logarithmic correction possible at O(eps^2). '
            f'The bracket is INDETERMINATE at leading order.'
        )
    else:
        sing_type = 'pole'
        pole_ord = int(math.ceil(-P - 1e-10))
        serre = (
            f'Nontrivial Serre: P = {P:.1f} gives a pole of order {pole_ord}. '
            f'The bracket has {pole_ord} independent term{"s" if pole_ord > 1 else ""}. '
        )
        if pole_ord == 1:
            serre += 'Simple pole: standard current algebra bracket.'
        elif pole_ord == 2:
            serre += 'Double pole: bracket + Schwinger term.'
        elif pole_ord >= 3:
            serre += (
                f'Higher pole: bracket + {pole_ord - 1} Serre constraints '
                f'from (z-w)^{{-2}}, ..., (z-w)^{{-{pole_ord}}}.'
            )

    return OPESingularity(
        D1=D1, D2=D2, ope_type=ope_type,
        exponent=P, singularity_type=sing_type,
        pole_order=pole_ord, serre_type=serre,
        inner_product=ip,
    )


