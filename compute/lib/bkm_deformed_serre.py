# 4. Cross-discriminant Serre table
# =========================================================================

def cross_serre_table(D_list: Optional[List[int]] = None,
                      epsilon: float = 1.0) -> Dict[str, Any]:
    r"""Compute the cross-discriminant Serre table.

    For each pair (D1, D2) with D1 <= D2, computes the cross-OPE
    exponent and classifies the Serre relation.

    At eps=1 with generic orthogonal roots:
        P_cross(D1, D2, 1) = D1 * D2

    This is:
    - Positive for D1, D2 > 0 (trivial cross-Serre)
    - Zero if D1 = 0 or D2 = 0 (marginal)
    - Negative if D1 < 0 and D2 > 0, i.e., D1 = -1 (Weyl) and D2 > 0

    Parameters
    ----------
    D_list : list of int or None
        Discriminants to include. Default: [-1, 0, 3, 4, 7, 8].
    epsilon : float
        Deformation parameter.

    Returns
    -------
    dict with cross-Serre table.
    """
    if D_list is None:
        D_list = [-1, 0, 3, 4, 7, 8]

    entries = []
    nontrivial = []

    for i, D1 in enumerate(D_list):
        for D2 in D_list[i:]:  # D2 >= D1
            if D1 == D2:
                # Self-OPE handled separately
                continue

            P = deformed_ope_exponent_cross(D1, D2, epsilon)
            sing = classify_ope_singularity(D1, D2, epsilon, inner_product=0)

            entry = {
                'D1': D1,
                'D2': D2,
                'cross_ope_exponent': P,
                'formula': f'D1*D2 = {D1}*{D2} = {D1*D2}',
                'singularity_type': sing.singularity_type,
                'pole_order': sing.pole_order,
            }
            entries.append(entry)

            if sing.singularity_type != 'regular':
                nontrivial.append(entry)

    return {
        'D_list': D_list,
        'epsilon': epsilon,
        'total_pairs': len(entries),
        'entries': entries,
        'nontrivial': nontrivial,
        'nontrivial_count': len(nontrivial),
        'structural_result': (
            f'Cross-Serre with generic orthogonal roots: '
            f'P_cross(D1, D2) = D1*D2. Nontrivial when D1*D2 <= 0. '
            f'For D_list = {D_list}: {len(nontrivial)} nontrivial pairs '
            f'(involving D = -1 or D = 0).'
        ),
        'status': STATUS,
    }


