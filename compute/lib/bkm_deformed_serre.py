def serre_at_discriminant(D: int, epsilon: float = 1.0) -> Dict[str, Any]:
    r"""Complete Serre analysis at a given discriminant D.

    Computes the self-OPE exponent, classifies the singularity, and
    determines the Serre relation type for the |c(D)| generators at
    discriminant D.

    Parameters
    ----------
    D : int
        Discriminant.
    epsilon : float
        Deformation parameter.

    Returns
    -------
    dict with keys:
        discriminant, c_value, multiplicity, parity, self_ope_exponent,
        singularity, serre_type, generator_status, status.
    """
    bkm_bar = _import_bkm_bar()
    table = bkm_bar.c_table_from_phi01(max(D + 10, 30))

    c_val = table.get(D, 0)
    if c_val == 0:
        return {
            'discriminant': D,
            'c_value': 0,
            'multiplicity': 0,
            'has_generators': False,
            'note': (
                f'No simple roots at D={D} (c(D)=0). '
                f'D mod 4 = {D % 4}. '
                f'Valid discriminants require D mod 4 in {{0, 3}} (AP-CY9).'
            ),
            'status': STATUS,
        }

    mult = abs(c_val)
    parity = 'bosonic' if c_val > 0 else 'fermionic'

    # Self-OPE exponent
    P_self = deformed_ope_exponent_self(D, epsilon)

    # Classification
    sing = classify_ope_singularity(D, D, epsilon)

    # Generator interaction status
    if sing.singularity_type == 'regular':
        gen_status = (
            f'{mult} {parity} generators are FREE at leading order '
            f'(trivial self-Serre, P = {P_self:.0f} > 0). '
            f'No constraints from the self-OPE.'
        )
    elif sing.singularity_type == 'marginal':
        gen_status = (
            f'{mult} {parity} generators have MARGINAL self-interaction '
            f'(P = 0). Logarithmic correction determines whether the '
            f'generators commute or have weak interactions. '
            f'Requires O(eps^2) analysis.'
        )
    else:  # pole
        gen_status = (
            f'{mult} {parity} generators have NONTRIVIAL self-Serre '
            f'with pole of order {sing.pole_order}. '
            f'The self-OPE produces {sing.pole_order} independent '
            f'Serre constraint{"s" if sing.pole_order > 1 else ""}.'
        )

    return {
        'discriminant': D,
        'c_value': c_val,
        'multiplicity': mult,
        'parity': parity,
        'has_generators': True,
        'self_ope_exponent': P_self,
        'self_ope_exponent_formula': f'D*(D-4) = {D}*({D}-4) = {D*(D-4)}',
        'singularity': sing._asdict(),
        'serre_type': sing.serre_type,
        'generator_status': gen_status,
        'status': STATUS,
    }


