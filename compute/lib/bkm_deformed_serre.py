def deformed_ope_exponent_self(D: int, epsilon: float = 1.0) -> float:
    r"""Compute the deformed self-OPE exponent P_self(D, eps).

    For a vertex operator V_eps(alpha, z) with alpha at discriminant D
    (meaning (alpha, alpha) = -2D in the BKM convention):

        V_eps(alpha, z) V_eps(alpha, w) ~ (z-w)^{P_self(D, eps)} * (...)

    Undeformed (eps=0):
        P_self(D, 0) = (alpha, alpha) = -2D

    Omega-deformed at leading order:
        P_self(D, eps) = -2D + eps * (D^2 - 2D)

    At eps=1 (formal Yangian limit):
        P_self(D, 1) = -2D + D^2 - 2D = D^2 - 4D = D*(D-4)

    The OPE is:
        REGULAR (no pole) when P_self >= 0: D <= 0 or D >= 4 (at eps=1)
        SINGULAR (pole) when P_self < 0: 0 < D < 4 (at eps=1)
        MARGINAL when P_self = 0: D = 0 or D = 4 (at eps=1)

    For the valid discriminants (AP-CY9: D = 0 or 3 mod 4):
        D = -1: P = (-1)(-5) = 5 (regular)
        D = 0:  P = 0*(-4) = 0 (marginal)
        D = 3:  P = 3*(-1) = -3 (POLE of order 3)
        D = 4:  P = 4*0 = 0 (marginal)
        D = 7:  P = 7*3 = 21 (regular)
        D = 8:  P = 8*4 = 32 (regular)

    Parameters
    ----------
    D : int
        Discriminant of the root.
    epsilon : float
        Deformation parameter (default 1.0 for Yangian limit).

    Returns
    -------
    float
        The deformed self-OPE exponent.

    Examples
    --------
    >>> deformed_ope_exponent_self(-1, 1.0)
    5.0
    >>> deformed_ope_exponent_self(0, 1.0)
    0.0
    >>> deformed_ope_exponent_self(3, 1.0)
    -3.0
    >>> deformed_ope_exponent_self(4, 1.0)
    0.0
    """
    undeformed = -2 * D
    correction = D * D - 2 * D
    return float(undeformed + epsilon * correction)


def deformed_ope_exponent_cross(D1: int, D2: int, epsilon: float = 1.0,
                                inner_product: int = 0) -> float:
    r"""Compute the deformed cross-OPE exponent P_cross(D1, D2, eps).

    For vertex operators V_eps(alpha, z) and V_eps(beta, w) with alpha
    at discriminant D1 and beta at discriminant D2:

        V_eps(alpha, z) V_eps(beta, w) ~ (z-w)^{P_cross} * (...)

    where:
        P_cross(D1, D2, eps) = (alpha, beta)
            + eps * [(alpha,alpha)(beta,beta)/4 + (alpha,beta)]

    For generic (orthogonal) roots: (alpha, beta) = 0, so:
        P_cross(D1, D2, eps) = eps * (-2*D1)*(-2*D2)/4
            = eps * D1 * D2

    For non-generic roots: (alpha, beta) = inner_product != 0, so:
        P_cross = inner_product + eps * (D1*D2 + inner_product)
        = inner_product * (1 + eps) + eps * D1 * D2

    At eps=1:
        P_cross(D1, D2, 1) = 2*inner_product + D1*D2

    Parameters
    ----------
    D1, D2 : int
        Discriminants of the two roots.
    epsilon : float
        Deformation parameter.
    inner_product : int
        The lattice inner product (alpha, beta). Default 0 (generic case).

    Returns
    -------
    float
        The deformed cross-OPE exponent.

    Examples
    --------
    >>> deformed_ope_exponent_cross(3, 4, 1.0)
    12.0
    >>> deformed_ope_exponent_cross(0, 3, 1.0)
    0.0
    >>> deformed_ope_exponent_cross(-1, 3, 1.0)
    -3.0
    """
    return float(inner_product * (1.0 + epsilon) + epsilon * D1 * D2)


