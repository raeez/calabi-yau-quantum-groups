def bar_differential_matrix_dims(k: int, n: int) -> Tuple[int, int]:
    """Dimensions of the bar differential d: B^k_n -> B^{k-1}_n.

    Returns (source_dim, target_dim).
    """
    source = bar_arity_k_dims(k, n + 1)[n]
    target = bar_arity_k_dims(k - 1, n + 1)[n]
    return source, target


def bar_euler_char_by_degree(N: int, max_arity: int = 6) -> List[Fraction]:
    """Euler characteristic chi(B(Y^+)) = sum_k (-1)^k dim B^k in each degree.

    By the bar complex being a resolution:
    chi(B(Y^+))_n = delta_{n,0}  (the augmentation is a quasi-iso).

    But more precisely: the REDUCED bar complex B_red(Y^+) = ker(augmentation)
    has chi = 0 in degree 0 and chi_n = alternating sum for n >= 1.

    For a (graded) commutative augmented algebra A:
    sum_k (-1)^k (A_+)^{otimes k} = 1 / A_+ ... No.

    Actually, the bar complex is acyclic in the sense that it resolves the
    trivial module. The generating function identity:

    sum_{k>=0} (-1)^k (M(q)-1)^k = 1/M(q) = prod_{n>=1} (1-q^n)^n

    This is the INVERSE MacMahon function.

    The Euler characteristic in degree n:
    chi_n = sum_{k=0}^{n} (-1)^k dim(B^k_n)
          = [q^n] 1/M(q)
          = [q^n] prod_{n>=1} (1-q^n)^n

    Returns [chi_0, chi_1, ..., chi_{N-1}].
    """
    # Compute 1/M(q) = prod_{n>=1} (1-q^n)^n directly
    result = [Fraction(0)] * N
    result[0] = Fraction(1)

    for m in range(1, N):
        # Multiply by (1-q^m)^m
        for _ in range(m):
            # Multiply by (1-q^m) in-place
            for j in range(N - 1, m - 1, -1):
                result[j] -= result[j - m]

    return result


def bar_euler_char_alternating_sum(N: int, max_arity: int = 8) -> List[Fraction]:
    """Compute Euler characteristic by explicit alternating sum of arity dimensions.

    chi_n = sum_{k=0}^{max_arity} (-1)^k dim(B^k_n)

    This is an independent computation (Path 4) that should agree with
    bar_euler_char_by_degree for n small enough (where max_arity is sufficient).

    Returns [chi_0, chi_1, ..., chi_{N-1}].
    """
    chi = [Fraction(0)] * N
    for k in range(max_arity + 1):
        gf_k = bar_arity_k_generating_function(k, N)
        sign = Fraction((-1) ** k)
        for n in range(N):
            chi[n] += sign * gf_k[n]
    return chi


