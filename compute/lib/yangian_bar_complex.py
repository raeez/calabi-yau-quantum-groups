# Summary report
# ---------------------------------------------------------------------------

def bar_complex_summary(N: int = 12, max_arity: int = 5) -> str:
    """Generate a human-readable summary of B(Y^+(gl_hat_1)) at low arities."""
    table = bar_complex_table(N, max_arity)
    bps = table['bps']
    pp = table['plane_partitions']

    lines = []
    lines.append("=" * 70)
    lines.append("BAR COMPLEX B(Y^+(gl_hat_1)) -- LOW ARITY SUMMARY")
    lines.append("=" * 70)
    lines.append("")

    # Plane partition counts
    lines.append("Plane partition counts p(n) = dim Y^+_n:")
    lines.append(f"  {pp[:N]}")
    lines.append("")

    # BPS invariants
    lines.append("BPS invariants Omega(n) (= n for C^3):")
    lines.append(f"  {bps[:N]}")
    lines.append("")

    # Bar complex dimensions
    lines.append("Bar complex dimensions dim B^k_n:")
    lines.append(f"  {'n':>4}" + "".join(f"  {n:>6}" for n in range(N)))
    for k in range(min(max_arity + 1, 6)):
        row = table['dims'].get(k, [0] * N)
        lines.append(f"  k={k}" + "".join(f"  {row[n]:>6}" for n in range(N)))
    lines.append("")

    # Euler characteristic
    lines.append("Bar Euler characteristic chi_n = [q^n] 1/M(q):")
    lines.append(f"  {table['euler_exact'][:N]}")
    lines.append("")

    # Cohomology (symmetric model)
    lines.append("Bar cohomology dim H^k_n (symmetric model, Wedge^k(V_BPS)):")
    cohom = table['cohomology_sym']
    for k in sorted(cohom.keys()):
        if k <= 4:
            lines.append(f"  k={k}: {cohom[k][:N]}")
    lines.append("")

    # Verification
    mac_check = verify_macmahon_bar_identity(min(N, 15))
    lines.append(f"MacMahon identity M(q) * (1/M(q)) = 1: {mac_check['product_is_identity']}")

    return "\n".join(lines)
