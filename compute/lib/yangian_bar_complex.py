def explicit_bar_elements_arity1(max_degree: int) -> Dict[int, List[str]]:
    """Explicit basis elements of B^1(Y^+) = Y^+_{>0} at each degree.

    The basis of Y^+_n is indexed by plane partitions of n.
    We use symbolic labels: 'pi_k' for the k-th plane partition of degree n.
    For degree 1: single box [1] -> 'e0' (the fundamental generator e_0).
    For degree 2: three plane partitions [[2]], [[1,1]], [[1],[1]] ->
                  'e0^2', 'e0*e0_alt', or by plane partition shape.

    Actually, Y^+_n has a basis indexed by plane partitions pi with |pi|=n.
    The BPS/primitive generators span a subspace of dimension n.
    """
    pp = plane_partition_counts(max_degree + 1)
    result = {}
    for n in range(1, max_degree + 1):
        result[n] = [f"pp_{n}_{i}" for i in range(pp[n])]
    return result


def explicit_bar_elements_arity2(max_degree: int) -> Dict[int, int]:
    """Dimensions of B^2(Y^+) = Y^+_{>0} tensor Y^+_{>0} at each total degree.

    dim(B^2_n) = sum_{a+b=n, a>=1, b>=1} p(a) * p(b).
    """
    pp = plane_partition_counts(max_degree + 1)
    result = {}
    for n in range(2, max_degree + 1):
        dim = 0
        for a in range(1, n):
            b = n - a
            dim += pp[a] * pp[b]
        result[n] = dim
    return result


