def bar_cohomology_generating_function(N: int, max_arity: int = 4) -> Dict[int, List[Fraction]]:
    """Generating functions for H^k(B(Y^+)) at each arity k.

    For the commutative model Sym(V_BPS):
    H^k = Wedge^k(V_BPS), so
    sum_k (-t)^k char(H^k) = prod_{n>=1} (1-t*q^n)^{dim V_n}
                            = prod_{n>=1} (1-t*q^n)^n

    The full generating function in (t, q):
    F(t,q) = prod_{n>=1} (1-t*q^n)^n

    At t = -1: F(-1,q) = prod_{n>=1} (1+q^n)^n
    At t = 1:  F(1,q) = prod_{n>=1} (1-q^n)^n = 1/M(q) (inverse MacMahon)

    For fixed k:
    char(H^k)(q) = [t^k] prod_{n>=1} (1 - t*q^n)^n

    Returns dict mapping arity k -> [h^k_0, h^k_1, ..., h^k_{N-1}].
    """
    # Build the generating function as a polynomial in t with q-series coefficients
    # F(t,q) = prod_{n>=1} (1 - t*q^n)^n mod q^N, up to t^{max_arity}

    # Start with F = 1
    # F is represented as a list of q-series, one for each power of t:
    # F[k] = coefficient of t^k in F(t,q)
    F = [[Fraction(0)] * N for _ in range(max_arity + 1)]
    F[0][0] = Fraction(1)

    for m in range(1, N):
        # Multiply F by (1 - t*q^m)^m
        # (1 - t*q^m)^m = sum_{j=0}^{m} binom(m,j) (-1)^j t^j q^{m*j}
        binomials = _binomial_row(m)

        for _ in range(1):  # we do the full product (1-tq^m)^m at once
            # Actually, multiply by (1-tq^m) a total of m times
            pass

        # More efficient: multiply by (1-tq^m)^m directly
        # (1-tq^m)^m = sum_{j=0}^{min(m, max_arity)} C(m,j) (-t)^j q^{jm}
        for rep in range(m):
            # Multiply F by (1 - t*q^m)
            # New_F[k][n] = F[k][n] - F[k-1][n-m]
            new_F = [[Fraction(0)] * N for _ in range(max_arity + 1)]
            for k in range(max_arity + 1):
                for n in range(N):
                    new_F[k][n] = F[k][n]
                    if k >= 1 and n >= m:
                        new_F[k][n] -= F[k - 1][n - m]
            F = new_F

    result = {}
    for k in range(max_arity + 1):
        result[k] = F[k]

    return result


def _binomial_row(n: int) -> List[int]:
    """Compute [C(n,0), C(n,1), ..., C(n,n)]."""
    row = [1]
    for k in range(1, n + 1):
        row.append(row[-1] * (n - k + 1) // k)
    return row


