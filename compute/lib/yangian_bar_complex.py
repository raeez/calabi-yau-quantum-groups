def plethystic_log_coefficients(f_coeffs: List[Fraction], N: int) -> List[Fraction]:
    """Compute the plethystic logarithm PLog(f(q)) mod q^N.

    Given f(q) = 1 + sum_{n>=1} f_n q^n with f_0 = 1,
    PLog(f(q)) = sum_{n>=1} mu(n)/n * log(f(q^n))
               = sum_{n>=1} (1/n) * sum_{d|n} mu(n/d) * log_coeff_d

    Equivalently, the Mobius inversion of the "Adams operations":
    PLog(f) = sum_{k>=1} mu(k)/k * log(f(q^k))

    But more directly: if f(q) = prod_{n>=1} (1-q^n)^{-a_n}, then
    PLog(f) = sum_{n>=1} a_n q^n.

    For computational purposes, we use:
    f(q) = exp(sum_{n>=1} b_n q^n/n) implies PLog = Mobius inversion of b.

    Actually, the cleanest formula: if log(f(q)) = sum_{n>=1} c_n q^n,
    then PLog(f)(q) = sum_{n>=1} (sum_{d|n} mu(n/d) c_d) q^n.

    We use the direct recursive definition instead:
    f(q) = PExp(g(q)) where g = PLog(f), meaning
    f(q) = prod_{n>=1} (1-q^n)^{-g_n} = exp(sum_{n>=1} g_n * sum_{m>=1} q^{mn}/m)

    So log(f(q)) = sum_{n>=1} g_n * sum_{m>=1} q^{mn}/m.

    Extracting coefficient of q^k from log(f):
    [q^k] log(f) = sum_{d|k} g_d * (1/(k/d)) = sum_{d|k} g_d * d/k

    Therefore: k * [q^k] log(f) = sum_{d|k} d * g_d.
    Mobius inversion: n * g_n = sum_{d|n} mu(n/d) * d * [q^d] log(f).

    We compute log(f) first, then apply Mobius inversion.
    """
    # Step 1: compute log(f) = log(1 + (f-1))
    # log(1+x) = x - x^2/2 + x^3/3 - ...
    # where x = f - 1 (starts at q^1)
    x = [Fraction(0)] * N  # x = f - 1
    for i in range(1, min(N, len(f_coeffs))):
        x[i] = f_coeffs[i]

    log_f = [Fraction(0)] * N
    # log(1+x) via power series: coefficient of q^n in log(1+x)
    # Use the recursion: if f = exp(g), then g' = f'/f
    # i.e., n * g_n = n * f_n - sum_{k=1}^{n-1} k * g_k * f_{n-k}
    # (where f_0 = 1)
    for n in range(1, N):
        fn = f_coeffs[n] if n < len(f_coeffs) else Fraction(0)
        s = Fraction(0)
        for k in range(1, n):
            fnk = f_coeffs[n - k] if (n - k) < len(f_coeffs) else Fraction(0)
            s += Fraction(k) * log_f[k] * fnk
        log_f[n] = fn - s / Fraction(n)

    # Step 2: Mobius inversion
    # n * g_n = sum_{d|n} mu(n/d) * (d * log_f[d])
    # where log_f[d] = [q^d] log(f)
    mu = _mobius_function(N)
    g = [Fraction(0)] * N
    for n in range(1, N):
        val = Fraction(0)
        for d in range(1, n + 1):
            if n % d == 0:
                val += Fraction(mu[n // d]) * Fraction(d) * log_f[d]
        g[n] = val / Fraction(n)

    return g


def _mobius_function(N: int) -> List[int]:
    """Compute Mobius function mu(n) for n = 0, 1, ..., N-1.

    mu(1) = 1
    mu(n) = 0 if n has a squared prime factor
    mu(n) = (-1)^k if n is a product of k distinct primes
    """
    mu = [0] * N
    if N > 1:
        mu[1] = 1
    # Sieve
    is_prime = [True] * N
    primes = []
    for i in range(2, N):
        if is_prime[i]:
            primes.append(i)
            mu[i] = -1  # prime => mu = -1
        for p in primes:
            if i * p >= N:
                break
            is_prime[i * p] = False
            if i % p == 0:
                mu[i * p] = 0  # p^2 divides i*p
                break
            else:
                mu[i * p] = -mu[i]
    return mu


def bps_invariants_c3(N: int) -> List[int]:
    """BPS invariants Omega(n) of C^3 for n = 0, 1, ..., N-1.

    For C^3: Omega(n) = n for all n >= 1, Omega(0) = 0.

    This is because M(q) = prod_{n>=1} (1-q^n)^{-n}, so the plethystic
    logarithm is PLog(M(q)) = sum_{n>=1} n * q^n.

    In DT theory: Omega(n) counts BPS bound states of n D0-branes on C^3.
    The value n comes from the fact that the moduli space of n points on C^3
    has (signed) Euler characteristic (-1)^{n-1} * n.
    """
    return [n for n in range(N)]


def bps_invariants_from_macmahon(N: int) -> List[Fraction]:
    """Compute BPS invariants by plethystic logarithm of the MacMahon function.

    This is an independent computation path (Path 3).
    """
    mac = macmahon_coefficients(N)
    return plethystic_log_coefficients(mac, N)


