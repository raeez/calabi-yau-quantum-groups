def bar_arity_k_dims(k: int, N: int) -> List[int]:
    """Dimensions of B^k(Y^+) in each total degree n.

    B^k(Y^+) = (Y^+_{>0})^{otimes k}, graded by total degree.
    An element [a_1|...|a_k] with a_i in Y^+_{n_i} (n_i >= 1) has
    total degree n = n_1 + ... + n_k.

    dim B^k_n = sum_{n_1+...+n_k = n, n_i >= 1} prod dim(Y^+_{n_i}).

    This is the k-fold convolution of the augmentation ideal dimensions.

    Returns [d_0, d_1, ..., d_{N-1}].
    """
    if k == 0:
        result = [0] * N
        result[0] = 1  # B^0 = Q (the ground field)
        return result

    aug = augmentation_ideal_dims(N)

    # k-fold convolution of aug with itself
    # Start with identity (delta at 0) and convolve k times
    current = [Fraction(0)] * N
    current[0] = Fraction(1)

    for _ in range(k):
        new = [Fraction(0)] * N
        for i in range(N):
            if current[i] == 0:
                continue
            for j in range(1, N - i):  # j >= 1 since we use augmentation ideal
                new[i + j] += current[i] * aug[j]
        current = new

    return [int(c) for c in current]


def bar_arity_k_generating_function(k: int, N: int) -> List[Fraction]:
    """Generating function for B^k(Y^+) as a power series in q.

    GF_k(q) = (M(q) - 1)^k  (the k-th power of the augmentation ideal character).

    This uses the fact that char(Y^+_{>0}) = M(q) - 1 and the bar complex at
    arity k is the k-fold tensor product.

    Returns exact Fraction coefficients [c_0, c_1, ..., c_{N-1}].
    """
    mac = macmahon_coefficients(N)
    # aug = M(q) - 1
    aug = list(mac)
    aug[0] = Fraction(0)

    if k == 0:
        result = [Fraction(0)] * N
        result[0] = Fraction(1)
        return result

    # Compute aug^k by repeated multiplication
    result = [Fraction(0)] * N
    result[0] = Fraction(1)
    for _ in range(k):
        result = _poly_mul_trunc(result, aug, N)

    return result


def _poly_mul_trunc(a: List[Fraction], b: List[Fraction],
                    N: int) -> List[Fraction]:
    """Multiply two truncated power series mod q^N."""
    result = [Fraction(0)] * N
    la, lb = len(a), len(b)
    for i in range(min(la, N)):
        if a[i] == 0:
            continue
        for j in range(min(lb, N - i)):
            result[i + j] += a[i] * b[j]
    return result


