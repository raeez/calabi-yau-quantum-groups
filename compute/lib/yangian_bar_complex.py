def indecomposables_dim(N: int) -> List[int]:
    r"""Dimension of the space of indecomposables Q(Y^+) = Y^+_{>0} / (Y^+_{>0})^2.

    The indecomposables are H^1(B(Y^+)) -- the arity-1 bar cohomology.
    For a commutative algebra, Q_n = dim(Y^+_n) - dim((Y^+_{>0})^2)_n.

    For Y^+ = CoHA(C^3), the key claim is that the BPS generators span
    the indecomposables: dim Q_n = Omega(n) = n.

    NOTE: Y^+ is NOT commutative. The CoHA multiplication depends on the
    ordering (it is the Hall algebra product, which is associative but not
    commutative in general). However, the ASSOCIATED GRADED with respect to
    the weight filtration IS commutative, and the plethystic logarithm
    computes the BPS invariants from the associated graded.

    For the COMMUTATIVE model (Sym(V_BPS)):
    If Y^+ were Sym(V) with dim(V_n) = n, then:
      dim(Y^+_n) = p(n)  [plane partitions = partitions into parts with
                           multiplicity, using n parts of size 1, n parts of size 2, etc.]

    Wait -- this is exactly right! The MacMahon function IS the character of
    Sym(V) with dim(V_n) = n:
      char(Sym(V)) = prod_{n>=1} 1/(1-q^n)^{dim V_n} = prod_{n>=1} 1/(1-q^n)^n = M(q).

    So the associated graded of Y^+ IS Sym(V_BPS) with dim(V_BPS)_n = n.
    The indecomposables are exactly V_BPS, and dim(Q_n) = n.

    Returns [Q_0, Q_1, ..., Q_{N-1}].
    """
    # Compute from the plethystic logarithm (exact BPS counts)
    mac = macmahon_coefficients(N)
    plog = plethystic_log_coefficients(mac, N)
    return [int(round(float(c))) for c in plog]


def bar_cohomology_arity1(N: int) -> List[int]:
    """H^1(B(Y^+)): bar cohomology at arity 1 = indecomposables.

    H^1_n = ker(d: B^1_n -> B^0_n) / im(d: B^2_n -> B^1_n)

    Since d: B^1 -> B^0 is the augmentation (which is surjective onto Q for
    n=0 and zero for n>0), and d: B^2 -> B^1 sends [a|b] to a*b, we have:

    H^1_n = Y^+_n / (Y^+_{>0} * Y^+_{>0})_n  for n >= 1
          = indecomposables = BPS generators.

    dim H^1_n = Omega(n) = n (for C^3).
    """
    return indecomposables_dim(N)


def bar_cohomology_arity2(N: int) -> List[int]:
    r"""H^2(B(Y^+)): bar cohomology at arity 2 = relations among generators.

    H^2_n = ker(d: B^2_n -> B^1_n) / im(d: B^3_n -> B^2_n)

    For the commutative model Sym(V_BPS):
    H^2 = Wedge^2(V_BPS) (the relations are the commutativity relations).
    dim(H^2_n) = dim(Wedge^2(V_BPS))_n.

    For the ACTUAL CoHA (non-commutative), the relations include BOTH the
    commutator relations AND the Yangian cubic Serre-type relations.
    The bar cohomology H^2 detects the "space of relations" in the
    minimal A_infinity resolution.

    For the commutative model, we compute:
    dim(Wedge^2(V))_n = sum_{a<b, a+b=n} dim(V_a)*dim(V_b)
                       + sum_{2a=n} binom(dim(V_a), 2)
    """
    bps = bps_invariants_c3(N)

    result = [0] * N
    for a in range(1, N):
        for b in range(a, N):
            if a + b >= N:
                break
            if a < b:
                result[a + b] += bps[a] * bps[b]
            else:  # a == b
                result[2 * a] += bps[a] * (bps[a] - 1) // 2
    return result


def bar_cohomology_arity2_sym(N: int) -> List[int]:
    r"""H^2 for the symmetric algebra model: Sym^2(V_BPS) component.

    In the symmetric model, the bar complex of Sym(V) has:
    H^k(B(Sym(V))) = Wedge^k(V)  (exterior powers).

    So H^2 = Wedge^2(V_BPS), with
    dim(Wedge^2(V))_n = sum_{a+b=n, a<b} a*b + sum_{2a=n} binom(a,2)
    (using dim(V_m) = m).
    """
    return bar_cohomology_arity2(N)


