r"""
yangian_bar_complex.py -- Bar complex of Y^+(gl_hat_1) at low arities.

Ground truth:
  Schiffmann-Vasserot (arXiv:1211.1287): CoHA(C^3) = Y^+(gl_hat_1)
  Kontsevich-Soibelman (arXiv:0811.2435): DT invariants from motivic Hall algebra
  Maulik-Nekrasov-Okounkov-Pandharipande (arXiv:math/0312059): DT/GW correspondence
  ~/chiral-bar-cobar/chapters/frame/bar_cobar_adjunction_curved.tex: bar complex
  ~/calabi-yau-quantum-groups/notes/theory_cy_to_chiral.tex: CY-to-chiral functor

MATHEMATICAL CONTENTS:

The positive half Y^+ = Y^+(gl_hat_1) of the affine Yangian of gl_1 is the
cohomological Hall algebra (CoHA) of C^3 (Schiffmann-Vasserot 2013). As a
graded algebra:
    Y^+ = bigoplus_{n >= 0} Y^+_n,   dim(Y^+_n) = p(n)
where p(n) counts plane partitions of n (OEIS A000219). The graded character
is the MacMahon function M(q) = prod_{n>=1} (1-q^n)^{-n}.

THE BAR COMPLEX B(Y^+):
    B^k(Y^+) = (Y^+)^{otimes k}  (desuspended, with bar differential)
    d_bar : B^k -> B^{k-1}  via multiplication mu : Y^+ otimes Y^+ -> Y^+.
The bar differential in arity k is:
    d_bar([a_1|...|a_k]) = sum_{i=1}^{k-1} (-1)^{eps_i} [a_1|...|mu(a_i,a_{i+1})|...|a_k]
where eps_i encodes the Koszul signs.

For a commutative graded algebra concentrated in degree 0, the bar complex is
the tensor coalgebra with the shuffle differential. Since Y^+ is concentrated
in cohomological degree 0 (the CoHA is in degree 0), the signs simplify:
    d_bar([a_1|...|a_k]) = sum_{i=1}^{k-1} (-1)^{i-1} [a_1|...|a_i * a_{i+1}|...|a_k]

KEY POINT: The bar complex computes Tor^{Y^+}(Q, Q) where Q is the trivial
module Y^+/Y^+_{>0}. In the commutative case, this is the cotangent complex /
Andre-Quillen homology. The generators of H^1(B(Y^+)) are the "indecomposables"
= algebra generators = BPS states.

For the CoHA of C^3:
  - Y^+ is generated by a single generator e_0 (adding a single box), but the
    FULL algebra is freely generated by plane-partition-indexed generators subject
    to the Yangian relations. It is NOT a free commutative algebra.
  - The CoHA multiplication is NOT commutative (it depends on the ordering of
    sheaves in the torus-fixed locus), but is associative.
  - The "commutative" shadow is the symmetric algebra Sym(V_BPS) where V_BPS
    is the BPS vector space (primitives under the coproduct).

DT INVARIANTS FROM BAR COHOMOLOGY:
The BPS invariants Omega(n) of C^3 are defined by the plethystic logarithm:
    sum_{n>=1} Omega(n) q^n = PLog(M(q)) = sum_{n>=1} (-1)^{n-1}/n * log(M(q^n))
                             = sum_{n>=1} n * q^n
    (That is: Omega(n) = n for all n >= 1.)

This follows from M(q) = prod_{n>=1} (1-q^n)^{-n}, so
    PLog(M(q)) = sum_{n>=1} n * q^n.

The bar cohomology should detect these: H^1(B(Y^+)) in degree n should have
dimension Omega(n) = n (these are the BPS generators / algebra generators).

MULTI-PATH VERIFICATION:
  Path 1: Direct bar differential computation at low arities
  Path 2: Comparison with plane partition counts p(n,k) at fixed arity k
  Path 3: Generating function comparison with MacMahon / plethystic logarithm
  Path 4: Euler characteristic chi(B(Y^+)) via alternating sum

CONVENTIONS:
  - q = formal variable (box-counting fugacity)
  - Bar arity k means k tensor factors (k=1 is the generators, k=2 is relations)
  - Cohomological grading: d_bar has degree +1 in bar degree (reduces arity by 1)
  - The augmentation ideal Y^+_{>0} has p(n)-delta_{n,0} dimensions in degree n
"""

