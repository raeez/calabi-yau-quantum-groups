# K3 Hodge numbers h^{p,q}
K3_HODGE: Dict[Tuple[int, int], int] = {
    (0, 0): 1,
    (1, 0): 0, (0, 1): 0,
    (2, 0): 1, (1, 1): 20, (0, 2): 1,
    (2, 1): 0, (1, 2): 0,
    (2, 2): 1,
}

K3_DIM = 2  # complex dimension
K3_REAL_DIM = 4


def k3_hodge_number(p: int, q: int) -> int:
    """Return h^{p,q}(K3)."""
    return K3_HODGE.get((p, q), 0)


# ===========================================================================
# 2. Derived loop space L(K3): functions = HH_*(O_{K3})
# ===========================================================================

class LoopSpaceData(NamedTuple):
    """Data of the derived loop space L(X) for a smooth projective variety X."""
    name: str
    complex_dim: int
    hh_decomposition: Dict[Tuple[int, int], int]  # (p, q) -> h^q(Omega^p)
    total_dim: int
    connes_B_matrix: Dict[Tuple[int, int], int]  # (p, q) -> rank of B: H^q(Omega^p) -> H^q(Omega^{p+1})
    is_B_zero: bool
    hc_minus: Dict[int, int]  # n -> dim HC^-_n
    cy_class_degree: Optional[int]  # degree of the CY structure class in HC^-


def derived_loop_space_k3() -> LoopSpaceData:
    r"""Compute the derived loop space data for K3.

    O(L(K3)) = HH_*(O_{K3}) = bigoplus_{p,q} H^q(K3, Omega^p)

    By HKR, the Hochschild homology of O_{K3} (or equivalently of D^b(Coh(K3))
    by Morita invariance) decomposes into Hodge components.

    The loop degree n = p (form degree) and the components are:
        n=0: H^*(K3, O) = H^0(O) + H^2(O) = 1 + 1 = 2
        n=1: H^*(K3, Omega^1) = H^1(Omega^1) = 20
        n=2: H^*(K3, Omega^2) = H^0(Omega^2) + H^2(Omega^2) = 1 + 1 = 2

    Total: 2 + 20 + 2 = 24.

    VERIFIED:
    [DC] Direct computation from K3 Hodge diamond
    [LT] Kontsevich (ICM 1994), Ben-Zvi--Nadler (2010)
    [CF] Matches phi_k3_explicit_evaluation.py total generator count = 24
    """
    d = K3_DIM

    # HKR decomposition: (p, q) -> h^{p,q} = dim H^q(K3, Omega^p)
    hh_decomp: Dict[Tuple[int, int], int] = {}
    for p in range(d + 1):
        for q in range(d + 1):
            hh_decomp[(p, q)] = k3_hodge_number(p, q)

    total = sum(hh_decomp.values())
    # VERIFIED: 24 = sum of all K3 Hodge numbers h^{p,q}
    # [DC] 1+0+0+1+20+1+0+0+1 = 24
    # [LT] Kontsevich ICM 1994; equals rank of Mukai lattice
    # [CF] phi_k3_explicit_evaluation.py: EXPECTED_RANK = 24
    assert total == 24, f"Total dim HH_*(O_K3) = {total}, expected 24"

    # Connes B operator: B: H^q(Omega^p) -> H^q(Omega^{p+1})
    # B is the de Rham differential under HKR.
    # Rank of B at (p, q) = min(h^{p,q}, h^{p+1,q}) when both nonzero,
    # but for K3 the global de Rham differential is zero on cohomology
    # (since d: H^q(Omega^p) -> H^q(Omega^{p+1}) is zero by Hodge theory:
    # the Hodge-to-de-Rham spectral sequence degenerates at E_1 for Kaehler
    # manifolds, meaning the de Rham differential is zero on the E_1 page).
    #
    # For K3 this is also visible directly: h^{1,0} = h^{0,1} = 0
    # kills all B-maps involving Omega^1.
    connes_B: Dict[Tuple[int, int], int] = {}
    for p in range(d):
        for q in range(d + 1):
            # B: H^q(Omega^p) -> H^q(Omega^{p+1})
            # By Hodge theory degeneration, this is the zero map.
            connes_B[(p, q)] = 0

    is_B_zero = all(v == 0 for v in connes_B.values())

    # Negative cyclic homology HC^-_n = prod_{k >= 0} HH_{n+2k}
    # Since B = 0, this is just the product of HH groups (no differential).
    # For K3 (d=2): HH_n = sum_q h^{n,q} for loop space convention.
    hh_by_degree: Dict[int, int] = {}
    for p in range(d + 1):
        hh_by_degree[p] = sum(hh_decomp.get((p, q), 0) for q in range(d + 1))
    # hh_by_degree: {0: 2, 1: 20, 2: 2}

    hc_minus: Dict[int, int] = {}
    for n in range(d + 1):
        # HC^-_n = sum_{k >= 0, n+2k <= d} dim HH_{n+2k}
        # (since HH is finite-dimensional, the product terminates)
        hc_minus[n] = sum(
            hh_by_degree.get(n + 2 * k, 0)
            for k in range(d + 1)
            if n + 2 * k <= d
        )
    # hc_minus: {0: 2 + 2 = 4, 1: 20, 2: 2}

    return LoopSpaceData(
        name="L(K3)",
        complex_dim=d,
        hh_decomposition=hh_decomp,
        total_dim=total,
        connes_B_matrix=connes_B,
        is_B_zero=is_B_zero,
        hc_minus=hc_minus,
        cy_class_degree=d,  # CY structure class in HC^-_d = HC^-_2
    )


