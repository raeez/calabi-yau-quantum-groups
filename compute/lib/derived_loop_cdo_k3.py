class CY2LoopCDOComparison(NamedTuple):
    """Loop space and CDO data for a CY_2 surface."""
    name: str
    hodge: Dict[Tuple[int, int], int]
    hh_total_dim: int
    chi_O: int  # = kappa_ch at d=2
    connes_B_zero: bool
    cdo_exists: bool
    decomposition: Dict[int, int]  # p -> dim HH_p (by form degree)


def abelian_surface_data() -> CY2LoopCDOComparison:
    r"""Loop space and CDO data for an abelian surface A.

    Abelian surface: h^{p,q} = binom(2,p) * binom(2,q).
    Hodge diamond:
            1
        2       2
    1       4       1
        2       2
            1

    (Corrected: h^{1,0}=2, h^{0,1}=2, h^{2,0}=1, h^{1,1}=4, h^{0,2}=1,
     h^{2,1}=2, h^{1,2}=2, h^{2,2}=1.)

    chi(O_A) = 1 - 2 + 1 = 0.
    Total dim HH = sum h^{p,q} = 16 = 4^2 = (b_0+b_1+b_2)^2... no.
    sum h^{p,q} = 1+2+2+1+4+1+2+2+1 = 16 = 4^2.

    The CDO exists (c_1 = 0, abelian surface is CY_2).
    kappa_ch = chi(O_A) = 0.

    VERIFIED:
    [DC] Direct from h^{p,q} = binom(2,p)*binom(2,q)
    [LT] Borisov-Libgober: Ell(A) = 0 for abelian surface
    [CF] phi_k3_explicit_evaluation.py: evaluate_phi_on_abelian_surface()
    """
    hodge: Dict[Tuple[int, int], int] = {}
    for p in range(3):
        for q in range(3):
            hodge[(p, q)] = math.comb(2, p) * math.comb(2, q)
    # hodge: (0,0)=1, (0,1)=2, (0,2)=1, (1,0)=2, (1,1)=4, (1,2)=2,
    #         (2,0)=1, (2,1)=2, (2,2)=1

    total = sum(hodge.values())
    # VERIFIED: sum binom(2,p)*binom(2,q) = (sum binom(2,p))^2 = 4^2 = 16
    # [DC] (1+2+1)^2 = 16
    # [LT] Betti numbers of abelian surface: b_0=1,b_1=4,b_2=6,b_3=4,b_4=1, sum=16
    assert total == 16, f"Total = {total}, expected 16"

    chi_O = hodge[(0, 0)] - hodge[(0, 1)] + hodge[(0, 2)]
    # VERIFIED: chi(O_A) = 1 - 2 + 1 = 0
    # [DC] Direct from h^{0,q}(A) = binom(2,q)
    # [LT] Standard: abelian surface has chi(O) = 0 (Mumford, "Abelian Varieties")
    assert chi_O == 0, f"chi(O_A) = {chi_O}, expected 0"

    decomp = {p: sum(hodge.get((p, q), 0) for q in range(3)) for p in range(3)}
    # decomp: {0: 4, 1: 8, 2: 4}

    # Connes B: for abelian surface, h^{1,0} = 2 != 0, so B is NOT zero.
    # B: H^q(Omega^0) -> H^q(Omega^1) can be nonzero.
    # Specifically, B maps H^0(O) -> H^0(Omega^1): rank at most min(1, 2).
    # On an abelian surface, the global 1-forms ARE d(coordinate functions),
    # so B has rank 2 on H^0: maps 1 |-> 0 (constants are closed, hence
    # in ker B under Hodge theory... actually B = d_{dR} and constants
    # are killed by d. So B(1) = 0 in H^0(Omega^1).
    #
    # By Hodge theory (degeneration at E_1 for Kaehler): B = 0 on cohomology.
    # This is true for ALL compact Kaehler manifolds, including abelian surfaces.
    connes_B_zero = True

    return CY2LoopCDOComparison(
        name="abelian_surface",
        hodge=hodge,
        hh_total_dim=total,
        chi_O=chi_O,
        connes_B_zero=connes_B_zero,
        cdo_exists=True,  # c_1 = 0
        decomposition=decomp,
    )


def enriques_surface_data() -> CY2LoopCDOComparison:
    r"""Loop space and CDO data for an Enriques surface S.

    Enriques surface: omega_S is 2-torsion (NOT trivial), so c_1 != 0 in
    H^1(S, Omega^1) BUT c_1 is 2-torsion. The CDO does NOT exist in the
    strict sense (c_1 != 0), but a Z/2-equivariant version exists on the
    K3 double cover.

    Hodge diamond:
            1
        0       0
    0      10      0
        0       0
            1

    h^{0,0}=1, h^{1,1}=10, h^{2,2}=1.
    h^{2,0}=0 (omega_S is 2-torsion, no global section).
    chi(O_S) = 1 - 0 + 0 = 1.

    VERIFIED:
    [DC] Standard Enriques surface Hodge numbers
    [LT] Barth-Hulek-Peters-Van de Ven, "Compact Complex Surfaces"
    """
    hodge: Dict[Tuple[int, int], int] = {
        (0, 0): 1,
        (1, 0): 0, (0, 1): 0,
        (2, 0): 0, (1, 1): 10, (0, 2): 0,
        (2, 1): 0, (1, 2): 0,
        (2, 2): 1,
    }

    total = sum(hodge.values())
    # VERIFIED: 1 + 0 + 0 + 0 + 10 + 0 + 0 + 0 + 1 = 12
    # [DC] Direct from Enriques Hodge diamond
    # [LT] Barth-Hulek-Peters-Van de Ven, "Compact Complex Surfaces", Table 10
    assert total == 12, f"Total = {total}, expected 12"

    chi_O = hodge[(0, 0)] - hodge.get((0, 1), 0) + hodge.get((0, 2), 0)
    # VERIFIED: chi(O_S) = 1 - 0 + 0 = 1
    # [DC] Direct from h^{0,q}(S): h^{0,0}=1, h^{0,1}=0, h^{0,2}=0
    # [LT] Standard: Enriques chi(O) = 1 (half of K3's chi(O) = 2)
    assert chi_O == 1, f"chi(O_S) = {chi_O}, expected 1"

    decomp = {p: sum(hodge.get((p, q), 0) for q in range(3)) for p in range(3)}
    # decomp: {0: 1, 1: 10, 2: 1}

    return CY2LoopCDOComparison(
        name="enriques_surface",
        hodge=hodge,
        hh_total_dim=total,
        chi_O=chi_O,
        connes_B_zero=True,  # B = 0 by Hodge theory (Kaehler)
        cdo_exists=False,  # c_1 is 2-torsion, NOT zero
        decomposition=decomp,
    )


