class CYTraceData(NamedTuple):
    """Data about the CY trace in negative cyclic homology."""
    hc_minus_d: int  # dim HC^-_d (where CY class lives)
    cy_class_exists: bool
    cy_class_source: str  # which component of HC^-_d contains it
    quantization_level: int  # the level parameter from the CY trace
    kappa_ch: int  # resulting kappa_ch


def cy_trace_k3() -> CYTraceData:
    r"""The CY trace for K3 in negative cyclic homology.

    The CY structure on D^b(Coh(K3)) provides a class sigma in HC^-_2(O_{K3}).
    This class is the lift of the holomorphic volume form [Omega_{K3}] in
    H^0(K3, Omega^2) to negative cyclic homology.

    Since B = 0 on K3 (Connes operator vanishes on cohomology):
        HC^-_2 = HH_2 = H^0(Omega^2) + H^2(Omega^2) = C^2

    The CY class lives in the H^0(Omega^2) component (the holomorphic
    volume form), NOT in H^2(Omega^2) (the top class).

    The quantization: the CY trace determines the level of the
    resulting Heisenberg VOA. For K3 at d=2:
        kappa_ch = chi(O_{K3}) = 2

    by Proposition prop:cy-kappa-d2.

    NOTE (AP-CY2): The CY trace lives in HC^-_d(C), NOT merely in HH_d -> k.
    The negative cyclic refinement is essential for the S^d-framing.

    VERIFIED:
    [DC] HC^-_2 = HH_2 = 2 since B = 0
    [LT] Kontsevich-Vlassopoulos (arXiv:2006.13542) for S^d-framing
    [CF] phi_k3_explicit_evaluation.py: kappa_ch = 2
    """
    loop = derived_loop_space_k3()

    # HC^-_2 contains the CY structure class
    hc_minus_2 = loop.hc_minus[2]
    # VERIFIED: HC^-_2 = HH_2 (since B=0) = H^0(Omega^2) + H^2(Omega^2) = 1+1 = 2
    # [DC] Direct: B=0 kills the differential, so HC^- = prod HH
    # [LT] Loday, "Cyclic Homology" (1998), Ch.5: SBI with B=0
    # [CF] cy3_hochschild.py: CyclicHomology for K3 (d=2) gives HC^-_2 = 2
    assert hc_minus_2 == 2, f"dim HC^-_2 = {hc_minus_2}, expected 2"

    return CYTraceData(
        hc_minus_d=hc_minus_2,
        cy_class_exists=True,
        cy_class_source="H^0(K3, Omega^2_{K3}) subset HC^-_2",
        quantization_level=2,  # kappa_ch = chi(O_{K3}) = 2
        kappa_ch=2,
    )


