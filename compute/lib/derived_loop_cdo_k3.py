class CDOData(NamedTuple):
    """Data of the sheaf of chiral differential operators on X."""
    name: str
    complex_dim: int
    c1_vanishes: bool  # existence condition for CDO
    cdo_exists: bool
    local_central_charge: int  # c of betagamma per coordinate patch
    effective_central_charge: int  # c_eff after topological twist
    cdr_central_charge: int  # c of the chiral de Rham complex
    n_susy: int  # amount of superconformal symmetry
    elliptic_genus_leading: int  # leading coefficient of elliptic genus
    kappa_ch: int  # kappa_ch from CDO/elliptic genus
    chi_O: int  # chi(O_X) = holomorphic Euler characteristic


def cdo_k3() -> CDOData:
    r"""Chiral differential operators on K3.

    The CDO D^{ch}_{K3} exists because c_1(T_{K3}) = 0 (CY condition).

    Local model on U ~ C^2:
        D^{ch}_U = betagamma(2) (rank-2 betagamma system)
        Fields: gamma^1, gamma^2 (weight 0), beta_1, beta_2 (weight 1)
        OPE: gamma^i(z) beta_j(w) ~ delta^i_j / (z-w)
        c_{betagamma} = 2 * dim_C = 4

    The chiral de Rham complex Omega^{ch}_{K3} is the BRST reduction.
    After the topological twist, the effective central charge is:
        c_{eff} = c_{betagamma} + c_{bc} = 2d - 2d = 0

    where the bc ghosts contribute c_{bc} = -2 per complex dimension.

    For K3 (hyperkaehler): N=4 superconformal symmetry at c=0.

    The CDO cohomology is the K3 elliptic genus:
        ch(H^*(K3, Omega^{ch})) = 2 phi_{0,1}(tau, z)  (Borisov-Libgober)

    The leading coefficient 2 = chi(O_{K3}) = kappa_ch.

    VERIFIED:
    [DC] Direct: c_1(K3) = 0, chi(O_{K3}) = h^{0,0} - h^{0,1} + h^{0,2} = 1 - 0 + 1 = 2
    [LT] Borisov-Libgober (2000), Malikov-Schechtman-Vaintrob (1999)
    [CF] Matches phi_k3_explicit_evaluation.py: kappa_ch = 2
    """
    d = K3_DIM

    # Existence: c_1(T_{K3}) = 0 (CY condition)
    c1_vanishes = True  # K3 is CY_2

    # Central charges
    c_bg = 2 * d  # betagamma: 2 per complex dimension
    c_bc = -2 * d  # bc ghosts: -2 per complex dimension
    c_eff = c_bg + c_bc  # effective after twist
    # VERIFIED: c_eff = 2d - 2d = 0 for any CY_d
    # [DC] 2*2 + (-2)*2 = 0
    # [LT] Malikov-Schechtman-Vaintrob (1999): CDR has c=0 on CY
    # [CF] rem:cdr-k3 in toroidal_elliptic.tex: "c_{betagamma}=+2 and c_{bc}=-2 cancel"
    assert c_eff == 0, f"c_eff = {c_eff}, expected 0"

    # Holomorphic Euler characteristic
    chi_O = k3_hodge_number(0, 0) - k3_hodge_number(0, 1) + k3_hodge_number(0, 2)
    # VERIFIED: chi(O_{K3}) = h^{0,0} - h^{0,1} + h^{0,2} = 1 - 0 + 1 = 2
    # [DC] Direct from K3 Hodge numbers
    # [LT] Standard: chi(O_{K3}) = 2 (e.g. Beauville, "Complex Algebraic Surfaces")
    # [CF] phi_k3_explicit_evaluation.py: EXPECTED_KAPPA_CH = 2
    assert chi_O == 2, f"chi(O_K3) = {chi_O}, expected 2"

    return CDOData(
        name="D^{ch}_{K3}",
        complex_dim=d,
        c1_vanishes=c1_vanishes,
        cdo_exists=c1_vanishes,  # CDO exists iff c_1 = 0
        local_central_charge=c_bg,
        effective_central_charge=c_eff,
        cdr_central_charge=c_eff,  # chiral de Rham has c = c_eff = 0
        n_susy=4,  # K3 hyperkaehler => N=4
        elliptic_genus_leading=chi_O,
        kappa_ch=chi_O,  # kappa_ch = chi(O_X) at d=2 (Prop prop:cy-kappa-d2)
        chi_O=chi_O,
    )


# ===========================================================================
# 4. CDO existence test for general surfaces
# ===========================================================================

class CDOExistenceResult(NamedTuple):
    """Result of CDO existence test for a smooth projective variety."""
    name: str
    complex_dim: int
    c1_class: str  # description of c_1
    c1_vanishes: bool
    cdo_exists: bool
    chi_O: int  # holomorphic Euler characteristic
    reason: str


def cdo_existence(name: str, dim: int, hodge: Dict[Tuple[int, int], int]) -> CDOExistenceResult:
    r"""Test CDO existence for a smooth projective variety.

    The CDO D^{ch}_X exists iff c_1(T_X) = 0 in H^1(X, Omega^1_X).

    For CY manifolds: c_1 = 0 by definition, so CDO always exists.
    For general varieties: the obstruction class in H^2(X, Omega^{2,cl})
    is related to c_1 via the exponential sequence.

    In practice: c_1 = 0 iff omega_X ~ O_X (trivial canonical bundle).
    """
    # Compute chi(O_X) = sum (-1)^q h^{0,q}
    chi_O = sum((-1)**q * hodge.get((0, q), 0) for q in range(dim + 1))

    # c_1 vanishes iff canonical bundle is trivial
    # For surfaces: this is equivalent to CY_2 (with h^{1,0} = 0 -> K3)
    # or abelian surface (h^{1,0} = 2), or Enriques (2-torsion canonical).
    # We detect CY by checking if h^{dim,0} = 1 (global holomorphic volume form).
    has_volume_form = hodge.get((dim, 0), 0) == 1
    # And also need c_1 = 0, not just c_1 torsion.
    # For simplicity: c_1 = 0 iff there exists a nonvanishing global
    # section of the canonical bundle, i.e., h^{dim,0} >= 1.
    # (Strictly: h^{dim,0} = 1 for CY; h^{dim,0} = 1 for abelian also.)
    c1_vanishes = has_volume_form

    if c1_vanishes:
        c1_class = "0 (trivial canonical bundle)"
        reason = f"c_1(T_X) = 0: holomorphic volume form exists (h^{{{dim},0}} = 1)"
    else:
        c1_class = "nonzero"
        reason = f"c_1(T_X) != 0: no holomorphic volume form (h^{{{dim},0}} = {hodge.get((dim, 0), 0)})"

    return CDOExistenceResult(
        name=name,
        complex_dim=dim,
        c1_class=c1_class,
        c1_vanishes=c1_vanishes,
        cdo_exists=c1_vanishes,
        chi_O=chi_O,
        reason=reason,
    )


