def cdo_cy3_examples() -> List[CDOExistenceResult]:
    r"""CDO existence for standard CY3 examples.

    All CY3 manifolds have c_1 = 0, so CDO exists for all of them.
    The kappa_ch values differ:

    K3 x E: chi(O) = chi(O_{K3}) * chi(O_E) = 2 * 0 = 0.
    Wait -- chi(O_{K3xE}) = sum (-1)^q h^{0,q}(K3 x E).
    By Kunneth: h^{0,q}(K3 x E) = sum_{a+b=q} h^{0,a}(K3) * h^{0,b}(E).
    h^{0,0} = 1, h^{0,1} = h^{0,1}(K3)*h^{0,0}(E) + h^{0,0}(K3)*h^{0,1}(E) = 0+1 = 1
    h^{0,2} = h^{0,2}(K3)*h^{0,0}(E) + h^{0,1}(K3)*h^{0,1}(E) + h^{0,0}(K3)*h^{0,2}(E)
            = 1 + 0 + 0 = 1  (E has dim 1, no h^{0,2})
    h^{0,3} = h^{0,2}(K3)*h^{0,1}(E) = 1
    chi(O_{K3xE}) = 1 - 1 + 1 - 1 = 0.

    Quintic: chi(O_Q) = 1 - 0 + 0 - 1 = 0.
    (For quintic: h^{0,0}=1, h^{0,1}=0, h^{0,2}=0, h^{0,3}=1.)

    Actually for ALL compact CY3:
    chi(O_X) = h^{0,0} - h^{0,1} + h^{0,2} - h^{0,3}.
    For strict CY3 (h^{1,0}=0): h^{0,1}=0, h^{0,2}=0, and
    h^{0,3} = h^{3,0} = 1 (CY condition). So chi(O_X) = 1-0+0-1 = 0.

    For K3 x E (not strict CY3, has h^{1,0}=1): chi(O) = 0.

    VERIFIED:
    [DC] Direct from Hodge numbers of each example
    [LT] Standard CY3 literature (Hubsch, "Calabi-Yau Manifolds")
    """
    results = []

    # K3 x E
    k3e_hodge_0q = {(0, 0): 1, (0, 1): 1, (0, 2): 1, (0, 3): 1}
    k3e_full = {
        (0, 0): 1, (1, 0): 1, (2, 0): 1, (3, 0): 1,
        (0, 1): 1, (1, 1): 21, (2, 1): 21, (3, 1): 1,
        (0, 2): 1, (1, 2): 21, (2, 2): 21, (3, 2): 1,
        (0, 3): 1, (1, 3): 1, (2, 3): 1, (3, 3): 1,
    }
    # Correction: K3 x E Hodge numbers via Kunneth
    # Using the proper computation from cy3_hochschild.py
    k3e_h = {}
    k3_h = K3_HODGE
    e_h = {(0, 0): 1, (1, 0): 1, (0, 1): 1, (1, 1): 1}
    for p in range(4):
        for q in range(4):
            val = 0
            for a in range(3):
                b = p - a
                if b < 0 or b > 1:
                    continue
                for c in range(3):
                    dd = q - c
                    if dd < 0 or dd > 1:
                        continue
                    val += k3_h.get((a, c), 0) * e_h.get((b, dd), 0)
            k3e_h[(p, q)] = val
    results.append(cdo_existence("K3 x E", 3, k3e_h))

    # Quintic
    quintic_h = {
        (0, 0): 1, (1, 0): 0, (0, 1): 0, (2, 0): 0, (1, 1): 1, (0, 2): 0,
        (3, 0): 1, (2, 1): 101, (1, 2): 101, (0, 3): 1,
        (3, 1): 0, (2, 2): 1, (1, 3): 0,
        (3, 2): 0, (2, 3): 0, (3, 3): 1,
    }
    results.append(cdo_existence("quintic", 3, quintic_h))

    return results


