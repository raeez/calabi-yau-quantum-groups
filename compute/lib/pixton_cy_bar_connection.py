# 1. Tautological ring data for Mbar_g
# =========================================================================

class TautologicalRingData(NamedTuple):
    """Dimensions of the tautological ring R*(Mbar_g) at genus g.

    R^k(Mbar_g) is the degree-k component of the tautological ring.
    Dimensions from Faber's computations and the Pixton-Zvonkine
    verification programme.

    NOTE: These are tautological kappa-classes kappa_j^{taut} (Miller-
    Morita-Mumford classes), NOT the modular characteristic kappa_ch.
    """
    genus: int
    dims: Dict[int, int]          # codimension k -> dim R^k(Mbar_g)
    total_dim: int
    socle_degree: int             # g-2: the socle (top) degree of R*(Mbar_g)


# Faber's computation of taut ring dimensions.
# R^k(Mbar_g) for small g.
_TAUT_RING_DIMS = {
    1: {0: 1, 1: 0},                                  # R^0=1, dim(Mbar_1)=1
    2: {0: 1, 1: 2, 2: 1},                            # socle at 0 = g-2
    3: {0: 1, 1: 3, 2: 4, 3: 1},                      # Faber's conjecture
    4: {0: 1, 1: 4, 2: 9, 3: 9, 4: 2},
    5: {0: 1, 1: 5, 2: 15, 3: 25, 4: 14, 5: 1},
}

# NOTE: g=2 R^0=1 is correct (connected Mbar_2). The Pixton
# relation in R^2(Mbar_2) reduces dim from 2 (free generators) to 1
# (modulo relations). But R^2(Mbar_2) = 1 means AFTER the relation.
# Before the relation, the free tautological ring at g=2 would have
# dim R^2 = 2 (from kappa_2 and kappa_1^2). The Pixton relation
# imposes one constraint, leaving dim 1.
# CORRECTION: The values in _TAUT_RING_DIMS are the dimensions of
# the ACTUAL tautological ring R*(Mbar_g) = free / Pixton ideal.
# So R^2(Mbar_2) = 1 is correct (one relation on two generators).


def tautological_ring_data(g: int) -> TautologicalRingData:
    """Return tautological ring data for Mbar_g.

    Uses tabulated values for g <= 5 (Faber's computations).
    """
    if g < 1:
        raise ValueError(f"genus must be >= 1, got {g}")
    if g not in _TAUT_RING_DIMS:
        raise ValueError(f"tautological ring data not tabulated for genus {g}")

    dims = _TAUT_RING_DIMS[g]
    total = sum(dims.values())
    socle = g - 2

    return TautologicalRingData(
        genus=g,
        dims=dims,
        total_dim=total,
        socle_degree=socle,
    )


