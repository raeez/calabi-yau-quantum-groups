# 4. CohFT kernel and Pixton ideal membership
# =========================================================================

class CohFTPixtonData(NamedTuple):
    """Data relating a CY shadow CohFT to the Pixton ideal.

    The CohFT omega_A: V^{tensor n} -> R*(Mbar_{g,n}) has a kernel.
    The Pixton ideal I_g is the full ideal of tautological relations.
    The CohFT satisfies: ker(omega_A) subset I_g.

    For rank-1 CohFTs (class G): ker is trivial (omega_A injective on
    the 1-dimensional space).
    For higher-rank CohFTs (class L, C, M): the kernel grows with
    the rank and genus.

    The key invariant is the PIXTON SATURATION: does the image of
    the CohFT span the full tautological ring, or only a subring?
    """
    family: str
    shadow_class: str
    rank: int                    # rank of the CohFT (dim of state space V)
    genus: int
    cohft_image_dim: int         # dim of image in R*(Mbar_g)
    taut_ring_dim: int           # dim of R*(Mbar_g)
    saturation_ratio: Fraction   # image_dim / taut_ring_dim
    pixton_relation_count: int   # number of Pixton relations at this genus
    all_relations_satisfied: bool  # True if the CohFT satisfies all Pixton rels


def cohft_pixton_analysis(
    family: str,
    shadow_class: str,
    kappa_ch: Fraction,
    rank: int,
    genus: int,
) -> CohFTPixtonData:
    """Analyze the relationship between a CY CohFT and the Pixton ideal.

    Parameters
    ----------
    family : str
        CY family name.
    shadow_class : str
        G, L, C, or M.
    kappa_ch : Fraction
        Modular characteristic kappa_ch (AP113).
    rank : int
        Rank of the CohFT (dimension of the state space).
    genus : int
        Genus for the analysis.
    """
    if genus < 1 or genus > 5:
        raise ValueError(f"genus must be 1-5, got {genus}")

    taut_data = tautological_ring_data(genus)
    taut_dim = taut_data.total_dim
    n_pixton = pixton_relation_count(genus)

    # CohFT image dimension depends on the class:
    # Class G (rank 1): image is 1-dimensional at each degree
    # Class L (rank > 1, finite depth): image grows with rank but saturates
    # Class M (infinite depth): image fills R*(Mbar_g) for large enough rank
    if shadow_class == "G":
        # Rank-1 CohFT: image is the scalar multiples of lambda classes
        # dim = number of nonzero lambda contributions = min(genus, 1+socle)
        image_dim = min(genus, taut_data.socle_degree + 1)
    elif shadow_class == "L":
        # Finite depth: image grows but caps at taut_dim
        image_dim = min(rank, taut_dim)
    elif shadow_class == "C":
        image_dim = min(rank * (rank + 1) // 2, taut_dim)
    else:  # M
        # Infinite depth: image fills taut ring
        image_dim = taut_dim

    saturation = Fraction(image_dim, taut_dim) if taut_dim > 0 else Fraction(1)

    # All CohFTs satisfy Pixton relations (proved by Janda-PPZ 2018).
    # The content of the Pixton-CohFT connection is that the CohFT
    # axioms FORCE all Pixton relations to be satisfied.
    all_satisfied = True

    return CohFTPixtonData(
        family=family,
        shadow_class=shadow_class,
        rank=rank,
        genus=genus,
        cohft_image_dim=image_dim,
        taut_ring_dim=taut_dim,
        saturation_ratio=saturation,
        pixton_relation_count=n_pixton,
        all_relations_satisfied=all_satisfied,
    )


