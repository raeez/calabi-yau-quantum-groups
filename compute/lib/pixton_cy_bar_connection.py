class ShadowTautDictionary(NamedTuple):
    """Dictionary between shadow coefficients S_k and tautological data.

    The shadow CohFT (Theorem thm:cy-shadow-cohft) produces classes
    in the tautological ring. The dictionary maps:
      S_2 = kappa_ch              <-> lambda_1 (genus 1 amplitude)
      S_3 = alpha (cubic shadow)  <-> kappa_1^{taut} correction at g=2
      S_4 = quartic shadow        <-> kappa_2^{taut} correction at g=2+

    The tautological content of the shadow tower is FULLY captured
    on the uniform-weight lane by the A-hat generating function.
    """
    shadow_class: str             # G, L, C, or M
    kappa_ch: Fraction            # S_2 = modular characteristic (AP113: subscripted)
    shadow_coefficients: Dict[int, Fraction]   # S_k for k >= 2
    taut_classes: Dict[int, str]  # k -> description of tautological class
    pixton_kernel_rank: int       # rank of the kernel in the Pixton ideal


def shadow_to_taut_dictionary(
    family: str,
    kappa_ch: Fraction,
    shadow_class: str,
    shadow_coeffs: Optional[Dict[int, Fraction]] = None,
) -> ShadowTautDictionary:
    """Build the shadow-tautological dictionary for a CY chiral algebra.

    Parameters
    ----------
    family : str
        Name of the CY family (e.g. "Heisenberg", "Virasoro", "K3 lattice").
    kappa_ch : Fraction
        The modular characteristic kappa_ch (AP113).
    shadow_class : str
        Shadow class: "G", "L", "C", or "M".
    shadow_coeffs : dict, optional
        Shadow coefficients S_k for k >= 2. If None, uses defaults
        from the shadow class.
    """
    if shadow_coeffs is None:
        shadow_coeffs = _default_shadow_coeffs(shadow_class, kappa_ch)

    # Build the tautological class dictionary
    taut_classes: Dict[int, str] = {
        2: "lambda_1 (Hodge class, genus 1 amplitude)",
    }
    if shadow_class in ("L", "C", "M"):
        taut_classes[3] = "kappa_1^{taut} * lambda_1 correction (genus 2)"
    if shadow_class in ("C", "M"):
        taut_classes[4] = "kappa_2^{taut} correction (genus 2+)"
    if shadow_class == "M":
        for k in range(5, 8):
            taut_classes[k] = f"kappa_{k-2}^{{taut}} correction (genus {k-1}+)"

    # Pixton kernel rank depends on the shadow class:
    # Class G: trivial CohFT (rank 1) -> all Pixton relations are in the kernel
    # Class L: finite shadow depth -> finite kernel
    # Class M: infinite shadow depth -> full Pixton ideal generated
    if shadow_class == "G":
        pixton_rank = 0  # trivial CohFT, no nontrivial kernel
    elif shadow_class == "L":
        pixton_rank = 1  # genus 2 relation
    elif shadow_class == "C":
        pixton_rank = 1
    else:  # class M
        pixton_rank = -1  # -1 signals "generates the full ideal"

    return ShadowTautDictionary(
        shadow_class=shadow_class,
        kappa_ch=kappa_ch,
        shadow_coefficients=shadow_coeffs,
        taut_classes=taut_classes,
        pixton_kernel_rank=pixton_rank,
    )


def _default_shadow_coeffs(
    shadow_class: str,
    kappa_ch: Fraction,
) -> Dict[int, Fraction]:
    """Default shadow coefficients by class.

    Ground truth from c3_shadow_tower.py and a_infinity_bar_w1inf.py.
    """
    coeffs: Dict[int, Fraction] = {2: kappa_ch}
    if shadow_class == "G":
        # Heisenberg: S_k = 0 for k >= 3 (Gaussian, depth 2)
        for k in range(3, 8):
            coeffs[k] = Fraction(0)
    elif shadow_class == "L":
        # Affine KM / K3 lattice: S_3 != 0, S_k = 0 for k >= 4
        coeffs[3] = Fraction(1)  # generic nonzero cubic shadow
        for k in range(4, 8):
            coeffs[k] = Fraction(0)
    elif shadow_class == "C":
        # betagamma: S_3 != 0, S_4 != 0, S_k = 0 for k >= 5
        coeffs[3] = Fraction(1)
        coeffs[4] = Fraction(1, 3)
        for k in range(5, 8):
            coeffs[k] = Fraction(0)
    else:  # M
        # Virasoro: all S_k != 0 (infinite tower)
        # Ground truth from c3_shadow_tower.py:
        #   Spin 2: kappa=1/2, alpha=2, S_4=10/27
        coeffs[3] = Fraction(2)      # alpha = 2 (cubic shadow)
        coeffs[4] = Fraction(10, 27) # S_4 = 10/27 (quartic)
        coeffs[5] = Fraction(1, 4)   # estimated from tower
        coeffs[6] = Fraction(1, 8)
        coeffs[7] = Fraction(1, 16)
    return coeffs


