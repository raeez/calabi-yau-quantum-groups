"""Finite certificates for chambered BPS positive geometry.

This module implements the finite quotient

    P^{BPS,motloc}_{sigma,S,o,T_eq,<=N,<=R}

used in the positive-geometry notes.  The object is not an analytic
approximation: it is the quotient by the closed Hall ideal generated by
charges outside a finite support-property bound.  Every infinite
identity is tested first in this quotient and only then passed to the
inverse limit.

The normalizations follow the Igusa square-root paper:

    phi_{0,1} is the one-particle input,
    f(0,0)/2 = 5 is the Borcherds weight,
    AutBorch(phi_{0,1}) = Delta_5,
    den(g_{Delta_5}) = 64^{-1} Delta_5(2Z),
    the scalar protected object is a square proportional to Delta_5^{-2}.

All arithmetic internal to the Hall quotient is exact.  Numerical
Igusa product evaluation is used only as a boundary witness and is
reported as such in the certificate source list.
"""

