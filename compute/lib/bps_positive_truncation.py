def master_truncation_certificate(
    geometry: Literal["C3", "conifold", "K3xE_boundary"],
    bound: TruncationBound,
) -> Certificate:
    truncation = finite_rank2_truncation(max_height=bound.N)
    certificates = [
        support_property_certificate(truncation, bound),
        orientation_certificate(truncation),
        hall_associativity_certificate(truncation),
        sector_descent_certificate(truncation),
    ]
    if bound.N > 1:
        certificates.append(
            transition_certificate(finite_rank2_truncation(bound.N - 1), truncation)
        )
    if geometry == "C3":
        certificates.append(toric_c3_collapse_certificate(bound.N + 1))
    elif geometry == "conifold":
        certificates.append(toric_conifold_collapse_certificate(bound.N + 4, bound.N))
    elif geometry == "K3xE_boundary":
        certificates.extend([
            ks_loop_holonomy_a2_certificate(max(5, bound.N)),
            igusa_normalization_certificate(),
        ])
    else:
        raise ValueError(f"unknown geometry: {geometry}")

    discrepancies = []
    checked = 0
    exact = True
    sources = []
    for certificate in certificates:
        checked += certificate.checked_items
        exact = exact and certificate.exact
        sources.extend(certificate.source_modules)
        for discrepancy in certificate.discrepancies:
            enriched = dict(discrepancy)
            enriched["certificate"] = certificate.name
            discrepancies.append(enriched)

    return Certificate(
        name=f"master_{geometry}",
        exact=exact,
        theorem_target=f"finite quotient certificate for {geometry}",
        normalization="finite-first chambered BPS positive geometry",
        checked_items=checked,
        discrepancies=tuple(discrepancies),
        source_modules=tuple(dict.fromkeys(sources)),
    )
