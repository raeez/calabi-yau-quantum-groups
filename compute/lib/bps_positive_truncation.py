def igusa_normalization_certificate(
    N_prod: int = 10,
    N_theta: int = 20,
    D_max: int = 60,
) -> Certificate:
    discrepancies = []
    if phi01_coefficient(0, -1) != 1:
        discrepancies.append({"coefficient": "f(0,-1)", "expected": 1, "actual": phi01_coefficient(0, -1)})
    if phi01_coefficient(0, 0) != 10:
        discrepancies.append({"coefficient": "f(0,0)", "expected": 10, "actual": phi01_coefficient(0, 0)})
    if phi01_coefficient(0, 1) != 1:
        discrepancies.append({"coefficient": "f(0,1)", "expected": 1, "actual": phi01_coefficient(0, 1)})
    if phi01_coefficient(0, 0) // 2 != 5:
        discrepancies.append({"check": "Borcherds weight c(0)/2"})
    if verify_bkm_identity(8):
        discrepancies.append({"check": "phi01 eta^9 false-positive guard"})
    if not verify_row_sum(4):
        discrepancies.append({"check": "phi01 row sums"})
    if not verify_symmetry(4):
        discrepancies.append({"check": "phi01 l-symmetry"})
    if not verify_discriminant_dependence(4):
        discrepancies.append({"check": "phi01 discriminant dependence"})

    product_result = verify_product_formula(
        2.0j, 0.1j, 2.0j,
        N_prod=N_prod,
        N_theta=N_theta,
        D_max=D_max,
    )
    if product_result["abs_relative_error"] >= 1e-6:
        discrepancies.append({
            "check": "Borcherds product versus theta product",
            "abs_relative_error": product_result["abs_relative_error"],
        })

    return Certificate(
        name="igusa_normalization",
        exact=False,
        theorem_target="AutBorch^{den}(phi_{0,1})=(Delta_5,nu,64^{-1}Delta_5(2Z))",
        normalization="f(0,0)/2=5; Delta_5 is the denominator half; scalar square is proportional to Delta_5^{-2}",
        checked_items=8,
        discrepancies=tuple(discrepancies),
        source_modules=(
            "compute.lib.phi01_fourier",
            "compute.lib.igusa_product_formula",
            "~/igusa-cusp-form/proj.tex",
        ),
    )


def quintic_excert_surface_certificate() -> Certificate:
    """Finite ledger for the quintic named-example certificate.

    This certificate is exact as a ledger but not exact as an unconditional
    realization of the quintic chamber: the Bridgeland/support/HN slot is
    still a named input.  The point of the certificate is to prevent the
    known HKR/PTVV/Yukawa data from being misreported as a constructed
    Bridgeland chamber.
    """

    discrepancies = []
    hkr = hkr_matching_theorem_quintic()
    ptvv = ptvv_quintic_existence()
    routes = tilting_complex_obstruction_routes()
    if not hkr["dimensions_match"] or not hkr["totals_match"]:
        discrepancies.append({"check": "quintic HKR dimension matching"})
