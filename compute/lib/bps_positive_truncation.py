def finite_lower_set_certificate(
    truncation: BPSMotivicTruncation,
    ambient_visible_monoid: Tuple[Charge, ...] | None = None,
) -> Certificate:
    """Exact check that retained charges are lower-set compatible.

    It verifies the condition needed by the quotient proof: every
    retained charge has retained HN summands for every decomposition
    visible in the ambient active monoid.  If no ambient monoid is
    supplied, the retained monoid is used as the ambient visible set.
    """

    charges = set(truncation.charges.charges)
    ambient = tuple(ambient_visible_monoid or truncation.charges.charges)
    ambient_set = set(ambient)
    discrepancies = []
    checked = 0
    for gamma in charges:
        for alpha in ambient:
            for beta in ambient:
                if alpha + beta != gamma:
                    continue
                checked += 1
                if alpha in charges and beta in charges:
                    continue
                if alpha not in ambient_set or beta not in ambient_set:
                    continue
                discrepancies.append({
                    "gamma": gamma.coords,
                    "alpha": alpha.coords,
                    "beta": beta.coords,
                    "failure": "retained charge has omitted ambient summand",
                })
    return Certificate(
        name="finite_lower_set",
        exact=True,
        theorem_target="finite saturated Hall-lower quotient condition",
        normalization="retained charges contain every ambient HN summand",
        checked_items=checked,
        discrepancies=tuple(discrepancies),
        source_modules=("compute.lib.bps_positive_truncation",),
    )


