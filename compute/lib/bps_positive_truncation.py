def transition_certificate(
    small: BPSMotivicTruncation,
    big: BPSMotivicTruncation,
) -> Certificate:
    """Exact finite transition check for a Hall-lower quotient map."""

    small_charges = set(small.charges.charges)
    big_charges = set(big.charges.charges)
    discrepancies = []
    checked = 0
    if not small_charges <= big_charges:
        missing = sorted(
            (charge.coords for charge in small_charges - big_charges),
            key=str,
        )
        discrepancies.append({
            "check": "retained charges restrict from larger quotient",
            "missing": missing,
        })
    lower = finite_lower_set_certificate(small, tuple(big.charges.charges))
    checked += lower.checked_items
    for discrepancy in lower.discrepancies:
        enriched = dict(discrepancy)
        enriched["check"] = "ambient lower-set transition"
        discrepancies.append(enriched)
    for alpha in small_charges:
        for beta in small_charges:
            checked += 1
            total = alpha + beta
            small_product = small.product_class(alpha, beta)
            big_product = (
                big.product_class(alpha, beta)
                if alpha in big_charges and beta in big_charges
                else MotivicClass.zero()
            )
            projected_big_product = (
                big_product if total in small_charges else MotivicClass.zero()
            )
            if small_product != projected_big_product:
                discrepancies.append({
                    "check": "Hall product restriction",
                    "alpha": alpha.coords,
                    "beta": beta.coords,
                    "small": repr(small_product),
                    "projected_big": repr(projected_big_product),
                })
    return Certificate(
        name="transition",
        exact=True,
        theorem_target="finite Hall-lower transition and pro-completion compatibility",
        normalization="larger quotient restricts to smaller quotient by a closed Hall ideal",
        checked_items=checked,
        discrepancies=tuple(discrepancies),
        source_modules=("compute.lib.bps_positive_truncation",),
    )


