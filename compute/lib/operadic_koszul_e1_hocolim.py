def conifold_bar_cobar_explicit(max_arity: int = 4) -> Dict[str, Any]:
    """Explicit bar-cobar computation for the conifold hocolim.

    Sets up the bar-cobar adjunction for the conifold CoHA and
    verifies Ω^{E₁}(B^{E₁}(A_conifold)) ≃ A_conifold.

    The conifold CoHA (in the flopped chamber) has:
      Generators: e₁ (1,0), e₂ (0,1), e₁₂ (1,1)
      Products: e₁ * e₂ = e₁₂, e₂ * e₁ = e₁₂ (with twist)
      All other products = 0

    The bar complex B^{E₁}:
      Arity 1: {e₁, e₂, e₁₂} -- dim = 3
      Arity 2: {e_i ⊗ e_j} -- dim = 9
        d([e₁|e₂]) = [e₁₂]  (from m₂(e₁,e₂) = e₁₂)
        d([e₂|e₁]) = [e₁₂]  (from m₂(e₂,e₁) = e₁₂)
        d([others]) = 0
      Arity 3: {e_i ⊗ e_j ⊗ e_k} -- dim = 27
    """
    e1 = HocolimGenerator("e1", charge=(1, 0), degree=0)
    e2 = HocolimGenerator("e2", charge=(0, 1), degree=0)
    e12 = HocolimGenerator("e12", charge=(1, 1), degree=0)

    products = {
        ("e1", "e2"): (Fraction(1), "e12"),
        ("e2", "e1"): (Fraction(1), "e12"),
        ("e1", "e1"): None,
        ("e2", "e2"): None,
        ("e1", "e12"): None,
        ("e12", "e1"): None,
        ("e2", "e12"): None,
        ("e12", "e2"): None,
        ("e12", "e12"): None,
    }

    bc = HocolimBarCobar(
        generators=[e1, e2, e12],
        products=products,
        kappa=Fraction(0),
        name="Conifold",
    )

    # Compute bar dimensions
    bar_dims = {n: bc.bar_dimension_at_arity(n) for n in range(1, max_arity + 1)}

    # Verify d² = 0 on arity-3 elements
    from itertools import product as iterproduct
    d_sq_results = {}
    for combo in iterproduct([e1, e2, e12], repeat=3):
        elem = BarElement(factors=tuple(combo))
        key = "|".join(g.name for g in combo)
        d_sq_results[key] = bc.d_squared_zero(elem)

    # Verify bar-cobar inversion
    inversion = bc.verify_bar_cobar_inversion(max_arity)

    # Bar differential action on arity-2 elements
    bar_diff_arity2 = {}
    for g1 in [e1, e2, e12]:
        for g2 in [e1, e2, e12]:
            elem = BarElement(factors=(g1, g2))
            d_elem = bc.bar_differential(elem)
            bar_diff_arity2[f"[{g1.name}|{g2.name}]"] = [str(t) for t in d_elem]

    # Count nontrivial bar differentials at arity 2
    nontrivial_d2 = sum(1 for v in bar_diff_arity2.values() if v)

    return {
        "bar_dims": bar_dims,
        "d_squared_zero_arity3": d_sq_results,
        "all_d_sq_zero": all(d_sq_results.values()),
        "bar_diff_arity2": bar_diff_arity2,
        "nontrivial_d2_count": nontrivial_d2,
        "inversion": inversion,
        "bar_euler_char": bc.bar_euler_char_exact(),
    }


def c3_bar_cobar_explicit(max_arity: int = 4) -> Dict[str, Any]:
    """Explicit bar-cobar computation for C³ (Heisenberg).

    The Heisenberg H₁ has one generator a with no bracket:
      a(z)a(w) ~ 1/(z-w)² (second-order pole only).
      m₂(a, a) = 0.

    The bar complex B^{E₁}(H₁):
      Arity n: dim = 1 (single generator, r=1).
      d = 0 everywhere (no bracket).

    The bar-cobar is trivially invertible:
      Ω^{E₁}(B^{E₁}(H₁)) ≃ H₁ because the bar has zero differential.
    """
    a = HocolimGenerator("a", charge=(1,), degree=0)

    products = {("a", "a"): None}

    bc = HocolimBarCobar(
        generators=[a],
        products=products,
        kappa=Fraction(1),
        name="C³",
    )

    bar_dims = {n: bc.bar_dimension_at_arity(n) for n in range(1, max_arity + 1)}

    # d = 0 everywhere
    d_results = {}
    for n in range(2, max_arity + 1):
        elem = BarElement(factors=tuple([a] * n))
        d = bc.bar_differential(elem)
        d_results[n] = len(d) == 0

    inversion = bc.verify_bar_cobar_inversion(max_arity)

    return {
        "bar_dims": bar_dims,
        "all_d_zero": all(d_results.values()),
        "d_results": d_results,
        "inversion": inversion,
        "bar_euler_char": bc.bar_euler_char_exact(),
    }


