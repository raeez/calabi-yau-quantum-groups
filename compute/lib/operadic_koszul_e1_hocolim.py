def en_koszul_comparison_table(max_n: int = 6, max_arity: int = 6) -> List[Dict[str, Any]]:
    """Comparison table: Koszul duality across E_n operads.

    Generates data for:
      n=1: E₁ = Ass, self-dual, shift 1
      n=2: E₂, self-dual, shift 2
      n=3: E₃, self-dual, shift 3
      ...
      n=∞: E_∞ = Com, NOT self-dual, dual = Lie
    """
    table = []

    for n in range(1, max_n + 1):
        data = en_koszul_data(n, max_arity)
        row = {
            "n": n,
            "operad": f"E_{n}",
            "is_self_dual": data.is_self_dual,
            "koszul_shift": data.koszul_shift,
            "dual_name": data.dual_operad_name,
            "dim_at_arity_3": data.arity_dims.get(3, 0),
            "dual_dim_at_arity_3": data.dual_arity_dims.get(3, 0),
        }
        table.append(row)

    # E_∞ = Com
    data_inf = en_koszul_data(10000, max_arity)  # use large n as proxy
    row_inf = {
        "n": "inf",
        "operad": "E_inf = Com",
        "is_self_dual": data_inf.is_self_dual,
        "koszul_shift": 0,
        "dual_name": data_inf.dual_operad_name,
        "dim_at_arity_3": data_inf.arity_dims.get(3, 0),
        "dual_dim_at_arity_3": data_inf.dual_arity_dims.get(3, 0),
    }
    table.append(row_inf)

    return table


