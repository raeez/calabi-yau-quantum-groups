#  9.  MASTER VERIFICATION
# =========================================================================

def master_verification() -> Dict[str, Any]:
    """Run all verifications and return comprehensive results.

    This is the top-level entry point for the operadic Koszul duality
    theory for the E₁ hocolim.

    Checks:
    1. E₁ self-duality (4 paths)
    2. E_∞ non-self-duality
    3. Bar-cobar inversion for C³
    4. Bar-cobar inversion for conifold
    5. Koszulness of Y⁺(ĝl₁)
    6. Koszulness of CoHA(conifold)
    7. Koszulness of CoHA(local P²)
    8. Curved bar-cobar for quintic (κ = -25/3)
    9. Minimal model for conifold (m₂, m₃)
    10. Formality of conifold hocolim
    """
    results = {}

    # 1. E₁ self-duality
    sd = verify_e1_self_duality()
    results["e1_self_duality"] = sd["e1_is_self_dual"]

    # 2. E_∞ non-self-duality
    e_inf = en_koszul_data(10000)
    results["e_inf_not_self_dual"] = not e_inf.is_self_dual

    # 3. C³ bar-cobar inversion
    c3 = c3_bar_cobar_explicit()
    results["c3_inversion"] = c3["inversion"]["inversion_holds"]

    # 4. Conifold bar-cobar inversion
    con = conifold_bar_cobar_explicit()
    results["conifold_inversion"] = con["inversion"]["inversion_holds"]
    results["conifold_d_sq_zero"] = con["all_d_sq_zero"]

    # 5. Koszulness of Y⁺(ĝl₁)
    k_y = check_koszulness_yangian_gl1()
    results["yangian_gl1_koszul"] = k_y.is_koszul

    # 6. Koszulness of CoHA(conifold)
    k_con = check_koszulness_coha_conifold()
    results["coha_conifold_koszul"] = k_con.is_koszul

    # 7. Koszulness of CoHA(local P²)
    k_p2 = check_koszulness_coha_local_p2()
    results["coha_local_p2_koszul"] = k_p2.is_koszul

    # 8. Curved bar-cobar for quintic
    q = curved_bar_cobar_quintic()
    results["quintic_kappa"] = q.kappa
    results["quintic_is_curved"] = q.is_curved
    results["quintic_kappa_equals_minus_25_over_3"] = (q.kappa == Fraction(-25, 3))

    # 9. Minimal model for conifold
    mm = minimal_model_conifold()
    results["conifold_m3_zero"] = mm.is_formal
    results["conifold_formality_obstruction"] = mm.formality_obstruction

    # 10. Formality
    f_con = check_formality_conifold()
    results["conifold_formal"] = f_con.is_formal
    f_c3 = check_formality_c3()
    results["c3_formal"] = f_c3.is_formal

    # Overall
    results["all_pass"] = all([
        results["e1_self_duality"],
        results["e_inf_not_self_dual"],
        results["c3_inversion"],
        results["conifold_inversion"],
        results["conifold_d_sq_zero"],
        results["yangian_gl1_koszul"],
        results["coha_conifold_koszul"],
        results["coha_local_p2_koszul"],
        results["quintic_kappa_equals_minus_25_over_3"],
        results["conifold_m3_zero"],
        results["conifold_formal"],
        results["c3_formal"],
    ])

    return results
