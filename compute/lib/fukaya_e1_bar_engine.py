def _koszul_sign_e1(degrees: Sequence[int], pos: int) -> int:
    r"""Koszul sign for E1 bar differential at position pos.

    For [a_1|...|a_n] with desuspended degrees |s^{-1}a_j| = |a_j| - 1,
    the sign for multiplying at position pos is:
        (-1)^{sum_{j=0}^{pos} (|a_j| - 1)}
    """
    exp = sum(d - 1 for d in degrees[:pos + 1])
    return (-1) ** exp


def _koszul_sign_ainfinity(degrees: Sequence[int], start: int, length: int) -> int:
    r"""Koszul sign for mu_k applied at positions start..start+length-1.

    For the A-infinity bar differential:
        d([a_1|...|a_n]) = sum_{k>=2, i} (-1)^{eps} [a_1|...|mu_k(a_i,...)|...|a_n]
    where eps = sum_{j<i} (|s^{-1}a_j|) = sum_{j<i} (|a_j| - 1).
    """
    exp = sum(d - 1 for d in degrees[:start])
    return (-1) ** exp


def _binomial(n: int, k: int) -> int:
    """Exact binomial coefficient."""
    if k < 0 or k > n:
        return 0
    return math.comb(n, k)


