@dataclass(frozen=True)
class E1BarElementFuk:
    """Element [a_1|...|a_n] of the E1 bar complex of A_{Fuk}.

    The factors are Floer generators, ordered (E1 = associative bar).
    """
    factors: Tuple[FloerGenerator, ...]
    coeff: object = Fraction(1)

    @property
    def arity(self) -> int:
        return len(self.factors)

    @property
    def total_degree(self) -> int:
        """Total cohomological degree after desuspension.

        |s^{-1}a_1 otimes ... otimes s^{-1}a_n| = sum(|a_i| - 1).
        """
        return sum(g.degree - 1 for g in self.factors)

    def __repr__(self) -> str:
        inner = "|".join(str(g) for g in self.factors)
        if self.coeff == 1:
            return f"[{inner}]"
        return f"{self.coeff}*[{inner}]"


class FukayaE1BarComplex:
    r"""E1 bar complex B^{E1}(A_{Fuk(X)}) for a CY3 Lagrangian.

    The E1 bar differential has TWO components:

    (a) The binary part d_2 (from mu_2):
        d_2([a_1|...|a_n]) = sum_{i=0}^{n-2} +/- [a_1|...|mu_2(a_i,a_{i+1})|...|a_n]

    (b) The higher A-infinity part d_k (from mu_k, k >= 3):
        d_k([a_1|...|a_n]) = sum_i +/- [a_1|...|mu_k(a_i,...,a_{i+k-1})|...|a_n]

    The FULL differential is d = sum_{k>=2} d_k.

    For formal A-infinity algebras (T*M with M exact): d = d_2 only.
    For non-formal algebras (quintic): d = d_2 + d_3 + ... .

    Parameters
    ----------
    floer : FloerCohomology
        The Floer cohomology data with A-infinity structure.
    max_arity : int
        Maximum bar arity to compute.
    """

    def __init__(self, floer: FloerCohomology, max_arity: int = 6):
        self.floer = floer
        self.max_arity = max_arity

    # ----- Dimensions -----

    def dimension_at_arity(self, n: int) -> int:
        """dim B^{E1}_n = r^n where r = rank HF*(L,L)."""
        if n < 1:
            return 0
        return self.floer.rank ** n

    def e_inf_dimension_at_arity(self, n: int) -> int:
        """dim B^{E_inf}_n = C(n+r-1, r-1) for comparison."""
        if n < 1:
            return 0
        r = self.floer.rank
        return _binomial(n + r - 1, r - 1)

    def dimension_table(self, max_n: int = 6) -> Dict[int, Dict[str, int]]:
        """Table of E1 vs E_inf dimensions."""
        table = {}
        for n in range(1, max_n + 1):
            d_e1 = self.dimension_at_arity(n)
            d_einf = self.e_inf_dimension_at_arity(n)
            table[n] = {
                'E1': d_e1,
                'E_inf': d_einf,
                'ratio': Fraction(d_e1, d_einf) if d_einf > 0 else None,
            }
        return table

    # ----- Bar differential -----

    def d_E1_binary(self, elem: E1BarElementFuk) -> List[E1BarElementFuk]:
        """Binary part d_2 of the E1 bar differential (from mu_2).

        d_2([a_1|...|a_n]) = sum_{i=0}^{n-2} (-1)^{eps_i}
            [a_1|...|mu_2(a_i, a_{i+1})|...|a_n]
        """
        factors = elem.factors
        n = len(factors)
        if n < 2:
            return []

        result = []
        for i in range(n - 1):
            mu_result = self.floer.mu_k(factors[i].name, factors[i + 1].name)
            if mu_result is None:
                continue
            coeff_mu, gen_mu = mu_result
            degrees = [g.degree for g in factors]
            sign = _koszul_sign_e1(degrees, i)
            new_factors = factors[:i] + (gen_mu,) + factors[i + 2:]
            new_coeff = elem.coeff * coeff_mu * sign
            result.append(E1BarElementFuk(factors=new_factors, coeff=new_coeff))

        return result

    def d_E1_higher(self, elem: E1BarElementFuk, k: int) -> List[E1BarElementFuk]:
        """Higher A-infinity part d_k of the E1 bar differential (from mu_k).

        d_k([a_1|...|a_n]) applies mu_k to each consecutive k-tuple.
        """
        factors = elem.factors
        n = len(factors)
        if n < k:
            return []

        result = []
        for i in range(n - k + 1):
            names = tuple(factors[j].name for j in range(i, i + k))
            mu_result = self.floer.mu_k(*names)
            if mu_result is None:
                continue
            coeff_mu, gen_mu = mu_result
            degrees = [g.degree for g in factors]
            sign = _koszul_sign_ainfinity(degrees, i, k)
            new_factors = factors[:i] + (gen_mu,) + factors[i + k:]
            new_coeff = elem.coeff * coeff_mu * sign
            result.append(E1BarElementFuk(factors=new_factors, coeff=new_coeff))

        return result

    def d_E1_full(self, elem: E1BarElementFuk) -> List[E1BarElementFuk]:
        """Full E1 bar differential d = sum_{k>=2} d_k.

        Uses all A-infinity operations present in the Floer data.
        """
        result = self.d_E1_binary(elem)
        # Higher mu_k terms: try k = 3, 4, ... up to arity of elem
        for k in range(3, elem.arity + 1):
            result.extend(self.d_E1_higher(elem, k))
        return result

    def d_squared_binary(self, elem: E1BarElementFuk) -> List[E1BarElementFuk]:
        """Compute d_2^2(elem). Should be zero for associative mu_2."""
        first = self.d_E1_binary(elem)
        result = []
        for term in first:
            result.extend(self.d_E1_binary(term))
        return result

    def verify_d_squared_zero(self, elem: E1BarElementFuk, full: bool = False
                              ) -> bool:
        """Check d^2 = 0 on a given element.

        If full=True, uses the full d (all mu_k). Otherwise just d_2.
        """
        if full:
            first_pass = self.d_E1_full(elem)
            second_pass = []
            for term in first_pass:
                second_pass.extend(self.d_E1_full(term))
        else:
            second_pass = self.d_squared_binary(elem)

        if not second_pass:
            return True

        # Collect and check cancellation
        coeff_map: Dict[Tuple, object] = defaultdict(lambda: Fraction(0))
        for term in second_pass:
            coeff_map[term.factors] += term.coeff

        return all(v == 0 for v in coeff_map.values())

    # ----- Basis enumeration -----

    def basis_at_arity(self, n: int) -> List[E1BarElementFuk]:
        """Generate all E1 bar basis elements at arity n."""
        from itertools import product as iterproduct
        gens = self.floer.generators
        elements = []
        for combo in iterproduct(gens, repeat=n):
            elements.append(E1BarElementFuk(factors=combo))
        return elements

    # ----- Cohomology -----

    def bar_cohomology_dimension(self, n: int) -> Dict[str, Any]:
        """Compute dim H^*(B^{E1}_n) by enumerating cycles and boundaries.

        This is exact for small arity/rank. For the Heisenberg-like case
        (mu_2 = 0 on generators): all differentials vanish, so
        H^* = B^{E1} itself.
        """
        basis = self.basis_at_arity(n)
        # Compute image of d: count elements with nonzero d
        kernel_count = 0
        for elem in basis:
            d_result = self.d_E1_binary(elem)
            if not d_result or all(t.coeff == 0 for t in d_result):
                kernel_count += 1

        # For the image: count elements in B^{E1}_{n+1} whose d lands in B^{E1}_n
        if n + 1 <= self.max_arity:
            basis_np1 = self.basis_at_arity(n + 1)
            image_elements = []
            for elem in basis_np1:
                d_result = self.d_E1_binary(elem)
                image_elements.extend(d_result)
            image_dim = len(set(t.factors for t in image_elements if t.coeff != 0))
        else:
            image_dim = 0

        return {
            'arity': n,
            'total_dim': len(basis),
            'kernel_dim': kernel_count,
            'image_dim': image_dim,
            'cohomology_dim_lower_bound': kernel_count - image_dim,
        }

    # ----- Deconcatenation coproduct -----

    def deconcatenation(self, elem: E1BarElementFuk
                        ) -> List[Tuple[E1BarElementFuk, E1BarElementFuk]]:
        """Deconcatenation coproduct.

        Delta([a_1|...|a_n]) = sum_{i=1}^{n-1} [a_1|...|a_i] otimes [a_{i+1}|...|a_n]
        """
        result = []
        n = elem.arity
        for i in range(1, n):
            left = E1BarElementFuk(factors=elem.factors[:i], coeff=elem.coeff)
            right = E1BarElementFuk(factors=elem.factors[i:])
            result.append((left, right))
        return result


