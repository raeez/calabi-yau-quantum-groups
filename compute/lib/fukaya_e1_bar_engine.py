def conifold_s3_floer() -> FloerCohomology:
    r"""Floer cohomology of S^3 in the deformed conifold T*S^3.

    The deformed conifold X = T*S^3 is a CY3 with a unique compact
    Lagrangian L = S^3 (the zero section).

    HF*(L, L) = H*(S^3; k) = k . 1 + k . omega
    where 1 is the unit in degree 0 and omega is the volume form in degree 3.

    A-infinity structure:
        mu_1 = 0  (S^3 is unobstructed: no holomorphic discs by exactness).
        mu_2(1, x) = x = mu_2(x, 1)  (unit axiom).
        mu_2(omega, omega) = 0  (degree: 3 + 3 = 6 > 3 = dim, so zero).
        mu_k = 0 for k >= 3  (the A-infinity algebra is FORMAL by exactness
        of T*S^3; the Fukaya category of an exact manifold is formal).

    The key fact: T*S^3 is EXACT (the symplectic form omega = d(lambda)
    is exact), so there are no pseudo-holomorphic discs (they would have
    positive area = integral of omega over the disc = integral of d(lambda)
    = integral of lambda over the boundary = 0 by exactness on L).

    Thus the A-infinity algebra is STRICTLY associative with trivial
    higher products. The bar differential d_{E1} uses only mu_2.

    Shadow invariants:
        kappa: since HF has rank 2 (dims 0 and 3), with the algebra being
        an exterior algebra Lambda(omega), the shadow class is G.
        kappa = 1 (from the single pair of Poincare-dual generators).
    """
    unit = FloerGenerator("1", degree=0)
    omega = FloerGenerator("omega", degree=3)

    mu_data = {
        # mu_2: unit axiom
        ("1", "1"): (1, "1"),
        ("1", "omega"): (1, "omega"),
        ("omega", "1"): (1, "omega"),
        # mu_2(omega, omega) = 0 by degree (degree 6 > 3)
        # All mu_k for k >= 3 vanish by exactness/formality
    }

    return FloerCohomology(
        name="HF*(S^3, S^3) in T*S^3 (deformed conifold)",
        generators=(unit, omega),
        cy_dim=3,
        mu_k_data=mu_data,
    )


def quintic_real_locus_floer() -> FloerCohomology:
    r"""Floer cohomology of the real quintic L_R in the quintic threefold Q.

    The real quintic L_R = Q(R) = {[x_0:...:x_4] in Q : x_i in R} is a
    real 3-dimensional Lagrangian in Q.  Its topology depends on the
    defining equation; for the Fermat quintic x_0^5 + ... + x_4^5 = 0,
    the real locus is RP^3.

    Over a field k of characteristic 0:
        H*(RP^3; k) = k (concentrated in degree 0, since RP^3 is
        rationally a sphere S^3 in the sense that H_i(RP^3; Q) =
        Q for i=0, Z/2 for i=1,2, Z for i=3).

    CORRECTED: Over Q, H*(RP^3; Q) has:
        H^0 = Q, H^1 = 0, H^2 = 0, H^3 = Q   (dim = 2)
    The torsion in H^1 and H^2 is killed by rational coefficients.

    For the GENERIC real quintic (not necessarily Fermat), the topology
    of L_R varies.  Smith theory gives b_i(L_R; Z/2) <= b_i(Q; Z/2),
    and the Euler characteristic chi(L_R) = chi(Q)/2 = -100 or 0
    depending on the orientation.

    For computation, we use the simplest model: L_R = RP^3 over Q.

    A-infinity structure:
        mu_1 = 0  (Lagrangian is unobstructed: proved by Walcher for
        specific models).
        mu_2 = cup product on H*(RP^3; Q).
        Higher mu_k count holomorphic discs with boundary on L_R.
        These are NONTRIVIAL (unlike T*S^3, the quintic is not exact).

    The open GW invariants n^{open}_d (Walcher 2007) record disc counts.
    These contribute to the A-infinity operations and hence to the
    E1 bar differential.
    """
    unit = FloerGenerator("1", degree=0)
    vol = FloerGenerator("v", degree=3)

    # Over Q: mu_2 is the cup product on H*(RP^3; Q)
    # 1 is the unit; v . v = 0 (degree 6 > 3)
    mu_data = {
        ("1", "1"): (1, "1"),
        ("1", "v"): (1, "v"),
        ("v", "1"): (1, "v"),
    }

    return FloerCohomology(
        name="HF*(L_R, L_R) in quintic (L_R = RP^3 model)",
        generators=(unit, vol),
        cy_dim=3,
        mu_k_data=mu_data,
    )


def cotangent_s3_wrapped_floer() -> FloerCohomology:
    r"""Wrapped Floer cohomology of S^3 in T*S^3.

    The wrapped Fukaya category W(T*S^3) has the zero section S^3 as a
    generating object.  The wrapped Floer cohomology is:

        HW*(S^3, S^3) = C_{-*}(Omega S^3)  (chains on the based loop space)

    By the James construction:
        H_*(Omega S^3; k) = k[x]  with |x| = 2
    (polynomial algebra on a single generator of degree 2).

    Converting to cohomological grading:
        HW^{-n}(S^3, S^3) = H_n(Omega S^3) = k . x^{n/2}  if 2|n, else 0

    As a graded algebra: HW* = k[x] with x in degree -2.

    For our E1 bar complex, we TRUNCATE to a finite-dimensional model.
    The truncation at degree >= -2N gives generators {1, x, x^2, ..., x^N}.

    A-infinity structure:
        mu_2(x^a, x^b) = x^{a+b}  (polynomial multiplication)
        All higher mu_k = 0 (the polynomial algebra is strictly associative).

    We model this with N = 3 (truncation to degree >= -6, giving 4 generators).
    """
    gens = tuple(
        FloerGenerator(f"x^{i}", degree=-2 * i)
        for i in range(4)
    )

    # mu_2 is polynomial multiplication (truncated)
    mu_data = {}
    for i in range(4):
        for j in range(4):
            if i + j < 4:
                mu_data[(f"x^{i}", f"x^{j}")] = (1, f"x^{i + j}")

    return FloerCohomology(
        name="HW*(S^3, S^3) in T*S^3 (truncated at x^3)",
        generators=gens,
        cy_dim=3,
        mu_k_data=mu_data,
    )


def cotangent_3manifold_floer(manifold: str = "S3") -> FloerCohomology:
    r"""Floer cohomology for the zero-section in T*M, 3-manifold M.

    By Floer's theorem (for exact Lagrangians in cotangent bundles):
        HF*(M, M) = H*(M; k)

    The A-infinity structure is FORMAL (Abouzaid, Fukaya-Oh-Ohta-Ono):
    all higher mu_k for k >= 3 vanish up to quasi-isomorphism.

    Specific cases:
        M = S^3: H* = k[0] + k[3], exterior algebra Lambda(omega).
        M = T^3: H* = Lambda(a,b,c) with |a|=|b|=|c|=1, rank = 8.
        M = S^1 x S^2: H* = k[0] + k[1] + k[2] + k[3], rank = 4.
        M = RP^3: H*(RP^3; Q) = Q[0] + Q[3], rank = 2.
    """
    if manifold == "S3":
        return conifold_s3_floer()
    elif manifold == "T3":
        a = FloerGenerator("1", degree=0)
        b1 = FloerGenerator("a", degree=1)
        b2 = FloerGenerator("b", degree=1)
        b3 = FloerGenerator("c", degree=1)
        c1 = FloerGenerator("ab", degree=2)
        c2 = FloerGenerator("ac", degree=2)
        c3 = FloerGenerator("bc", degree=2)
        d = FloerGenerator("abc", degree=3)
        gens = (a, b1, b2, b3, c1, c2, c3, d)
        # mu_2 = exterior (wedge) product
        mu_data = {
            # unit
            ("1", "1"): (1, "1"),
            ("1", "a"): (1, "a"), ("1", "b"): (1, "b"), ("1", "c"): (1, "c"),
            ("1", "ab"): (1, "ab"), ("1", "ac"): (1, "ac"), ("1", "bc"): (1, "bc"),
            ("1", "abc"): (1, "abc"),
            ("a", "1"): (1, "a"), ("b", "1"): (1, "b"), ("c", "1"): (1, "c"),
            ("ab", "1"): (1, "ab"), ("ac", "1"): (1, "ac"), ("bc", "1"): (1, "bc"),
            ("abc", "1"): (1, "abc"),
            # wedge products
            ("a", "b"): (1, "ab"), ("b", "a"): (-1, "ab"),
            ("a", "c"): (1, "ac"), ("c", "a"): (-1, "ac"),
            ("b", "c"): (1, "bc"), ("c", "b"): (-1, "bc"),
            ("a", "bc"): (1, "abc"), ("bc", "a"): (-1, "abc"),
            ("b", "ac"): (-1, "abc"), ("ac", "b"): (1, "abc"),
            ("c", "ab"): (1, "abc"), ("ab", "c"): (-1, "abc"),
        }
        return FloerCohomology(
            name="HF*(T^3, T^3) in T*T^3",
            generators=gens, cy_dim=3, mu_k_data=mu_data,
        )
    elif manifold == "S1xS2":
        gens = (
            FloerGenerator("1", degree=0),
            FloerGenerator("alpha", degree=1),
            FloerGenerator("beta", degree=2),
            FloerGenerator("gamma", degree=3),
        )
        mu_data = {
            ("1", "1"): (1, "1"),
            ("1", "alpha"): (1, "alpha"), ("alpha", "1"): (1, "alpha"),
            ("1", "beta"): (1, "beta"), ("beta", "1"): (1, "beta"),
            ("1", "gamma"): (1, "gamma"), ("gamma", "1"): (1, "gamma"),
            ("alpha", "beta"): (1, "gamma"), ("beta", "alpha"): (-1, "gamma"),
        }
        return FloerCohomology(
            name="HF*(S^1 x S^2, S^1 x S^2) in T*(S^1 x S^2)",
            generators=gens, cy_dim=3, mu_k_data=mu_data,
        )
    elif manifold == "RP3":
        return quintic_real_locus_floer()
    else:
        raise ValueError(f"Unknown manifold: {manifold}")


