class AInfinityBarIdentification:
    r"""Identification of A-infinity structure with E1 bar differentials.

    The A-infinity operations mu_k of Fuk(X) are EXACTLY the components
    of the E1 bar differential:

        d^{E1} = sum_{k>=2} d_k

    where d_k([a_1|...|a_n]) = sum_i +/- [a_1|...|mu_k(a_i,...,a_{i+k-1})|...|a_n].

    This identification means:
    (1) mu_2 = the binary bar differential (Hochschild boundary).
    (2) mu_3 = the ternary correction (first obstruction to associativity).
    (3) mu_k for k >= 4 = higher bar differential corrections.
    (4) The A-infinity relations (sum +/- mu_o mu = 0) are EXACTLY d^2 = 0.

    Parameters
    ----------
    bar_cx : FukayaE1BarComplex
        The E1 bar complex built from Floer data.
    """

    def __init__(self, bar_cx: FukayaE1BarComplex):
        self.bar_cx = bar_cx

    def mu_k_from_bar_diff(self, k: int) -> str:
        """Describe how mu_k appears in the bar differential."""
        return (f"mu_{k} = d_{k} component of d^{{E1}}: "
                f"contracts {k} adjacent factors via the "
                f"degree-{k} A-infinity operation.")

    def verify_ainfinity_relation_from_d_squared(
        self, elem: E1BarElementFuk
    ) -> Dict[str, Any]:
        """Verify A-infinity relation sum +/- mu_o(mu) = 0 via d^2 = 0.

        The A-infinity relations are EQUIVALENT to d^2 = 0 on the bar
        complex. We verify both sides.
        """
        d_squared_zero = self.bar_cx.verify_d_squared_zero(elem, full=True)
        return {
            'd_squared_zero': d_squared_zero,
            'ainfinity_relation_satisfied': d_squared_zero,
            'element': str(elem),
        }

    def bar_differential_term_count(self, n: int) -> Dict[str, int]:
        """Count d^{E1} terms at arity n from each mu_k component.

        At arity n, the d_k component contributes (n - k + 1) terms
        (one for each consecutive k-tuple in a length-n word).
        """
        counts = {}
        for k in range(2, n + 1):
            terms = n - k + 1
            if terms > 0:
                counts[f'mu_{k}'] = terms
        total = sum(counts.values())
        return {
            'arity': n,
            'component_counts': counts,
            'total_terms': total,
        }

    def formal_implies_d_equals_d2(self) -> bool:
        """Whether the A-infinity algebra is formal (d = d_2 only).

        For cotangent bundles T*M: YES (all mu_k = 0 for k >= 3).
        For the quintic: NO (holomorphic discs contribute mu_k != 0).
        """
        floer = self.bar_cx.floer
        # Check if any mu_k for k >= 3 is stored
        for key in floer.mu_k_data:
            if len(key) >= 3:
                return False
        return True


