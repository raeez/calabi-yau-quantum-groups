class QuinticE1Engine:
    r"""E1 bar complex computations for the quintic threefold.

    The quintic Q = {x_0^5 + ... + x_4^5 = 0} in P^4 is the canonical
    compact CY3 example. Its Fukaya category is rich with disc contributions.

    The E1 bar complex of A_{Fuk(Q)} incorporates:
    - The binary product mu_2 (cup product on Floer cohomology).
    - Higher products mu_k from holomorphic disc counts.
    - The full E1 differential d = sum d_k.

    The shadow obstruction tower encodes the genus-g GW potential
    via F_g = kappa * lambda_g^{FP} on the scalar (constant-map) lane.
    Instanton corrections are SEPARATE from the shadow tower.

    Hodge data: h^{1,1} = 1, h^{2,1} = 101, chi = -200.
    kappa = -chi = 200 (from constant maps).
    """

    CHI = -200
    H11 = 1
    H21 = 101

    # Genus-0 GV invariants (CDGP)
    GV_GENUS0 = {1: 2875, 2: 609250, 3: 317206375, 4: 242467530000}

    # Walcher disc invariants
    DISC_INVARIANTS = {1: 30, 2: 0, 3: 2760, 4: 0, 5: 5765760}

    def __init__(self):
        self.floer = quintic_real_locus_floer()
        self.bar_cx = FukayaE1BarComplex(self.floer, max_arity=6)
        self.shadow = FukayaE1ShadowTower(self.bar_cx)

    def kappa_constant_map(self) -> Fraction:
        """kappa from constant maps: kappa = -chi(Q) = 200."""
        return Fraction(-self.CHI)

    def genus_g_constant_map(self, g: int) -> Fraction:
        """F_g from constant maps: kappa * lambda_g^{FP}."""
        kappa = self.kappa_constant_map()
        if g < 1 or g not in _FP_LAMBDA:
            raise ValueError(f"genus {g} not available")
        return kappa * _FP_LAMBDA[g]

    def gv_multicover(self, max_d: int = 5) -> Dict[int, Fraction]:
        """Genus-0 GW from GV via multi-cover: N_{0,d} = sum_{k|d} n_0(d/k)/k^3."""
        result = {}
        for d in range(1, max_d + 1):
            val = Fraction(0)
            for k in _divisors(d):
                dprime = d // k
                if dprime in self.GV_GENUS0:
                    val += Fraction(self.GV_GENUS0[dprime], k ** 3)
            result[d] = val
        return result

    def e1_bar_data(self) -> Dict[str, Any]:
        """E1 bar complex data for the quintic."""
        return {
            'floer_rank': self.floer.rank,
            'kappa': self.kappa_constant_map(),
            'dim_arity_1': self.bar_cx.dimension_at_arity(1),
            'dim_arity_2': self.bar_cx.dimension_at_arity(2),
            'dim_arity_3': self.bar_cx.dimension_at_arity(3),
            'chi': self.CHI,
        }

    def hms_bar_comparison(self) -> Dict[str, Any]:
        """HMS comparison for quintic/mirror quintic."""
        return HMSBarComparison.quintic_comparison()


def _divisors(n: int) -> List[int]:
    """All positive divisors of n."""
    divs = []
    for d in range(1, int(math.isqrt(n)) + 1):
        if n % d == 0:
            divs.append(d)
            if d != n // d:
                divs.append(n // d)
    return sorted(divs)


