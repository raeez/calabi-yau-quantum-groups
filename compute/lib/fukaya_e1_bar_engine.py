class OpenGWE1Shadow:
    r"""Open Gromov-Witten invariants as E1 shadow amplitudes.

    The open GW invariants (counting holomorphic discs with boundary on L)
    are the E1 shadow obstruction tower evaluated on L:

        F_g^{open}(L) = <L | F_g^{E1}(A_{Fuk}) | L>

    At genus 0: the disc invariant is the superpotential W(L).
    At genus g >= 1: the open amplitude is kappa * lambda_g^{FP} on the
    scalar lane (for formal Lagrangians).

    KEY DISTINCTION:
    - CLOSED GW invariants = E_inf shadow of the CLOSED-string chiral algebra.
    - OPEN GW invariants = E1 shadow evaluated on a Lagrangian boundary condition.
    - The open-closed map OC: HH_*(WFuk) -> SH* mediates between the two.
    """

    @staticmethod
    def conifold_genus0_disc(degree: int = 1) -> Fraction:
        r"""Genus-0 open GW of the conifold (disc invariant).

        For the resolved conifold O(-1)+O(-1) -> P^1 with Lagrangian
        being the real slice (Aganagic-Vafa brane), the open GW
        generating function at genus 0 is:

            W(X) = sum_{d>=1} (-1)^{d-1}/d^2 * X^d = Li_2(-X)

        where Li_2 is the dilogarithm.  The disc invariant at degree d is:
            n^{open}_{0,d} = (-1)^{d-1}/d^2  [NOT integer; these are virtual]

        The GV reformulation: the open BPS invariant is n^{open,BPS}_1 = 1
        (one disc), and higher degrees come from multi-covering.
        """
        return Fraction((-1) ** (degree - 1), degree ** 2)

    @staticmethod
    def conifold_open_gw_gf(max_d: int = 10) -> Dict[int, Fraction]:
        """Generating function of genus-0 open GW of the conifold."""
        return {d: Fraction((-1) ** (d - 1), d ** 2) for d in range(1, max_d + 1)}

    @staticmethod
    def quintic_disc_invariants() -> Dict[int, int]:
        """Walcher's disc invariants for the quintic real Lagrangian.

        Source: Walcher, "Opening mirror symmetry on the quintic" (2007).
        """
        return {1: 30, 2: 0, 3: 2760, 4: 0, 5: 5765760}

    @staticmethod
    def open_shadow_genus_g(kappa: Fraction, g: int) -> Fraction:
        r"""Open shadow amplitude at genus g on the scalar lane.

        F_g^{open}(L) = kappa^{E1}(L) * lambda_g^{FP}

        where kappa^{E1}(L) is the E1 modular characteristic of the
        Lagrangian L (from the Floer cohomology data).
        """
        if g < 1 or g not in _FP_LAMBDA:
            raise ValueError(f"genus {g} not available")
        return kappa * _FP_LAMBDA[g]

    @staticmethod
    def open_closed_relation_conifold() -> Dict[str, Any]:
        r"""Open/closed relation for the conifold at genus 0.

        CLOSED: N_{0,d} = 1/d^3  (Aspinwall-Morrison from a single P^1)
        OPEN: n^{open}_{0,d} = (-1)^{d-1}/d^2

        Relation: n^{open}_{0,d} = (-1)^{d-1} * d * N_{0,d}

        This is the disc-to-sphere relation: each degree-d disc wraps
        the P^1 with a factor of d (the degree of the boundary map
        from the disc boundary to the Lagrangian).
        """
        relations = {}
        for d in range(1, 11):
            n_open = Fraction((-1) ** (d - 1), d ** 2)
            n_closed = Fraction(1, d ** 3)
            ratio = n_open / n_closed if n_closed != 0 else None
            relations[d] = {
                'open': n_open,
                'closed': n_closed,
                'ratio': ratio,
                'expected_ratio': (-1) ** (d - 1) * d,
            }
        return relations


