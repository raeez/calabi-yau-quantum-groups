class FukayaE1ShadowTower:
    r"""Shadow obstruction tower of A_{Fuk(X)} in the E1 setting.

    The E1 shadow obstruction tower Theta^{E1}_{Fuk} encodes:
        - kappa^{E1}: the E1 modular characteristic (genus-1 invariant).
        - C^{E1}: the cubic shadow (from mu_3 / A-infinity non-formality).
        - Q^{E1}: the quartic shadow (from mu_4).
        - F_g^{E1}: the genus-g scalar shadow amplitude.

    For formal Lagrangians (T*M): all higher shadows vanish (class G).
    For non-formal Lagrangians (quintic L_R): higher shadows are nonzero.
    """

    def __init__(self, bar_cx: FukayaE1BarComplex):
        self.bar_cx = bar_cx

    def kappa_e1(self) -> Fraction:
        """E1 modular characteristic.

        For formal algebras with r generators in complementary degrees
        (satisfying CY3 Poincare duality): kappa = r/2 where r is the
        rank of the generating space excluding the unit.

        For S^3 in T*S^3: HF has rank 2, one Poincare-dual pair,
        kappa = 1 (one bosonic degree of freedom).

        For T^3 in T*T^3: HF has rank 8 = 2^3, three Poincare-dual pairs
        plus two self-dual generators, kappa = 4 (from chi(T^3)/2... no).

        More precisely: kappa counts the number of INDEPENDENT bosonic
        modes in the genus-1 torus amplitude. For a formal algebra with
        generators in complementary degrees summing to d=3:
            kappa = number of degree-0/degree-3 pairs = b_0
        since each such pair contributes one bosonic propagator on the torus.

        For S^3: b_0 = 1 pair -> kappa = 1.
        For T^3: b_0 = 1, b_1 = 3, b_2 = 3, b_3 = 1.
            Pairs: (b_0, b_3) = 1 pair, (b_1, b_2) = 3 pairs -> kappa = 4.
        For S^1 x S^2: b_0 = 1, b_1 = 1, b_2 = 1, b_3 = 1.
            Pairs: (b_0, b_3) = 1 pair, (b_1, b_2) = 1 pair -> kappa = 2.
        """
        floer = self.bar_cx.floer
        b = floer.betti_numbers()
        d = floer.cy_dim

        # Count Poincare-dual pairs contributing to kappa
        kappa = Fraction(0)
        counted = set()
        for deg, count in b.items():
            dual_deg = d - deg
            if dual_deg in b and deg not in counted and dual_deg not in counted:
                pairs = min(count, b[dual_deg])
                if deg == dual_deg:
                    # Self-dual: contributes pairs/2 to kappa
                    kappa += Fraction(pairs, 2)
                else:
                    kappa += Fraction(pairs)
                counted.add(deg)
                counted.add(dual_deg)

        return kappa

    def shadow_amplitude(self, g: int) -> Fraction:
        """F_g^{E1} = kappa^{E1} * lambda_g^{FP} on the scalar lane."""
        kappa = self.kappa_e1()
        if g < 1 or g not in _FP_LAMBDA:
            raise ValueError(f"genus {g} not available")
        return kappa * _FP_LAMBDA[g]

    def shadow_depth_class(self) -> str:
        """Shadow depth classification.

        Formal A-infinity algebras: class G (Gaussian, depth 2).
        Non-formal: class M (mixed, infinite depth) generically.
        """
        aid = AInfinityBarIdentification(self.bar_cx)
        if aid.formal_implies_d_equals_d2():
            return "G"
        return "M"

    def full_shadow_data(self) -> Dict[str, Any]:
        """Complete shadow obstruction tower data."""
        kappa = self.kappa_e1()
        depth_class = self.shadow_depth_class()
        data = {
            'kappa_E1': kappa,
            'depth_class': depth_class,
            'shadow_depth': 2 if depth_class == 'G' else 'infinite',
            'F_1': self.shadow_amplitude(1),
            'F_2': self.shadow_amplitude(2),
            'cubic_shadow': Fraction(0) if depth_class == 'G' else 'nonzero',
            'quartic_shadow': Fraction(0) if depth_class == 'G' else 'nonzero',
        }
        return data


