class E1BarGeneratingFunction:
    r"""Generating functions for E1 bar complex dimensions.

    For r generators: dim B^{E1}_n = r^n.
    Generating function: sum_{n>=1} r^n t^n = rt/(1-rt).

    For comparison:
    E_inf: dim B^{E_inf}_n = C(n+r-1, r-1).
    GF: (1/(1-t)^r - 1) = sum_{n>=1} C(n+r-1, r-1) t^n.

    The ratio r^n / C(n+r-1, r-1) grows exponentially for r >= 2.
    """

    @staticmethod
    def e1_gf_coefficient(r: int, n: int) -> int:
        """Coefficient of t^n in the E1 bar GF = r^n."""
        return r ** n

    @staticmethod
    def einf_gf_coefficient(r: int, n: int) -> int:
        """Coefficient of t^n in the E_inf bar GF = C(n+r-1, r-1)."""
        return _binomial(n + r - 1, r - 1)

    @staticmethod
    def ratio(r: int, n: int) -> Fraction:
        """Ratio dim B^{E1}_n / dim B^{E_inf}_n."""
        e1 = r ** n
        einf = _binomial(n + r - 1, r - 1)
        if einf == 0:
            return Fraction(0)
        return Fraction(e1, einf)

    @staticmethod
    def asymptotic_ratio(r: int, n: int) -> float:
        """Asymptotic ratio for large n.

        r^n / C(n+r-1, r-1) ~ r^n * (r-1)! / n^{r-1} for large n.
        """
        if r == 1:
            return 1.0
        return float(r ** n * math.factorial(r - 1)) / float(n ** (r - 1))
