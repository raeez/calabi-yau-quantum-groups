class WrappedFukayaE1Bar:
    r"""E1 bar complex for wrapped Fukaya categories of cotangent bundles.

    For T*M with 3-manifold M, the wrapped Floer cohomology is:
        HW*(M, M) = C_{-*}(Omega M)  (chains on based loop space)

    This is an E1 algebra (via the Pontryagin product) whose E1 bar complex
    encodes the homotopy type of Omega M.

    The E1 bar-cobar inversion:
        Omega^{E1}(B^{E1}(C_{-*}(Omega M))) ~ C_{-*}(Omega M)

    Key computational fact: for M = S^3,
        H_*(Omega S^3) = k[x] with |x| = 2
    so B^{E1}(k[x]) is the bar complex of the polynomial algebra.
    The bar cohomology is:
        H^*(B^{E1}(k[x])) = k . s^{-1}x  (one generator in bar degree 1)
    since k[x] is Koszul (polynomial algebra is Koszul with dual = exterior).
    """

    def __init__(self, manifold: str = "S3", truncation: int = 3):
        self.manifold = manifold
        self.truncation = truncation
        self._floer = self._build_wrapped_floer()
        self.bar_cx = FukayaE1BarComplex(self._floer, max_arity=truncation + 2)

    def _build_wrapped_floer(self) -> FloerCohomology:
        if self.manifold == "S3":
            return cotangent_s3_wrapped_floer()
        raise ValueError(f"Wrapped Floer not implemented for {self.manifold}")

    def koszul_dual_algebra(self) -> str:
        """The E1 Koszul dual of the wrapped Floer algebra.

        For k[x] (polynomial on one generator): the E1 Koszul dual is
        the exterior algebra Lambda(x*) = k[x*]/(x*^2) on the dual generator.

        Dimension: 2 (generators 1 and x*).

        This is the standard Koszul duality: Poly^! = Exterior.
        """
        if self.manifold == "S3":
            return "Lambda(x*) = k[x*]/(x*^2), |x*| = -3"
        return "unknown"

    def bar_cohomology_concentrated(self) -> bool:
        """Whether bar cohomology is concentrated in bar degree 1 (Koszulness).

        For k[x] (polynomial algebra): YES. The bar complex of k[x] has
        cohomology k.x* in bar degree 1 only.

        This is equivalent to saying the polynomial algebra is Koszul.
        """
        if self.manifold == "S3":
            return True
        return False  # generic case unknown

    def bar_cohomology_description(self) -> Dict[str, Any]:
        """Describe H*(B^{E1}(HW*))."""
        if self.manifold == "S3":
            return {
                'concentrated_in_bar_degree_1': True,
                'H1_dim': 1,
                'H1_generator': 's^{-1}x (degree -3)',
                'Hk_for_k_geq_2': 0,
                'koszul': True,
                'koszul_dual': 'Lambda(x*)',
            }
        return {'concentrated_in_bar_degree_1': False}


