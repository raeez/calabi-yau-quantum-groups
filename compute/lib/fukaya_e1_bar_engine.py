@dataclass(frozen=True)
class FloerGenerator:
    """A generator of the Floer cohomology HF*(L, L).

    Attributes
    ----------
    name : str
        Symbol name.
    degree : int
        Cohomological (Maslov) degree.
    """
    name: str
    degree: int = 0

    def desuspended_degree(self) -> int:
        """Degree after bar desuspension: |s^{-1}v| = |v| - 1."""
        return self.degree - 1

    def __repr__(self) -> str:
        return f"{self.name}[{self.degree}]"


@dataclass(frozen=True)
class FloerCohomology:
    """Floer cohomology HF*(L, L) of a Lagrangian L in a CY manifold.

    Carries:
    - Generators (as a graded vector space).
    - CY dimension d (for Poincare duality HF^i ~ HF^{d-i}*).
    - A-infinity structure maps mu_k.

    The mu_k data is stored as:
        mu_k_data[(gen_names_tuple)] = (coefficient, result_gen_name)
    where gen_names_tuple has length k.
    """
    name: str
    generators: Tuple[FloerGenerator, ...]
    cy_dim: int = 3
    mu_k_data: Dict[Tuple[str, ...], Tuple[object, str]] = field(
        default_factory=dict,
        hash=False,
    )

    @property
    def rank(self) -> int:
        """Total rank = dim HF*(L, L)."""
        return len(self.generators)

    def betti_numbers(self) -> Dict[int, int]:
        """Betti numbers b_i = dim HF^i(L, L)."""
        b: Dict[int, int] = defaultdict(int)
        for g in self.generators:
            b[g.degree] += 1
        return dict(b)

    def euler_characteristic(self) -> int:
        """Euler characteristic chi = sum (-1)^i b_i."""
        return sum((-1) ** g.degree for g in self.generators)

    def poincare_dual_gen(self, gen: FloerGenerator) -> Optional[FloerGenerator]:
        """Find the Poincare dual generator in degree d - deg."""
        target_deg = self.cy_dim - gen.degree
        for g in self.generators:
            if g.degree == target_deg and g is not gen:
                return g
        # Self-dual case
        for g in self.generators:
            if g.degree == target_deg:
                return g
        return None

    def poincare_duality_holds(self) -> bool:
        """Check CY Poincare duality: dim HF^i = dim HF^{d-i}."""
        b = self.betti_numbers()
        for i, count in b.items():
            dual_count = b.get(self.cy_dim - i, 0)
            if count != dual_count:
                return False
        return True

    def get_generator(self, name: str) -> Optional[FloerGenerator]:
        for g in self.generators:
            if g.name == name:
                return g
        return None

    def mu_k(self, *gen_names: str) -> Optional[Tuple[object, FloerGenerator]]:
        """Evaluate mu_k(g_1, ..., g_k) from stored data.

        Returns (coefficient, result_generator) or None if zero.
        """
        key = gen_names
        if key not in self.mu_k_data:
            return None
        coeff, result_name = self.mu_k_data[key]
        result_gen = self.get_generator(result_name)
        if result_gen is None:
            return None
        return (coeff, result_gen)


