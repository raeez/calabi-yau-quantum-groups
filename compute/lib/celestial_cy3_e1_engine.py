def shadow_tower_virasoro_channel(c: Fraction, max_arity: int = 8
                                   ) -> Dict[int, Fraction]:
    """Shadow obstruction tower on the Virasoro (T-line) channel.

    Uses the shadow metric Q_L(t) = (2*kappa + 3*alpha*t)^2 + 2*Delta*t^2
    with kappa=c/2, alpha=2, S_4=10/[c(5c+22)], Delta=8*kappa*S_4.

    The tower coefficients S_r = a_{r-2}/r where a_n are Taylor coefficients
    of sqrt(Q_L(t)).
    """
    c_f = _frac(c)
    if c_f <= 0:
        raise ValueError(f"Shadow tower requires c > 0, got c = {c_f}")

    kappa = c_f / 2
    alpha = Fraction(2)

    # Quartic contact (AP1: recomputed)
    denom = c_f * (5 * c_f + 22)
    if denom == 0:
        raise ValueError(f"Q^contact singular at c = {c_f}")
    S4 = Fraction(10) / denom

    # Shadow metric coefficients
    q0 = 4 * kappa ** 2
    q1 = 12 * kappa * alpha
    q2 = 9 * alpha ** 2 + 16 * kappa * S4

    # Taylor coefficients of sqrt(Q_L(t)) via recursion
    a0 = 2 * kappa
    max_n = max_arity - 2 + 1
    a = [Fraction(0)] * (max_n + 1)
    a[0] = a0

    if max_n >= 1:
        a[1] = q1 / (2 * a0)
    if max_n >= 2:
        a[2] = (q2 - a[1] ** 2) / (2 * a0)
    for n in range(3, max_n + 1):
        conv = sum(a[j] * a[n - j] for j in range(1, n))
        a[n] = -conv / (2 * a0)

    coefficients = {}
    for r in range(2, max_arity + 1):
        idx = r - 2
        if idx <= max_n:
            coefficients[r] = a[idx] / r
        else:
            coefficients[r] = Fraction(0)

    return coefficients


def shadow_discriminant_virasoro(c: Fraction) -> Fraction:
    """Critical discriminant Delta = 8*kappa*S_4 on the Virasoro channel.

    Delta = 8*(c/2)*10/[c(5c+22)] = 40/(5c+22).

    Nonzero for all c != -22/5 -> confirms class M (infinite tower).
    """
    c_f = _frac(c)
    denom = 5 * c_f + 22
    if denom == 0:
        raise ValueError("Discriminant singular at c = -22/5")
    return Fraction(40) / denom


