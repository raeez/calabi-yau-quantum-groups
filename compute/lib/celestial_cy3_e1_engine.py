def kappa_cy3_graviton(c: Fraction) -> Fraction:
    """Graviton contribution to kappa: c/2 from the Virasoro (spin-2) sector.

    The soft graviton produces a spin-2 current (the stress tensor T).
    Its self-OPE T(z)T(w) ~ (c/2)/(z-w)^4 + ... gives kappa_grav = c/2.

    CAUTION (AP9): this is the graviton CHANNEL only.
    CAUTION (AP48): for the full algebra, kappa != c/2 in general.
    """
    return _frac(c) / 2


def kappa_cy3_graviphoton(c: Fraction, h11: int) -> Fraction:
    """Graviphoton contribution to kappa.

    Each graviphoton (spin-1 current) J^a(z) has self-OPE
    J^a(z) J^a(w) ~ k_a / (z-w)^2 at level k_a.
    For Type IIA on CY3: the level is determined by the Kahler metric,
    and each current contributes kappa_a = k_a to the total.

    At the normalization where J^a has self-OPE coefficient 1:
    kappa_per_current = 1 (like Heisenberg at k=1).
    Total: kappa_photon = h^{1,1} * 1 = h^{1,1}.

    This is the Kac-Moody sector with gauge algebra u(1)^{h^{1,1}}.
    kappa(KM_{u(1)^r, k=1}) = r (sum of Heisenberg contributions).
    """
    return Fraction(h11)


def kappa_cy3_total(cy3: CY3HodgeData, c: Fraction) -> Dict[str, Fraction]:
    """Total modular characteristic from all sectors.

    Returns channel-refined kappa:
      kappa_grav = c/2 (graviton / Virasoro)
      kappa_photon = h^{1,1} (graviphotons / KM)
      kappa_total = c/2 + h^{1,1} (total from leading sectors)

    NOTE: the scalar sector (spin 0) does NOT contribute to kappa
    at leading order because spin-0 operators have no self-OPE pole.
    (The spin-0 OPE J^0(z) J^0(w) is regular at z=w for conformally
    coupled scalars.)
    """
    c_f = _frac(c)
    k_grav = kappa_cy3_graviton(c_f)
    k_photon = kappa_cy3_graviphoton(c_f, cy3.h11)
    return {
        "kappa_graviton": k_grav,
        "kappa_graviphoton": k_photon,
        "kappa_scalar": Fraction(0),
        "kappa_total": k_grav + k_photon,
    }


