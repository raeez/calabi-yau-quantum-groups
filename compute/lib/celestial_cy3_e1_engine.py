@dataclass(frozen=True)
class OmegaDeformationData:
    """Omega-deformation parameters for the affine Yangian Y(gl_hat_1).

    The structure function g(z) = (z-h1)(z-h2)(z-h3)/((z+h1)(z+h2)(z+h3))
    with CY condition h1 + h2 + h3 = 0.

    Parameters:
      sigma_1 = h1 + h2 + h3 = 0 (CY condition)
      sigma_2 = h1*h2 + h1*h3 + h2*h3
      sigma_3 = h1*h2*h3

    The central charge: c = -sigma_2^3 / sigma_3^2
    (from the W_{1+inf} identification).

    Classical limit: sigma_3 -> 0 gives w_{1+inf} (area-preserving diffeos).
    Quantum: sigma_3 != 0 gives the full W_{1+inf}.
    """
    h1: Fraction
    h2: Fraction
    h3: Fraction  # = -(h1 + h2) by CY condition

    @property
    def sigma_1(self) -> Fraction:
        """sigma_1 = h1 + h2 + h3 = 0 (CY condition)."""
        return self.h1 + self.h2 + self.h3

    @property
    def sigma_2(self) -> Fraction:
        """sigma_2 = h1*h2 + h1*h3 + h2*h3."""
        return self.h1 * self.h2 + self.h1 * self.h3 + self.h2 * self.h3

    @property
    def sigma_3(self) -> Fraction:
        """sigma_3 = h1*h2*h3 (the Omega-deformation parameter)."""
        return self.h1 * self.h2 * self.h3

    @property
    def central_charge(self) -> Optional[Fraction]:
        """c = -sigma_2^3 / sigma_3^2 when sigma_3 != 0.

        This is the central charge of the W_{1+inf} algebra identified
        with Y(gl_hat_1) at these parameters.

        At sigma_3 = 0: the central charge is infinite (classical limit).
        """
        s3 = self.sigma_3
        if s3 == 0:
            return None  # classical limit
        s2 = self.sigma_2
        return -s2 ** 3 / s3 ** 2

    @property
    def is_classical(self) -> bool:
        """Whether sigma_3 = 0 (classical w_{1+inf} limit)."""
        return self.sigma_3 == 0


def make_omega_deformation(h1: Fraction, h2: Fraction) -> OmegaDeformationData:
    """Construct Omega-deformation data with CY condition h3 = -(h1+h2)."""
    h1_f = _frac(h1)
    h2_f = _frac(h2)
    h3_f = -(h1_f + h2_f)
    return OmegaDeformationData(h1=h1_f, h2=h2_f, h3=h3_f)


def self_dual_omega() -> OmegaDeformationData:
    """The self-dual point: h1=1, h2=-1, h3=0.

    sigma_2 = 1*(-1) + 1*0 + (-1)*0 = -1
    sigma_3 = 1*(-1)*0 = 0

    This is the CLASSICAL limit (sigma_3=0), giving w_{1+inf}.
    """
    return make_omega_deformation(Fraction(1), Fraction(-1))


def standard_quantum_omega(epsilon: Fraction) -> OmegaDeformationData:
    """The quantum deformation: h1=1, h2=epsilon, h3=-(1+epsilon).

    sigma_2 = epsilon + (-1-epsilon) + epsilon*(-1-epsilon)
            = epsilon - 1 - epsilon - epsilon - epsilon^2
            = -1 - epsilon - epsilon^2
    sigma_3 = epsilon * (-1-epsilon) = -epsilon(1+epsilon)

    Central charge: c = (1 + epsilon + epsilon^2)^3 / (epsilon^2 * (1+epsilon)^2)

    At epsilon -> 0: sigma_3 -> 0, c -> infinity (classical limit).
    At epsilon = 1: h = (1, 1, -2), sigma_3 = -2.
    """
    return make_omega_deformation(Fraction(1), _frac(epsilon))


def structure_function_coefficients_from_omega(
    omega: OmegaDeformationData, max_order: int = 10
) -> List[Fraction]:
    """Compute phi_j coefficients of g(z) = sum phi_j z^{-j}.

    g(z) = (z-h1)(z-h2)(z-h3)/((z+h1)(z+h2)(z+h3))

    Uses the power-sum expansion:
      log g(z) = -2 * sum_{k odd} p_k / (k * z^k)
    where p_k = h1^k + h2^k + h3^k.

    Then phi_j are computed by exponentiating.
    """
    h1, h2, h3 = omega.h1, omega.h2, omega.h3

    # Power sums p_k = h1^k + h2^k + h3^k
    def pk(k: int) -> Fraction:
        return h1 ** k + h2 ** k + h3 ** k

    # Log coefficients alpha_k = -2 * p_k / k for odd k >= 1
    # (Even k >= 2 alpha_k = 0 because g(z)*g(-z) = 1)
    alpha = [Fraction(0)] * (max_order + 1)
    for k in range(1, max_order + 1, 2):
        alpha[k] = Fraction(-2) * pk(k) / k

    # Exponentiate: phi_j from the recursion j*phi_j = sum_{k=1}^{j} k*alpha_k*phi_{j-k}
    phi = [Fraction(0)] * (max_order + 1)
    phi[0] = Fraction(1)
    for j in range(1, max_order + 1):
        s = Fraction(0)
        for k in range(1, j + 1):
            if alpha[k] != 0:
                s += k * alpha[k] * phi[j - k]
        phi[j] = s / j

    return phi


