def genus_g_obstruction_scalar(kappa: Fraction, g: int) -> Fraction:
    """Genus-g scalar obstruction: F_g = kappa * lambda_g^{FP}.

    The Faber-Pandharipande lambda_g values:
      lambda_1 = 1/24
      lambda_2 = 7/5760
      lambda_3 = 31/967680

    General formula: lambda_g = |B_{2g}| / (2g * (2g)!)
    where B_{2g} are Bernoulli numbers.

    F_g(A) = kappa(A) * lambda_g^{FP} for uniform-weight modular Koszul algebras.
    """
    if g <= 0:
        raise ValueError(f"Genus must be >= 1, got {g}")

    # lambda_g^{FP} = |B_{2g}| / (2g * (2g)!)
    B2g = bernoulli_number(2 * g)
    lambda_g = abs(B2g) / (2 * g * factorial(2 * g))
    return kappa * lambda_g


def genus_expansion_c3(c: Fraction, max_genus: int = 5,
                        N_max: int = 2) -> Dict[int, Fraction]:
    """Genus expansion for C^3 at given c and spin truncation.

    F_g = kappa * lambda_g^{FP}

    For the Virasoro channel (N_max=2): kappa = c/2.
    For full W_{1+inf} (N_max -> inf): kappa diverges (needs regularization).
    """
    c_f = _frac(c)
    # Use spin-2 (Virasoro) channel for the graviton sector
    kappa = kappa_c3_virasoro_channel(c_f)

    result = {}
    for g in range(1, max_genus + 1):
        result[g] = genus_g_obstruction_scalar(kappa, g)

    return result


