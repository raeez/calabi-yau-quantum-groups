def cross_volume_kappa_check() -> Dict[str, Any]:
    """Verify kappa values match across Vol I, Vol III formulas.

    Vol I (celestial_shadow_engine.py): kappa(W_N) = c * (H_N - 1) for spins 2..N
    Vol III (this module): kappa(W_{1+inf}) = c * H_N for spins 1..N

    Difference: the spin-1 channel contributes c/1 = c.
    So: kappa_full = kappa_WN + c.

    Consistency: kappa(W_N) = c*(H_N - 1) and kappa_full(N) = c*H_N.
    kappa_full - kappa_WN = c*(H_N - (H_N - 1)) = c. Correct.
    """
    c = Fraction(1)
    checks = {}
    for N in [2, 3, 5, 10]:
        kappa_wn = c * (harmonic_number(N) - Fraction(1))  # Vol I: spins 2..N
        kappa_full = c * harmonic_number(N)                 # Vol III: spins 1..N
        checks[N] = {
            "kappa_WN_vol1": kappa_wn,
            "kappa_full_vol3": kappa_full,
            "difference": kappa_full - kappa_wn,
            "difference_equals_c": (kappa_full - kappa_wn == c),
        }

    return {
        "central_charge": c,
        "checks": checks,
        "all_consistent": all(v["difference_equals_c"] for v in checks.values()),
    }


