@dataclass(frozen=True)
class CelestialSoftTheorem:
    """A soft theorem derived from the E_1 shadow obstruction tower.

    The arity-r shadow projection Theta^{E_1, <=r}(A_X) produces the
    sub^{r-2}-leading soft theorem.

    For CY3 = C^3:
      r=2: kappa * eta tensor Lambda -> Weinberg leading soft factor
      r=3: cubic shadow C -> Cachazo-Strominger subleading
      r=4: quartic shadow Q -> sub-subleading with Q^contact
    """
    order: int                # n in S^{(n)}, where soft order = arity - 2
    arity: int                # arity r of the shadow projection
    shadow_invariant: str     # name of the shadow invariant
    coefficient: Fraction     # the numerical coefficient
    celestial_current: str    # associated celestial symmetry current
    ward_identity: str        # schematic form of the Ward identity


def soft_theorem_leading(kappa: Fraction) -> CelestialSoftTheorem:
    """Leading soft graviton theorem from kappa (arity 2).

    S^{(0)}:
      <S^{(0)}_q prod_k O_{p_k}> = kappa * sum_k (eps.p_k)/(q.p_k) <prod O>

    The soft factor is universal: sum_k 1/(q.p_k) with coefficient kappa.
    This is the Weinberg (1965) result.

    For C^3 at c=1: kappa_grav = c/2 = 1/2 from the graviton channel.
    """
    return CelestialSoftTheorem(
        order=0,
        arity=2,
        shadow_invariant="kappa (modular characteristic)",
        coefficient=kappa,
        celestial_current="supertranslation (BMS)",
        ward_identity=f"kappa * sum_k (eps.p_k)/(q.p_k), kappa = {kappa}",
    )


def soft_theorem_subleading(cubic_shadow: Fraction) -> CelestialSoftTheorem:
    """Subleading soft graviton theorem from cubic shadow C (arity 3).

    S^{(1)}:
      <S^{(1)}_q prod_k O_{p_k}> = C * sum_k (eps.J_k.q)/(q.p_k) <prod O>

    The soft factor involves the angular momentum operator J^{mu nu},
    which generates the Virasoro (superrotation) subalgebra.

    For the Virasoro channel: cubic shadow S_3 = 2 (independent of c).
    This is the Cachazo-Strominger (2014) result.
    """
    return CelestialSoftTheorem(
        order=1,
        arity=3,
        shadow_invariant="C (cubic shadow)",
        coefficient=cubic_shadow,
        celestial_current="superrotation (Virasoro)",
        ward_identity=f"C * sum_k (eps.J_k.q)/(q.p_k), C = {cubic_shadow}",
    )


def soft_theorem_subsubleading(q_contact: Fraction) -> CelestialSoftTheorem:
    """Sub-subleading soft graviton theorem from quartic shadow Q (arity 4).

    S^{(2)}:
      <S^{(2)}_q prod_k O_{p_k}> = Q * sum_k (eps.T_k.q^2)/(q.p_k) <prod O>

    Q^contact encodes the 4-particle contact interaction, beyond the
    tree-exchange contributions from lower arities.

    For Virasoro: Q^contact = 10 / [c(5c+22)].
    At c=1: Q^contact = 10/(1*27) = 10/27.
    """
    return CelestialSoftTheorem(
        order=2,
        arity=4,
        shadow_invariant="Q^contact (quartic contact invariant)",
        coefficient=q_contact,
        celestial_current="spin-3 W-current",
        ward_identity=f"Q * sum_k (eps.T_k.q^2)/(q.p_k), Q = {q_contact}",
    )


def compute_soft_theorems_c3(c: Fraction = Fraction(1)) -> List[CelestialSoftTheorem]:
    """Compute the first three soft theorems for C^3 at central charge c.

    Channel: Virasoro (spin-2 graviton) channel only.
    kappa_grav = c/2.
    S_3 = 2 (Virasoro cubic shadow, independent of c).
    Q^contact_Vir = 10 / [c(5c+22)] (Virasoro quartic contact).
    """
    c_f = _frac(c)
    kappa = c_f / 2

    # Cubic shadow on Virasoro channel: S_3 = 2
    S3 = Fraction(2)

    # Quartic contact: Q^contact = 10 / [c(5c+22)]
    denom = c_f * (5 * c_f + 22)
    if denom == 0:
        raise ValueError(f"Q^contact singular at c = {c_f}")
    Q_contact = Fraction(10) / denom

    return [
        soft_theorem_leading(kappa),
        soft_theorem_subleading(S3),
        soft_theorem_subsubleading(Q_contact),
    ]


