@dataclass(frozen=True)
class CY3HodgeData:
    """Hodge numbers of a Calabi-Yau threefold X.

    For a CY3: h^{0,0} = h^{3,3} = 1, h^{1,0} = h^{2,0} = 0.
    The independent numbers are h^{1,1} and h^{2,1}.
    Euler characteristic: chi = 2(h^{1,1} - h^{2,1}).
    """
    name: str
    h11: int   # h^{1,1}(X) = number of Kahler moduli
    h21: int   # h^{2,1}(X) = number of complex structure moduli

    @property
    def euler_characteristic(self) -> int:
        """Topological Euler characteristic chi(X) = 2(h^{1,1} - h^{2,1})."""
        return 2 * (self.h11 - self.h21)

    @property
    def num_vector_multiplets(self) -> int:
        """Number of 4d N=2 vector multiplets = h^{1,1}."""
        return self.h11

    @property
    def num_hyper_multiplets(self) -> int:
        """Number of 4d N=2 hypermultiplets = h^{2,1} + 1."""
        return self.h21 + 1

    @property
    def total_massless_scalars(self) -> int:
        """Total number of massless real scalars in 4d.

        Vector multiplets: h^{1,1} * 2 real scalars each
        Hypermultiplets: (h^{2,1}+1) * 4 real scalars each
        """
        return 2 * self.h11 + 4 * (self.h21 + 1)

    @property
    def chi_top_over_24(self) -> Fraction:
        """chi(X)/24 -- the BCOV genus-1 invariant contribution."""
        return Fraction(self.euler_characteristic, 24)


