def all_cohomology_pn_twist(n: int, m: int) -> Dict[int, int]:
    """All H^k(P^n, O(m)) in a single dict."""
    result = {}
    for k in range(n + 1):
        val = h_k_pn_o_m(n, k, m)
        if val > 0:
            result[k] = val
    return result


def cohomology_table_pn(n: int, m_range: Tuple[int, int]) -> List[Dict[str, Any]]:
    """Table of H^k(P^n, O(m)) for m in [m_range[0], m_range[1]]."""
    table = []
    for m in range(m_range[0], m_range[1] + 1):
        row = {"m": m}
        for k in range(n + 1):
            row[f"H^{k}"] = h_k_pn_o_m(n, k, m)
        row["chi"] = euler_char_pn_o_m(n, m)
        table.append(row)
    return table


