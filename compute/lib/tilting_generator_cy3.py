r"""
tilting_generator_cy3.py -- Tilting generators, Ext-quivers, and quiver-with-potential
for derived categories of CY3 varieties and related spaces.

Ground truth:
  Bondal, "Representations of associative algebras and coherent sheaves" (1990).
  Bondal-Van den Bergh, "Generators and representability of functors" (2003).
  Van den Bergh, "Non-commutative crepant resolutions" (2004).
  Beilinson, "Coherent sheaves on P^n" (1978).
  Bridgeland, "Flops and derived categories" (2002).
  Aspinwall et al., "Dirichlet branes and mirror symmetry" (2009).
  Keller-Yang, "Derived equivalences from mutations of quivers with potential" (2011).
  Ginzburg, "CY algebras" (2006).

MATHEMATICAL CONTENTS:

1. TILTING GENERATORS FOR SMOOTH PROJECTIVE VARIETIES.
   By the Bondal-Van den Bergh theorem (2003), for a smooth projective variety X
   over k, D^b(Coh(X)) has a tilting generator T: an object satisfying
     (i) thick(T) = D^b(Coh(X))  (T generates the category)
     (ii) Ext^{>0}(T, T) = 0     (T has no higher self-extensions)

   The endomorphism algebra A = End(T) then gives an equivalence:
     D^b(Coh(X)) ~ D^b(mod-A)

   For the BVdB theorem: the tilting generator exists for any smooth projective X.
   For SINGULAR varieties, Van den Bergh's noncommutative crepant resolution
   provides a tilting generator under suitable conditions (rational singularities).

2. BEILINSON'S THEOREM FOR P^n.
   The Beilinson collection on P^n is:
     T = O + O(1) + ... + O(n)
   This is a full strong exceptional collection: Ext^{>0}(O(i), O(j)) = 0 for
   all i <= j, and Ext^*(O(i), O(j)) = 0 for i > j+n (by Serre duality + vanishing).

   The Ext-quiver has n+1 vertices and arrows from Ext^1 computations.
   For P^n: Ext^1(O(i), O(j)) = H^1(P^n, O(j-i)) for 0 <= i < j <= n.
   By Bott's theorem: H^k(P^n, O(m)) is nonzero only when:
     - k=0 and m >= 0: dim = binom(n+m, n)
     - k=n and m <= -(n+1): dim = binom(-m-1, n)
   All other cohomology groups vanish.

   Therefore for P^n with the Beilinson collection:
     Ext^1(O(i), O(j)) = 0 for all 0 <= i < j <= n (since j-i <= n and
     H^1(P^n, O(j-i)) = 0 for all j-i > 0 by Bott vanishing).

   The NON-ZERO morphisms are Hom = H^0:
     Hom(O(i), O(j)) = H^0(P^n, O(j-i)) for j >= i.
     dim = binom(n + j - i, n).

   For P^3: arrows are generated by Hom(O(i), O(i+1)) = H^0(P^3, O(1)) = C^4.
   So the Beilinson quiver for P^3 has 4 vertices with 4 arrows between
   consecutive vertices.

3. RESTRICTION TO HYPERSURFACE: KOSZUL RESOLUTION.
   For a smooth hypersurface Y = {f_d = 0} in P^n of degree d:
     0 -> O(-d) -> O -> O_Y -> 0 (Koszul exact sequence)

   This gives for any coherent sheaf F on P^n:
     H^k(Y, F|_Y) fits in the long exact sequence:
     ... -> H^k(P^n, F(-d)) -> H^k(P^n, F) -> H^k(Y, F|_Y) -> H^{k+1}(P^n, F(-d)) -> ...

   For the quintic Q in P^4 (d=5, n=4):
     Ext^k_Q(O(i)|_Q, O(j)|_Q) = Ext^k_Q(O_Q, O(j-i)|_Q)
   We compute from the long exact sequence of Koszul.

4. COMPLETE INTERSECTION CY3.
   For a CI Y = {f_{d_1} = 0} ∩ ... ∩ {f_{d_r} = 0} in P^{n+r}:
   The Koszul resolution is:
     0 -> O(-D) -> ... -> ⊕ O(-d_i) -> O -> O_Y -> 0
   where D = d_1 + ... + d_r.
   CY condition: D = n+r+1 (so K_Y = O_Y).

   The Ext groups are computed from the multi-step Koszul filtration.

5. CY3 CONSTRAINT: SERRE DUALITY ON THE QUIVER.
   For a CY3 category with tilting generator T = ⊕ T_i:
     dim Ext^1(T_i, T_j) = dim Ext^2(T_j, T_i)
   This is Serre duality for a CY3 (omega_X = O_X, dim X = 3).
   Consequence: the Ext-quiver is CY3-SELF-DUAL.
   If there are a_{ij} arrows from i to j in the Ext^1 quiver,
   then there are a_{ji} arrows from j to i in the Ext^2 "reverse" quiver,
   and the quiver with potential (Q, W) must satisfy the CY3 Ginzburg condition.

6. SINGULAR CY3: CONIFOLD.
   The conifold singularity: xy = zw in C^4 (an ODP = ordinary double point).
   The small resolution X = Tot(O(-1) + O(-1) -> P^1) has:
     T = O_X + O_X(1)  (tilting on the resolution)
   giving the Klebanov-Witten quiver: 2 vertices, 4 arrows (2 in each direction),
   with potential W = tr(A_1 B_1 A_2 B_2 - A_1 B_2 A_2 B_1).

7. TILTING GENERATOR AND E_1 CHIRAL ALGEBRA.
   The tilting generator T determines the E_1 chiral algebra:
     A_X = Fact_X(End(T))
   For C^3: T = O, End(T) = C, Fact(C) = Heisenberg = W_{1+infty} at c=0.
   For the conifold: End(T) = the KW path algebra, giving a non-abelian chiral algebra.

CONVENTIONS:
  - Cohomological grading (|d| = +1).
  - All Fraction arithmetic for exact computations.
  - Ext^k(E, F) = H^k(RHom(E, F)).
  - For line bundles on P^n: Ext^k(O(i), O(j)) = H^k(P^n, O(j-i)).
  - Bott's formula for H^k(P^n, O(m)):
      k=0, m >= 0: binom(n+m, n)
      k=n, m <= -(n+1): binom(-m-1, n)
      all other: 0.

REFERENCES:
  Beilinson, "Coherent sheaves on P^n" (1978).
  Bondal, "Representations of associative algebras" (1990).
  Bondal-Van den Bergh, "Generators and representability" (2003).
  Van den Bergh, "Non-commutative crepant resolutions" (2004).
  Bridgeland, "Flops and derived categories" (2002).
  Keller-Yang, "Derived equivalences from mutations" (2011).
  Ginzburg, "CY algebras" (2006).
  Aspinwall et al., "Dirichlet branes and mirror symmetry" (2009).
  Candelas-de la Ossa-Green-Parkes, NPB 359 (1991).
"""

