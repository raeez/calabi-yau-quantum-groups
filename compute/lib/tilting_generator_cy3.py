class TiltingGenerator(NamedTuple):
    """A tilting generator T for D^b(Coh(X)).

    T = ⊕ T_i with Ext^{>0}(T, T) = 0 and thick(T) = D^b.
    The endomorphism algebra End(T) = ⊕ Hom(T_i, T_j) determines
    the quiver with relations.
    """
    summands: List[str]
    num_summands: int
    ext_matrix: Dict[Tuple[int, int], ExtData]
    is_tilting: bool  # Ext^{>0}(T, T) = 0
    is_generator: bool  # thick(T) = D^b
    variety: str
    cy_dimension: Optional[int]
    quiver: Optional[QuiverData]


def tilting_generator_pn(n: int) -> TiltingGenerator:
    r"""Beilinson tilting generator on P^n: T = O ⊕ O(1) ⊕ ... ⊕ O(n).

    For P^3: T = O ⊕ O(1) ⊕ O(2) ⊕ O(3).
    The Ext-quiver has n+1 vertices with dim Hom(O(i), O(i+1)) = n+1
    arrows from vertex i to vertex i+1 (for i = 0, ..., n-1).
    """
    ec = beilinson_collection_pn(n)
    quiver = ext_quiver(ec, cy_dim=None)

    return TiltingGenerator(
        summands=ec.objects,
        num_summands=n + 1,
        ext_matrix=ec.ext_matrix,
        is_tilting=ec.is_strong,  # strong exceptional => tilting
        is_generator=ec.is_full,
        variety=f"P^{n}",
        cy_dimension=None,  # P^n is Fano, not CY
        quiver=quiver,
    )


def tilting_generator_quintic() -> TiltingGenerator:
    r"""Tilting generator for D^b(Coh(Q)) where Q is the quintic CY3 in P^4.

    T = ⊕_{i=0}^{4} O(i)|_Q  (restriction of Beilinson collection).

    IMPORTANT: This is NOT an exceptional collection on Q. On P^4 it is
    exceptional, but the restriction to Q may have nonzero Ext groups
    between the restricted line bundles. However, T is still a GENERATOR
    (it generates the derived category) and may still be TILTING
    (have vanishing higher self-Ext).

    For the quintic:
      Ext^k_Q(O(i)|_Q, O(j)|_Q) = H^k(Q, O(j-i)|_Q)
    computed via the Koszul resolution of Q in P^4.
    """
    n = 4  # ambient P^4
    d = 5  # quintic
    num_summands = 5

    summands = [f"O({i})|_Q" for i in range(num_summands)]
    ext_matrix: Dict[Tuple[int, int], ExtData] = {}

    is_tilting = True

    for i in range(num_summands):
        for j in range(num_summands):
            ed = ext_on_hypersurface(n, d, i, j)
            ext_matrix[(i, j)] = ed

            # Check tilting condition: Ext^{>0}(T, T) = 0
            for k_deg, dim_val in ed.dims.items():
                if k_deg > 0 and dim_val > 0:
                    is_tilting = False

    quiver = _build_quiver_from_ext(num_summands, summands, ext_matrix, "quintic CY3", 3)

    return TiltingGenerator(
        summands=summands,
        num_summands=num_summands,
        ext_matrix=ext_matrix,
        is_tilting=is_tilting,
        is_generator=True,  # generates D^b by restriction of Beilinson
        variety="quintic CY3 in P^4",
        cy_dimension=3,
        quiver=quiver,
    )


def tilting_generator_cicy33() -> TiltingGenerator:
    r"""Tilting generator for the CICY (3,3) in P^5.

    The (3,3) complete intersection in P^5 is a CY3:
      Y = {f_3 = 0} ∩ {g_3 = 0} in P^5
    with h^{1,1} = 1, h^{2,1} = 73, chi = -144.

    T = ⊕_{i=0}^{5} O(i)|_Y  (restriction of line bundles from P^5).
    """
    n = 5  # ambient P^5
    degrees = (3, 3)
    num_summands = 6

    summands = [f"O({i})|_Y" for i in range(num_summands)]
    ext_matrix: Dict[Tuple[int, int], ExtData] = {}

    is_tilting = True

    for i in range(num_summands):
        for j in range(num_summands):
            ed = ext_on_cicy(n, degrees, i, j)
            ext_matrix[(i, j)] = ed
            for k_deg, dim_val in ed.dims.items():
                if k_deg > 0 and dim_val > 0:
                    is_tilting = False

    quiver = _build_quiver_from_ext(num_summands, summands, ext_matrix, "CICY (3,3) in P^5", 3)

    return TiltingGenerator(
        summands=summands,
        num_summands=num_summands,
        ext_matrix=ext_matrix,
        is_tilting=is_tilting,
        is_generator=True,
        variety="CICY (3,3) in P^5",
        cy_dimension=3,
        quiver=quiver,
    )


def _build_quiver_from_ext(
    num_summands: int,
    summands: List[str],
    ext_matrix: Dict[Tuple[int, int], ExtData],
    variety: str,
    cy_dim: Optional[int],
) -> QuiverData:
    """Build a QuiverData from an Ext matrix."""
    arrows: Dict[Tuple[int, int], int] = {}
    ext2: Dict[Tuple[int, int], int] = {}

    for i in range(num_summands):
        for j in range(num_summands):
            ed = ext_matrix[(i, j)]
            a1 = ed.dims.get(1, 0)
            a2 = ed.dims.get(2, 0)
            if a1 > 0:
                arrows[(i, j)] = a1
            if a2 > 0:
                ext2[(i, j)] = a2

    is_cy3 = True
    if cy_dim == 3:
        for i in range(num_summands):
            for j in range(num_summands):
                a1_ij = arrows.get((i, j), 0)
                a2_ji = ext2.get((j, i), 0)
                if a1_ij != a2_ji:
                    is_cy3 = False
                    break
            if not is_cy3:
                break
    else:
        is_cy3 = False

    return QuiverData(
        num_vertices=num_summands,
        vertex_labels=summands,
        arrows=arrows,
        ext2_arrows=ext2,
        variety=variety,
        is_cy3_self_dual=is_cy3,
        potential_terms=sum(ext2.values()),
    )


