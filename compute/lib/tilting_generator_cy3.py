class QuiverWithPotential(NamedTuple):
    """A quiver with potential (Q, W) satisfying the CY3/Ginzburg condition.

    The potential W is a linear combination of oriented cycles in Q.
    The Jacobian algebra Jac(Q, W) = kQ / (dW/da for each arrow a)
    is the endomorphism algebra of the tilting generator.

    For CY3: W comes from the A_infinity m_3 product (the CY3 formality
    theorem ensures m_k = 0 for k >= 4 in many cases).
    """
    num_vertices: int
    arrows: List[Tuple[int, int, str]]  # (source, target, label)
    potential_terms: List[Tuple[str, int]]  # (cycle_monomial, coefficient)
    is_cy3: bool
    jacobian_dim: Optional[int]  # dim Jac(Q, W) if finite


def conifold_qwp() -> QuiverWithPotential:
    """The Klebanov-Witten quiver with potential for the conifold.

    Q: 2 vertices {0, 1}.
    Arrows: a1, a2: 0 -> 1 and b1, b2: 1 -> 0.
    W = a1 b1 a2 b2 - a1 b2 a2 b1 (the commutator potential).

    The Jacobian relations:
      dW/da1 = b1 a2 b2 - b2 a2 b1 = 0
      dW/da2 = b2 a1 b1 - b1 a1 b2 = 0  (cyclic version)
      dW/db1 = a2 b2 a1 - a1 ... (similarly)
      dW/db2 = a1 b1 a2 - a2 b1 a1 = 0

    These are the commutativity relations of the conifold coordinate ring
    C[x, y, z, w] / (xy - zw).
    """
    arrows = [
        (0, 1, "a1"), (0, 1, "a2"),
        (1, 0, "b1"), (1, 0, "b2"),
    ]
    potential = [
        ("a1*b1*a2*b2", 1),
        ("a1*b2*a2*b1", -1),
    ]
    return QuiverWithPotential(
        num_vertices=2,
        arrows=arrows,
        potential_terms=potential,
        is_cy3=True,
        jacobian_dim=None,  # infinite-dimensional (conifold is non-compact)
    )


def p3_quiver() -> QuiverWithPotential:
    r"""The Beilinson quiver for P^3.

    4 vertices {0, 1, 2, 3} with 4 arrows between consecutive vertices:
      x_i^{(k)}: vertex k -> vertex k+1 for i = 0, 1, 2, 3 (corresponding
      to the 4 homogeneous coordinates on P^3).

    The potential W comes from the commutativity relations:
      x_i^{(k)} x_j^{(k+1)} = x_j^{(k)} x_i^{(k+1)}
    which are encoded as the potential:
      W = sum_{i<j, k} (x_i^{(k)} x_j^{(k+1)} x_m^{(k+2)} -
                         x_j^{(k)} x_i^{(k+1)} x_m^{(k+2)})
    (summing over all 3-cycles).

    NOTE: P^3 is NOT CY3. It is Fano. The quiver with potential structure
    still exists but does not satisfy the CY3 Ginzburg condition.
    """
    arrows = []
    for k in range(3):  # edges from vertex k to k+1
        for i in range(4):  # 4 arrows per edge
            arrows.append((k, k + 1, f"x{i}_{k}"))

    # Potential: commutativity relations as 3-cycles
    # Each relation x_i^{(k)} x_j^{(k+1)} = x_j^{(k)} x_i^{(k+1)}
    # generates a term in W.
    potential = []
    for k in range(1):  # only one 3-cycle layer (0->1->2->3 is a 3-step path)
        for i in range(4):
            for j in range(i + 1, 4):
                potential.append((f"x{i}_{0}*x{j}_{1}*x{i}_{2}", 1))
                potential.append((f"x{j}_{0}*x{i}_{1}*x{i}_{2}", -1))

    return QuiverWithPotential(
        num_vertices=4,
        arrows=arrows,
        potential_terms=potential,
        is_cy3=False,  # P^3 is Fano, not CY
        jacobian_dim=None,
    )


