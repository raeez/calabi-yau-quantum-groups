# Section 8: Conifold tilting generator (Van den Bergh NCCR)
# =========================================================================

class ConifoldTiltingData(NamedTuple):
    """Tilting generator data for the conifold resolution.

    The resolved conifold X = Tot(O(-1) ⊕ O(-1) -> P^1) has:
      T = O_X ⊕ O_X(1) (= O_P1 ⊕ O_P1(1) considered on the total space)

    The endomorphism algebra is the KW (Klebanov-Witten) path algebra:
      End(T) = ( Hom(O, O)   Hom(O, O(1)) )  =  ( C    C^2 )
               ( Hom(O(1),O) Hom(O(1),O(1)))     ( C^2  C   )

    where Hom(O, O(1)) = H^0(P^1, O(1)) = C^2 and
          Hom(O(1), O) = Ext^1(O(1), O) by Serre duality + CY3.
    But actually on the total space O(-1)⊕O(-1) -> P^1, the calculation
    uses the local CY3 structure.

    The KW quiver has:
      - 2 vertices (corresponding to O and O(1))
      - 2 arrows a_1, a_2: vertex 0 -> vertex 1
      - 2 arrows b_1, b_2: vertex 1 -> vertex 0
    with potential W = a_1 b_1 a_2 b_2 - a_1 b_2 a_2 b_1
                     = tr(a_1 [b_1, a_2] b_2)  (= commutator potential)
    """
    num_vertices: int
    arrows_01: int  # arrows from vertex 0 to vertex 1
    arrows_10: int  # arrows from vertex 1 to vertex 0
    is_cy3_self_dual: bool
    potential: str
    nccr_algebra_dim: int  # dim End(T) as a vector space


def conifold_tilting() -> ConifoldTiltingData:
    r"""Tilting generator for the resolved conifold.

    The resolved conifold is X = Tot(O(-1) ⊕ O(-1) -> P^1).
    The tilting generator is T = O_X ⊕ L where L = O(1) restricted to X.

    By Van den Bergh (2004), End(T) is a noncommutative crepant resolution
    (NCCR) of the conifold singularity xy = zw.

    The Ext computation on the total space X:
      The local CY3 condition means Ext^k(F, G) on X has Serre duality:
        Ext^k(F, G) ~ Ext^{3-k}(G, F)^*

      For T = O ⊕ O(1) on P^1 (the zero section):
        Hom(O, O) = C           Hom(O, O(1)) = C^2
        Hom(O(1), O) = 0        Hom(O(1), O(1)) = C

      But on the TOTAL SPACE (not just P^1), the CY3 structure gives
      additional Ext groups from the normal bundle O(-1)⊕O(-1).

      The correct computation uses the Koszul resolution of O_{P^1} in X:
        Ext^k_X(O_{P^1}, O_{P^1}) depends on the normal bundle.
        N_{P^1/X} = O(-1)⊕O(-1), so /\^k N^* = O(k) for k=0,1,2.
        Actually: /\^0 N^* = O, /\^1 N^* = O(1)⊕O(1), /\^2 N^* = O(2).

      The key result (Bridgeland 2002, Van den Bergh 2004):
        The KW quiver has 2 vertices with 2 arrows in each direction.
        dim End(T) = 1 + 2 + 2 + 1 = 6  (as vector space:
          Hom(0,0)=1, Hom(0,1)=2, Hom(1,0)=2, Hom(1,1)=1)

      This is NOT the naive P^1 computation but the CY3 computation.
    """
    return ConifoldTiltingData(
        num_vertices=2,
        arrows_01=2,
        arrows_10=2,
        is_cy3_self_dual=True,  # 2 = 2 (arrows balanced)
        potential="a1*b1*a2*b2 - a1*b2*a2*b1",
        nccr_algebra_dim=6,
    )


# =========================================================================
# Section 9: CY3 constraint verification
# =========================================================================

def verify_cy3_serre_duality(
    ext_matrix: Dict[Tuple[int, int], ExtData],
    num_summands: int,
) -> Tuple[bool, List[str]]:
    r"""Verify the CY3 Serre duality constraint on the Ext-quiver.

    For a CY3 X with tilting generator T = ⊕ T_i:
      dim Ext^1(T_i, T_j) = dim Ext^2(T_j, T_i)
      dim Ext^0(T_i, T_j) = dim Ext^3(T_j, T_i)

    This is Serre duality with omega_X = O_X and dim X = 3.

    Returns (is_satisfied, list of violations).
    """
    violations = []
    is_satisfied = True

    for i in range(num_summands):
        for j in range(num_summands):
            ed_ij = ext_matrix[(i, j)]
            ed_ji = ext_matrix[(j, i)]

            # Ext^1(T_i, T_j) = Ext^2(T_j, T_i)
            e1_ij = ed_ij.dims.get(1, 0)
            e2_ji = ed_ji.dims.get(2, 0)
            if e1_ij != e2_ji:
                violations.append(
                    f"Ext^1(T_{i}, T_{j})={e1_ij} != Ext^2(T_{j}, T_{i})={e2_ji}"
                )
                is_satisfied = False

            # Ext^0(T_i, T_j) = Ext^3(T_j, T_i)
            e0_ij = ed_ij.dims.get(0, 0)
            e3_ji = ed_ji.dims.get(3, 0)
            if e0_ij != e3_ji:
                violations.append(
                    f"Ext^0(T_{i}, T_{j})={e0_ij} != Ext^3(T_{j}, T_{i})={e3_ji}"
                )
                is_satisfied = False

    return is_satisfied, violations


