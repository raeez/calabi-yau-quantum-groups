# Section 10: Euler form and chi on derived categories
# =========================================================================

def euler_form_pn(n: int, i: int, j: int) -> int:
    r"""Euler form chi(O(i), O(j)) = sum_k (-1)^k dim Ext^k(O(i), O(j)) on P^n.

    By HRR: chi(O(i), O(j)) = chi(P^n, O(j-i)) = C(n+j-i, n).
    """
    return euler_char_pn_o_m(n, j - i)


def euler_form_hypersurface(n: int, d: int, i: int, j: int) -> int:
    r"""Euler form chi(O(i)|_Y, O(j)|_Y) for Y = {f_d=0} in P^n.

    chi(Y, O(m)|_Y) = chi(P^n, O(m)) - chi(P^n, O(m-d))
                     = C(n+m, n) - C(n+m-d, n).
    """
    m = j - i
    return euler_char_pn_o_m(n, m) - euler_char_pn_o_m(n, m - d)


def euler_form_cicy(ambient_dim: int, degrees: Tuple[int, ...], i: int, j: int) -> int:
    r"""Euler form chi(O(i)|_Y, O(j)|_Y) for a CICY Y in P^n.

    chi(Y, O(m)|_Y) = sum_{S subset degrees} (-1)^{|S|} chi(P^n, O(m - sum_S)).
    """
    m = j - i
    n = ambient_dim
    r = len(degrees)
    chi_val = 0
    for mask in range(1 << r):
        sign = (-1) ** bin(mask).count('1')
        d_sum = sum(degrees[idx] for idx in range(r) if mask & (1 << idx))
        chi_val += sign * euler_char_pn_o_m(n, m - d_sum)
    return chi_val


def euler_form_matrix_pn(n: int) -> List[List[int]]:
    """Euler form matrix for the Beilinson collection on P^n.

    Returns chi(O(i), O(j)) for 0 <= i, j <= n.
    """
    return [[euler_form_pn(n, i, j) for j in range(n + 1)] for i in range(n + 1)]


def euler_form_matrix_quintic() -> List[List[int]]:
    """Euler form matrix for the restricted Beilinson collection on the quintic."""
    return [[euler_form_hypersurface(4, 5, i, j) for j in range(5)] for i in range(5)]


def euler_form_matrix_cicy33() -> List[List[int]]:
    """Euler form matrix for the restricted Beilinson collection on CICY (3,3) in P^5."""
    return [[euler_form_cicy(5, (3, 3), i, j) for j in range(6)] for i in range(6)]


