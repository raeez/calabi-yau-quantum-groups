def cicy_hodge(ambient_dim: int, degrees: Tuple[int, ...]) -> Tuple[int, int]:
    r"""Compute (h^{1,1}, h^{2,1}) for a CICY in P^n via the Lefschetz+Euler method.

    For a smooth CICY Y of dimension 3 in P^n with multi-degree (d_1, ..., d_r):
      h^{1,1} = 1 (by Lefschetz hyperplane theorem, for codimension <= n-4 = dim Y - 1)
      h^{2,1} = 1 - chi(Y)/2  (from chi = 2(h^{1,1} - h^{2,1}) with h^{1,1} = 1)

    The Euler characteristic:
      chi(Y) = integral over Y of c_3(TY)
    For a CI of type (d_1, ..., d_r) in P^n:
      chi = coefficient of H^n in n! * [prod_{i} d_i * H / (1 + d_i * H)]
            * [(1+H)^{n+1} / prod_{i} (1 + d_i * H)]... no.

    Actually, the Euler characteristic of a CI can be computed from the
    Chern classes of the tangent bundle of Y:
      TY = TP^n|_Y - N_{Y/P^n}
    where N = ⊕ O(d_i).

    The total Chern class:
      c(TY) = c(TP^n)|_Y / c(N)|_Y = (1+H)^{n+1} / prod_i (1 + d_i H)

    restricted to Y (where H is the hyperplane class and H^{dim Y + 1} = 0 on Y,
    but we need to integrate H^{dim Y} which is the degree = prod d_i).

    chi(Y) = integral_Y c_{dim Y}(TY)
           = deg(Y) * [coefficient of H^{dim Y} in c(TY)]
    where deg(Y) = prod d_i.

    Actually, for a CI of dimension dim_Y in P^n:
      chi(Y) = prod(d_i) * coefficient of t^{dim_Y} in
        [(1+t)^{n+1} / prod_i (1 + d_i t)] expanded in t, then evaluated
        at t = 0... no, we need the c_{dim_Y} coefficient.

    The correct formula: expand
      c(TY) = (1+H)^{n+1} / prod_i (1 + d_i H)
    as a polynomial in H (modulo H^{dim_Y + 1}), then
      chi(Y) = deg(Y) * coefficient of H^{dim_Y} in c_{dim_Y}(TY).

    Wait: c(TY) = 1 + c_1 + c_2 + c_3 + ..., and chi(Y) = integral c_{dim_Y}.
    For Y of dimension 3: chi = integral c_3(TY).
    On Y: H^3 integrates to deg(Y) = prod d_i.
    So chi = [coefficient of H^3 in c_3(TY)] * prod d_i.

    But c_3 is the degree-3 part of (1+H)^{n+1} / prod (1+d_i H), which is
    a formal power series in H.
    """
    n = ambient_dim
    r = len(degrees)
    dim_Y = n - r

    if dim_Y != 3:
        raise ValueError(f"Expected CY3 (dim 3), got dim {dim_Y}")

    # Check CY condition: sum(d_i) = n + 1
    if sum(degrees) != n + 1:
        raise ValueError(f"Not CY: sum of degrees {sum(degrees)} != {n+1}")

    # Compute c(TY) = (1+H)^{n+1} / prod (1+d_i H) as a polynomial in H
    # up to degree 3.

    # Numerator: (1+H)^{n+1}
    # Expand to get coefficients: C(n+1, k) for k = 0, 1, 2, 3.
    num = [binomial(n + 1, k) for k in range(4)]

    # Denominator: prod (1 + d_i H)
    # We need the inverse: 1 / prod(1 + d_i H) = prod 1/(1+d_i H)
    # Each factor: 1/(1+d_i H) = 1 - d_i H + d_i^2 H^2 - d_i^3 H^3 + ...
    # Product of geometric series truncated to degree 3.

    denom_inv = [Fraction(1), Fraction(0), Fraction(0), Fraction(0)]
    for di in degrees:
        # Multiply denom_inv by (1 - di H + di^2 H^2 - di^3 H^3)
        geo = [Fraction((-di) ** k) for k in range(4)]
        new = [Fraction(0)] * 4
        for a in range(4):
            for b in range(4 - a):
                new[a + b] += denom_inv[a] * geo[b]
        denom_inv = new

    # c(TY) = num * denom_inv
    c_ty = [Fraction(0)] * 4
    for a in range(4):
        for b in range(4 - a):
            c_ty[a + b] += Fraction(num[a]) * denom_inv[b]

    # c_3(TY) = c_ty[3] (the coefficient of H^3)
    c3 = c_ty[3]

    # chi(Y) = deg(Y) * c3
    deg_Y = 1
    for di in degrees:
        deg_Y *= di

    chi_Y = int(deg_Y * c3)

    # For Lefschetz: h^{1,1} = 1 for CI of dim >= 3 in P^n
    h11 = 1

    # chi = 2(h^{1,1} - h^{2,1}) => h^{2,1} = h^{1,1} - chi/2
    h21 = h11 - chi_Y // 2

    return (h11, h21)


