# =========================================================================
# Section 0: Combinatorial utilities
# =========================================================================

def binomial(n: int, k: int) -> int:
    """Binomial coefficient C(n, k) for arbitrary integer n, non-negative k.

    Uses the generalized formula: C(n, k) = n*(n-1)*...*(n-k+1) / k!
    Returns 0 if k < 0 or (for non-negative n) if k > n.
    """
    if k < 0:
        return 0
    if k == 0:
        return 1
    # For non-negative n with k > n: return 0
    if n >= 0 and k > n:
        return 0
    result = 1
    for i in range(k):
        result = result * (n - i)
    result = result // math.factorial(k)
    return result


# =========================================================================
# Section 1: Cohomology of line bundles on P^n (Bott's theorem)
# =========================================================================

def h_k_pn_o_m(n: int, k: int, m: int) -> int:
    r"""Compute dim H^k(P^n, O(m)) via Bott's theorem.

    Bott's vanishing theorem for projective space:
      H^0(P^n, O(m)) = C(n+m, n) if m >= 0, else 0.
      H^n(P^n, O(m)) = C(-m-1, n) if m <= -(n+1), else 0.
      H^k(P^n, O(m)) = 0          for 0 < k < n.

    Proof sketch: Cech cohomology on the standard affine cover of P^n
    gives the explicit computation. The vanishing for 0 < k < n is
    Bott's theorem (the Euler sequence splits the tangent bundle
    cohomology; for line bundles, this reduces to the above).

    Parameters
    ----------
    n : dimension of P^n
    k : cohomological degree
    m : twist degree of O(m)

    Returns
    -------
    dim H^k(P^n, O(m))
    """
    if k < 0 or k > n:
        return 0
    if k == 0:
        # H^0(P^n, O(m)) = C(n+m, n) for m >= 0, else 0
        if m >= 0:
            return binomial(n + m, n)
        else:
            return 0
    elif k == n:
        # H^n(P^n, O(m)) = C(-m-1, n) for m <= -(n+1), else 0
        # This comes from Serre duality: H^n(P^n, O(m)) = H^0(P^n, O(-m-n-1))^*
        # So dim = C(n + (-m-n-1), n) = C(-m-1, n) when -m-1 >= 0, i.e., m <= -1
        # But actually: H^n(P^n, O(m)) != 0 only when m <= -(n+1).
        # By Serre duality: H^n(P^n, O(m)) ~ H^0(P^n, O(-m-n-1))^*
        # and H^0 != 0 iff -m-n-1 >= 0, i.e., m <= -(n+1).
        if m <= -(n + 1):
            return binomial(-m - 1, n)
        else:
            return 0
    else:
        # Bott vanishing: H^k(P^n, O(m)) = 0 for 0 < k < n
        return 0


def euler_char_pn_o_m(n: int, m: int) -> int:
    r"""Euler characteristic chi(P^n, O(m)) = sum_k (-1)^k H^k(P^n, O(m)).

    By Hirzebruch-Riemann-Roch: chi(P^n, O(m)) = C(n+m, n) for all m.
    (This formula holds for ALL m, including negative.)

    Verification: For m >= 0, only H^0 contributes: chi = C(n+m, n).
    For m <= -(n+1), only H^n contributes: chi = (-1)^n * C(-m-1, n).
    Check: C(n+m, n) with m <= -(n+1) gives C(n+m, n) with n+m <= -1,
    so C(n+m, n) = C(negative, n) = (-1)^n * C(n - (n+m) - 1, n) = (-1)^n * C(-m-1, n).
    Consistent.
    """
    return binomial(n + m, n)


# =========================================================================
# Section 2: Ext groups for line bundles on P^n
# =========================================================================

class ExtData(NamedTuple):
    """Ext group data between two objects in D^b(Coh(X))."""
    source: str  # label for source object
    target: str  # label for target object
    dims: Dict[int, int]  # degree k -> dim Ext^k

    @property
    def total_dim(self) -> int:
        return sum(self.dims.values())

    @property
    def euler(self) -> int:
        return sum((-1) ** k * d for k, d in self.dims.items())


def ext_line_bundles_pn(n: int, i: int, j: int) -> ExtData:
    """Compute Ext^*(O(i), O(j)) on P^n.

    Ext^k(O(i), O(j)) = H^k(P^n, O(j-i)).
    """
    m = j - i
    dims = {}
    for k in range(n + 1):
        d = h_k_pn_o_m(n, k, m)
        if d > 0:
            dims[k] = d
    return ExtData(source=f"O({i})", target=f"O({j})", dims=dims)


# =========================================================================
# Section 3: Beilinson exceptional collection on P^n
# =========================================================================

class ExceptionalCollection(NamedTuple):
    """An exceptional collection E_0, ..., E_r in D^b(Coh(X)).

    An exceptional collection satisfies:
      Ext^*(E_i, E_i) = k (in degree 0 only)
      Ext^*(E_i, E_j) = 0 for i > j
    It is STRONG if additionally Ext^{>0}(E_i, E_j) = 0 for all i, j.
    It is FULL if it generates D^b(Coh(X)).

    The tilting generator is T = bigoplus E_i.
    """
    objects: List[str]
    ext_matrix: Dict[Tuple[int, int], ExtData]
    is_exceptional: bool
    is_strong: bool
    is_full: bool
    variety: str


def beilinson_collection_pn(n: int) -> ExceptionalCollection:
    r"""Beilinson's exceptional collection on P^n: {O, O(1), ..., O(n)}.

    This is a full strong exceptional collection:
      Ext^k(O(i), O(j)) = H^k(P^n, O(j-i))
    For 0 <= i <= j <= n: j-i ranges from 0 to n.
      H^k(P^n, O(m)) for 0 <= m <= n: only H^0 is nonzero.
    So Ext^{>0}(O(i), O(j)) = 0 for i <= j (strong).
    For i > j: j-i < 0 and j-i >= -n, so m in {-n,...,-1}.
      H^k(P^n, O(m)) = 0 for all k when -n <= m <= -1 (Bott gap).
    So Ext^*(O(i), O(j)) = 0 for i > j (exceptional).

    FULL: This is Beilinson's theorem (1978).
    """
    objects = [f"O({i})" for i in range(n + 1)]
    ext_matrix: Dict[Tuple[int, int], ExtData] = {}

    is_exceptional = True
    is_strong = True

    for i in range(n + 1):
        for j in range(n + 1):
            ed = ext_line_bundles_pn(n, i, j)
            ext_matrix[(i, j)] = ed

            if i == j:
                # Must have Ext^* = k in degree 0 only
                if ed.dims != {0: 1}:
                    is_exceptional = False
            elif i > j:
                # Must have Ext^* = 0
                if ed.total_dim != 0:
                    is_exceptional = False
            else:
                # i < j: for strong, need Ext^{>0} = 0
                for k, d in ed.dims.items():
                    if k > 0 and d > 0:
                        is_strong = False

    return ExceptionalCollection(
        objects=objects,
        ext_matrix=ext_matrix,
        is_exceptional=is_exceptional,
        is_strong=is_strong,
        is_full=True,  # Beilinson's theorem
        variety=f"P^{n}",
    )


# =========================================================================
# Section 4: Ext-quiver of an exceptional collection
# =========================================================================

class QuiverData(NamedTuple):
    """Quiver data extracted from an exceptional collection or tilting generator.

    Vertices correspond to indecomposable summands of the tilting generator.
    Arrows from i to j are counted by dim Ext^1(T_i, T_j).
    For CY3: also record Ext^2 (= opposite arrows by Serre duality).
    """
    num_vertices: int
    vertex_labels: List[str]
    arrows: Dict[Tuple[int, int], int]  # (i, j) -> number of arrows i -> j
    ext2_arrows: Dict[Tuple[int, int], int]  # Ext^2 data
    variety: str
    is_cy3_self_dual: bool  # arrows(i,j) = ext2_arrows(j,i) for all i,j
    potential_terms: int  # number of terms in the potential W


def ext_quiver(ec: ExceptionalCollection, cy_dim: Optional[int] = None) -> QuiverData:
    r"""Extract the Ext-quiver from an exceptional collection.

    The quiver Q has:
      - Vertices: one for each object in the collection.
      - Arrows from i to j: dim Ext^1(E_i, E_j).
      - For CY3: Ext^2(E_j, E_i) = dim reverse arrows (Serre duality).

    The quiver with potential (Q, W) gives:
      D^b(Coh(X)) ~ D^b(Rep(Q, W))  (Bondal-type equivalence)

    For CY3: the potential W comes from the A_infinity m_3 product.
    The number of terms in W is related to dim Ext^2 (which counts
    relations in the path algebra).
    """
    n = len(ec.objects)
    arrows: Dict[Tuple[int, int], int] = {}
    ext2: Dict[Tuple[int, int], int] = {}

    for i in range(n):
        for j in range(n):
            ed = ec.ext_matrix[(i, j)]
            a1 = ed.dims.get(1, 0)
            a2 = ed.dims.get(2, 0)
            if a1 > 0:
                arrows[(i, j)] = a1
            if a2 > 0:
                ext2[(i, j)] = a2

    # CY3 self-duality check: dim Ext^1(E_i, E_j) = dim Ext^2(E_j, E_i)
    is_cy3 = True
    if cy_dim == 3:
        for i in range(n):
            for j in range(n):
                a1_ij = arrows.get((i, j), 0)
                a2_ji = ext2.get((j, i), 0)
                if a1_ij != a2_ji:
                    is_cy3 = False
                    break
            if not is_cy3:
                break
    else:
        is_cy3 = False  # not applicable

    # Potential terms: for a quiver with potential, the number of
    # potential terms equals the number of oriented 3-cycles weighted
    # by the A_infinity m_3 structure constants.
    # For the Beilinson quiver on P^n (n >= 3), potential terms come from
    # Ext^2 (= relations in the path algebra).
    potential_terms = sum(ext2.values())

    return QuiverData(
        num_vertices=n,
        vertex_labels=ec.objects,
        arrows=arrows,
        ext2_arrows=ext2,
        variety=ec.variety,
        is_cy3_self_dual=is_cy3,
        potential_terms=potential_terms,
    )


# =========================================================================
# Section 5: Restriction to hypersurface via Koszul resolution
# =========================================================================

def h_k_hypersurface_o_m(n: int, d: int, k: int, m: int) -> int:
    r"""Compute dim H^k(Y, O(m)|_Y) for Y = {f_d = 0} in P^n via Koszul.

    The Koszul exact sequence for Y (smooth hypersurface of degree d in P^n):
      0 -> O(-d) -> O -> O_Y -> 0

    gives the long exact sequence:
      ... -> H^k(P^n, O(m-d)) -> H^k(P^n, O(m)) -> H^k(Y, O(m)|_Y)
          -> H^{k+1}(P^n, O(m-d)) -> ...

    We compute H^k(Y, O(m)|_Y) from this LES.

    In general, the LES gives:
      H^k(Y, O(m)|_Y) = coker(H^k(P^n, O(m-d)) -> H^k(P^n, O(m)))
                       + ker(H^{k+1}(P^n, O(m-d)) -> H^{k+1}(P^n, O(m)))

    When the connecting maps are explicit, this reduces to:
      dim H^k(Y, ...) = dim H^k(P^n, O(m)) - dim im(alpha_k)
                       + dim ker(alpha_{k+1})
    where alpha_k: H^k(P^n, O(m-d)) -> H^k(P^n, O(m)) is multiplication by f_d.

    For line bundles on smooth hypersurfaces, the map alpha_k is:
    - INJECTIVE when both source and target are in the H^0 range (m-d >= 0, m >= 0)
    - SURJECTIVE when ... (depends on the specific case)
    - ZERO when source and target are in different cohomological ranges

    The dimension of Y is n-1. So H^k(Y, ...) = 0 for k > n-1.

    We compute this case by case using the explicit H^k(P^n, O(m)) values.
    """
    dim_Y = n - 1

    # H^k(Y, ...) = 0 for k > dim Y
    if k < 0 or k > dim_Y:
        return 0

    # The LES splits into short exact pieces.
    # Define a_k = dim H^k(P^n, O(m-d)) and b_k = dim H^k(P^n, O(m)).
    # The LES is:
    #   0 -> coker(a_k -> b_k) -> H^k(Y, ...) -> ker(a_{k+1} -> b_{k+1}) -> 0
    # But this is NOT always exact in this simple form. The full LES is:
    #
    # ... -> H^{k-1}(Y) -> H^k(P^n, O(m-d)) -f-> H^k(P^n, O(m)) -> H^k(Y) -> ...
    #
    # We need to track the connecting homomorphisms carefully.
    # For smooth hypersurfaces, there's a simpler approach: iterate.

    # For the specific cases we need (CY3 hypersurfaces), we use the
    # alternating sum (exact) plus case-by-case vanishing.

    # Strategy: compute via the Euler characteristic identity
    #   chi(Y, O(m)|_Y) = chi(P^n, O(m)) - chi(P^n, O(m-d))
    # and then use vanishing theorems to pin down individual H^k.

    # First compute all H^k(P^n, O(m)) and H^k(P^n, O(m-d)).
    a = [h_k_pn_o_m(n, kk, m - d) for kk in range(n + 1)]
    b = [h_k_pn_o_m(n, kk, m) for kk in range(n + 1)]

    # The Euler characteristic:
    chi_Y = sum((-1)**kk * b[kk] for kk in range(n + 1)) - \
            sum((-1)**kk * a[kk] for kk in range(n + 1))

    # For smooth CY hypersurface Y in P^n of degree d = n+1:
    # Kodaira vanishing: if m > 0, H^k(Y, O(m)|_Y) = 0 for k > 0
    #                    if m < 0, H^k(Y, O(m)|_Y) = 0 for k < dim_Y
    #                    (Kodaira: ample + positive => vanishing)

    # Case: m > 0 and m - d >= 0 (both in H^0 range)
    if m > 0 and m - d >= 0:
        # Only H^0 survives (Kodaira vanishing on Y for ample O(m)|_Y)
        # H^0(Y, O(m)|_Y) = H^0(P^n, O(m)) - H^0(P^n, O(m-d))
        # (the restriction map is surjective, and the kernel is f_d * H^0(O(m-d)))
        return b[0] - a[0] if k == 0 else 0

    # Case: m > 0 and m - d < 0 but m - d > -(n+1) (in the Bott gap)
    if m > 0 and m - d < 0 and m - d > -(n + 1):
        # H^k(P^n, O(m-d)) = 0 for all k (Bott gap: -(n) <= m-d <= -1)
        # So H^k(Y, O(m)|_Y) = H^k(P^n, O(m)) for k < dim_Y,
        # and the LES gives an exact answer.
        # By Kodaira on Y: H^k(Y, O(m)|_Y) = 0 for 0 < k < dim_Y when m > 0.
        # So only H^0 can be nonzero.
        if k == 0:
            return b[0]
        return 0

    # Case: m = 0
    if m == 0:
        # H^0(P^n, O) = 1, H^0(P^n, O(-d)) = 0
        # LES: 0 -> H^0(Y, O_Y) -> H^1(P^n, O(-d)) -> H^1(P^n, O) -> H^1(Y, O_Y) -> ...
        # H^1(P^n, O(-d)) = 0 (in Bott gap for d <= n)
        # H^1(P^n, O) = 0 (Bott)
        # So H^0(Y, O_Y) = 1 and H^1(Y, O_Y) comes from H^2(P^n, O(-d)).
        if k == 0:
            return 1
        # For CY: H^k(Y, O_Y) = h^{0,k}(Y).
        # By CY condition with omega_Y = O_Y:
        #   h^{0,k} = h^{dim_Y, dim_Y - k} by Hodge symmetry + Serre duality
        # For CY3 (dim_Y = 3): h^{0,0}=1, h^{0,1}=0, h^{0,2}=0, h^{0,3}=1.
        # For CY2 (dim_Y = 2, e.g. quartic in P^3): h^{0,0}=1, h^{0,1}=0, h^{0,2}=1.
        # More generally: from the LES, H^k(Y, O_Y) = ker(H^{k+1}(P^n, O(-d)) -> H^{k+1}(P^n, O)).
        # H^{k+1}(P^n, O(-d)) is zero unless k+1 = n and -d <= -(n+1), i.e., d >= n+1.
        # For CY (d = n+1): H^n(P^n, O(-(n+1))) = C(-(-n-1)-1, n) = C(n, n) = 1.
        # And H^n(P^n, O) = 0. So the map is 0 -> 1 -> 0, giving H^{n-1}(Y, O) = 1.
        # For k != 0 and k != n-1: H^k(Y, O_Y) = 0.
        if k == dim_Y and d == n + 1:
            return 1  # CY condition: h^{dim_Y,0} = 1
        return 0

    # Case: m < 0 and m > -(d):  (in the "interesting" range)
    # This is where Ext^1 and Ext^2 live for the CY restriction.
    if m < 0:
        # Use Serre duality on Y: H^k(Y, O(m)) = H^{dim_Y - k}(Y, O(-m))^*
        # (since omega_Y = O_Y for CY).
        # For CY (d = n+1): this is exact.
        if d == n + 1:
            # CY Serre duality
            return h_k_hypersurface_o_m(n, d, dim_Y - k, -m)
        # Non-CY case: omega_Y = O(d - n - 1)|_Y
        # Serre duality: H^k(Y, O(m)) = H^{dim_Y - k}(Y, O(d - n - 1 - m))^*
        return h_k_hypersurface_o_m(n, d, dim_Y - k, d - n - 1 - m)

    # Fallback: compute from the LES numerically
    # This handles edge cases not covered above.
    # For the LES: dim H^k(Y) = b[k] - im(alpha_k) + ker(alpha_{k+1})
    # In general, without knowing the maps, we use:
    #   dim H^k(Y) = b[k] + a[k+1] - (rank of combined map)
    # This is not computable in general. Return the Euler characteristic bound.
    # For our applications, the cases above should cover everything.
    return max(0, chi_Y) if k == 0 else 0


def ext_on_hypersurface(n: int, d: int, i: int, j: int) -> ExtData:
    r"""Compute Ext^*(O(i)|_Y, O(j)|_Y) for Y = {f_d = 0} in P^n.

    Ext^k_Y(O(i)|_Y, O(j)|_Y) = H^k(Y, O(j-i)|_Y)  (for line bundles).
    """
    m = j - i
    dim_Y = n - 1
    dims = {}
    for k in range(dim_Y + 1):
        val = h_k_hypersurface_o_m(n, d, k, m)
        if val > 0:
            dims[k] = val
    return ExtData(source=f"O({i})|_Y", target=f"O({j})|_Y", dims=dims)


# =========================================================================
# Section 6: Complete intersection CY3
# =========================================================================

def h_k_cicy_o_m(ambient_dim: int, degrees: Tuple[int, ...], k: int, m: int) -> int:
    r"""Compute dim H^k(Y, O(m)|_Y) for a CICY Y in P^n.

    Y is a complete intersection of hypersurfaces of degrees (d_1, ..., d_r) in P^n.
    dim Y = n - r.

    Uses iterated Koszul resolution:
      0 -> O(-D) -> ... -> ⊕ O(-d_i) -> O -> O_Y -> 0
    where D = sum(d_i).

    The cohomology is computed by iterating the hypersurface case:
    first restrict to the first hypersurface, then the second, etc.

    For small codimension (r = 1, 2), this is manageable.
    """
    n = ambient_dim
    r = len(degrees)
    dim_Y = n - r

    if k < 0 or k > dim_Y:
        return 0

    if r == 0:
        # Y = P^n itself
        return h_k_pn_o_m(n, k, m)

    if r == 1:
        return h_k_hypersurface_o_m(n, degrees[0], k, m)

    # For r >= 2: use the iterated Koszul resolution.
    # Strategy: write the Koszul complex for the last hypersurface as:
    #   0 -> F(-d_r) -> F -> F|_{Y_r} -> 0
    # where F is the restriction to the intersection of the first r-1 hypersurfaces.
    #
    # Alternatively: use the full Koszul resolution and take the alternating sum.
    # The full Koszul complex is:
    #   0 -> O(-D) -> ⊕_{|S|=r-1} O(-D_S) -> ... -> ⊕_i O(-d_i) -> O -> O_Y -> 0
    # where D_S = sum_{i in S} d_i.
    #
    # The Euler characteristic is:
    #   chi(Y, O(m)) = sum_{S subset [r]} (-1)^{|S|} chi(P^n, O(m - D_S))

    # For the full computation, we iterate the hypersurface case.
    # For r = 2: Y = Y_1 ∩ Y_2 where Y_1 = {f_{d_1} = 0}.
    # First restrict to Y_1 (a smooth hypersurface of degree d_1 in P^n),
    # then restrict to Y_2 ∩ Y_1 = Y (a hypersurface of degree d_2 in Y_1).

    # For CY3 (3,3) in P^5 (n=5, r=2, degrees=(3,3)):
    # Y_1 is a cubic 4-fold in P^5, then Y is a cubic surface in Y_1... no.
    # Y_1 is a smooth cubic 4-fold, Y is the intersection with another cubic.

    # Use the Koszul spectral sequence for CI.
    # For r = 2: the Koszul resolution of O_Y on P^n is:
    #   0 -> O(-d_1-d_2) -> O(-d_1) ⊕ O(-d_2) -> O -> O_Y -> 0
    # Long exact sequence approach: split into two short exact sequences.

    if r == 2:
        d1, d2 = degrees
        return _h_k_ci2_o_m(n, d1, d2, k, m)

    # For r >= 3: recursive approach
    # Not needed for our standard CY3 examples (which are r <= 2)
    # but include for completeness.
    # Use chi only.
    chi_Y = 0
    for mask in range(1 << r):
        sign = (-1) ** bin(mask).count('1')
        d_sum = sum(degrees[i] for i in range(r) if mask & (1 << i))
        chi_Y += sign * euler_char_pn_o_m(n, m - d_sum)

    # Without full vanishing analysis, return chi for k=0 (assuming vanishing
    # for k > 0, which holds for m >> 0).
    if m > 0 and k == 0:
        return chi_Y
    if m == 0:
        if k == 0:
            return 1
        if k == dim_Y and sum(degrees) == n + 1:
            return 1  # CY condition
        return 0
    if m < 0 and sum(degrees) == n + 1:
        # CY Serre duality
        return h_k_cicy_o_m(n, degrees, dim_Y - k, -m)

    return max(0, chi_Y) if k == 0 else 0


def _h_k_ci2_o_m(n: int, d1: int, d2: int, k: int, m: int) -> int:
    r"""H^k(Y, O(m)|_Y) for Y = CI(d1, d2) in P^n via the two-step Koszul.

    The Koszul complex is:
      0 -> O(-d1-d2) -> O(-d1) ⊕ O(-d2) -> O -> O_Y -> 0

    This gives a 3-term complex whose cohomology groups are related to
    H^k(P^n, O(m-d1-d2)), H^k(P^n, O(m-d1)), H^k(P^n, O(m-d2)), H^k(P^n, O(m)).

    The Euler characteristic:
      chi(Y, O(m)) = chi(P^n, O(m)) - chi(P^n, O(m-d1)) - chi(P^n, O(m-d2))
                   + chi(P^n, O(m-d1-d2))
    """
    dim_Y = n - 2
    if k < 0 or k > dim_Y:
        return 0

    # Compute all ambient cohomology groups
    c = [[h_k_pn_o_m(n, kk, m + shift) for kk in range(n + 1)]
         for shift in [0, -d1, -d2, -d1 - d2]]

    # Euler characteristic for verification
    chi_Y = sum((-1)**kk * c[0][kk] for kk in range(n+1)) \
          - sum((-1)**kk * c[1][kk] for kk in range(n+1)) \
          - sum((-1)**kk * c[2][kk] for kk in range(n+1)) \
          + sum((-1)**kk * c[3][kk] for kk in range(n+1))

    # Use vanishing to determine individual H^k
    # Case m > 0:
    if m > 0:
        # For m sufficiently positive: only H^0 survives
        # Specifically: if m > d1 + d2, all twists are >= 0 and only H^0 matters
        if m > d1 + d2:
            return (c[0][0] - c[1][0] - c[2][0] + c[3][0]) if k == 0 else 0
        # Otherwise use chi (all higher vanish by Kodaira on a CI of ample type)
        if k == 0:
            return chi_Y
        return 0

    if m == 0:
        if k == 0:
            return 1
        if k == dim_Y and d1 + d2 == n + 1:
            return 1  # CY condition
        return 0

    # m < 0: use Serre duality if CY
    if d1 + d2 == n + 1:
        return _h_k_ci2_o_m(n, d1, d2, dim_Y - k, -m)

    # Non-CY case with m < 0: use omega_Y = O(d1+d2-n-1)|_Y
    return _h_k_ci2_o_m(n, d1, d2, dim_Y - k, d1 + d2 - n - 1 - m)


def ext_on_cicy(ambient_dim: int, degrees: Tuple[int, ...], i: int, j: int) -> ExtData:
    r"""Compute Ext^*(O(i)|_Y, O(j)|_Y) for a CICY Y in P^n."""
    m = j - i
    dim_Y = ambient_dim - len(degrees)
    dims = {}
    for k in range(dim_Y + 1):
        val = h_k_cicy_o_m(ambient_dim, degrees, k, m)
        if val > 0:
            dims[k] = val
    return ExtData(source=f"O({i})|_Y", target=f"O({j})|_Y", dims=dims)


