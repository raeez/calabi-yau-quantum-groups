class FRTData(NamedTuple):
    """FRT (Faddeev-Reshetikhin-Takhtajan) reconstruction data.

    Given an R-matrix R(u) satisfying YBE, the FRT construction produces
    a bialgebra A(R) generated by matrix entries T^i_j(u) with RTT relations.

    For R_{K3}(u): the FRT algebra A(R_{K3}) IS C(g_{K3}, q).
    """
    r_matrix_dim: int               # 24 (acts on C^{24})
    num_rtt_generators: int         # 24^2 = 576 (entries of T^i_j)
    r_matrix_degree: Tuple[int, int]  # (24, 24) rational function
    ybe_verified: bool              # True (diagonal R -> automatic)
    unitarity_verified: bool        # True: R(u)R(-u) = I
    crossing_property: str          # description
    status: str


def frt_reconstruction(
    params: Optional[MukaiLatticeParams] = None,
) -> FRTData:
    r"""The FRT reconstruction of C(g_{K3}, q) from R_{K3}(z).

    The FRT construction (Faddeev-Reshetikhin-Takhtajan 1989):

    INPUT: An R-matrix R(u) in End(V tensor V) satisfying YBE.
    OUTPUT: A bialgebra A(R) generated by T^i_j(u) with:

        R_{12}(u-v) T_1(u) T_2(v) = T_2(v) T_1(u) R_{12}(u-v)

    For R_{K3}(u) = diag((u-h_i)/(u+h_i)):

    The RTT relations for the DIAGONAL R-matrix decouple into 24 independent
    rank-1 sectors:

        g_a(u-v) T^a_a(u) T^a_a(v) = T^a_a(v) T^a_a(u) g_a(u-v)

    Since g_a is a scalar (commutes with T), this becomes:
        T^a_a(u) T^a_a(v) = T^a_a(v) T^a_a(u)

    So the RTT algebra for the abelian K3 Yangian has COMMUTING generators
    within each Mukai direction.  The off-diagonal entries T^a_b for a != b
    are the e, f generators that create/annihilate excitations between
    Mukai directions.

    For the abelian (gl_1) case: T is DIAGONAL (T^a_b = 0 for a != b),
    and the FRT algebra reduces to 24 commuting copies of the rank-1
    Yangian, coupled through the psi-generators via the Mukai pairing.

    STATUS: The FRT construction is a THEOREM (Faddeev-Reshetikhin-Takhtajan).
    The identification A(R_{K3}) = C(g_{K3}, q) is CONJECTURAL (AP-CY14).
    """
    return FRTData(
        r_matrix_dim=NUM_PARAMS,
        num_rtt_generators=NUM_PARAMS ** 2,
        r_matrix_degree=(NUM_PARAMS, NUM_PARAMS),
        ybe_verified=True,
        unitarity_verified=True,
        crossing_property=(
            'R(u)^{t_1} = -(u + epsilon)/(u) * R(-u - epsilon)^{t_1}. '
            'For diagonal R: automatic from g(u) crossing symmetry.'
        ),
        status=CY_C_STATUS,
    )


