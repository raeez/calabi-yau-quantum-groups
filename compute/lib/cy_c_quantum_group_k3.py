    if params is None:
        params = kummer_k3_parameters()

    # Verify: g(z) * g^!(z) = g(z) * 1/g(z) = 1
    z_test = Rational(3)
    g_val = structure_function_evaluate(z_test, params)

    # g^!(z) with h_i -> -h_i
    h_dual = [-hi for hi in params.h]
    # Verify CY_2 for dual: sum(-h_i) = -sum(h_i) = 0
    dual_sum = sum(h_dual)

    # g^!(z) = prod(z - (-h_i))/(z + (-h_i)) = prod(z + h_i)/(z - h_i) = 1/g(z)
    g_dual = Rational(1)
    for hi in h_dual:
        g_dual *= (z_test - hi) / (z_test + hi)

    product = g_val * g_dual

    return {
        'koszul_conductor': 0,
        'kappa_ch_C': 2,       # kappa_ch(K3) = chi(O_{K3}) = 2
        'kappa_ch_C_dual': -2,  # kappa_ch(C^!) = -kappa_ch(C) when K=0
        'dual_parameters': 'h_i -> -h_i',
        'dual_structure_fn': 'g^!(z) = 1/g(z)',
        'g_times_g_dual_at_test': product,
        'product_is_one': product == 1,
        'dual_cy2_sum': dual_sum,
        'dual_cy2_satisfied': dual_sum == 0,
        'ap_cy10_note': (
            'Flop PRESERVES kappa (kappa(A_X) = kappa(A_{X^+})). '
            'Koszul INVERTS: kappa(C) + kappa(C^!) = K = 0.'
        ),
        'pass': product == 1 and dual_sum == 0,
        'status': CY_C_STATUS,
    }


