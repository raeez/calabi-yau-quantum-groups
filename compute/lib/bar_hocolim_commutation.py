# 9. DT partition function from bar complex
# =========================================================================

def dt_from_bar_euler_char(algebra: E1Algebra,
                           max_bar_degree: int = 4,
                           charges: Optional[List[Tuple[int, ...]]] = None,
                           ) -> Dict[str, Any]:
    """Extract DT invariants from bar complex Euler characteristics.

    The numerical DT invariant Ω(γ) at charge γ is:
        Ω(γ) = χ(B_γ) = Σ_k (-1)^k dim B^k_γ

    For the conifold:
        Ω(1,0) = -1 (single BPS state)
        Ω(0,1) = -1
        Ω(1,1) = -1 (in chamber II) or 0 (in chamber I)
    """
    bc = E1BarComplex(algebra, max_bar_degree)

    if charges is None:
        all_charges = set()
        for k in range(1, max_bar_degree + 1):
            all_charges.update(bc.bar_dimension_by_charge(k).keys())
        charges = sorted(all_charges)

    dt_inv = {}
    for ch in charges:
        chi = bc.euler_char_by_charge(ch)
        dt_inv[ch] = chi

    return {
        "algebra": algebra.name,
        "dt_invariants": {str(k): str(v) for k, v in dt_inv.items()},
        "charges_computed": [str(c) for c in charges],
    }


