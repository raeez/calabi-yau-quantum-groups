@dataclass
class E1AlgMorphism:
    """A morphism f: A → B of E₁ algebras.

    Given by the image of each generator of A in B.
    The image f(a) is expressed as a linear combination of generators of B.
    """
    source: E1Algebra
    target: E1Algebra
    # source_gen_name -> [(coeff, target_gen_name)]
    gen_map: Dict[str, List[Tuple[Fraction, str]]]

    def apply_to_generator(self, g: E1Generator) -> List[Tuple[Fraction, E1Generator]]:
        """Apply the morphism to a generator of the source."""
        images = self.gen_map.get(g.name, [])
        result = []
        for coeff, tgt_name in images:
            tgt_gen = self.target.generator_by_name(tgt_name)
            if tgt_gen is not None:
                result.append((coeff, tgt_gen))
        return result


@dataclass
class E1Diagram:
    """A diagram D: I → E₁-Alg for computing homotopy colimits.

    I is the indexing category. For our applications:
      - Conifold: I = (• ← • → •), a span (2 objects, 1 overlap)
      - Local P²: I = the nerve of a 3-chart cover (3 objects, 3 overlaps)

    The diagram is given by:
      - A list of E₁ algebras (the objects)
      - A list of morphisms (the arrows)
    """
    name: str
    algebras: Dict[str, E1Algebra]  # label -> algebra
    morphisms: List[Tuple[str, str, E1AlgMorphism]]  # (src_label, tgt_label, morph)

    @property
    def num_objects(self) -> int:
        return len(self.algebras)

    @property
    def num_morphisms(self) -> int:
        return len(self.morphisms)


