def local_p2_chart_algebra(chart_idx: int) -> E1Algebra:
    """CoHA chart for local P² at the i-th torus-fixed point.

    At large volume, each chart contributes a single Heisenberg boson
    (one per fixed point of P²). The chart algebra is H₁ (Heisenberg at level 1).

    Generator: J^{(i)} of charge (i, ) with κ = 1/2.
    The charge distinguishes which fixed point.
    """
    name = f"J{chart_idx}"
    gen = E1Generator(name, charge=(chart_idx,), weight=1)
    return E1Algebra(
        name=f"Chart_{chart_idx} (local P², fixed point p_{chart_idx})",
        generators=(gen,),
        mult_table={(name, name): None},
        kappa_value=Fraction(1, 2),  # Each Heisenberg contributes κ = 1/2
    )


def local_p2_overlap_algebra(i: int, j: int) -> E1Algebra:
    """Overlap algebra K_{ij} for charts i and j of local P².

    The overlap region between two torus-fixed points of P² is
    the torus-invariant P¹ connecting them.  At large volume,
    the overlap algebra is trivial (zero generators, κ = 0).
    """
    return E1Algebra(
        name=f"Overlap_{i}{j} (local P²)",
        generators=(),
        mult_table={},
        kappa_value=Fraction(0),
    )


def local_p2_triple_overlap() -> E1Algebra:
    """Triple overlap K_{012} for local P².

    The triple overlap of the three torus charts is the dense torus
    orbit (C*)² ⊂ P². At large volume, this is trivial.
    """
    return E1Algebra(
        name="Triple_overlap_012 (local P²)",
        generators=(),
        mult_table={},
        kappa_value=Fraction(0),
    )


def local_p2_three_chart_hocolim(max_bar_degree: int = 4) -> ThreeChartHocolim:
    """Build the 3-chart hocolim for local P²."""
    algebras = {
        "0": local_p2_chart_algebra(0),
        "1": local_p2_chart_algebra(1),
        "2": local_p2_chart_algebra(2),
    }
    overlaps = {
        "01": local_p2_overlap_algebra(0, 1),
        "12": local_p2_overlap_algebra(1, 2),
        "02": local_p2_overlap_algebra(0, 2),
    }
    triple = local_p2_triple_overlap()
    return ThreeChartHocolim(algebras, overlaps, triple, max_bar_degree)


def local_p2_bar_hocolim_full(max_bar_degree: int = 4) -> Dict[str, Any]:
    """Full bar-hocolim computation for local P²."""
    hc = local_p2_three_chart_hocolim(max_bar_degree)

    local_dims = hc.local_bar_dimensions()
    kappa_ie = hc.kappa_inclusion_exclusion()

    # Expected global κ: χ(P²)/2 = 3/2
    kappa_expected = Fraction(3, 2)

    return {
        "name": "local_P2",
        "num_charts": 3,
        "num_overlaps": 3,
        "local_bar_dims": local_dims,
        "kappa_inclusion_exclusion": kappa_ie,
        "kappa_expected": kappa_expected,
        "kappa_match": kappa_ie == kappa_expected,
        "local_kappas": {
            "chart_0": Fraction(1, 2),
            "chart_1": Fraction(1, 2),
            "chart_2": Fraction(1, 2),
            "overlap_01": Fraction(0),
            "overlap_12": Fraction(0),
            "overlap_02": Fraction(0),
            "triple_012": Fraction(0),
        },
    }


