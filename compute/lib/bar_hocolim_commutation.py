@dataclass(frozen=True)
class E1Generator:
    """A generator of an E₁ algebra (charge-graded)."""
    name: str
    charge: Tuple[int, ...] = (0,)
    cohom_degree: int = 0
    weight: int = 1

    def __repr__(self):
        return self.name


@dataclass(frozen=True)
class E1Algebra:
    """An E₁ algebra with explicit generators and multiplication table.

    The algebra is charge-graded by a lattice Gamma.
    Generators live in specific charge sectors.
    The product mu(a, b) is specified by the multiplication table.

    For a CoHA: the product is the KS shuffle product.
    For transition algebras: the product is the restriction.
    """
    name: str
    generators: Tuple[E1Generator, ...]
    # (gen_name_1, gen_name_2) -> (coefficient, gen_name_result) or None
    mult_table: Dict[Tuple[str, str], Optional[Tuple[Fraction, str]]]
    kappa_value: Fraction

    @property
    def num_generators(self) -> int:
        return len(self.generators)

    def generator_by_name(self, name: str) -> Optional[E1Generator]:
        for g in self.generators:
            if g.name == name:
                return g
        return None

    def multiply(self, g1: E1Generator,
                 g2: E1Generator) -> Optional[Tuple[Fraction, E1Generator]]:
        """Compute mu(g1, g2). Returns (coeff, result_gen) or None."""
        key = (g1.name, g2.name)
        result = self.mult_table.get(key)
        if result is None:
            return None
        coeff, gen_name = result
        gen = self.generator_by_name(gen_name)
        if gen is None:
            return None
        return (coeff, gen)

    def charge_sectors(self) -> List[Tuple[int, ...]]:
        return sorted(set(g.charge for g in self.generators))


