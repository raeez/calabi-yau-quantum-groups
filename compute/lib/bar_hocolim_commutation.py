# 6. Three-chart hocolim
# =========================================================================

class ThreeChartHocolim:
    """Hocolim for a 3-chart atlas (e.g. local P²).

    Three charts A₁, A₂, A₃ with overlaps K₁₂, K₂₃, K₁₃ and
    triple overlap K₁₂₃.

    The hocolim is computed by iterating the 2-chart construction:
        Step 1: hocolim₁₂ = hocolim(A₁ ← K₁₂ → A₂)
        Step 2: hocolim₁₂₃ = hocolim(hocolim₁₂ ← K₁₃,K₂₃ → A₃)

    At the level of κ (Mayer-Vietoris):
        κ(A_X) = κ(A₁) + κ(A₂) + κ(A₃) − κ(K₁₂) − κ(K₂₃) − κ(K₁₃) + κ(K₁₂₃)
    (inclusion-exclusion).
    """

    def __init__(self, algebras: Dict[str, E1Algebra],
                 overlaps: Dict[str, E1Algebra],
                 triple_overlap: Optional[E1Algebra] = None,
                 max_bar_degree: int = 4):
        self.algebras = algebras  # {"1": A1, "2": A2, "3": A3}
        self.overlaps = overlaps  # {"12": K12, "23": K23, "13": K13}
        self.triple_overlap = triple_overlap  # K123
        self.max_bar_degree = max_bar_degree

        self._bars: Dict[str, E1BarComplex] = {}
        for label, alg in {**algebras, **overlaps}.items():
            self._bars[label] = E1BarComplex(alg, max_bar_degree)
        if triple_overlap:
            self._bars["123"] = E1BarComplex(triple_overlap, max_bar_degree)

    def kappa_inclusion_exclusion(self) -> Fraction:
        """κ from inclusion-exclusion.

        κ(X) = Σ κ(Aᵢ) − Σ κ(Kᵢⱼ) + κ(K₁₂₃)
        """
        kappa = Fraction(0)
        for alg in self.algebras.values():
            kappa += alg.kappa_value
        for alg in self.overlaps.values():
            kappa -= alg.kappa_value
        if self.triple_overlap:
            kappa += self.triple_overlap.kappa_value
        return kappa

    def local_bar_dimensions(self) -> Dict[str, Dict[int, int]]:
        result = {}
        for label, bc in self._bars.items():
            result[label] = {k: bc.bar_dimension(k)
                             for k in range(1, self.max_bar_degree + 1)}
        return result

    def euler_char_inclusion_exclusion(self,
                                       charge: Tuple[int, ...]) -> Fraction:
        """Euler characteristic from inclusion-exclusion on bar complexes.

        χ(B(X)_γ) = Σ χ(B(Aᵢ)_γ) − Σ χ(B(Kᵢⱼ)_γ) + χ(B(K₁₂₃)_γ)
        """
        chi = Fraction(0)
        for label, bc in self._bars.items():
            c = bc.euler_char_by_charge(charge)
            if label in self.algebras:
                chi += c
            elif label in self.overlaps:
                chi -= c
            elif label == "123" and self.triple_overlap:
                chi += c
        return chi


