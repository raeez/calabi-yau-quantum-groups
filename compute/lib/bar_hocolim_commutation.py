def grand_verification(max_bar_degree: int = 4) -> Dict[str, Any]:
    """Run all bar-hocolim commutation verifications.

    Tests:
    1. Local bar complexes have d² = 0
    2. Bar is a chain-level functor (B(f) is a chain map)
    3. Hocolim differential has d² = 0
    4. κ from Mayer-Vietoris matches expected value
    5. Shadow towers from local data match global computation
    """
    results = {}

    # Conifold
    hc_con = conifold_two_chart_hocolim(max_bar_degree)

    # d² = 0 for local bar complexes
    for label, bc in [("A", hc_con.bar_A), ("B", hc_con.bar_B),
                      ("K", hc_con.bar_K)]:
        charges = list(set(g.charge for g in bc.algebra.generators))
        for ch in charges:
            results[f"d2_zero_{label}_{ch}"] = bc.verify_d_squared_zero(ch)

    # d² = 0 for hocolim
    for ch in [(1, 0), (0, 1), (1, 1)]:
        results[f"d2_zero_hocolim_{ch}"] = hc_con.verify_d_squared_zero(ch)

    # Chain map verification
    for k in range(2, max_bar_degree + 1):
        for ch in [(1, 1)]:
            results[f"chain_map_g_k{k}_{ch}"] = bar_commutes_with_morphism(
                hc_con.morph_g, hc_con.bar_K, hc_con.bar_B, k, ch)

    # Kappa Mayer-Vietoris
    kappa_mv = hc_con.kappa_mayer_vietoris()
    results["kappa_mv_conifold"] = str(kappa_mv)
    results["kappa_mv_conifold_expected"] = str(Fraction(1) + Fraction(1) - Fraction(1))
    results["kappa_mv_conifold_match"] = (kappa_mv == Fraction(1))

    # Local P²
    lp2 = local_p2_three_chart_hocolim(max_bar_degree)
    kappa_lp2 = lp2.kappa_inclusion_exclusion()
    results["kappa_ie_local_p2"] = str(kappa_lp2)
    results["kappa_ie_local_p2_expected"] = str(Fraction(3, 2))
    results["kappa_ie_local_p2_match"] = (kappa_lp2 == Fraction(3, 2))

    # Shadow tower consistency
    con_shadow = conifold_shadow_from_hocolim()
    results["conifold_kappa_from_shadow"] = str(con_shadow["kappa_ch"])
    lp2_shadow = local_p2_shadow_from_hocolim()
    results["local_p2_kappa_from_shadow"] = str(lp2_shadow["kappa_ch"])

    results["all_passed"] = all(
        v is True for k, v in results.items() if isinstance(v, bool))

    return results
