# 7. Conifold: the canonical 2-chart example
# =========================================================================

def conifold_coha_chart_I() -> E1Algebra:
    """CoHA of the conifold in Chamber I (large volume).

    2 generators: e₁ (charge (1,0)), e₂ (charge (0,1)).
    Product: e₁ * e₂ = e_{12} (charge (1,1)) with coefficient ⟨γ₁,γ₂⟩ = 1.
    But e_{12} is NOT a generator in Chamber I.
    So the product within the 2-generator algebra is zero.

    For the bar complex: the only nontrivial product uses the
    antisymmetric pairing to give a coefficient, but the result
    must land in a generator charge sector. In Chamber I, charge (1,1)
    is not populated, so the bar differential is effectively zero
    on the generators.

    CORRECTION: In the CoHA, the product of generators of charge γ₁, γ₂
    lands in the charge sector γ₁ + γ₂. Even if γ₁ + γ₂ is not a
    "primitive" BPS charge, the product is nonzero in the CoHA
    (it gives a multi-particle state). For the bar complex, we work
    with the algebra generated by the BPS states.

    For the purposes of the bar-hocolim computation, we model the
    CoHA as a free algebra on the generators (d_bar = 0, all products
    zero within the primitive generators).  The nontrivial bar differential
    only appears when we include bound states.
    """
    e1 = E1Generator("e1", charge=(1, 0))
    e2 = E1Generator("e2", charge=(0, 1))
    return E1Algebra(
        name="CoHA_I (conifold, chamber I)",
        generators=(e1, e2),
        mult_table={
            ("e1", "e1"): None, ("e2", "e2"): None,
            ("e1", "e2"): None, ("e2", "e1"): None,
        },
        kappa_value=Fraction(1),
    )


def conifold_coha_chart_II() -> E1Algebra:
    """CoHA of the conifold in Chamber II (flopped).

    3 generators: e₁ (charge (1,0)), e₂ (charge (0,1)), e₁₂ (charge (1,1)).
    Products:
      e₁ * e₂ = e₁₂  (coefficient = ⟨(1,0),(0,1)⟩ = 1)
      e₂ * e₁ = -e₁₂  (antisymmetry of ⟨·,·⟩)

    Other products are zero in the primitive-generator truncation.
    """
    e1 = E1Generator("e1", charge=(1, 0))
    e2 = E1Generator("e2", charge=(0, 1))
    e12 = E1Generator("e12", charge=(1, 1))
    return E1Algebra(
        name="CoHA_II (conifold, chamber II)",
        generators=(e1, e2, e12),
        mult_table={
            ("e1", "e1"): None, ("e2", "e2"): None,
            ("e12", "e12"): None,
            ("e1", "e2"): (Fraction(1), "e12"),
            ("e2", "e1"): (Fraction(-1), "e12"),
            ("e1", "e12"): None, ("e12", "e1"): None,
            ("e2", "e12"): None, ("e12", "e2"): None,
        },
        kappa_value=Fraction(1),
    )


def conifold_transition_algebra() -> E1Algebra:
    """The transition algebra K_{(1,1)} for the conifold.

    The overlap between the two charts is controlled by the wall-crossing
    locus.  The transition algebra has a single generator e₁₂ of charge (1,1).

    This models the BPS state that appears/disappears at the wall.

    The wall algebra has kappa = 1: the transition is an EQUIVALENCE
    (wall-crossing preserves the modular characteristic), so the wall
    algebra inherits the same kappa as each chart.  The MV formula
    then gives: kappa(global) = 1 + 1 - 1 = 1, matching the BCOV
    engine's conifold_data().kappa = 1 (from chi_top(P^1)/2).
    """
    e12 = E1Generator("e12", charge=(1, 1))
    return E1Algebra(
        name="K_{(1,1)} (conifold transition)",
        generators=(e12,),
        mult_table={("e12", "e12"): None},
        kappa_value=Fraction(1),  # Wall algebra has same κ as charts
    )


def conifold_morphism_f() -> E1AlgMorphism:
    """Morphism f: K → CoHA_I.

    In Chamber I, charge (1,1) is not a generator, so the transition
    generator maps to zero.  This is the inclusion of the wall-crossing
    locus into the large-volume chamber.
    """
    K = conifold_transition_algebra()
    A = conifold_coha_chart_I()
    return E1AlgMorphism(
        source=K, target=A,
        gen_map={"e12": []},  # Maps to zero (not a generator in Ch I)
    )


def conifold_morphism_g() -> E1AlgMorphism:
    """Morphism g: K → CoHA_II.

    In Chamber II, charge (1,1) IS a generator, so the transition
    generator maps to e₁₂ in Chamber II.
    """
    K = conifold_transition_algebra()
    B = conifold_coha_chart_II()
    return E1AlgMorphism(
        source=K, target=B,
        gen_map={"e12": [(Fraction(1), "e12")]},
    )


def conifold_two_chart_hocolim(max_bar_degree: int = 5) -> TwoChartHocolim:
    """Build the 2-chart hocolim for the conifold."""
    return TwoChartHocolim(
        alg_A=conifold_coha_chart_I(),
        alg_B=conifold_coha_chart_II(),
        alg_K=conifold_transition_algebra(),
        morph_f=conifold_morphism_f(),
        morph_g=conifold_morphism_g(),
        max_bar_degree=max_bar_degree,
    )


def conifold_bar_hocolim_full(max_bar_degree: int = 4) -> BarHocolimData:
    """Full bar-hocolim computation for the conifold."""
    hc = conifold_two_chart_hocolim(max_bar_degree)

    local_dims = {
        "CoHA_I": {k: hc.bar_A.bar_dimension(k)
                   for k in range(1, max_bar_degree + 1)},
        "CoHA_II": {k: hc.bar_B.bar_dimension(k)
                    for k in range(1, max_bar_degree + 1)},
        "K": {k: hc.bar_K.bar_dimension(k)
              for k in range(1, max_bar_degree + 1)},
    }

    local_kappas = {
        "CoHA_I": hc.alg_A.kappa_value,
        "CoHA_II": hc.alg_B.kappa_value,
        "K": hc.alg_K.kappa_value,
    }

    # Hocolim dimensions
    charges = [(1, 0), (0, 1), (1, 1), (2, 0), (0, 2)]
    hocolim_dims = {}
    for k in range(1, max_bar_degree + 1):
        total = 0
        for ch in charges:
            total += hc.hocolim_dimension(k, ch)
        hocolim_dims[k] = total

    hocolim_euler = {}
    for ch in charges:
        hocolim_euler[ch] = hc.hocolim_euler_char(ch)

    mv_data = {}
    for ch in charges:
        mv_data[str(ch)] = hc.mayer_vietoris_sequence(ch)

    kappa_mv = hc.kappa_mayer_vietoris()
    # The global κ of the conifold resolved = 1 (from the pair of P¹s)
    kappa_ch = Fraction(1)

    return BarHocolimData(
        name="conifold",
        local_bar_dims=local_dims,
        local_bar_cohom={},
        local_kappas=local_kappas,
        hocolim_bar_dims=hocolim_dims,
        hocolim_euler=hocolim_euler,
        global_kappa=kappa_ch,
        kappa_mayer_vietoris=kappa_mv,
        kappa_match=(kappa_ch == kappa_mv),
        mayer_vietoris=mv_data,
    )


