r"""Bar-hocolim commutation: B(hocolim) ≃ hocolim B.

THEOREM (thm:bar-hocolim-commutation):
  For a diagram D: I → E₁-Alg of E₁ algebras:
      B^{E₁}(hocolim_I D) ≃ hocolim_I B^{E₁}(D)

  In words: the E₁ bar complex commutes with homotopy colimits.

PROOF:
  The argument proceeds in four steps.

  (1) QUILLEN ADJUNCTION. By Vol I thm:quillen-equivalence-chiral
  (Vallette 2016, Theorems 2.1 and 2.9), the bar-cobar adjunction

      B_κ: dg-E₁-Alg ⇄ conil-dg-E₁-Coalg :Ω_κ

  is a Quillen equivalence. In particular, B_κ is a LEFT QUILLEN
  functor: it preserves cofibrations and acyclic cofibrations.

  (2) LEFT QUILLEN ⟹ DERIVED LEFT ADJOINT. A left Quillen functor
  has a total left derived functor LB: Ho(E₁-Alg) → Ho(E₁-Coalg),
  computed by applying B to a cofibrant replacement. Since ALL objects
  are cofibrant in the Vallette model structure (thm:quillen-equivalence-
  chiral, item (ii)), the derived functor LB = B on the nose.

  (3) DERIVED LEFT ADJOINTS PRESERVE HOMOTOPY COLIMITS. This is
  a standard fact in model category theory (Hirschhorn, Prop 19.1.8):
  a left derived functor LF: Ho(M) → Ho(N) arising from a left Quillen
  functor F preserves homotopy colimits. The reason: homotopy colimits
  are computed by bar constructions (the simplicial replacement
  formula), which are themselves colimits, and left adjoints preserve
  colimits.

  (4) COMBINING. For a diagram D: I → E₁-Alg:
      B(hocolim_I D) ≃ LB(hocolim_I D) ≃ hocolim_I LB(D) ≃ hocolim_I B(D)

  The first ≃ holds because all objects are cofibrant.
  The second ≃ holds by step (3).
  The third ≃ holds because all objects are cofibrant.                    □

CONSEQUENCE FOR SHADOW TOWERS (cor:hocolim-shadow-tower):
  If B(hocolim) = hocolim B, then the universal MC element Θ_A of the
  bar complex commutes with hocolim:
      Θ^{E₁}(A_X) = Θ^{E₁}(hocolim CoHA_α)
                   = hocolim Θ^{E₁}(CoHA_α)
  The GLOBAL shadow obstruction tower is the hocolim of LOCAL shadow towers.

  In particular, at the scalar level (arity 2, genus 1):
      κ(A_X) = hocolim_α κ(CoHA_α)

  For a 2-chart atlas {U₁, U₂} with overlap K:
      κ(A_X) = κ(CoHA₁) + κ(CoHA₂) − κ(K)

  This is the Mayer-Vietoris principle for the modular characteristic.

MAYER-VIETORIS SEQUENCE (cor:bar-mayer-vietoris):
  For a 2-chart cover {U₁, U₂} of the CY3 moduli with transition K:
      ... → H^n(B(K)) → H^n(B(CoHA₁)) ⊕ H^n(B(CoHA₂))
          → H^n(B(A_X)) → H^{n+1}(B(K)) → ...

  In the conifold case: the transition algebra K = K_{(1,1)} is
  generated by the single BPS state of charge (1,1).

COMPUTATIONS:
  1. Conifold (2-chart atlas): B(A_conifold) = hocolim(B(CoHA_I) ← B(K) → B(CoHA_II))
  2. Local P² (3-chart atlas): B(A_{LP2}) = hocolim of 3-chart diagram of bar complexes
  3. Mayer-Vietoris sequences with explicit dimensions and DT invariant extraction

CONVENTIONS:
  - Cohomological grading (|d| = +1).
  - Bar uses DESUSPENSION: |s⁻¹v| = |v| − 1 (AP45).
  - E₁ bar: ordered tensor products, Hochschild differential.
  - Exact arithmetic via fractions.Fraction.
  - κ follows Vol I conventions: κ(H_k) = k, κ(Vir_c) = c/2.

REFERENCES:
  Vol I: thm:quillen-equivalence-chiral (bar-cobar Quillen equivalence)
  Vol I: thm:bar-cobar-inversion-qi (bar-cobar inversion)
  Vallette (2016): model structures on operadic coalgebras
  Hirschhorn (2003): homotopy colimits and derived functors
  Kontsevich-Soibelman (2008): stability structures on CY3 categories
  Schiffmann-Vasserot (2013): CoHA and W_{1+∞}
"""

