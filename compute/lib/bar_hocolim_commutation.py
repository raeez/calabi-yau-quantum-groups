def _matrix_rank(mat: List[List[Fraction]]) -> int:
    """Compute rank of a matrix over Q via Gaussian elimination."""
    if not mat or not mat[0]:
        return 0
    rows = len(mat)
    cols = len(mat[0])
    m = [[mat[i][j] for j in range(cols)] for i in range(rows)]

    rank = 0
    for col in range(cols):
        pivot = None
        for row in range(rank, rows):
            if m[row][col] != Fraction(0):
                pivot = row
                break
        if pivot is None:
            continue
        m[rank], m[pivot] = m[pivot], m[rank]
        inv_piv = Fraction(1) / m[rank][col]
        for j in range(cols):
            m[rank][j] *= inv_piv
        for row in range(rows):
            if row == rank:
                continue
            factor = m[row][col]
            if factor != Fraction(0):
                for j in range(cols):
                    m[row][j] -= factor * m[rank][j]
        rank += 1
    return rank


def _matrix_kernel_dim(mat: List[List[Fraction]]) -> int:
    """Dimension of the kernel of a matrix."""
    if not mat or not mat[0]:
        return 0
    cols = len(mat[0])
    return cols - _matrix_rank(mat)


def _matrix_multiply(A: List[List[Fraction]],
                     B: List[List[Fraction]]) -> List[List[Fraction]]:
    """Multiply two matrices over Q."""
    if not A or not B or not A[0] or not B[0]:
        return []
    rA, cA = len(A), len(A[0])
    rB, cB = len(B), len(B[0])
    assert cA == rB, f"Matrix dims: {rA}x{cA} times {rB}x{cB}"
    result = [[Fraction(0)] * cB for _ in range(rA)]
    for i in range(rA):
        for k in range(cA):
            if A[i][k] == Fraction(0):
                continue
            for j in range(cB):
                result[i][j] += A[i][k] * B[k][j]
    return result


def _matrix_is_zero(mat: List[List[Fraction]]) -> bool:
    """Check if a matrix is identically zero."""
    return all(mat[i][j] == Fraction(0)
               for i in range(len(mat))
               for j in range(len(mat[0])))


