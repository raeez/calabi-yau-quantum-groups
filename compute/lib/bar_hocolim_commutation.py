def bar_of_morphism_matrix(morph: E1AlgMorphism,
                           bar_src: E1BarComplex,
                           bar_tgt: E1BarComplex,
                           k: int,
                           charge: Tuple[int, ...]) -> List[List[Fraction]]:
    """Matrix of B(f): B^k(A) → B^k(B) induced by f: A → B.

    For a bar element [a₁|...|aₖ], the induced map is:
        B(f)([a₁|...|aₖ]) = [f(a₁)|...|f(aₖ)]
    This uses the tensor-functor property of the bar construction.
    """
    src_basis = bar_src.basis_at_charge(k, charge)
    tgt_basis = bar_tgt.basis_at_charge(k, charge)

    if not src_basis or not tgt_basis:
        return []

    tgt_idx = {}
    for idx, elem in enumerate(tgt_basis):
        tgt_idx[elem.factor_names()] = idx

    mat = [[Fraction(0)] * len(src_basis) for _ in range(len(tgt_basis))]

    for j, src_elem in enumerate(src_basis):
        # Apply f to each factor
        # For simplicity, handle the case where f maps generators to generators
        # (not linear combinations)
        all_images: List[List[Tuple[Fraction, E1Generator]]] = []
        for g in src_elem.factors:
            images = morph.apply_to_generator(g)
            if not images:
                # Generator maps to zero; the whole bar element maps to zero
                all_images = []
                break
            all_images.append(images)

        if not all_images:
            continue

        # Expand the tensor product of images
        # For each factor, take each possible image generator
        # This implements the tensor product of the image maps
        from itertools import product as itprod
        for combo in itprod(*all_images):
            coeff = Fraction(1)
            factors = []
            for c, g in combo:
                coeff *= c
                factors.append(g)
            key = tuple(f.name for f in factors)
            if key in tgt_idx:
                row = tgt_idx[key]
                mat[row][j] += coeff

    return mat


class HocolimBarComplex:
    """Homotopy colimit of a diagram of bar complexes.

    For a diagram D: I → E₁-Alg, the bar-hocolim commutation gives:
        B(hocolim_I D) ≃ hocolim_I B(D)

    For a SPAN diagram (A ← K → B) (the 2-chart case):
        hocolim(B(A) ← B(K) → B(B)) is computed by the MAPPING CONE:

        hocolim^k = B^k(A) ⊕ B^k(B) ⊕ B^{k-1}(K)

    with differential:
        d_hocolim(a, b, x) = (d_A(a) + B(f)(x), d_B(b) - B(g)(x), -d_K(x))

    where f: K → A and g: K → B are the morphisms.

    The resulting long exact sequence is Mayer-Vietoris:
        ... → H^n(B(K)) → H^n(B(A)) ⊕ H^n(B(B)) → H^n(hocolim) → H^{n+1}(B(K)) → ...

    For a 3-chart diagram with overlaps, we iterate: first take the hocolim
    of 2 charts, then attach the 3rd via a mapping cone with the overlaps.
    """

    def __init__(self, diagram: E1Diagram, max_bar_degree: int = 5):
        self.diagram = diagram
        self.max_bar_degree = max_bar_degree
        self._bar_complexes: Dict[str, E1BarComplex] = {}
        self._build_local_bars()

    def _build_local_bars(self):
        for label, alg in self.diagram.algebras.items():
            self._bar_complexes[label] = E1BarComplex(
                alg, self.max_bar_degree)

    def local_bar(self, label: str) -> E1BarComplex:
        return self._bar_complexes[label]

    def local_bar_dimensions(self) -> Dict[str, Dict[int, int]]:
        result = {}
        for label, bc in self._bar_complexes.items():
            result[label] = {k: bc.bar_dimension(k)
                             for k in range(1, self.max_bar_degree + 1)}
        return result

    def local_kappas(self) -> Dict[str, Fraction]:
        return {label: alg.kappa_value
                for label, alg in self.diagram.algebras.items()}


