def verify_d_CE_arity1(k: float = 1.0) -> Dict[str, object]:
    """d_CE(s^{-1}J_{-n}) = 0 for all n."""
    eng = DeformedChiralCE(k=k)
    all_zero = True
    for n in range(-5, 6):
        result = eng.d_CE_arity1(n)
        if not result.is_zero():
            all_zero = False
    return {"ok": all_zero, "description": "d_CE = 0 on arity 1 (abelian gl_1)"}


def verify_d_CE_arity2(k: float = 1.0) -> Dict[str, object]:
    """d_CE on arity-2 elements: nonzero only when m+n=0."""
    eng = DeformedChiralCE(k=k)
    errors = []

    # m + n != 0: should be zero
    for m in range(-3, 4):
        for n in range(-3, 4):
            if m + n == 0:
                continue
            result = eng.d_CE_arity2(m, n)
            if not result.is_zero():
                errors.append(f"d_CE([J_{{-{m}}}|J_{{-{n}}}]) nonzero but m+n={m+n}!=0")

    # m + n = 0: should give k*m * (scalar)
    for m in range(-3, 4):
        n = -m
        result = eng.d_CE_arity2(m, n)
        expected_coeff = k * m
        actual_coeff = result.terms.get((), 0.0)
        if abs(actual_coeff - expected_coeff) > 1e-12:
            errors.append(
                f"d_CE([J_{{-{m}}}|J_{{{m}}}]) = {actual_coeff}, "
                f"expected {expected_coeff}"
            )

    return {"ok": len(errors) == 0, "errors": errors}


def verify_d_h_equals_d_CE_diagonal(
    k: float = 1.0, h: Tuple[complex, complex, complex] = (1.0, -0.5, -0.5)
) -> Dict[str, object]:
    """For diagonal embedding with h1+h2+h3=0, d_h = d_CE at all arities.

    This is the E_3 Koszul triviality for the Heisenberg.
    """
    eng = DeformedChiralCE(k=k, h=h, embedding=diagonal_embedding())
    errors = []

    # Arity 1
    for n in range(-3, 4):
        dh = eng.d_h_arity1(n)
        dce = eng.d_CE_arity1(n)
        diff = dh + (-1.0) * dce
        if not diff.is_zero():
            errors.append(f"arity 1, n={n}: d_h != d_CE, diff = {diff}")

    # Arity 2
    for m in range(-2, 3):
        for n in range(-2, 3):
            dh = eng.d_h_arity2(m, n)
            dce = eng.d_CE_arity2(m, n)
            diff = dh + (-1.0) * dce
            if not diff.is_zero():
                errors.append(f"arity 2, m={m}, n={n}: d_h != d_CE, diff = {diff}")

    # Arity 3
    for m in range(-1, 2):
        for n in range(-1, 2):
            for p in range(-1, 2):
                dh = eng.d_h_arity3(m, n, p)
                dce = eng.d_CE_arity3(m, n, p)
                diff = dh + (-1.0) * dce
                if not diff.is_zero():
                    errors.append(
                        f"arity 3, ({m},{n},{p}): d_h != d_CE, diff = {diff}"
                    )

    return {
        "ok": len(errors) == 0,
        "errors": errors,
        "h_sum": abs(eng.h_sum),
        "description": "d_h = d_CE for diagonal embedding (E_3 Koszul triviality)",
    }


def verify_d_h_squared_zero(
    k: float = 1.0,
    h: Tuple[complex, complex, complex] = (1.0, -0.3, -0.7),
    embedding: Optional[EquivariantEmbedding] = None,
) -> Dict[str, object]:
    """d_h^2 = 0 at arities 1, 2, 3."""
    emb = embedding or diagonal_embedding()
    eng = DeformedChiralCE(k=k, h=h, embedding=emb)
    errors = []

    # Arity 1: d_h^2 automatically zero (maps to arity -1)
    for n in range(-3, 4):
        result = eng.d_h_squared_arity1(n)
        if not result.is_zero():
            errors.append(f"arity 1, n={n}: d_h^2 != 0, got {result}")

    # Arity 2
    for m in range(-2, 3):
        for n in range(-2, 3):
            result = eng.d_h_squared_arity2(m, n)
            if not result.is_zero():
                errors.append(f"arity 2, ({m},{n}): d_h^2 != 0, got {result}")

    # Arity 3
    for m in range(-1, 2):
        for n in range(-1, 2):
            for p in range(-1, 2):
                result = eng.d_h_squared_arity3(m, n, p)
                if not result.is_zero():
                    errors.append(
                        f"arity 3, ({m},{n},{p}): d_h^2 != 0, got {result}"
                    )

    return {
        "ok": len(errors) == 0,
        "errors": errors,
        "embedding": emb.name,
        "h": (eng.h1, eng.h2, eng.h3),
        "h_sum": abs(eng.h_sum),
    }


def verify_d_h_nontrivial_axis(
    k: float = 1.0,
    h: Tuple[complex, complex, complex] = (1.0, -0.3, -0.7),
) -> Dict[str, object]:
    """For axis embedding, d_h != d_CE generically (deformation is visible).

    The axis embedding places the boson along one coordinate. The equivariant
    weight is nonzero only for that coordinate, so partial_1 acts nontrivially
    while partial_2 = partial_3 = 0. The total deformation h_1*partial_1
    does not vanish (even though h_1+h_2+h_3=0).
    """
    emb = axis_embedding(axis=1)
    eng = DeformedChiralCE(k=k, h=h, embedding=emb)
    found_nontrivial = False

    for n in range(-3, 4):
        if n == 0:
            continue
        dh = eng.d_h_arity1(n)
        dce = eng.d_CE_arity1(n)
        diff = dh + (-1.0) * dce
        if not diff.is_zero():
            found_nontrivial = True
            break

    return {
        "ok": found_nontrivial,
        "description": "d_h != d_CE for axis embedding (deformation visible)",
    }


def verify_d_h_squared_axis_violates(
    k: float = 1.0,
    h: Tuple[complex, complex, complex] = (1.0, -0.3, -0.7),
) -> Dict[str, object]:
    """For axis embedding with CY constraint, d_h^2 = 0 still holds.

    Even though the axis embedding is not CY_3, the differential d_h^2 = 0
    for the Heisenberg because the Lie algebra is abelian. The key insight:
    d_CE = 0 on arity 1, and partial_i^2 = 0 (contraction squared vanishes),
    and the cross-terms d_CE * partial_i + partial_i * d_CE vanish because
    d_CE = 0 on arity 1.

    For non-abelian algebras, d_h^2 = 0 would genuinely require h1+h2+h3=0
    AND a specific embedding. For the abelian case, d_h^2 = 0 is automatic.
    """
    emb = axis_embedding(axis=1)
    eng = DeformedChiralCE(k=k, h=h, embedding=emb)
    errors = []

    for m in range(-2, 3):
        for n in range(-2, 3):
            result = eng.d_h_squared_arity2(m, n)
            if not result.is_zero():
                errors.append(f"arity 2, ({m},{n}): d_h^2 != 0, got {result}")

    return {
        "ok": len(errors) == 0,
        "errors": errors,
        "description": (
            "d_h^2 = 0 for axis embedding (automatic for abelian algebra)"
        ),
    }


def verify_arity2_explicit(k: float = 1.0) -> Dict[str, object]:
    r"""Explicit computation of d_h(s^{-1}J_{-m} | s^{-1}J_{-n}) for
    several (m, n) pairs with generic h.

    Expected results for diagonal embedding with h1+h2+h3=0:
        d_h = d_CE (Koszul triviality), so:
        - (m, n) with m+n != 0: d_h = 0
        - (m, -m): d_h = k*m * (scalar)

    Expected results for axis-1 embedding:
        d_h has additional arity-1 terms from partial_1.
    """
    results = {}

    # Diagonal
    h = (0.5 + 0.1j, -0.2 + 0.3j, -0.3 - 0.4j)
    eng_diag = DeformedChiralCE(k=k, h=h, embedding=diagonal_embedding())

    for m, n in [(1, -1), (2, -2), (1, 2), (0, 0), (1, 0), (-1, 1)]:
        dh = eng_diag.d_h_arity2(m, n)
        dce = eng_diag.d_CE_arity2(m, n)
        diff = dh + (-1.0) * dce
        results[f"diag_({m},{n})_equals_dCE"] = diff.is_zero()

    # Axis-1
    eng_axis = DeformedChiralCE(k=k, h=h, embedding=axis_embedding(1))

    # For axis-1: d_h has extra terms h_1 * partial_1
    # partial_1([s^{-1}J_{-m}|s^{-1}J_{-n}]) = m*s^{-1}J_{-n} - n*s^{-1}J_{-m}
    # So d_h = d_CE + h_1*(m*[J_{-n}] - n*[J_{-m}])
    dh_axis = eng_axis.d_h_arity2(1, -1)
    # d_CE part: k*1 = k (scalar)
    # partial_1 part: h_1*(1*s^{-1}J_1 - (-1)*s^{-1}J_{-1})
    #               = h_1*(s^{-1}J_1 + s^{-1}J_{-1})
    # So we expect arity-0 coeff k and arity-1 terms h_1*[J_1] and h_1*[J_{-1}]
    expected_scalar = k * 1  # from d_CE
    expected_J_neg1 = h[0] * (-1) * (-1)  # h_1 * (-(-1)) = h_1
    expected_J_1 = h[0] * 1  # h_1 * w_1(1) = h_1*1 on s^{-1}J_1 slot
    # partial_1([s^{-1}J_{-1}|s^{-1}J_1]) = w_1(1)*s^{-1}J_1 - w_1(-1)*s^{-1}J_{-1}
    # = 1*s^{-1}J_1 - (-1)*s^{-1}J_{-1} = s^{-1}J_1 + s^{-1}J_{-1}
    # So h_1*partial_1 gives h_1*s^{-1}J_1 + h_1*s^{-1}J_{-1} at arity 1

    actual_scalar = dh_axis.terms.get((), 0.0)
    actual_J_neg1 = dh_axis.terms.get((-1,), 0.0)  # coefficient of s^{-1}J_1
    actual_J_1 = dh_axis.terms.get((1,), 0.0)  # coefficient of s^{-1}J_{-1}

    results["axis_(1,-1)_scalar"] = abs(actual_scalar - k) < 1e-12
    results["axis_(1,-1)_J1_coeff"] = abs(actual_J_neg1 - h[0]) < 1e-12
    results["axis_(1,-1)_Jneg1_coeff"] = abs(actual_J_1 - h[0]) < 1e-12

    all_ok = all(results.values())
    return {"ok": all_ok, "details": results}


def verify_h_constraint_violation(k: float = 1.0) -> Dict[str, object]:
    """When h1+h2+h3 != 0, d_h^2 may fail for non-abelian algebras.

    For the abelian gl_1, d_h^2 = 0 regardless because d_CE is trivial.
    We verify this: even with h1+h2+h3 != 0, d_h^2 = 0 for the Heisenberg.
    """
    h_bad = (1.0, 1.0, 1.0)  # h1+h2+h3 = 3 != 0
    eng = DeformedChiralCE(k=k, h=h_bad, embedding=diagonal_embedding())

    assert not eng.calabi_yau_satisfied, "CY should be violated"

    errors = []
    for m in range(-2, 3):
        for n in range(-2, 3):
            result = eng.d_h_squared_arity2(m, n)
            if not result.is_zero():
                errors.append(f"({m},{n}): d_h^2 != 0")

    return {
        "ok": len(errors) == 0,
        "h_sum": eng.h_sum,
        "description": (
            "d_h^2 = 0 even with CY violation (abelian algebra is special)"
        ),
    }


def verify_general_embedding_compatible(k: float = 1.0) -> Dict[str, object]:
    """General non-diagonal embedding with h . W = 0 (compatible).

    W = (1, 2, -3) with h chosen so that h . W = h_1 + 2*h_2 - 3*h_3 = 0.
    This ensures d_h^2 = 0 at all arities.
    """
    W = np.array([1.0, 2.0, -3.0])
    # Choose h with h . W = 0: h_1 + 2*h_2 - 3*h_3 = 0
    # e.g. h = (1, -2, -1): 1 + (-4) - (-3) = 1 - 4 + 3 = 0.
    h = (1.0, -2.0, -1.0)  # h . W = 1 - 4 + 3 = 0
    emb = general_embedding(W)
    eng = DeformedChiralCE(k=k, h=h, embedding=emb)

    assert eng.embedding_compatible, f"h.W = {eng.h_dot_W(1)} should be 0"

    # d_h != d_CE (non-diagonal, but compatible)
    found_diff = False
    for n in range(-3, 4):
        if n == 0:
            continue
        dh = eng.d_h_arity1(n)
        dce = eng.d_CE_arity1(n)
        diff = dh + (-1.0) * dce
        if not diff.is_zero():
            found_diff = True
            break

    # d_h^2 = 0 at arity 2 and 3 (compatible embedding)
    errors = []
    for m in range(-2, 3):
        for n in range(-2, 3):
            result = eng.d_h_squared_arity2(m, n)
            if not result.is_zero():
                errors.append(f"arity2 ({m},{n})")

    for m in range(-1, 2):
        for n in range(-1, 2):
            for p in range(-1, 2):
                result = eng.d_h_squared_arity3(m, n, p)
                if not result.is_zero():
                    errors.append(f"arity3 ({m},{n},{p})")

    return {
        "ok": found_diff and len(errors) == 0,
        "nontrivial_deformation": found_diff,
        "d_h_squared_zero": len(errors) == 0,
        "h_dot_W": eng.h_dot_W(1),
    }


def verify_general_embedding_incompatible(k: float = 1.0) -> Dict[str, object]:
    """General non-diagonal embedding with h . W != 0 (incompatible).

    W = (1, 2, -3) with generic h satisfying h_1+h_2+h_3=0 but NOT h.W=0.
    d_h^2 should FAIL at arity 3 (but succeed at arity 2 for abelian gl_1).
    """
    W = np.array([1.0, 2.0, -3.0])
    h = (0.5, -0.2, -0.3)  # h . W = 0.5 - 0.4 + 0.9 = 1.0 != 0
    emb = general_embedding(W)
    eng = DeformedChiralCE(k=k, h=h, embedding=emb)

    assert not eng.embedding_compatible, f"h.W = {eng.h_dot_W(1)} should be nonzero"

    # d_h^2 at arity 2: still 0 (abelian)
    arity2_ok = True
    for m in range(-2, 3):
        for n in range(-2, 3):
            result = eng.d_h_squared_arity2(m, n)
            if not result.is_zero():
                arity2_ok = False
                break

    # d_h^2 at arity 3: should FAIL for some triples
    found_failure = False
    for m in range(-1, 2):
        for n in range(-1, 2):
            for p in range(-1, 2):
                result = eng.d_h_squared_arity3(m, n, p)
                if not result.is_zero():
                    found_failure = True
                    break
            if found_failure:
                break
        if found_failure:
            break

    return {
        "ok": arity2_ok and found_failure,
        "arity2_ok": arity2_ok,
        "arity3_fails": found_failure,
        "h_dot_W": eng.h_dot_W(1),
        "description": (
            "Incompatible embedding: d_h^2=0 at arity 2 (abelian), "
            "d_h^2!=0 at arity 3 (h.W != 0)"
        ),
    }


