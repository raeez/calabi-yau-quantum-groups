# =========================================================================
#  1. Bar generators and elements
# =========================================================================

@dataclass(frozen=True)
class BarGenerator:
    """A bar generator s^{-1}J_{-n} of the bar complex B(V_k(gl_1)).

    Attributes
    ----------
    mode : int
        The mode index n in J_{-n}. Convention: mode=n means the generator
        is s^{-1}J_{-n}. Positive n = creation modes, negative n = annihilation.
    """
    mode: int

    @property
    def degree(self) -> int:
        """Cohomological degree = |J_{-n}| - 1 = 1 in this CE model."""
        return 1

    def __repr__(self) -> str:
        return f"s^{{-1}}J_{{-{self.mode}}}"


@dataclass
class BarElement:
    """A linear combination of tensor products of bar generators.

    An element of B_p(V_k(gl_1)) is a linear combination of
    s^{-1}J_{-n_1} | ... | s^{-1}J_{-n_p} (arity p).

    Stored as a dictionary: {(n_1, ..., n_p): coefficient}.
    """
    terms: Dict[Tuple[int, ...], complex]

    @property
    def arity(self) -> Optional[int]:
        """Arity (bar degree). None if mixed or empty."""
        arities = {len(k) for k in self.terms if self.terms[k] != 0}
        if len(arities) == 1:
            return arities.pop()
        if len(arities) == 0:
            return 0
        return None  # mixed arity

    def __repr__(self) -> str:
        if not self.terms:
            return "0"
        parts = []
        for modes, coeff in sorted(self.terms.items()):
            if abs(coeff) < 1e-15:
                continue
            gens = " | ".join(f"s^{{-1}}J_{{-{n}}}" for n in modes)
            if abs(coeff - 1.0) < 1e-15:
                parts.append(f"[{gens}]")
            elif abs(coeff + 1.0) < 1e-15:
                parts.append(f"-[{gens}]")
            else:
                parts.append(f"{coeff}*[{gens}]")
        return " + ".join(parts) if parts else "0"

    def __add__(self, other: "BarElement") -> "BarElement":
        result = dict(self.terms)
        for k, v in other.terms.items():
            result[k] = result.get(k, 0.0) + v
        return BarElement(result)

    def __rmul__(self, scalar: complex) -> "BarElement":
        return BarElement({k: scalar * v for k, v in self.terms.items()})

    def __neg__(self) -> "BarElement":
        return BarElement({k: -v for k, v in self.terms.items()})

    def is_zero(self, tol: float = 1e-12) -> bool:
        return all(abs(v) < tol for v in self.terms.values())

    def cleaned(self, tol: float = 1e-12) -> "BarElement":
        """Remove near-zero terms."""
        return BarElement({k: v for k, v in self.terms.items() if abs(v) >= tol})

    @staticmethod
    def zero() -> "BarElement":
        return BarElement({})

    @staticmethod
    def basis(modes: Tuple[int, ...], coeff: complex = 1.0) -> "BarElement":
        """Create a basis element coeff * [s^{-1}J_{-n_1} | ... | s^{-1}J_{-n_p}]."""
        return BarElement({modes: coeff})


# =========================================================================
#  2. Weight data: equivariant embeddings into C^3
# =========================================================================

@dataclass
class EquivariantEmbedding:
    """Specifies how V_k(gl_1) sits inside the C^3 Omega-background.

    The three equivariant vector fields xi_i = z_i d/dz_i (i=1,2,3)
    act on the mode J_{-n} with weight w_i(n).

    Attributes
    ----------
    weight_fn : callable
        weight_fn(i, n) -> weight of J_{-n} under xi_i (i in {1,2,3}).
    name : str
        Human-readable name for the embedding type.
    """
    name: str
    _weight_fn: object  # callable (i: int, n: int) -> complex

    def weight(self, i: int, n: int) -> complex:
        """Weight of s^{-1}J_{-n} under the i-th equivariant action."""
        assert i in (1, 2, 3), f"i must be 1, 2, or 3, got {i}"
        return self._weight_fn(i, n)


def diagonal_embedding() -> EquivariantEmbedding:
    """Diagonal CY_3 embedding: w_i(n) = n for all i.

    This is the natural embedding for a single boson in C^3 where the mode
    J_{-n} couples equally to all three coordinates. The CY condition
    h_1+h_2+h_3=0 then ensures the total deformation vanishes.
    """
    return EquivariantEmbedding(
        name="diagonal",
        _weight_fn=lambda i, n: n,
    )


def axis_embedding(axis: int = 1) -> EquivariantEmbedding:
    """Axis-aligned embedding: w_axis(n) = n, w_j(n) = 0 for j != axis.

    This places the boson along a single coordinate axis in C^3. The
    deformation d_h = d_CE + h_axis * n does NOT vanish generically.
    """
    return EquivariantEmbedding(
        name=f"axis-{axis}",
        _weight_fn=lambda i, n, ax=axis: n if i == ax else 0,
    )


def general_embedding(W: np.ndarray) -> EquivariantEmbedding:
    """General embedding from a 3-vector of weights.

    W = (w_1, w_2, w_3): the mode J_{-n} has weight w_i * n under xi_i.

    d_h^2 = 0 requires h . W = h_1*w_1 + h_2*w_2 + h_3*w_3 = 0.
    The CY condition h_1+h_2+h_3=0 guarantees this only when W is
    proportional to (1,1,1) (the diagonal embedding).
    """
    assert W.shape == (3,), f"W must be a 3-vector, got shape {W.shape}"
    return EquivariantEmbedding(
        name=f"general({W[0]},{W[1]},{W[2]})",
        _weight_fn=lambda i, n, _W=W: _W[i - 1] * n,
    )


# =========================================================================
#  3. The deformed chiral CE differential engine
# =========================================================================

class DeformedChiralCE:
    """Engine for the deformed chiral CE differential d_h on B(V_k(gl_1)).

    d_h = d_CE + h_1 * partial_1 + h_2 * partial_2 + h_3 * partial_3

    Parameters
    ----------
    k : float
        Level of V_k(gl_1). This is kappa_{ch} in the kappa-spectrum.
    h : tuple of 3 complex numbers
        Omega-background parameters (h_1, h_2, h_3).
    embedding : EquivariantEmbedding
        How V_k(gl_1) sits in C^3.
    """

    def __init__(
        self,
        k: float = 1.0,
        h: Tuple[complex, complex, complex] = (0.0, 0.0, 0.0),
        embedding: Optional[EquivariantEmbedding] = None,
    ):
        self.k = k
        self.h1, self.h2, self.h3 = h
        self.embedding = embedding or diagonal_embedding()

    @property
    def h_sum(self) -> complex:
        """h_1 + h_2 + h_3. Must be 0 for d_h^2 = 0."""
        return self.h1 + self.h2 + self.h3

    @property
    def calabi_yau_satisfied(self) -> bool:
        """Check h_1 + h_2 + h_3 = 0."""
        return abs(self.h_sum) < 1e-12

    def h_dot_W(self, n: int = 1) -> complex:
        """Compute h . W(n) = h_1*w_1(n) + h_2*w_2(n) + h_3*w_3(n).

        This is the effective deformation weight on the mode J_{-n}.
        d_h^2 = 0 requires h . W = 0 for all n (which for linear weights
        w_i(n) = W_i * n reduces to h_1*W_1 + h_2*W_2 + h_3*W_3 = 0).

        For the diagonal embedding (W_i = 1), this is h_1 + h_2 + h_3.
        """
        return sum(
            hi * self.embedding.weight(i, n)
            for i, hi in enumerate([self.h1, self.h2, self.h3], start=1)
        )

    @property
    def embedding_compatible(self) -> bool:
        """Check h . W = 0 (necessary for d_h^2 = 0 at arity >= 3).

        For the abelian gl_1, d_h^2 = 0 at arity 2 is automatic (the
        cross-terms from d_CE and partial_i cancel independently). At
        arity 3, d_h^2 = 0 requires the full compatibility h . W = 0.
        """
        return abs(self.h_dot_W(1)) < 1e-12

    # ----- d_CE: the undeformed CE differential -----

    def d_CE_arity1(self, n: int) -> BarElement:
        """d_CE(s^{-1}J_{-n}) for a single bar generator.

        For gl_1 (abelian Lie algebra): d_CE = 0 on arity-1 elements.
        The CE differential of an abelian Lie algebra is zero on degree-1
        cochains because there is no Lie bracket to dualize.
        """
        return BarElement.zero()

    def d_CE_arity2(self, m: int, n: int) -> BarElement:
        r"""d_CE(s^{-1}J_{-m} | s^{-1}J_{-n}) on an arity-2 bar element.

        The bar differential d_2 on B_2 -> B_1 encodes the commutator:
            d_CE([s^{-1}J_{-m} | s^{-1}J_{-n}])
                = commutator contribution to arity 1
                = [J_{-m}, J_{-n}] expressed in bar generators

        For V_k(gl_1):
            [J_{-m}, J_{-n}] = k*(-m)*delta_{-m+(-n),0}
                              = -k*m*delta_{m+n,0}

        So d_CE is nonzero only when m + n = 0 (i.e. n = -m), and gives:

            d_CE([s^{-1}J_{-m} | s^{-1}J_{m}]) = -k*m * (vacuum bar element)

        The vacuum bar element is the arity-0 unit in the bar complex (a scalar).
        We represent this as the empty tuple () with the appropriate coefficient.

        Sign convention: d_bar on [a|b] = a*b - (-1)^{|a||b|} b*a in the universal
        enveloping algebra. With |a|=|b|=1 (bar degree), this is a*b + b*a.
        For the Heisenberg: J_{-m}*J_{-n} + J_{-n}*J_{-m} = [J_{-m}, J_{-n}]
        (since gl_1 is abelian, the product in U(gl_1) is commutative, and the
        antisymmetrization gives the bracket). Actually in the Lie algebra context:

        The CE differential on the exterior algebra Lambda^*(g^*) is dual to the
        bracket. On the bar complex B(g) = T^c(g[1]), the differential is:

            d_2([a|b]) = [a, b]   (the Lie bracket, landing in arity 1)

        For our conventions with s^{-1}J modes:
            d_CE([s^{-1}J_{-m} | s^{-1}J_{-n}]) corresponds to [J_{-m}, J_{-n}]

        Since [J_{-m}, J_{-n}] = k*(-m)*delta_{m+n,0} is a SCALAR (central
        extension), it maps to the arity-0 piece (a scalar coefficient).

        We include the Koszul sign: for two degree-1 elements a, b,
            d_2([a|b]) = (-1)^{|a|} [a, b] = -[a, b]
        (the sign comes from the bar desuspension convention).

        Result: d_CE([s^{-1}J_{-m} | s^{-1}J_{-n}]) = -[J_{-m}, J_{-n}]
              = k*m*delta_{m+n,0} * (scalar)
        """
        if m + n != 0:
            return BarElement.zero()
        # m + n = 0, so n = -m.
        # [J_{-m}, J_{-n}] = [J_{-m}, J_m] = k*(-m)*delta_{0,0} = -k*m
        # With Koszul sign: d_CE = -[J_{-m}, J_m] = k*m
        coeff = self.k * m
        if abs(coeff) < 1e-15:
            return BarElement.zero()
        return BarElement({(): coeff})

    # ----- partial_i: equivariant contraction operators -----

    def partial_i_arity1(self, i: int, n: int) -> BarElement:
        r"""partial_i(s^{-1}J_{-n}) = iota_{xi_i}(s^{-1}J_{-n}).

        The contraction iota_{xi_i} with the equivariant vector field
        xi_i = z_i d/dz_i acts on bar generators by the weight:

            partial_i(s^{-1}J_{-n}) = w_i(n) * s^{-1}J_{-n}

        where w_i(n) is the weight of J_{-n} under the i-th torus action,
        determined by the embedding type.

        On arity-1 elements, partial_i is multiplication by the weight.
        It maps B_1 -> B_0 (contraction reduces arity by 1 when acting on
        the "form" direction, but on the bar complex, iota_{xi_i} acts as
        a derivation). For a single generator:

            iota_{xi_i}(s^{-1}J_{-n}) = w_i(n) * (arity-0 unit)

        Actually, more precisely: iota_{xi_i} is a degree -1 derivation of
        the bar complex. On a single bar generator (arity 1, degree 1),
        it produces a degree-0, arity-0 element (a scalar).

        For the DIAGONAL embedding: w_i(n) = n, so
            partial_i(s^{-1}J_{-n}) = n * (scalar)
        """
        w = self.embedding.weight(i, n)
        if abs(w) < 1e-15:
            return BarElement.zero()
        return BarElement({(): w})

    def partial_i_arity2(self, i: int, m: int, n: int) -> BarElement:
        r"""partial_i(s^{-1}J_{-m} | s^{-1}J_{-n}).

        As a derivation of the bar complex, partial_i satisfies the Leibniz rule:

            partial_i([a|b]) = partial_i(a) * b + (-1)^{|a|} a * partial_i(b)

        where * denotes the shuffle product on the bar complex.

        For degree-1 generators a = s^{-1}J_{-m}, b = s^{-1}J_{-n}:
            partial_i([a|b]) = w_i(m) * s^{-1}J_{-n}
                             + (-1)^1 * w_i(n) * s^{-1}J_{-m}
                             = w_i(m) * [s^{-1}J_{-n}]
                             - w_i(n) * [s^{-1}J_{-m}]

        This maps arity-2 to arity-1 (contraction reduces arity).
        """
        wm = self.embedding.weight(i, m)
        wn = self.embedding.weight(i, n)
        result = BarElement.zero()
        if abs(wm) >= 1e-15:
            result = result + BarElement.basis((n,), wm)
        if abs(wn) >= 1e-15:
            result = result + BarElement.basis((m,), -wn)
        return result

    # ----- d_h: the full deformed differential -----

    def d_h_arity1(self, n: int) -> BarElement:
        r"""d_h(s^{-1}J_{-n}) = d_CE + h_1*partial_1 + h_2*partial_2 + h_3*partial_3.

        On arity-1 elements:
            d_CE(s^{-1}J_{-n}) = 0  (abelian)
            partial_i(s^{-1}J_{-n}) = w_i(n) * (scalar)

        So d_h(s^{-1}J_{-n}) = (h_1*w_1(n) + h_2*w_2(n) + h_3*w_3(n)) * (scalar)

        For DIAGONAL embedding (w_i(n) = n for all i):
            d_h(s^{-1}J_{-n}) = n*(h_1+h_2+h_3) * (scalar) = 0
            when h_1+h_2+h_3 = 0.

        This is the E_3 KOSZUL TRIVIALITY for the free field.
        """
        result = self.d_CE_arity1(n)  # = 0
        for idx, hi in enumerate([self.h1, self.h2, self.h3], start=1):
            if abs(hi) >= 1e-15:
                result = result + hi * self.partial_i_arity1(idx, n)
        return result

    def d_h_arity2(self, m: int, n: int) -> BarElement:
        r"""d_h(s^{-1}J_{-m} | s^{-1}J_{-n}).

        d_h = d_CE + h_1*partial_1 + h_2*partial_2 + h_3*partial_3

        On arity-2 elements, the result has components in arity 1 AND arity 0:

        Arity-0 component (from d_CE):
            d_CE([s^{-1}J_{-m} | s^{-1}J_{-n}]) = k*m*delta_{m+n,0} * (scalar)

        Arity-1 component (from partial_i):
            h_i * partial_i([s^{-1}J_{-m} | s^{-1}J_{-n}])
                = h_i * [w_i(m)*s^{-1}J_{-n} - w_i(n)*s^{-1}J_{-m}]

        Total arity-1 piece:
            sum_i h_i * [w_i(m)*s^{-1}J_{-n} - w_i(n)*s^{-1}J_{-m}]

        For DIAGONAL embedding:
            = m*(h_1+h_2+h_3)*s^{-1}J_{-n} - n*(h_1+h_2+h_3)*s^{-1}J_{-m}
            = 0 when h_1+h_2+h_3 = 0.

        So for the diagonal Heisenberg: d_h = d_CE at ALL arities.
        """
        result = self.d_CE_arity2(m, n)  # arity-0 piece
        for idx, hi in enumerate([self.h1, self.h2, self.h3], start=1):
            if abs(hi) >= 1e-15:
                result = result + hi * self.partial_i_arity2(idx, m, n)
        return result

    # ----- d_h^2 verification -----

    def d_h_squared_arity1(self, n: int) -> BarElement:
        r"""Compute d_h(d_h(s^{-1}J_{-n})) and verify it is zero.

        d_h maps arity 1 -> arity 0.
        d_h on arity 0 is zero (there's nothing below arity 0).
        So d_h^2 on arity 1 is automatically zero.

        This is trivial but we include it for completeness.
        """
        inner = self.d_h_arity1(n)
        # inner is an arity-0 element (scalar). d_h on scalars = 0.
        return BarElement.zero()

    def d_h_squared_arity2(self, m: int, n: int) -> BarElement:
        r"""Compute d_h(d_h(s^{-1}J_{-m} | s^{-1}J_{-n})).

        d_h on arity 2 produces:
            arity-0: k*m*delta_{m+n,0}
            arity-1: sum_i h_i * [w_i(m)*(n) - w_i(n)*(m)]
                     = sum_i h_i * [w_i(m)*s^{-1}J_{-n} - w_i(n)*s^{-1}J_{-m}]

        Then d_h on the arity-1 piece:
            d_h(coeff_n * s^{-1}J_{-n}) = coeff_n * d_h_arity1(n)
                = coeff_n * (h_1*w_1(n) + h_2*w_2(n) + h_3*w_3(n)) * (scalar)

        For the full d_h^2, we need:
            d_h applied to the arity-1 output of the first d_h.

        d_h^2 = 0 is guaranteed when h_1+h_2+h_3 = 0 for the diagonal
        embedding. For general embeddings, d_h^2 = 0 requires a more
        detailed analysis.
        """
        # First application: d_h on arity-2
        first = self.d_h_arity2(m, n)

        # The arity-0 part of `first` is killed by d_h (nothing below arity 0).
        # The arity-1 part of `first` needs d_h applied to it.
        result = BarElement.zero()
        for modes, coeff in first.terms.items():
            if abs(coeff) < 1e-15:
                continue
            if len(modes) == 1:
                # arity-1 element: coeff * s^{-1}J_{-modes[0]}
                inner = self.d_h_arity1(modes[0])
                result = result + coeff * inner
            # arity-0 elements (len(modes) == 0) are killed by d_h
        return result

    # ----- Higher arity: arity 3 -----

    def d_CE_arity3(self, m: int, n: int, p: int) -> BarElement:
        r"""d_CE(s^{-1}J_{-m} | s^{-1}J_{-n} | s^{-1}J_{-p}).

        The bar differential on arity-3 elements of an abelian Lie algebra:

            d_CE([a|b|c]) = [a,b] | c - [a,c] | b + [b,c] | a
                          (with Koszul signs for degree-1 elements)

        More precisely, the bar differential d_2 on B_3 -> B_2 is:
            d_2([a|b|c]) = -([a,b]|c) + ([a,c]|b) - ([b,c]|a)

        For abelian gl_1 with [J_{-m}, J_{-n}] = -k*m*delta_{m+n,0}:

            d_CE = -(-k*m*delta_{m+n,0})*[c] + (-k*m*delta_{m+p,0})*[b]
                   -(-k*n*delta_{n+p,0})*[a]

        where [c] means s^{-1}J_{-p} in arity 1, etc.

        Simplifying with Koszul signs for three degree-1 elements [a|b|c]:
        The standard bar differential is:
            d([a|b|c]) = [a*b|c] - [a|b*c]
        where a*b means the product in the Lie algebra (= bracket for CE).
        But for the COALGEBRA bar complex, it maps B_3 -> B_2:
            d_bar([a|b|c]) = [a,b] tensor c  -  a tensor [b,c]

        With signs (|a|=|b|=|c|=1 after desuspension, so shifted degree is 0):
            d_bar([a|b|c]) = [a,b]|c + (-1)^{|a'|} a|[b,c]
        where |a'| = |a|-1 = 0 (bar-shifted degree), so the sign is +.

        For the Chevalley-Eilenberg complex of an abelian Lie algebra:
            d_bar([a|b|c]) = [J_{-m}, J_{-n}] | s^{-1}J_{-p}
                           + s^{-1}J_{-m} | [J_{-n}, J_{-p}]

        Each bracket gives a scalar times the identity (central extension),
        so the result is in arity 1:

            = -k*m*delta_{m+n,0} * s^{-1}J_{-p}
            + (-k*n)*delta_{n+p,0} * s^{-1}J_{-m}

        Wait -- the bracket [J_{-n}, J_{-p}] = k*(-n)*delta_{n+p,0} = -k*n*delta_{n+p,0}.
        When this is nonzero (a scalar), it multiplies s^{-1}J_{-m} in arity 1.
        But scalars times bar generators... the scalar from the bracket replaces
        the two generators [b|c] with a scalar, leaving [a] * scalar.

        Let me be more careful. The bar differential d: B_3 -> B_2 is:
            d([a|b|c]) = mu(a,b)|c - a|mu(b,c)

        where mu is the Lie bracket. For gl_1:
            mu(J_{-m}, J_{-n}) = [J_{-m}, J_{-n}] = -k*m*delta_{m+n,0} * 1

        So mu maps to a SCALAR (the identity element in U(gl_1)). In the bar
        complex, a scalar times c means we get a single bar element:

            d([a|b|c]) = mu(a,b) * [c] - [a] * mu(b,c)

        where mu(a,b) is a scalar coefficient.

        Result:
            d_CE([s^{-1}J_{-m} | s^{-1}J_{-n} | s^{-1}J_{-p}])
                = -k*m*delta_{m+n,0} * [s^{-1}J_{-p}]
                - (-k*n*delta_{n+p,0}) * [s^{-1}J_{-m}]
                = -k*m*delta_{m+n,0} * [s^{-1}J_{-p}]
                + k*n*delta_{n+p,0} * [s^{-1}J_{-m}]
        """
        result = BarElement.zero()

        # First term: mu(J_{-m}, J_{-n}) | s^{-1}J_{-p}
        # [J_{-m}, J_{-n}] = -k*m*delta_{m+n,0}
        if m + n == 0:
            coeff1 = -self.k * m
            result = result + BarElement.basis((p,), coeff1)

        # Second term: -s^{-1}J_{-m} | mu(J_{-n}, J_{-p})
        # [J_{-n}, J_{-p}] = -k*n*delta_{n+p,0}
        # With the minus sign from the bar differential: -(-k*n*delta_{n+p,0})
        if n + p == 0:
            coeff2 = self.k * n
            result = result + BarElement.basis((m,), coeff2)

        return result

    def partial_i_arity3(self, i: int, m: int, n: int, p: int) -> BarElement:
        r"""partial_i on an arity-3 bar element.

        Leibniz rule for the degree -1 derivation partial_i:
            partial_i([a|b|c]) = w_i(m)*[b|c] - w_i(n)*[a|c] + w_i(p)*[a|b]

        (Signs from Koszul: partial_i past a degree-1 element picks up (-1)^1.)
        """
        wm = self.embedding.weight(i, m)
        wn = self.embedding.weight(i, n)
        wp = self.embedding.weight(i, p)
        result = BarElement.zero()
        if abs(wm) >= 1e-15:
            result = result + BarElement.basis((n, p), wm)
        if abs(wn) >= 1e-15:
            result = result + BarElement.basis((m, p), -wn)
        if abs(wp) >= 1e-15:
            result = result + BarElement.basis((m, n), wp)
        return result

    def d_h_arity3(self, m: int, n: int, p: int) -> BarElement:
        """d_h on an arity-3 bar element."""
        result = self.d_CE_arity3(m, n, p)
        for idx, hi in enumerate([self.h1, self.h2, self.h3], start=1):
            if abs(hi) >= 1e-15:
                result = result + hi * self.partial_i_arity3(idx, m, n, p)
        return result

    def d_h_squared_arity3(self, m: int, n: int, p: int) -> BarElement:
        r"""Compute d_h(d_h(s^{-1}J_{-m} | s^{-1}J_{-n} | s^{-1}J_{-p})).

        d_h maps arity 3 -> {arity 2, arity 1}.
        Then d_h on arity-2 pieces -> {arity 1, arity 0}.
        Then d_h on arity-1 pieces -> arity 0.
        We collect all contributions and check they cancel.
        """
        first = self.d_h_arity3(m, n, p)

        result = BarElement.zero()
        for modes, coeff in first.terms.items():
            if abs(coeff) < 1e-15:
                continue
            if len(modes) == 2:
                inner = self.d_h_arity2(modes[0], modes[1])
                result = result + coeff * inner
            elif len(modes) == 1:
                inner = self.d_h_arity1(modes[0])
                result = result + coeff * inner
            # arity-0 killed by d_h
        return result


