r"""Deformed chiral CE differential d_h for V_k(gl_1).

MATHEMATICAL FRAMEWORK
=======================

Construction 5.12 (constr:quantum-ce-deformation) introduces the deformed
differential on chiral CE cochains:

    d_h = d_CE + h_1 * partial_1 + h_2 * partial_2 + h_3 * partial_3

where (h_1, h_2, h_3) are the Omega-background parameters with h_1+h_2+h_3=0,
and partial_i = iota_{xi_i} is contraction with the equivariant vector field
xi_i = z_i d/dz_i on C^3.

This engine makes d_h EXPLICIT for the simplest case: V_k(gl_1), the rank-1
Kac-Moody vertex algebra (Heisenberg VOA) with single generator J(z) and OPE

    J(z)J(w) ~ k/(z-w)^2.

BAR GENERATORS
==============

The bar complex B(V_k(gl_1)) is generated by desuspended modes:

    s^{-1}J_{-n}   for n in Z

with cohomological degree |s^{-1}J_{-n}| = |J_{-n}| - 1 = 1 in this
CE model. Desuspension lowers cohomological degree by 1.
In the bar complex, arity-p elements are tensor products:

    s^{-1}J_{-n_1} tensor ... tensor s^{-1}J_{-n_p}

THE CE DIFFERENTIAL d_CE
========================

The chiral CE differential encodes the OPE/commutator structure:

(i) On arity 1 (single bar generator):
    d_CE(s^{-1}J_{-n}) = 0

    for gl_1, because the Lie algebra is ABELIAN: the first-order pole in
    J(z)J(w) vanishes, so the Lie bracket is zero, and d_CE on a single
    generator has no target.

(ii) On arity 2 (tensor of two generators):
    d_CE(s^{-1}J_{-m} tensor s^{-1}J_{-n})
        = [J_m, J_n] contracted into arity-1 bar elements
        = k*m*delta_{m+n,0} * (unit)

    More precisely, d_CE on B_2 -> B_1 is the dual of the Lie bracket.
    Since [J_m, J_n] = k*m*delta_{m+n,0} * 1 (central), the CE differential
    kills arity-2 elements when m+n != 0 and sends the diagonal elements to
    a scalar (the cocycle evaluating the central extension).

    In the CE complex (not the bar complex), the differential on C^2 -> C^3
    would use the bracket. In the bar complex (coalgebra side), the
    differential on B_2 -> B_1 is:

    d_CE(s^{-1}J_{-m} | s^{-1}J_{-n}) = k*m*delta_{m+n,0} * (vacuum element)

    This is the bar differential d_2 encoding the commutator.

THE EQUIVARIANT OPERATORS partial_i
=====================================

The equivariant vector fields xi_i = z_i d/dz_i on C^3 act on the mode
J_{-n} by its weight under the i-th C^* action. For V_k(gl_1) placed on the
i-th copy of C in C^3, a mode J_{-n} has weight n under xi_i and weight 0
under the other xi_j.

More generally, in the Omega-background on C^3, the three C^* actions
correspond to three independent gradings of the algebra. For a single gl_1
(one complex boson), the natural grading is:

    partial_i(s^{-1}J_{-n}) = w_i(n) * s^{-1}J_{-n}

where w_i(n) is the weight of the mode J_{-n} under the i-th torus action.

The SIMPLEST and most natural choice (holomorphic CS on C^3 with the boson
along the diagonal): w_i(n) = n for all i. This is the "diagonal embedding"
where J_{-n} carries weight n under each of the three torus rotations.

With this choice:
    partial_i(s^{-1}J_{-n}) = n * s^{-1}J_{-n}

and the deformation becomes:
    d_h(s^{-1}J_{-n}) = d_CE(s^{-1}J_{-n}) + (h_1 + h_2 + h_3)*n * s^{-1}J_{-n}
                       = 0 + 0  (since h_1+h_2+h_3 = 0)

This is the E_3 KOSZUL TRIVIALITY: for the Heisenberg (free field), the
deformed differential d_h is IDENTICALLY d_CE. The Omega-background does
NOT deform the free field, because the three equivariant weights are all
equal (diagonal embedding) and the calabi-yau condition h_1+h_2+h_3=0
forces the total deformation to vanish.

For a NON-DIAGONAL embedding (e.g. J_{-n} on the first coordinate with
w_1(n)=n, w_2(n)=0, w_3(n)=0), partial_1 acts nontrivially but
partial_2 = partial_3 = 0, and d_h = d_CE + h_1*n, which is generically
nonzero. This breaks the CY condition: the boson is not CY_3 but CY_1,
and the h_1+h_2+h_3=0 constraint does not help.

d_h^2 = 0 CONSTRAINT (general embedding)
==========================================

For a general embedding W = (w_1, w_2, w_3) (where partial_i acts as
w_i * n on the mode J_{-n}), the condition d_h^2 = 0 requires:

    h . W = h_1*w_1 + h_2*w_2 + h_3*w_3 = 0

This is the COMPATIBILITY between the Omega-background and the embedding.
For the diagonal embedding W = (1,1,1), this reduces to h_1+h_2+h_3 = 0
(the standard CY constraint). For general W, it is a stronger condition.

Physically: the CY condition means the determinant of the normal bundle is
trivial. The diagonal embedding is the unique (up to scale) embedding where
the CY constraint on h (h_1+h_2+h_3=0) automatically ensures d_h^2 = 0.
Non-diagonal embeddings require h to lie in the kernel of the weight
matrix, which generically constrains h beyond h_1+h_2+h_3=0.

The GENERAL multi-boson case (rank N): N bosons J^a_{-n} (a=1,...,N)
placed along different directions in C^3. Then:
    partial_i(s^{-1}J^a_{-n}) = w^a_i(n) * s^{-1}J^a_{-n}
where w^a_i(n) depends on the direction of the a-th boson in C^3.

WHAT THIS ENGINE COMPUTES
=========================

1. The CE differential d_CE on bar elements of V_k(gl_1), arity 1 and 2.
2. The equivariant operators partial_i for three embedding types:
   (a) Diagonal: w_i(n) = n for all i (CY_3 embedding)
   (b) Axis-aligned: w_1(n) = n, w_2 = w_3 = 0 (CY_1 embedding)
   (c) General: w_i(n) specified by a weight matrix
3. The full d_h = d_CE + h_1*partial_1 + h_2*partial_2 + h_3*partial_3.
4. Verification that d_h^2 = 0 when h_1+h_2+h_3 = 0.
5. Verification that d_h = d_CE for the diagonal (CY_3) embedding.
6. Arity-2 computation: d_h on tensor products s^{-1}J_{-m} | s^{-1}J_{-n}.

CONVENTIONS
===========
- k = level of V_k(gl_1) (the OPE coefficient). Denoted Psi in the coproduct
  engines for consistency with the Yangian literature.
- [J_m, J_n] = k*m*delta_{m+n,0}
- Bar generators: s^{-1}J_{-n} has cohomological degree 1.
- Koszul signs: standard (desuspension by 1).
- Mode numbering: J_{-n} creates, J_n annihilates (for n > 0).

MANUSCRIPT REFERENCES
=====================
- chapters/theory/quantum_chiral_algebras.tex, Construction 5.12
  (constr:quantum-ce-deformation), lines 400-412.
- chapters/theory/quantum_chiral_algebras.tex, Remark rem:e3-not-symmetric
  (the E_3 structure is nontrivial only AFTER deformation).
- compute/lib/e2_bar_complex.py: E_2 bar complex (d_Y = 0 for Heisenberg
  confirms our d_CE = 0 at arity 1).
"""

