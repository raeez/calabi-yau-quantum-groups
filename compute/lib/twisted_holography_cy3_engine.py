def sigma_consistency_checks(h1: Fraction, h2: Fraction) -> Dict[str, bool]:
    """Verify consistency relations for CY3 parameters.

    1. CY condition: h1 + h2 + h3 = 0
    2. Power sum p_1 = 0
    3. sigma_2 = -(h1² + h1*h2 + h2²)
    4. sigma_3 = -h1*h2*(h1+h2)
    5. g(-z) = 1/g(z) (unitarity, via convolution identity on phi_j)
    6. Log-series alpha_k = 0 for even k (CY symmetry on the classical r-matrix)
    """
    h3 = -(h1 + h2)
    checks = {}

    # CY condition
    checks['cy_condition'] = (h1 + h2 + h3 == 0)

    # p_1 = 0
    checks['p1_vanishes'] = (power_sum(1, h1, h2) == 0)

    # sigma_2 formula
    s2_direct = h1*h2 + h1*h3 + h2*h3
    s2_formula = -(h1**2 + h1*h2 + h2**2)
    checks['sigma2_formula'] = (s2_direct == s2_formula)

    # sigma_3 formula
    s3_direct = h1 * h2 * h3
    s3_formula = -h1 * h2 * (h1 + h2)
    checks['sigma3_formula'] = (s3_direct == s3_formula)

    # Unitarity g(z)*g(-z) = 1
    checks['unitarity'] = (structure_function_unitarity_check(h1, h2) == 0)

    # Log-series alpha_k = 0 for even k (classical r-matrix has only odd poles)
    checks['log_odd_only'] = log_structure_odd_only(h1, h2)

    return checks


def kappa_additivity_check(spin_cutoff: int,
                           c_val: Fraction = Fraction(1)) -> bool:
    """Verify kappa additivity: kappa(W_{1+∞}) = sum_s kappa_s.

    This is a consequence of independent sum factorization (Vol I,
    prop:independent-sum-factorization): for independent channels,
    kappa is additive.
    """
    total_from_channels = sum(kappa_per_channel(s, c_val)
                              for s in range(1, spin_cutoff + 1))
    total_direct = kappa_boundary_c3(spin_cutoff, c_val)
    return total_from_channels == total_direct


def complementarity_check(spin_cutoff: int,
                          c_val: Fraction = Fraction(1)) -> Dict[str, Any]:
    """Verify the complementarity pairing for C³.

    For KM/free field families (AP24):
      kappa(A) + kappa(A^!) = 0

    For W_{1+∞}: A and A^! have reflected parameters, so
      kappa(A^!) = -kappa(A)  (each channel negates)
      kappa(A) + kappa(A^!) = 0

    This is EXACT at every finite cutoff.
    """
    k = kappa_boundary_c3(spin_cutoff, c_val)
    k_dual = kappa_koszul_dual_c3(spin_cutoff, c_val)
    total = k + k_dual

    return {
        'kappa_A': k,
        'kappa_A_dual': k_dual,
        'sum': total,
        'vanishes': (total == 0),
        'family': 'KM/free field (AP24-safe)',
    }


