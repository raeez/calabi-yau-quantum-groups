def kappa_boundary_c3(spin_cutoff: int, c_val: Fraction = Fraction(1)
                      ) -> Fraction:
    """Modular characteristic kappa of the boundary algebra W_{1+∞} at c.

    kappa^{E₁}(W_{1+∞}, cutoff N) = c * H_N    (including spin-1)

    CAUTION (AP48): The TOTAL kappa diverges as N → ∞ (harmonic series).
    This divergence is the VOA manifestation of the non-compactness of C³.
    Physical regularization: use W_N truncation with finite N.
    """
    h_n = sum(Fraction(1, s) for s in range(1, spin_cutoff + 1))
    return c_val * h_n


def kappa_per_channel(spin: int, c_val: Fraction = Fraction(1)) -> Fraction:
    """Per-channel kappa for spin-s generator of W_{1+∞}.

    kappa_s = c / s.
    The total is sum_{s=1}^{N} c/s = c * H_N.
    """
    if spin < 1:
        raise ValueError(f"Spin must be >= 1, got {spin}")
    return c_val / Fraction(spin)


