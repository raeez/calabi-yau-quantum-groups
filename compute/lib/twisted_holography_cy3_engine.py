def koszul_dual_c3(h1: Fraction, h2: Fraction) -> Dict[str, Any]:
    """The E₁ Koszul dual A_{C³}^! for the boundary algebra W_{1+∞}.

    In the Costello-Li framework:
      - LEFT boundary of R² → A = W_{1+∞} at parameters (h₁, h₂, h₃)
      - RIGHT boundary of R² → A^! = W_{1+∞} at parameters (-h₁, -h₂, -h₃)

    The parameter reflection (h_i → -h_i) preserves the CY condition
    and inverts the structure function: g^!(z) = g(z)^{-1} = g(-z).

    This is the E₁ (associative) Koszul duality, NOT the chiral (E_∞)
    Koszul duality of Vol I. The two agree for the Heisenberg (spin-1)
    sector but differ for higher spins where the braiding is nontrivial.

    CAUTION (AP33): A^! ≠ A at negative level. The Koszul dual uses
    Hochschild duality (endomorphism reversal), not Feigin-Frenkel
    involution (level negation within the same family).

    For the modular characteristic:
      kappa(A^!) = -kappa(A)  per channel (parameter negation)
      kappa_s(A^!) = -c/s    (each channel negates)
      Total: kappa(A^!) = -c * H_N  (regulated)

    NOTE: kappa(A) + kappa(A^!) = 0 for the Heisenberg / W_{1+∞} family.
    This is the AP24-safe regime: KM/free field families have anti-symmetric
    kappa pairing.
    """
    h3 = -(h1 + h2)
    h1_dual = -h1
    h2_dual = -h2
    h3_dual = -h3  # = h1 + h2

    s2_dual = sigma_2_cy(h1_dual, h2_dual)
    s3_dual = sigma_3_cy(h1_dual, h2_dual)

    return {
        'algebra': 'W_{1+inf}^! (E₁ Koszul dual)',
        'identification': 'Y(gl_hat_1) at reflected parameters',
        'parameters': {'h1': h1_dual, 'h2': h2_dual, 'h3': h3_dual},
        'sigma_2': s2_dual,
        'sigma_3': s3_dual,
        'central_charge': Fraction(1),  # c=1 for both A and A^!
        'kappa_relation': 'kappa(A^!) = -kappa(A) per channel',
        'structure_function': 'g^!(z) = g(-z) = 1/g(z)',
        'brane_origin': 'M5-branes wrapping CY3 / Kodaira-Spencer theory',
    }


def kappa_koszul_dual_c3(spin_cutoff: int, c_val: Fraction = Fraction(1)
                         ) -> Fraction:
    """kappa of the Koszul dual A^! at spin cutoff N.

    kappa(A^!) = -kappa(A) = -c * H_N.
    """
    return -kappa_boundary_c3(spin_cutoff, c_val)


def kappa_complementarity_c3(spin_cutoff: int, c_val: Fraction = Fraction(1)
                             ) -> Fraction:
    """Verify kappa(A) + kappa(A^!) = 0 (AP24-safe for KM/free field families).

    For W_{1+∞}: kappa + kappa^! = c*H_N + (-c*H_N) = 0.
    This holds exactly at every finite cutoff.
    """
    return kappa_boundary_c3(spin_cutoff, c_val) + kappa_koszul_dual_c3(spin_cutoff, c_val)


