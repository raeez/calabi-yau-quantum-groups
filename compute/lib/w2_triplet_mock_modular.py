def _partition_function(max_n: int) -> Dict[int, int]:
    """Compute p(n) = number of partitions, through n = max_n."""
    p = [0] * (max_n + 1)
    p[0] = 1
    for k in range(1, max_n + 1):
        for n in range(k, max_n + 1):
            p[n] += p[n - k]
    return {i: p[i] for i in range(max_n + 1)}


