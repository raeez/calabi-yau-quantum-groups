def theta_rp_coefficients(r: int, p: int, max_n: int) -> Dict[Fraction, Fraction]:
    r"""Compute q-expansion coefficients of theta_{r,p}(tau).

    theta_{r,p}(tau) = sum_{n in Z} q^{(2pn+r)^2/(4p)}

    Returns dict: exponent (as Fraction) -> coefficient (as Fraction).
    Exponents are non-negative rationals of the form (2pn+r)^2/(4p).
    Coefficients are always integers (counting lattice points).

    We compute all terms with q-power <= max_n.
    """
    coeffs: Dict[Fraction, Fraction] = {}
    # Need (2pn+r)^2/(4p) <= max_n, so |2pn+r| <= sqrt(4p*max_n)
    bound = int(math.isqrt(4 * p * max_n)) + 1
    for n in range(-bound, bound + 1):
        val = 2 * p * n + r
        exp = Fraction(val * val, 4 * p)
        if exp > max_n:
            continue
        coeffs[exp] = coeffs.get(exp, Fraction(0)) + Fraction(1)
    return coeffs


def partial_theta_rp_coefficients(r: int, p: int, max_n: int) -> Dict[Fraction, Fraction]:
    r"""Compute q-expansion of the derivative (1/(2*pi*i)) * d/dtau [theta_{r,p}].

    (1/(2*pi*i)) * d/dtau [q^a] = a * q^a.

    So partial_theta_{r,p} = sum_n ((2pn+r)^2/(4p)) * q^{(2pn+r)^2/(4p)}.

    This is the "number operator" version: each term multiplied by its exponent.
    """
    theta = theta_rp_coefficients(r, p, max_n)
    result: Dict[Fraction, Fraction] = {}
    for exp, coeff in theta.items():
        result[exp] = coeff * exp
    return result


