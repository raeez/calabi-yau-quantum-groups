class StructureFunctionC3(NamedTuple):
    """The affine Yangian structure function for C^3.

    g(z) = (z - h_1)(z - h_2)(z - h_3) / ((z + h_1)(z + h_2)(z + h_3))

    With CY constraint h_1 + h_2 + h_3 = 0:
    g(z) = (z^3 + sigma_2 * z - sigma_3) / (z^3 + sigma_2 * z + sigma_3)

    where sigma_2 = h_1*h_2 + h_1*h_3 + h_2*h_3,
          sigma_3 = h_1*h_2*h_3.
    """
    h: Tuple[F, F, F]
    sigma_2: F
    sigma_3: F


def structure_function_c3(
    h: Tuple[F, F, F] = (F(1), F(-2), F(1)),
) -> StructureFunctionC3:
    """Construct the C^3 structure function data.

    Args:
        h: equivariant parameters (h_1, h_2, h_3) with sum = 0.

    Returns:
        StructureFunctionC3 with computed symmetric functions.
    """
    h1, h2, h3 = h
    assert h1 + h2 + h3 == 0, f"CY constraint violated: sum = {h1 + h2 + h3}"
    sigma_2 = h1 * h2 + h1 * h3 + h2 * h3
    sigma_3 = h1 * h2 * h3
    return StructureFunctionC3(h=h, sigma_2=sigma_2, sigma_3=sigma_3)


def eval_g(h: Tuple[F, ...], z: F) -> F:
    """Evaluate g(z) = prod (z - h_i) / (z + h_i).

    AP-CY28: caller must ensure z avoids poles at +/- h_i.
    """
    result = F(1)
    for hi in h:
        result *= (z - hi) / (z + hi)
    return result


def eval_g_from_sigma(sigma_2: F, sigma_3: F, z: F) -> F:
    r"""Evaluate g(z) = (z^3 + sigma_2*z - sigma_3) / (z^3 + sigma_2*z + sigma_3).

    Uses the reduced form valid when h_1 + h_2 + h_3 = 0.

    Derivation: with s_1 = h_1+h_2+h_3 = 0, s_2 = sigma_2, s_3 = sigma_3:
      (z-h_1)(z-h_2)(z-h_3) = z^3 - s_1*z^2 + s_2*z - s_3
                             = z^3 + s_2*z - s_3
      (z+h_1)(z+h_2)(z+h_3) = z^3 + s_1*z^2 + s_2*z + s_3
                             = z^3 + s_2*z + s_3
    """
    num = z ** 3 + sigma_2 * z - sigma_3
    den = z ** 3 + sigma_2 * z + sigma_3
    return num / den


