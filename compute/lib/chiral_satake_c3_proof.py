class FiberFunctorData(NamedTuple):
    """Fiber functor F: D-mod(Gr^{ch}_{GL_1}(C^3)) -> Vect.

    For GL_1 (abelian), the fiber functor is:
      F(M) = global sections Gamma(Gr, M)
    decomposed by charge: F(M) = bigoplus_n F_n(M).

    At charge n, F_n has dimension p(n) (partitions of n).
    """
    charge: int
    fiber_dim: int            # dim(F_n) = p(n)
    partition_count: int       # p(n) = number of partitions of n
    partitions: List[Tuple[int, ...]]  # the actual partitions
    is_faithful: bool          # fiber functor is faithful (GL_1 abelian)
    is_exact: bool             # fiber functor is exact (GL_1 abelian)


def fiber_functor(charge: int) -> FiberFunctorData:
    r"""Construct the fiber functor at charge n.

    For GL_1 on C^3, the charge-n D-module category has p(n) simple objects,
    indexed by partitions of n (= T-fixed points of Hilb^n(C^2)).

    The fiber functor F_n extracts a p(n)-dimensional vector space.
    It is faithful and exact because GL_1 is abelian.

    Mathematical proof:
    - GL_1 orbits on Gr_{GL_1} are single points (abelian group)
    - IC sheaves are skyscraper sheaves (trivial intersection cohomology)
    - The fiber functor F = Gamma(Gr, -) is therefore the stalk functor
    - Faithfulness: different IC sheaves have different stalks
    - Exactness: skyscraper sheaves form a semisimple category

    The partition indexing comes from the C^3 geometry:
    - Hilb^n(C^2) has T-fixed points indexed by partitions of n
    - The C^3 equivariant structure refines this to coloured partitions
    - For GL_1 (charge only, no colour): just ordinary partitions

    Args:
        charge: the charge n.

    Returns:
        FiberFunctorData.
    """
    parts = partitions_of(charge)
    pn = len(parts)
    return FiberFunctorData(
        charge=charge,
        fiber_dim=pn,
        partition_count=pn,
        partitions=parts,
        is_faithful=True,   # GL_1 is abelian
        is_exact=True,       # semisimple category for GL_1
    )


