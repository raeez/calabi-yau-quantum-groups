class MonoidalStructureData(NamedTuple):
    """Monoidal structure on D-mod(Gr^{ch}_{GL_1}(C^3)).

    The convolution product is:
      charge-n * charge-m -> charge-(n+m)

    The internal decomposition uses partition-indexed MV cycles.
    For GL_1, the MV cycles are in bijection with partitions:
      MV^{ch}_lambda for lambda a partition of n.

    The tensor product on the Yangian side:
      F_n tensor F_m -> F_{n+m}
    decomposes via the Littlewood-Richardson rule.
    """
    charges_in: Tuple[int, int]
    charge_out: int
    dim_in_1: int             # p(n)
    dim_in_2: int             # p(m)
    dim_out: int              # p(n+m)
    mv_cycle_count: int       # number of MV cycles at charge n+m
    is_associative: bool      # monoidal product is associative
    is_braided: bool          # has E_2 braiding (not symmetric)


def monoidal_convolution(n: int, m: int) -> MonoidalStructureData:
    r"""Compute the monoidal convolution product at charges n and m.

    The convolution on D-mod(Gr^{ch}_{GL_1}):
      D-mod^n * D-mod^m -> D-mod^{n+m}
    corresponds under Satake to the tensor product on Yangian representations:
      F_n tensor F_m -> F_{n+m}

    The dimension of the output: p(n+m).

    The associativity follows from the associativity of the convolution
    on the Grassmannian (which is a group operation for GL_1).

    The braiding is E_2 (from the factorization structure), not symmetric.

    Args:
        n, m: input charges.

    Returns:
        MonoidalStructureData.
    """
    pn = num_partitions(n)
    pm = num_partitions(m)
    pnm = num_partitions(n + m)
    return MonoidalStructureData(
        charges_in=(n, m),
        charge_out=n + m,
        dim_in_1=pn,
        dim_in_2=pm,
        dim_out=pnm,
        mv_cycle_count=pnm,
        is_associative=True,   # convolution on Gr_{GL_1} is associative
        is_braided=True,       # E_2 braiding from factorization
    )


def verify_monoidal_associativity(max_charge: int = 5) -> Dict[str, Any]:
    r"""Verify associativity: (n * m) * k = n * (m * k) at charge level.

    For GL_1, both give charge n + m + k.

    At the partition level, associativity means:
    p(n+m+k) is the same regardless of grouping.

    Returns:
        Dict with verification data.
    """
    tests = []
    for n in range(max_charge + 1):
        for m in range(max_charge + 1 - n):
            for k in range(max_charge + 1 - n - m):
                # (n * m) * k
                lhs = monoidal_convolution(
                    monoidal_convolution(n, m).charge_out, k
                )
                # n * (m * k)
                rhs = monoidal_convolution(
                    n, monoidal_convolution(m, k).charge_out
                )
                match = (lhs.charge_out == rhs.charge_out
                         and lhs.dim_out == rhs.dim_out)
                tests.append({
                    "n": n, "m": m, "k": k,
                    "charge": n + m + k,
                    "dim": lhs.dim_out,
                    "match": match,
                })
    all_pass = all(t["match"] for t in tests)
    return {"tests": tests, "num_tests": len(tests), "all_pass": all_pass}


