def verify_ybe_charge1(
    h: Tuple[F, F, F] = (F(1), F(-2), F(1)),
) -> Dict[str, Any]:
    r"""Verify the Yang-Baxter equation at charge 1.

    At charge 1, R(z) = g(z) is a scalar (1x1 matrix).
    The YBE:
      R_{12}(z_{12}) R_{13}(z_{13}) R_{23}(z_{23})
      = R_{23}(z_{23}) R_{13}(z_{13}) R_{12}(z_{12})

    For scalars: g(z_{12}) g(z_{13}) g(z_{23}) = g(z_{23}) g(z_{13}) g(z_{12}).
    This is TRIVIALLY TRUE (commutativity of multiplication).
    """
