# 1. Partition function (uncoloured)
# =========================================================================

def num_partitions(n: int) -> int:
    """Number of partitions of n (uncoloured).

    Computed via the recurrence with Euler's pentagonal theorem:
      p(n) = sum_{k != 0} (-1)^{k+1} p(n - k(3k-1)/2)

    Ground truth from OEIS A000041.
    """
    if n < 0:
        return 0
    if n == 0:
        return 1
    # Dynamic programming
    table = [0] * (n + 1)
    table[0] = 1
    for i in range(1, n + 1):
        for j in range(i, n + 1):
            table[j] += table[j - i]
    return table[n]


def partitions_of(n: int) -> List[Tuple[int, ...]]:
    """Enumerate all partitions of n as tuples in decreasing order.

    Returns list of tuples (lambda_1, lambda_2, ...) with
    lambda_1 >= lambda_2 >= ... >= 1 and sum = n.
    """
    if n == 0:
        return [()]
    result: List[Tuple[int, ...]] = []
    _partition_helper(n, n, (), result)
    return result


def _partition_helper(n: int, max_part: int, current: Tuple[int, ...],
                      result: List[Tuple[int, ...]]) -> None:
    if n == 0:
        result.append(current)
        return
    for k in range(min(n, max_part), 0, -1):
        _partition_helper(n - k, k, current + (k,), result)


