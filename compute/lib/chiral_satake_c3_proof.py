def verify_partition_ground_truth(max_n: int = 20) -> Dict[str, Any]:
    """Verify partition function p(n) against OEIS A000041 ground truth."""
    results = []
    for n in range(min(max_n + 1, len(PARTITIONS_GROUND_TRUTH))):
        computed = num_partitions(n)
        expected = PARTITIONS_GROUND_TRUTH[n]
        results.append({
            "n": n,
            "computed": computed,
            "expected": expected,
            "match": computed == expected,
        })
    all_pass = all(r["match"] for r in results)
    return {"results": results, "num_checked": len(results), "all_pass": all_pass}


def verify_partition_enumeration(max_n: int = 10) -> Dict[str, Any]:
    """Verify that len(partitions_of(n)) = num_partitions(n)."""
    results = []
    for n in range(max_n + 1):
        parts = partitions_of(n)
        pn = num_partitions(n)
        results.append({
            "n": n,
            "enumerated": len(parts),
            "formula": pn,
            "match": len(parts) == pn,
        })
    all_pass = all(r["match"] for r in results)
    return {"results": results, "all_pass": all_pass}


