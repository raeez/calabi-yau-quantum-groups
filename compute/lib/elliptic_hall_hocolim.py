def sl2z_action_verification() -> Dict[str, Any]:
    r"""Verify SL_2(Z) action consistency on E_{q,t}.

    SL_2(Z) is generated by S and T with relations:
      (ST)^3 = S^2 = C  (the central element, charge conjugation)
      S^4 = 1

    We verify:
    1. S^2 acts as (r,d) -> (-r,-d) on charges.
    2. (ST)^3 = S^2 on charges.
    3. S and T are E_1 automorphisms.
    4. The action is consistent with the Euler form.
    """
    # S: (r,d) -> (d,-r)
    # S^2: (r,d) -> S(d,-r) = (-r,-d)  CHECK: charge conjugation
    # T: (r,d) -> (r, d+r)
    # ST: (r,d) -> S(r, d+r) = (d+r, -r)
    # (ST)^2: (r,d) -> ST(d+r, -r) = ST applied: (-r+d+r, -(d+r)) = (d, -d-r)
    #   Wait: ST(r,d) = S(T(r,d)) = S(r, d+r) = (d+r, -r)
    # (ST)^2(r,d) = ST(d+r, -r) = S(d+r, -r+d+r) = S(d+r, d) = (d, -(d+r))
    # (ST)^3(r,d) = ST(d, -(d+r)) = S(d, -(d+r)+d) = S(d, -r) = (-r, -d)
    # So (ST)^3 = S^2. CHECK.

    test_charges = [(1, 0), (0, 1), (1, 1), (2, 3), (3, -1)]
    results = {}

    for r, d in test_charges:
        # S^2
        s1 = (d, -r)
        s2 = (s1[1], -s1[0])
        s2_is_neg = (s2 == (-r, -d))

        # (ST)^3
        st1 = (d + r, -r)            # ST
        st2_t = (st1[0], st1[1] + st1[0])  # T of ST = (d+r, d)
        st2 = (st2_t[1], -st2_t[0])   # S of T(ST) = (d, -(d+r))
        st3_t = (st2[0], st2[1] + st2[0])  # T of (ST)^2 = (d, -r)
        st3 = (st3_t[1], -st3_t[0])   # S of T((ST)^2) = (-r, -d)
        st3_is_s2 = (st3 == (-r, -d))

        results[(r, d)] = {
            'S^2': s2,
            'S^2 = -id': s2_is_neg,
            '(ST)^3': st3,
            '(ST)^3 = S^2': st3_is_s2,
        }

    all_s2_correct = all(v['S^2 = -id'] for v in results.values())
    all_st3_correct = all(v['(ST)^3 = S^2'] for v in results.values())

    return {
        'charge_tests': results,
        'S^2_is_charge_conjugation': all_s2_correct,
        '(ST)^3_equals_S^2': all_st3_correct,
        'sl2z_relations_satisfied': all_s2_correct and all_st3_correct,
    }


