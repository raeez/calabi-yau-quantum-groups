class MukaiCharge(NamedTuple):
    """A charge in the Mukai lattice of K3.

    For K3, the Mukai vector is v = (r, c_1, s) where:
      r = rank
      c_1 in H^{1,1}(K3, Z) (the first Chern class)
      s = ch_2 + r (the shifted second Chern character)

    For computational purposes, we work with the reduced charge
    (r, l, m) where:
      r = rank
      l = degree (projection of c_1 to a chosen polarization)
      m = instanton number (ch_2)

    Discriminant: D = 4rm - l^2 (determines root multiplicity).
    """
    r: int      # rank
    l: int      # degree / fiber class
    m: int      # instanton number

    @property
    def discriminant(self) -> int:
        """D = 4rm - l^2."""
        return 4 * self.r * self.m - self.l * self.l

    def __repr__(self) -> str:
        return f"v({self.r},{self.l},{self.m})"


