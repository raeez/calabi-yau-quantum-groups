FPS = List[Fraction]


def _fps_zero(N: int) -> FPS:
    return [Fraction(0)] * N


def _fps_one(N: int) -> FPS:
    f = _fps_zero(N)
    if N > 0:
        f[0] = Fraction(1)
    return f


def _fps_mul(a: FPS, b: FPS, N: int) -> FPS:
    result = _fps_zero(N)
    la, lb = len(a), len(b)
    for i in range(min(la, N)):
        if a[i] == 0:
            continue
        for j in range(min(lb, N - i)):
            result[i + j] += a[i] * b[j]
    return result


def _fps_inv(a: FPS, N: int) -> FPS:
    """Invert power series a(q) mod q^N. Requires a[0] != 0."""
    assert a[0] != 0, "Cannot invert: a[0] = 0"
    inv0 = Fraction(1) / a[0]
    result = _fps_zero(N)
    result[0] = inv0
    for n in range(1, N):
        s = Fraction(0)
        for k in range(1, min(n + 1, len(a))):
            s += a[k] * result[n - k]
        result[n] = -inv0 * s
    return result


def _fps_add(a: FPS, b: FPS, N: int) -> FPS:
    result = _fps_zero(N)
    for i in range(min(len(a), N)):
        result[i] += a[i]
    for i in range(min(len(b), N)):
        result[i] += b[i]
    return result


def _fps_sub(a: FPS, b: FPS, N: int) -> FPS:
    result = _fps_zero(N)
    for i in range(min(len(a), N)):
        result[i] += a[i]
    for i in range(min(len(b), N)):
        result[i] -= b[i]
    return result


def _fps_scale(a: FPS, c: Fraction, N: int) -> FPS:
    return [c * a[i] if i < len(a) else Fraction(0) for i in range(N)]


def _fps_exp(f: FPS, N: int) -> FPS:
    """exp(f(q)) mod q^N, f[0] = 0."""
    assert f[0] == 0, "exp requires f[0] = 0"
    g = _fps_zero(N)
    g[0] = Fraction(1)
    for n in range(1, N):
        s = Fraction(0)
        for k in range(1, n + 1):
            fk = f[k] if k < len(f) else Fraction(0)
            s += Fraction(k) * fk * g[n - k]
        g[n] = s / Fraction(n)
    return g


def _fps_log(g: FPS, N: int) -> FPS:
    """log(g(q)) mod q^N, g[0] = 1."""
    assert g[0] == Fraction(1), "log requires g[0] = 1"
    f = _fps_zero(N)
    for n in range(1, N):
        gn = g[n] if n < len(g) else Fraction(0)
        s = Fraction(0)
        for k in range(1, n):
            s += Fraction(k) * f[k] * (g[n - k] if n - k < len(g) else Fraction(0))
        f[n] = gn - s / Fraction(n)
    return f


def _fps_power(a: FPS, k: int, N: int) -> FPS:
    """a(q)^k mod q^N."""
    if k == 0:
        return _fps_one(N)
    if k < 0:
        return _fps_power(_fps_inv(a, N), -k, N)
    if k == 1:
        return list(a[:N]) + _fps_zero(max(0, N - len(a)))
    result = _fps_one(N)
    base = list(a[:N]) + _fps_zero(max(0, N - len(a)))
    while k > 0:
        if k % 2 == 1:
            result = _fps_mul(result, base, N)
        base = _fps_mul(base, base, N)
        k //= 2
    return result


def eta_fps(N: int) -> FPS:
    r"""Dedekind eta function eta(q) = q^{1/24} prod_{n>=1} (1-q^n).

    We compute the product part prod_{n>=1} (1-q^n) mod q^N.
    The q^{1/24} prefactor is omitted (AP46: it is essential in the
    analytic theory, but for power series computations we track it
    separately).
    """
    result = _fps_one(N)
    for k in range(1, N):
        # Multiply by (1 - q^k)
        for n in range(N - 1, k - 1, -1):
            result[n] -= result[n - k]
    return result


def eta_inv_fps(N: int) -> FPS:
    r"""1/eta(q) = 1/prod_{n>=1}(1-q^n) = prod_{n>=1} 1/(1-q^n) mod q^N.

    This is the partition function P(q) = sum p(n) q^n.
    """
    return _fps_inv(eta_fps(N), N)


def macmahon_fps(N: int) -> FPS:
    r"""MacMahon function M(q) = prod_{n>=1} 1/(1-q^n)^n mod q^N.

    Plane partition generating function.
    """
    result = _fps_one(N)
    for k in range(1, N):
        fac = _fps_one(N)
        for _ in range(k):
            for n in range(k, N):
                fac[n] += fac[n - k]
        result = _fps_mul(result, fac, N)
    return result


