# 0. EXACT ARITHMETIC HELPERS
# =========================================================================

FPS = List[Fraction]


def _fps_zero(N: int) -> FPS:
    return [Fraction(0)] * N


def _fps_one(N: int) -> FPS:
    f = _fps_zero(N)
    if N > 0:
        f[0] = Fraction(1)
    return f


def _fps_mul(a: FPS, b: FPS, N: int) -> FPS:
    result = _fps_zero(N)
    la, lb = len(a), len(b)
    for i in range(min(la, N)):
        if a[i] == 0:
            continue
        for j in range(min(lb, N - i)):
            result[i + j] += a[i] * b[j]
    return result


def _fps_inv(a: FPS, N: int) -> FPS:
    """Invert power series a(q) mod q^N.  Requires a[0] != 0."""
    assert a[0] != 0
    inv0 = Fraction(1) / a[0]
    result = _fps_zero(N)
    result[0] = inv0
    for n in range(1, N):
        s = Fraction(0)
        for k in range(1, min(n + 1, len(a))):
            s += a[k] * result[n - k]
        result[n] = -inv0 * s
    return result


def _macmahon(N: int) -> FPS:
    """MacMahon function M(q) = prod_{n>=1} (1-q^n)^{-n} mod q^N.

    Counts plane partitions.
    """
    result = _fps_one(N)
    for n in range(1, N):
        # Multiply by (1 - q^n)^{-n}
        factor = _fps_zero(N)
        factor[0] = Fraction(1)
        if n < N:
            factor[n] = Fraction(-1)
        factor_inv = _fps_inv(factor, N)
        # Raise to power n: (1-q^n)^{-n} = ((1-q^n)^{-1})^n
        power = _fps_one(N)
        for _ in range(n):
            power = _fps_mul(power, factor_inv, N)
        result = _fps_mul(result, power, N)
    return result


def _euler_function(N: int) -> FPS:
    """Euler function P(q) = prod_{n>=1} (1-q^n)^{-1} mod q^N.

    Counts partitions.
    """
    result = _fps_one(N)
    for n in range(1, N):
        factor = _fps_zero(N)
        factor[0] = Fraction(1)
        if n < N:
            factor[n] = Fraction(-1)
        result = _fps_mul(result, _fps_inv(factor, N), N)
    return result


