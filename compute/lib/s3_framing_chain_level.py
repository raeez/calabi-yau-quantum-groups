@dataclass(frozen=True)
class CyclicGenerator:
    """A generator of a CY category for the cyclic bar complex.

    Attributes
    ----------
    name : str
        Symbol name (e.g. 'a' for Heisenberg, 'e_gamma' for BPS state).
    degree : int
        Cohomological degree.
    charge : Tuple[int, ...]
        Charge vector in the lattice Gamma.
    """
    name: str
    degree: int = 0
    charge: Tuple[int, ...] = ()

    def __repr__(self) -> str:
        return self.name


@dataclass(frozen=True)
class CyclicBarElement:
    r"""An element of the cyclic bar complex CC_n(C).

    The cyclic bar complex CC_n(C) = C^{\otimes n+1} / Z_{n+1} with the
    cyclic differential.  We represent elements as ordered tuples
    (a_0, a_1, ..., a_n) subject to the cyclic relation:

        (a_0, ..., a_n) ~ (-1)^{|a_n|(|a_0|+...+|a_{n-1}|)}
                          (a_n, a_0, ..., a_{n-1})

    Attributes
    ----------
    factors : tuple of CyclicGenerator
        The ordered generators (a_0, ..., a_n).
    coeff : Fraction
        Rational coefficient.
    """
    factors: Tuple[CyclicGenerator, ...]
    coeff: Fraction = Fraction(1)

    @property
    def bar_degree(self) -> int:
        """Bar degree n (number of bars = len(factors) - 1)."""
        return len(self.factors) - 1

    @property
    def total_degree(self) -> int:
        """Total cohomological degree after desuspension.

        Each factor in the bar has desuspended degree |a_i| - 1 (AP45).
        The first factor a_0 is NOT desuspended (it is the cyclic element).
        """
        n = len(self.factors)
        if n == 0:
            return 0
        # a_0 keeps its degree; a_1, ..., a_n are desuspended
        return self.factors[0].degree + sum(
            g.degree - 1 for g in self.factors[1:]
        )

    def __repr__(self) -> str:
        inner = ", ".join(str(g) for g in self.factors)
        if self.coeff == Fraction(1):
            return f"({inner})"
        return f"{self.coeff}*({inner})"


