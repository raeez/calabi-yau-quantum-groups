# 10. CONNES-FRAMING HIERARCHY RELATIONS
# =========================================================================

class ConnesFramingHierarchy:
    """The full hierarchy of Connes operators B^{(k)} for k = 0, ..., d.

    For CY_d, the hierarchy B^{(0)}, B^{(1)}, ..., B^{(d)} satisfies:

        sum_{i+j=d} B^{(i)} B^{(j)} = 0    (total nilpotence)

    which gives d+1 component relations:

    For d = 3:
        B^{(0)}B^{(3)} + B^{(1)}B^{(2)} + B^{(2)}B^{(1)} + B^{(3)}B^{(0)} = 0

    Writing B = B^{(0)} and F = B^{(3)}:
        BF + FB + B^{(1)}B^{(2)} + B^{(2)}B^{(1)} = 0
        i.e. {B, F} = -[B^{(1)}, B^{(2)}]_+    (anticommutator)

    Wait: the sign convention matters. Let me be precise.
    With the convention that B^{(k)} has degree 1-k:
        |B^{(0)}| = 1, |B^{(1)}| = 0, |B^{(2)}| = -1, |B^{(3)}| = -2

    The nilpotence relation for even total degree:
        (B + B^{(1)} + B^{(2)} + F)^2 = 0

    Expanding:
        B^2 + BB^{(1)} + B^{(1)}B + BB^{(2)} + B^{(2)}B + BF + FB
        + (B^{(1)})^2 + B^{(1)}B^{(2)} + B^{(2)}B^{(1)}
        + B^{(1)}F + FB^{(1)} + (B^{(2)})^2 + B^{(2)}F + FB^{(2)} + F^2 = 0

    Grouping by total degree:
        Degree 2:  B^2 = 0
        Degree 1:  BB^{(1)} + B^{(1)}B = 0   (i.e. [B, B^{(1)}] = 0)
        Degree 0:  BB^{(2)} + B^{(2)}B + (B^{(1)})^2 = 0
        Degree -1: BF + FB + B^{(1)}B^{(2)} + B^{(2)}B^{(1)} = 0
        Degree -2: B^{(1)}F + FB^{(1)} + (B^{(2)})^2 = 0
        Degree -3: B^{(2)}F + FB^{(2)} = 0
        Degree -4: F^2 = 0

    So for CY3: the key relations are:
        B^2 = 0                                          (degree 2)
        {B, B^{(1)}} = 0                                 (degree 1)
        {B, B^{(2)}} + (B^{(1)})^2 = 0                   (degree 0)
        {B, F} + {B^{(1)}, B^{(2)}} = 0                  (degree -1)
        {B^{(1)}, F} + (B^{(2)})^2 = 0                   (degree -2)
        {B^{(2)}, F} = 0                                 (degree -3)
        F^2 = 0                                          (degree -4)
    """

    def __init__(self, cy_dim: int):
        self.d = cy_dim
        self._relations = self._compute_relations()

    def _compute_relations(self) -> List[Dict[str, Any]]:
        """Compute the hierarchy relations grouped by total degree."""
        d = self.d
        relations = []
        # The total nilpotence (B^{(0)} + ... + B^{(d)})^2 = 0
        # Groups by total degree from 2 down to -2d+2 (or -2*(d-1))
        # Actually by degree from 2 down to -2d.
        # Wait: degree of B^{(i)}B^{(j)} = (1-i)+(1-j) = 2-i-j.
        # The relation groups terms with i+j = const.
        # For sum_{i+j=s} B^{(i)}B^{(j)} = 0, where s ranges from 0 to 2d.
        for s in range(2 * d + 1):
            terms = []
            for i in range(d + 1):
                j = s - i
                if 0 <= j <= d:
                    terms.append((i, j))
            if terms:
                total_degree = 2 - s
                relations.append({
                    "total_degree": total_degree,
                    "sum_index": s,
                    "terms": terms,
                    "description": " + ".join(
                        f"B^{{({i})}}B^{{({j})}}" for i, j in terms
                    ) + " = 0",
                })
        return relations

    @property
    def relations(self) -> List[Dict[str, Any]]:
        return self._relations

    def relation_count(self) -> int:
        """Number of independent hierarchy relations."""
        return len(self._relations)

    def key_relation_BF(self) -> Optional[Dict[str, Any]]:
        """The relation involving both B = B^{(0)} and F = B^{(d)}.

        This is the relation at sum index s = d:
            sum_{i+j=d} B^{(i)}B^{(j)} = 0
        """
        for rel in self._relations:
            if rel["sum_index"] == self.d:
                return rel
        return None

    def verify_relation_count(self) -> bool:
        """Verify the number of relations is 2d+1.

        For CY_d: the total nilpotence gives 2d+1 relations
        (one for each value of i+j from 0 to 2d).
        """
        return self.relation_count() == 2 * self.d + 1


