# 5. E_n STRUCTURE FROM S^d-FRAMING
# =========================================================================

class EnFromFraming:
    """Determine the E_n algebraic structure from the S^d-framing.

    The CY dimension d determines the native E_n structure via:
      d=1: E_infty (S^1-action, pi_1(Conf_2(R^1)) = Z, symmetric braiding)
           Actually, for d=1, the algebra is commutative (E_infty).
      d=2: E_2 (S^2-framing, pi_1(Conf_2(R^2)) = Z, nontrivial braiding)
      d=3: E_1 (S^3-framing, pi_1(Conf_2(R^3)) = 0, no braiding)
      d>=4: E_1 (stabilization, additional shifted structure from pi_d(BU))

    The key computation: pi_1(Conf_2(R^d)) determines whether the
    representation category has a braiding.
      d=1: pi_1 = Z (braid group of R^1), but the braiding is symmetric
           because pi_2(S^0) = 0 (the permutation is an involution)
      d=2: pi_1 = Z (braid group of R^2), nonsymmetric braiding
      d=3: pi_1 = 0 (trivial: R^3 is simply connected after removing a point)
    """

    @staticmethod
    def pi1_conf2(d: int) -> str:
        """pi_1(Conf_2(R^d)) = pi_1(S^{d-1}).

        Conf_2(R^d) = R^d x (R^d minus {0}) ~ S^{d-1} (by translation and scaling).
        So pi_1(Conf_2(R^d)) = pi_1(S^{d-1}).
        """
        if d < 1:
            return "undefined"
        if d == 1:
            # S^0 = {+1, -1}, pi_1(S^0) = 0 (discrete, connected components)
            # But Conf_2(R^1) ~ R x (R \ {0}) which has 2 components.
            # pi_1 of each component = 0 (contractible).
            # The relevant group for braiding is pi_0 = Z_2 (exchange).
            return "Z"  # Convention: braid group on R^1
        if d == 2:
            return "Z"  # pi_1(S^1) = Z (the integers, braid group)
        # For d >= 3: pi_1(S^{d-1}) = 0 (spheres of dim >= 2 are simply connected)
        return "0"

    @staticmethod
    def native_en(d: int) -> str:
        """Native E_n structure for CY dimension d.

        This is the CORRECT E_n, accounting for:
          - d=1: E_infty (symmetric monoidal, braiding trivial)
          - d=2: E_2 (braided monoidal, nontrivial braiding)
          - d=3: E_1 (associative, no braiding -- E_2 via Drinfeld center)
          - d>=4: E_1 (stabilized, shifted structure from Bott periodicity)
        """
        if d <= 0:
            return "undefined"
        if d == 1:
            return "E_infty"
        if d == 2:
            return "E_2"
        return "E_1"

    @staticmethod
    def has_braiding(d: int) -> bool:
        """Whether the S^d-framing induces a NONTRIVIAL braiding.

        True only for d=2 (the E_2 case).

        For d=1: braiding exists but is symmetric (trivial as braiding).
        For d=3: no braiding from the framing; recovered via Drinfeld center.
        For d>=4: no braiding from the framing.
        """
        return d == 2

    @staticmethod
    def e2_recovery_mechanism(d: int) -> Optional[str]:
        """How to recover E_2 structure for d >= 3.

        For d=3: Drinfeld center Z(Rep^{E_1}(A_C)) = Rep^{E_2}(Y(g_X)).
        For d>=4: same mechanism (Drinfeld center of E_1 rep category).
        """
        if d <= 2:
            return None  # E_2 is native, no recovery needed
        return "Drinfeld_center"

    @staticmethod
    def framing_obstruction_group(d: int) -> str:
        """The homotopy group where the S^d-framing obstruction lives.

        Obstruction in pi_d(BU) (unitary reduction via complex structure).

        pi_d(BU) = Z for d even (d >= 2), 0 for d odd.
        """
        if d <= 0:
            return "undefined"
        if d % 2 == 0 and d >= 2:
            return "Z"
        return "0"

    @staticmethod
    def framing_obstruction_trivial(d: int) -> bool:
        """Whether the S^d-framing obstruction vanishes.

        For d odd (including d=3): pi_d(BU) = 0, so the obstruction
        vanishes and the framing exists.

        For d even: pi_d(BU) = Z, so there is a Z-valued obstruction
        (the Chern class).  For CY2 (d=2): the obstruction is the
        Chern class, which IS the braiding datum (not an obstruction
        to existence, but a classification).
        """
        return d % 2 == 1 or d < 2


