# 2. CONNES OPERATOR AND ITS HIERARCHY
# =========================================================================

class ConnesOperator:
    """The Connes B-operator on the normalized cyclic bar complex.

    B: CC_n -> CC_{n+1} is defined by:

        B(a_0, ..., a_n) = sum_{i=0}^{n} (-1)^{ni}
            (1, a_i, a_{i+1}, ..., a_n, a_0, ..., a_{i-1})

    where 1 is the unit of C.  This satisfies B^2 = 0.

    NORMALIZATION: We work on the NORMALIZED cyclic bar complex, where
    elements containing the unit 1 in any bar position (i.e., in
    positions a_1, ..., a_n) are identified with zero.  This is the
    standard normalization (Loday, "Cyclic Homology", Section 1.1.13).
    The position a_0 MAY contain the unit (it is the cyclic slot, not
    a bar slot).

    B^2 = 0 holds on the normalized complex because:
      - B inserts one copy of 1 at position a_0 and shifts the rest
        into bar positions a_1, ..., a_{n+1}
      - B^2 inserts a second copy of 1, and the resulting element
        has the first inserted 1 now in a bar position
      - In the normalized complex, this element is zero (degenerate)

    For CY_d, the B-operator admits a refinement via the holomorphic
    volume form Omega:

        B^{(k)}: CC_n -> CC_{n+1-k}  for k = 0, 1, ..., d

    with B^{(0)} = B.
    """

    def __init__(self, unit: CyclicGenerator):
        """Initialize with the unit element of the category."""
        self.unit = unit

    def _is_normalized(self, factors: Tuple[CyclicGenerator, ...]) -> bool:
        """Check if an element is in the normalized complex.

        An element (a_0, a_1, ..., a_n) is normalized if none of the
        BAR positions a_1, ..., a_n are the unit.  The cyclic position
        a_0 may be the unit.
        """
        for g in factors[1:]:
            if g == self.unit:
                return False
        return True

    def apply_B(self, elem: CyclicBarElement) -> List[CyclicBarElement]:
        """Apply the Connes operator B = B^{(0)}.

        B(a_0, ..., a_n) = sum_{i=0}^{n} (-1)^{ni}
            (1, a_i, ..., a_n, a_0, ..., a_{i-1})

        We work on the normalized complex: any resulting element with
        a unit in a bar position (positions 1, ..., n+1) is dropped.
        """
        factors = elem.factors
        n = len(factors) - 1  # bar degree
        result = []

        for i in range(n + 1):
            sign = (-1) ** (n * i)
            # Cyclic rotation: (a_i, ..., a_n, a_0, ..., a_{i-1})
            rotated = factors[i:] + factors[:i]
            # Insert unit at position 0: (1, a_i, ..., a_n, a_0, ..., a_{i-1})
            new_factors = (self.unit,) + rotated
            # Normalization: drop if any bar position (1..n+1) is the unit
            if not self._is_normalized(new_factors):
                continue
            new_coeff = elem.coeff * Fraction(sign)
            if new_coeff != 0:
                result.append(CyclicBarElement(
                    factors=new_factors,
                    coeff=new_coeff,
                ))

        return result

    def verify_B_squared_zero(self, elem: CyclicBarElement) -> bool:
        """Verify B^2 = 0 on a given element.

        On the normalized complex, B^2 = 0 because B inserts a unit
        at position a_0, pushing the previous a_0 into a bar position.
        When B is applied again, the previously inserted unit is now
        in a bar position, making the element degenerate (= 0 in the
        normalized complex).

        Concretely: B(a_0, ..., a_n) has the form (1, a_i, ...).
        Applying B again gives (1, 1, a_j, ...) or (1, ..., 1, ...),
        where the second 1 is always in a bar position.  On the
        normalized complex, these are zero.
        """
        first = self.apply_B(elem)
        # Apply B to each term and collect
        all_terms: Dict[Tuple[CyclicGenerator, ...], Fraction] = defaultdict(Fraction)
        for term in first:
            second = self.apply_B(term)
            for s in second:
                all_terms[s.factors] += s.coeff

        # Check all coefficients are zero
        return all(v == 0 for v in all_terms.values())


