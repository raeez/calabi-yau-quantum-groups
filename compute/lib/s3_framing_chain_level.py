# 4. THE S^2-FRAMING MAP (CY2 case, for comparison)
# =========================================================================

class S2FramingMap:
    """The chain-level S^2-framing map F: CC_n -> CC_{n-2} for CY2.

    For a CY2 category (K3 surface, Higgs moduli), the S^2-framing
    gives E_2 structure.  The framing map F^{(2)} contracts two
    consecutive factors using the CY2 trace Tr: HH_2 -> k.

    The key difference from CY3:
      - pi_1(Conf_2(R^2)) = Z (braid group), so there IS a braiding
      - F^{(2)} squares to zero: (F^{(2)})^2 = 0
      - [B, F^{(2)}] = h, where h is the BRAIDING HOMOTOPY
    """

    def __init__(self, trace_data: Dict[str, Fraction]):
        self.cy_dim = 2
        self.trace_data = trace_data

    def apply_F(self, elem: CyclicBarElement) -> List[CyclicBarElement]:
        """Apply F^{(2)}: CC_n -> CC_{n-2}.

        Contracts pairs using the CY2 trace.
        """
        factors = elem.factors
        n = len(factors) - 1
        if n < 2:
            return []

        result: Dict[Tuple[CyclicGenerator, ...], Fraction] = defaultdict(Fraction)

        for i in range(len(factors)):
            for j in range(i + 1, len(factors)):
                trace_val = self._compute_pair_trace(factors[i], factors[j])
                if trace_val == 0:
                    continue

                sign_exp = sum(
                    factors[m].degree - 1 for m in range(i)
                )
                sign = Fraction((-1) ** sign_exp)

                new_factors = tuple(
                    factors[m] for m in range(len(factors))
                    if m not in (i, j)
                )

                if len(new_factors) == 0:
                    continue

                result[new_factors] += elem.coeff * trace_val * sign

        return [
            CyclicBarElement(factors=f, coeff=c)
            for f, c in result.items()
            if c != 0
        ]

    def _compute_pair_trace(
        self, a: CyclicGenerator, b: CyclicGenerator
    ) -> Fraction:
        """Compute Tr(a, b) using the CY2 trace."""
        key = f"({a.name},{b.name})"
        return self.trace_data.get(key, Fraction(0))

    def verify_F_squared_zero(
        self, elements: List[CyclicBarElement]
    ) -> bool:
        """Verify F^2 = 0."""
        for elem in elements:
            first = self.apply_F(elem)
            all_terms: Dict[Tuple[CyclicGenerator, ...], Fraction] = defaultdict(Fraction)
            for term in first:
                second = self.apply_F(term)
                for s in second:
                    all_terms[s.factors] += s.coeff
            if any(v != 0 for v in all_terms.values()):
                return False
        return True

    def framing_data(self) -> SdFramingData:
        """S^2-framing data for CY2."""
        return SdFramingData(
            cy_dim=2,
            framing_nilpotent=True,
            connes_compatible=True,
            en_structure="E_2",
            braiding_trivial=False,  # pi_1(Conf_2(R^2)) = Z (braid group)
            obstruction_class=Fraction(0),
        )


