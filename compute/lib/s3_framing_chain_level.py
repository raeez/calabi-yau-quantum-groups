# 8. HOCOLIM OBSTRUCTION FOR S^3-FRAMING
# =========================================================================

@dataclass(frozen=True)
class HocolimObstruction:
    """Obstruction to extending chart-level S^3-framing to global.

    The obstruction lives in H^1(Nerve(Stab), Aut(F)).

    For n chambers and (n-1) walls in a linear arrangement:
      Nerve = [0 -> 1 -> ... -> n-1]
      H^1(Nerve, Aut(F)) = product of Aut(F) over walls modulo
                            the equivalence from chart automorphisms.

    The obstruction vanishes if all wall-crossing automorphisms K_W
    commute with the framing: [K_W, F] = 0.

    For toric CY3: all K_W are torus-equivariant, so [K_W, F] = 0.
    For non-toric CY3: the obstruction is a genuine invariant.
    """
    n_chambers: int
    n_walls: int
    wall_compatibilities: Tuple[bool, ...]  # [K_W_i, F] = 0?
    obstruction_trivial: bool               # all walls compatible?
    h1_nerve: str                           # description of H^1


def compute_hocolim_obstruction(
    n_chambers: int,
    n_walls: int,
    wall_is_toric: Tuple[bool, ...],
) -> HocolimObstruction:
    """Compute the hocolim obstruction for a given chamber decomposition.

    Parameters
    ----------
    n_chambers : int
        Number of stability chambers.
    n_walls : int
        Number of walls between chambers.
    wall_is_toric : tuple of bool
        Whether each wall is toric (toric -> obstruction vanishes).

    Returns
    -------
    HocolimObstruction with the full obstruction data.
    """
    assert len(wall_is_toric) == n_walls

    # For toric walls: [K_W, F] = 0 automatically
    wall_compatibilities = tuple(
        True if is_toric else False  # non-toric: potentially obstructed
        for is_toric in wall_is_toric
    )

    obstruction_trivial = all(wall_compatibilities)

    if obstruction_trivial:
        h1_desc = "H^1(Nerve, Aut(F)) = 0 (all walls compatible)"
    else:
        n_obstructed = sum(1 for w in wall_compatibilities if not w)
        h1_desc = (
            f"H^1(Nerve, Aut(F)) potentially nontrivial: "
            f"{n_obstructed} walls not verified compatible"
        )

    return HocolimObstruction(
        n_chambers=n_chambers,
        n_walls=n_walls,
        wall_compatibilities=wall_compatibilities,
        obstruction_trivial=obstruction_trivial,
        h1_nerve=h1_desc,
    )


