def bps_invariants_rank1(N: int) -> Dict[int, int]:
    """BPS invariants Omega(1, d) for rank-1 Higgs sheaves on P^1.

    The BPS invariants are the "primitive" invariants from which the
    full CoHA Hilbert series is reconstructed via plethystic exponential:

        H_1(q) = PE[sum_d Omega(1,d) q^d]

    For rank 1 on P^1:
        H_1(q) = 1/(1-q)^2 = PE[2q/(1-q)] = PE[sum_{d>=1} 2 q^d]

    Wait: PE[f(q)] = exp(sum_{k>=1} f(q^k)/k).
    For f(q) = 2q + 2q^2 + ... = 2q/(1-q):
        PE[f] = exp(sum_k (2q^k/(1-q^k))/k)
             = exp(sum_k sum_m 2 q^{km}/(k))
             = exp(2 sum_{n>=1} (sum_{k|n} 1/k) q^n)
    This does not simplify to 1/(1-q)^2 directly.

    Actually, PE[2q] = 1/(1-q)^2 since PE[a*q^d] = 1/(1-q^d)^a.
    But that's only the single-letter index.

    For the BPS interpretation: the multi-cover / plethystic structure is:
        H_1(q) = prod_{d>=1} 1/(1-q^d)^{Omega(1,d)}

    Matching with 1/(1-q)^2: this requires Omega(1,1) = 2, Omega(1,d) = 0
    for d >= 2. This means the ONLY rank-1 BPS states are at degree 1,
    with multiplicity 2.

    But wait: 1/(1-q)^2 = sum (d+1) q^d, while prod 1/(1-q^d)^{Omega_d}
    with Omega_1 = 2, Omega_d = 0 for d >= 2 gives 1/(1-q)^2. Yes, correct.

    Returns dict d -> Omega(1, d).
    """
    # Omega(1,1) = 2: two BPS states at degree 1 (the two generators of gl_2
    # in the Cartan direction: h_1 and h_2).
    # All higher Omega(1,d) = 0: multi-particle states account for all of H_1.
    result = {}
    result[1] = 2
    for d in range(2, N):
        result[d] = 0
    return result


def bps_invariants_from_hilbert_series(hilbert: List[Fraction],
                                        N: int) -> List[int]:
    """Extract BPS invariants from a Hilbert series via plethystic logarithm.

    Given H(q) = prod_{k>=1} 1/(1-q^k)^{Omega_k}, recover the Omega_k
    by taking the plethystic logarithm:

        PLog[H(q)] = sum_{k>=1} mu(k)/k * log H(q^k)

    In practice, we use the logarithmic derivative:
        q d/dq log H(q) = sum_{k>=1} Omega_k * k*q^k/(1-q^k)

    and extract Omega_k by Mobius inversion.

    Parameters:
        hilbert: coefficients [H_0, H_1, ..., H_{N-1}] of the Hilbert series.
        N: truncation order.

    Returns [Omega_1, Omega_2, ..., Omega_{N-1}].
    """
    # Step 1: compute log H(q) mod q^N via log(1 + (H-1))
    # H(q) = 1 + h_1 q + h_2 q^2 + ...
    # log H = (H-1) - (H-1)^2/2 + (H-1)^3/3 - ...
    # Or more directly: d/dq log H = H'/H.
    #
    # We use: q d/dq log H(q) = sum_k Omega_k * sum_{m>=1} k q^{mk}
    # Let S_n = coeff of q^n in q d/dq log H(q) = sum_k k Omega_k sum_m q^{mk}
    # Then S_n = sum_{k|n} k * Omega_k.
    # By Mobius inversion: n * Omega_n = sum_{k|n} mu(n/k) * S_k.

    if len(hilbert) < N:
        hilbert = list(hilbert) + [Fraction(0)] * (N - len(hilbert))

    # Compute q d/dq log H via the formula: if H = sum h_n q^n, then
    # H' = sum n h_n q^{n-1}, so q H' = sum n h_n q^n, and
    # q H'/H has coefficients S_n.
    #
    # S_n = n*h_n - sum_{k=1}^{n-1} S_k * h_{n-k} (from H * (qH'/H) = qH').
    # Dividing by h_0 = 1.

    S = [Fraction(0)] * N
    h = [Fraction(0)] * N
    for k in range(min(len(hilbert), N)):
        h[k] = hilbert[k]

    for n in range(1, N):
        S[n] = Fraction(n) * h[n]
        for k in range(1, n):
            S[n] -= S[k] * h[n - k]
        # Divide by h[0] = 1 (already assumed)

    # Mobius inversion: n * Omega_n = sum_{d|n} mu(n/d) * S_d
    def mobius(m: int) -> int:
        """Mobius function mu(m)."""
        if m == 1:
            return 1
        # Factor m
        factors = []
        temp = m
        for p in range(2, m + 1):
            if p * p > temp and temp > 1:
                factors.append(temp)
                break
            while temp % p == 0:
                factors.append(p)
                temp //= p
            if temp == 1:
                break
        # Check for repeated prime factors
        if len(factors) != len(set(factors)):
            return 0
        return (-1) ** len(factors)

    omegas = [0] * N
    for n in range(1, N):
        val = Fraction(0)
        for d in range(1, n + 1):
            if n % d == 0:
                val += mobius(n // d) * S[d]
        # val should equal n * Omega_n
        omega_frac = val / Fraction(n)
        omegas[n] = int(omega_frac)

    return omegas


