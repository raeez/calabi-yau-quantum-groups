"""Cohomological Hall algebra (CoHA) of Higgs sheaves on P^1.

The category Higgs(P^1) = Coh(T*P^1) is a CY_2 category. Its CoHA
carries a rich algebraic structure connected to the Yangian Y(gl_2).

Ground truth from the literature:
  - Schiffmann-Vasserot (2012): The CoHA of Higgs sheaves on a curve C
    is related to the Yangian of gl_{r} where r is the rank.
  - For P^1, the CoHA in the (rank, degree) grading is generated by
    Hecke operators and produces Y(gl_2) or a close variant.
  - Kontsevich-Soibelman (2011): motivic DT theory framework for CY_2.
  - The moduli space M(1,d) of rank-1, degree-d Higgs sheaves on P^1
    is T^*P^d (the cotangent bundle to the d-th symmetric product / P^d).

Hilbert scheme / Gottsche formula:
  For a smooth quasi-projective surface S with Betti numbers b_i(S),
  the generating function for the Poincare polynomials of Hilb^n(S) is:

    sum_{n>=0} P_t(Hilb^n(S)) q^n
      = prod_{k>=1} prod_{i=0}^{4} 1/(1 - (-t)^{2k-2+i} q^k)^{(-1)^i b_i(S)}

  For S = T*P^1: this is a non-compact surface. We use the compactly-supported
  or BM-homology Betti numbers. As an algebraic variety, T*P^1 = O(-2) over P^1
  has BM Betti numbers b_0=1, b_1=0, b_2=2, b_3=0, b_4=1 in compact support,
  but for the CoHA computation we use the fact that Hilb^n(T*P^1) is the
  moduli of rank-1, degree-0 torsion-free Higgs sheaves with second Chern
  class n. The Euler characteristics (virtual Poincare polynomials) are
  computed by the Gottsche-type formula.

  For T*P^1 specifically, the relevant Betti numbers for the Gottsche
  formula are those of the minimal resolution, which equals T*P^1 itself.
  Using ordinary cohomology: b_0=1, b_1=0, b_2=1, b_3=0, b_4=0
  (T*P^1 is homotopy equivalent to P^1).

CY_2 root datum:
  The charge lattice is Gamma = Z^2 with basis (rank, degree).
  The Euler form is chi((r1,d1),(r2,d2)) = r1*d2 - r2*d1 (antisymmetric
  for CY_2 categories, since Serre duality gives chi(E,F) = -chi(F,E)).
  Real roots: {(1,d) : d in Z} and {(-1,d) : d in Z} (rank +/-1 sheaves,
    moduli space is smooth, multiplicity 1).
  Imaginary roots: {(r,d) : r >= 2, gcd(r,d) divides the multiplicity}
    (higher-rank Higgs sheaves, moduli spaces have singularities).
  The root multiplicity of alpha = (r,d) with r>=1 is:
    mult(alpha) = dim H^*(M(r,d)^{ss}) for the semistable locus.
  For coprime (r,d) with r>=2, the multiplicity grows with r.

Yangian Y(gl_2) connection:
  The Yangian Y(gl_2) has generators T_{ij}^{(s)} for 1<=i,j<=2, s>=1
  with the RTT relation. In the "new Drinfeld" presentation:
    generators: e_r, f_r, h_{i,r} for r>=0, i=1,2
  The positive half Y^+(gl_2) has graded dimension in degree n:
    dim Y^+(gl_2)_n = p_2(n) where p_2(n) counts 2-colored partitions
    (pairs of partitions (lambda, mu) with |lambda|+|mu| = n).
  Generating function: prod_{k>=1} 1/(1-q^k)^2 = (P(q))^2 where
  P(q) = prod 1/(1-q^k) is the partition generating function.

CONVENTIONS:
  - (r, d) = (rank, degree) in Z^2
  - q = formal variable for degree grading
  - t = formal variable for cohomological/Poincare grading
  - Euler form chi((r1,d1),(r2,d2)) = r1*d2 - d1*r2 (CY_2 antisymmetric)
  - Stability: slope mu = d/r (Mumford stability for sheaves)

KNOWN VALUES:
  - Betti of T*P^1: b_0=1, b_2=1 (homotopy type of P^1)
  - Euler char of Hilb^n(T*P^1): from Gottsche with chi(T*P^1) = chi(P^1) = 2
  - Hilbert series of Y^+(gl_2)_n: p_2(n) = number of pairs of partitions
    summing to n. First values: 1, 2, 5, 10, 20, 36, 65, 110, ...
  - 2-colored partitions: OEIS A000712
"""

from __future__ import annotations

from fractions import Fraction
from typing import Dict, List, Optional, Tuple

# Type alias for a charge vector (rank, degree)
ChargeVector = Tuple[int, int]


# ---------------------------------------------------------------------------
# Core: power series arithmetic over Q (exact rational coefficients)
# ---------------------------------------------------------------------------

def _poly_mul_trunc(a: List[Fraction], b: List[Fraction],
                    N: int) -> List[Fraction]:
    """Multiply two truncated power series (as lists of Fraction) mod q^N."""
    result = [Fraction(0)] * N
    la, lb = len(a), len(b)
    for i in range(min(la, N)):
        if a[i] == 0:
            continue
        for j in range(min(lb, N - i)):
            result[i + j] += a[i] * b[j]
    return result


def _poly_inv_trunc(a: List[Fraction], N: int) -> List[Fraction]:
    """Invert a power series a(q) mod q^N, assuming a[0] != 0."""
    if a[0] == 0:
        raise ValueError("Cannot invert power series with zero constant term")
    inv_a0 = Fraction(1, 1) / a[0]
    result = [Fraction(0)] * N
    result[0] = inv_a0
    la = len(a)
    for n in range(1, N):
        s = Fraction(0)
        for k in range(1, min(n + 1, la)):
            s += a[k] * result[n - k]
        result[n] = -inv_a0 * s
    return result


# ---------------------------------------------------------------------------
# Section 1: Partition generating functions
# ---------------------------------------------------------------------------

def partition_function(N: int) -> List[Fraction]:
    """Compute P(q) = prod_{k>=1} 1/(1-q^k) mod q^N.

    P(q) = sum_{n>=0} p(n) q^n where p(n) is the number of ordinary
    (integer) partitions of n. (OEIS A000041)

    Returns [P_0, P_1, ..., P_{N-1}].
    """
    result = [Fraction(0)] * N
    result[0] = Fraction(1)
    for k in range(1, N):
        for n in range(k, N):
            result[n] += result[n - k]
    return result


def two_colored_partition_function(N: int) -> List[Fraction]:
    """Compute P(q)^2 = prod_{k>=1} 1/(1-q^k)^2 mod q^N.

    The coefficient of q^n is the number of 2-colored partitions of n,
    i.e., pairs (lambda, mu) of ordinary partitions with |lambda|+|mu| = n.
    (OEIS A000712)

    This is the Hilbert series of Y^+(gl_2) in degree n.

    Returns [c_0, c_1, ..., c_{N-1}].
    """
    p = partition_function(N)
    return _poly_mul_trunc(p, p, N)


def multi_colored_partition_function(N: int, colors: int) -> List[Fraction]:
    """Compute P(q)^colors = prod_{k>=1} 1/(1-q^k)^colors mod q^N.

    The coefficient of q^n counts the number of (colors)-colored partitions.
    For colors=1: ordinary partitions (A000041).
    For colors=2: 2-colored partitions (A000712), Yangian Y^+(gl_2).
    For colors=r: r-colored partitions, Yangian Y^+(gl_r).

    Returns [c_0, c_1, ..., c_{N-1}].
    """
    if colors <= 0:
        raise ValueError(f"colors must be positive, got {colors}")

    p = partition_function(N)
    result = [Fraction(0)] * N
    result[0] = Fraction(1)
    for _ in range(colors):
        result = _poly_mul_trunc(result, p, N)
    return result


# ---------------------------------------------------------------------------
# Section 2: Euler form and CY_2 root datum
# ---------------------------------------------------------------------------

def euler_form(alpha: ChargeVector, beta: ChargeVector) -> int:
    """The Euler form chi(alpha, beta) on the charge lattice Z^2.

    For Higgs(P^1) = Coh(T*P^1), the Euler form on the Grothendieck group
    K_0(Higgs(P^1)) = Z^2 (rank, degree) is:

        chi((r1,d1), (r2,d2)) = r1*d2 - d1*r2

    This is antisymmetric: chi(alpha, beta) = -chi(beta, alpha), which is
    the hallmark of the CY_2 condition (Serre duality acts as -1 on K_0).

    For a general curve C of genus g, the Euler form on Coh(C) is
    chi((r1,d1),(r2,d2)) = r1*d2 - r2*d1 + (1-g)*r1*r2. For Higgs sheaves
    on C (equivalently Coh(T*C)), the CY_2 structure makes the symmetric
    part vanish, leaving only the antisymmetric part r1*d2 - r2*d1.

    Returns an integer.
    """
    r1, d1 = alpha
    r2, d2 = beta
    return r1 * d2 - d1 * r2


def euler_form_symmetric(alpha: ChargeVector, beta: ChargeVector) -> int:
    """The symmetrized Euler form (alpha, beta) = chi(alpha, beta) + chi(beta, alpha).

    For CY_2, this is identically zero:
        (alpha, beta) = (r1*d2 - d1*r2) + (r2*d1 - d2*r1) = 0.

    This vanishing is equivalent to the CY_2 condition.
    """
    return euler_form(alpha, beta) + euler_form(beta, alpha)


def slope(alpha: ChargeVector) -> Optional[Fraction]:
    """The Mumford slope mu(alpha) = d/r for a charge vector (r, d).

    Returns None if r = 0 (torsion sheaves have infinite slope).
    """
    r, d = alpha
    if r == 0:
        return None
    return Fraction(d, r)


def is_real_root(alpha: ChargeVector) -> bool:
    """Check if alpha is a real root of the CY_2 root datum.

    Real roots are charge vectors (r, d) with |r| = 1. These correspond
    to line bundles (and their Higgs-field deformations): the moduli space
    M(1,d) = T*P^d is smooth, and the CoHA contribution is 1-dimensional.

    We also include (-1, d) as real roots (dual sheaves / anti-branes).
    """
    r, d = alpha
    return abs(r) == 1


def is_imaginary_root(alpha: ChargeVector) -> bool:
    """Check if alpha is an imaginary root of the CY_2 root datum.

    Imaginary roots are charge vectors (r, d) with |r| >= 2. These
    correspond to higher-rank Higgs sheaves whose moduli spaces are
    singular (or have positive-dimensional stabilizers for non-coprime).
    The root multiplicities are nontrivial and encode dim H^*(M(r,d)).
    """
    r, d = alpha
    return abs(r) >= 2


def real_roots(d_max: int) -> List[ChargeVector]:
    """List all real roots (1, d) for |d| <= d_max.

    These are the simple/real roots of the CY_2 root system associated
    to Higgs(P^1). Each has multiplicity 1 (smooth moduli space T*P^d).
    """
    return [(1, d) for d in range(-d_max, d_max + 1)]


def positive_roots(r_max: int, d_max: int) -> List[ChargeVector]:
    """List all positive roots (r, d) with 1 <= r <= r_max, |d| <= d_max.

    Positive means r >= 1 (the effective cone in the charge lattice).
    Includes both real roots (r=1) and imaginary roots (r>=2).
    """
    roots = []
    for r in range(1, r_max + 1):
        for d in range(-d_max, d_max + 1):
            roots.append((r, d))
    return roots


def root_multiplicity_rank1(d: int) -> int:
    """Root multiplicity of the real root (1, d).

    For rank 1 Higgs sheaves on P^1, the moduli space M(1,d) is T*P^d
    (cotangent bundle of the d-th symmetric product, which for P^1 is P^d).
    For d >= 0, this is smooth of complex dimension 2d.

    The BM-homology contribution to the CoHA is 1-dimensional (concentrated
    in the fundamental class), so mult(1,d) = 1.

    For d < 0, M(1,d) is empty (no rank-1 sheaves of negative degree on P^1
    that are semistable), so mult(1,d) = 0.
    """
    if d < 0:
        return 0
    return 1


# ---------------------------------------------------------------------------
# Section 3: Hilbert scheme Betti numbers via Gottsche's formula
# ---------------------------------------------------------------------------

def gottsche_hilb_series(N: int, betti: List[int],
                         two_variable: bool = False) -> List[Fraction]:
    """Gottsche's formula for the Hilbert scheme of n points on a surface S.

    For a smooth quasi-projective surface S with Betti numbers
    b_0, b_1, b_2, b_3, b_4, the generating function of Euler
    characteristics of Hilb^n(S) is:

        sum_{n>=0} chi(Hilb^n(S)) q^n = prod_{k>=1} 1/(1-q^k)^{chi(S)}

    where chi(S) = sum (-1)^i b_i is the topological Euler characteristic.

    This is the "Euler characteristic specialization" of the full
    Gottsche formula (setting t = -1 in the Poincare polynomial version).

    Parameters:
        N: truncation order (compute coefficients up to q^{N-1}).
        betti: list [b_0, b_1, b_2, b_3, b_4] of Betti numbers of S.
        two_variable: if True, return the full Poincare polynomial version
            (not implemented here; use gottsche_poincare_series instead).

    Returns [chi(Hilb^0(S)), chi(Hilb^1(S)), ..., chi(Hilb^{N-1}(S))].
    """
    if two_variable:
        raise NotImplementedError("Use gottsche_poincare_series for 2-variable")

    chi_S = sum((-1)**i * betti[i] for i in range(len(betti)))

    # prod_{k>=1} 1/(1-q^k)^{chi(S)} mod q^N
    # Computed iteratively: multiply by 1/(1-q^k) exactly chi(S) times.
    # For chi(S) < 0, we multiply by (1-q^k)^{|chi(S)|} instead.
    result = [Fraction(0)] * N
    result[0] = Fraction(1)

    for k in range(1, N):
        if chi_S >= 0:
            # Multiply by 1/(1-q^k) chi_S times
            for _ in range(chi_S):
                for n in range(k, N):
                    result[n] += result[n - k]
        else:
            # Multiply by (1-q^k)^{|chi_S|} times
            for _ in range(-chi_S):
                for n in range(N - 1, k - 1, -1):
                    result[n] -= result[n - k]

    return result


def gottsche_poincare_series(N: int, betti: List[int],
                              max_cohom_deg: int = 20) -> List[List[Fraction]]:
    """Full Gottsche formula: Poincare polynomials of Hilb^n(S).

    The Gottsche formula gives:

      sum_{n>=0} P_t(Hilb^n(S)) q^n
        = prod_{k>=1} prod_{i=0}^{4} 1/(1-(-t)^{2k-2+i} q^k)^{(-1)^i b_i}

    Returns a list of length N, where entry n is a list of Fraction
    giving the coefficients of the Poincare polynomial P_t(Hilb^n(S))
    in powers of t, up to degree max_cohom_deg.

    For S = T*P^1 (homotopy type P^1): betti = [1, 0, 1, 0, 0].

    Parameters:
        N: number of Hilbert scheme levels (n = 0, ..., N-1).
        betti: Betti numbers [b_0, ..., b_4] of the surface S.
        max_cohom_deg: maximum cohomological degree to track.

    Returns list of length N, each entry a list of Fraction of length
    max_cohom_deg + 1 representing the Poincare polynomial.
    """
    T = max_cohom_deg + 1  # number of t-coefficients to track

    # We work with power series in q whose coefficients are polynomials in t.
    # Each coefficient is represented as a list of Fraction of length T.
    # result[n][j] = coefficient of t^j q^n in the generating function.

    result = [[Fraction(0)] * T for _ in range(N)]
    result[0][0] = Fraction(1)  # constant term: Hilb^0 = point, P_t = 1

    for k in range(1, N):
        for i in range(min(len(betti), 5)):
            bi = betti[i] if i < len(betti) else 0
            if bi == 0:
                continue
            # Exponent of (-t) in the factor: 2k - 2 + i
            t_exp = 2 * k - 2 + i
            # Sign: (-t)^{t_exp} = (-1)^{t_exp} t^{t_exp}
            sign = (-1) ** t_exp
            # Power of this factor: (-1)^i * b_i
            # If (-1)^i * b_i > 0: multiply by 1/(1 - sign*t^{t_exp} * q^k)
            # If (-1)^i * b_i < 0: multiply by (1 - sign*t^{t_exp} * q^k)
            power = ((-1) ** i) * bi
            if power > 0:
                for _ in range(power):
                    _hilb_multiply_factor(result, N, T, k, t_exp, sign)
            elif power < 0:
                for _ in range(-power):
                    _hilb_divide_factor(result, N, T, k, t_exp, sign)

    return result


def _hilb_multiply_factor(result: List[List[Fraction]], N: int, T: int,
                           k: int, t_exp: int, sign: int) -> None:
    """Multiply the q-series (with t-polynomial coefficients) by
    1/(1 - sign * t^{t_exp} * q^k) in place.

    This maps result[n] -> result[n] + sign * t^{t_exp} * result[n-k]
    for n >= k, working in-place from bottom up.
    """
    if t_exp >= T:
        return  # t^{t_exp} is beyond our tracking range
    for n in range(k, N):
        for j in range(T - t_exp):
            result[n][j + t_exp] += sign * result[n - k][j]


def _hilb_divide_factor(result: List[List[Fraction]], N: int, T: int,
                         k: int, t_exp: int, sign: int) -> None:
    """Multiply the q-series by (1 - sign * t^{t_exp} * q^k) in place.

    This maps result[n] -> result[n] - sign * t^{t_exp} * result[n-k]
    for n >= k, working in-place from top down.
    """
    if t_exp >= T:
        return
    for n in range(N - 1, k - 1, -1):
        for j in range(T - t_exp):
            result[n][j + t_exp] -= sign * result[n - k][j]


def hilb_euler_characteristics_tp1(N: int) -> List[int]:
    """Euler characteristics chi(Hilb^n(T*P^1)) for n = 0, ..., N-1.

    T*P^1 is homotopy equivalent to P^1, so its Betti numbers are
    b_0 = 1, b_1 = 0, b_2 = 1, b_3 = 0, b_4 = 0, giving chi = 2.

    By Gottsche's formula:
        sum_{n>=0} chi(Hilb^n(T*P^1)) q^n = prod_{k>=1} 1/(1-q^k)^2

    So chi(Hilb^n(T*P^1)) = p_2(n) = number of 2-colored partitions.

    This is EXACTLY the Hilbert series of Y^+(gl_2)!
    """
    betti_tp1 = [1, 0, 1, 0, 0]
    coeffs = gottsche_hilb_series(N, betti_tp1)
    return [int(c) for c in coeffs]


def hilb_poincare_polynomials_tp1(N: int,
                                    max_deg: int = 20) -> List[List[int]]:
    """Poincare polynomials P_t(Hilb^n(T*P^1)) for n = 0, ..., N-1.

    Returns list of lists, where entry n is the list of Betti numbers
    [b_0, b_1, ..., b_{max_deg}] of Hilb^n(T*P^1).
    """
    betti_tp1 = [1, 0, 1, 0, 0]
    polys = gottsche_poincare_series(N, betti_tp1, max_cohom_deg=max_deg)
    return [[int(c) for c in poly] for poly in polys]


