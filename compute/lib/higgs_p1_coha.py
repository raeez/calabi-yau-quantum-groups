def verify_euler_form_antisymmetry(r_max: int = 3,
                                     d_max: int = 5) -> Dict[str, object]:
    """Verify the Euler form is antisymmetric (CY_2 condition)."""
    violations = []
    for r1 in range(r_max + 1):
        for d1 in range(-d_max, d_max + 1):
            for r2 in range(r_max + 1):
                for d2 in range(-d_max, d_max + 1):
                    alpha = (r1, d1)
                    beta = (r2, d2)
                    if euler_form(alpha, beta) + euler_form(beta, alpha) != 0:
                        violations.append((alpha, beta))

    return {
        "antisymmetric": len(violations) == 0,
        "violations": violations[:5] if violations else [],
    }


