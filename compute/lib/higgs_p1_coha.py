# Section 7: Generating function for the CoHA character
# ---------------------------------------------------------------------------

def coha_character_all_ranks(N: int, r_max: int = 4) -> List[List[Fraction]]:
    """Character of CoHA(Higgs(P^1)) graded by (rank, degree).

    The full character is:
        chi_{CoHA}(q, x) = sum_{r>=1} x^r * H_r(q)
    where H_r(q) is the Hilbert series in the rank-r sector.

    By the Schiffmann-Vasserot / Kontsevich-Soibelman framework, for
    Higgs sheaves on P^1 the character factorizes as:
        chi_{CoHA}(q, x) = prod_{k>=1} prod_{r=1}^{infty}
                           1/(1 - q^k x^r)^{a_{k,r}}
    where a_{k,r} are the "BPS multiplicities".

    For the simplest approximation (genus 0, CY_2):
        H_r(q) = P(q)^{2r} (r copies of the 2-colored partition function)
    restricted to the "rank-r PBW filtration".

    In practice, we compute:
        rank 1: H_1(q) = 1/(1-q)^2  (chi of T*P^d = d+1 for degree d)
        rank 2: H_2(q) from the Harder-Narasimhan recursion
        etc.

    Parameters:
        N: truncation in q-degree.
        r_max: maximum rank.

    Returns list of length r_max+1 (index 0 unused), where entry r is
    the list [H_r(0), H_r(1), ..., H_r(N-1)] of the rank-r Hilbert series.
    """
    result: List[List[Fraction]] = [[Fraction(0)] * N]  # index 0: unused

    for r in range(1, r_max + 1):
        if r == 1:
            # H_1(q) = sum_{d>=0} (d+1) q^d = 1/(1-q)^2
            hr = [Fraction(0)] * N
            for d in range(N):
                hr[d] = Fraction(d + 1)
            result.append(hr)
        else:
            # For rank r >= 2, the Hilbert series involves the plethystic
            # exponential of the rank-1 series. At genus 0 on P^1:
            # H_r(q) encodes the Euler chars of moduli of rank-r Higgs bundles.
            #
            # Using the CoHA product structure, the rank-r piece is obtained
            # from the r-fold product of rank-1 contributions, modulo the
            # Yangian relations. The total is P(q)^{2r} / (correction).
            #
            # For a simpler (but correct at the level of Euler chars) formula:
            # the generating function sum_r H_r(q) x^r has plethystic log
            # equal to x * 1/(1-q)^2, meaning:
            #   sum_r H_r(q) x^r = PE[x/(1-q)^2]
            #     = prod_{d>=0} 1/(1-x*q^d)^{d+1}
            #
            # So H_r(q) = coeff of x^r in prod_{d>=0} 1/(1-x*q^d)^{d+1}.
            # This is the r-th symmetric function of the rank-1 spectrum.
            hr = _extract_rank_r_from_plethystic(r, N)
            result.append(hr)

    return result


def _extract_rank_r_from_plethystic(r: int, N: int) -> List[Fraction]:
    """Extract the rank-r coefficient from the plethystic exponential.

    PE[x * sum_{d>=0} (d+1) q^d] = prod_{d>=0} 1/(1 - x q^d)^{d+1}

    The coefficient of x^r gives the rank-r Hilbert series H_r(q).

    This is computed by expanding the product and collecting terms.
    We track the q-series for each power of x up to x^r.

    Returns the rank-r Hilbert series [H_r(0), ..., H_r(N-1)].
    """
    # series[j] = coefficient of x^j as a q-series, for j = 0, ..., r
    series = [[Fraction(0)] * N for _ in range(r + 1)]
    series[0][0] = Fraction(1)

    for d in range(N):
        multiplicity = d + 1  # the exponent (d+1) in 1/(1-x*q^d)^{d+1}
        # Multiply by 1/(1 - x*q^d)^{multiplicity}
        # This means: for each power of x*q^d, distribute into series.
        # One factor of 1/(1 - x*q^d) maps:
        #   series[j][n] += series[j-1][n-d] (for j >= 1, n >= d)
        # Apply multiplicity times.
        for _ in range(multiplicity):
            # Apply one factor of 1/(1 - x*q^d):
            # series_new[j][n] = series[j][n] + series[j-1][n-d]
            # Process j from low to high: this is the standard algorithm for
            # multiplying by 1/(1-z) where z = x*q^d. Low-to-high in j allows
            # accumulation of all powers of x from the geometric series, just
            # as the standard partition algorithm processes n from k upward.
            for j in range(1, r + 1):
                for n in range(d, N):
                    series[j][n] += series[j - 1][n - d]

    return series[r]


