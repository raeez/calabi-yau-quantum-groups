# Section 5: CoHA multiplication (Hall algebra style)
# ---------------------------------------------------------------------------

def ext_euler_char(alpha: ChargeVector, beta: ChargeVector) -> int:
    """Virtual dimension of the extension space Ext^1(E_alpha, E_beta).

    For the CY_2 category Higgs(P^1), we have:
        dim Ext^0 - dim Ext^1 + dim Ext^2 = chi(alpha, beta)
    and by Serre duality (CY_2):
        Ext^2(E, F) = Ext^0(F, E)^*

    For generic stable sheaves:
        dim Ext^0 = dim Hom = [slope condition]
        dim Ext^2 = dim Hom^* in other direction
        dim Ext^1 = dim Ext^0 + dim Ext^2 - chi(alpha, beta)

    For two rank-1 sheaves O(d1) and O(d2) with d2 >= d1:
        Hom(O(d1), O(d2)) = H^0(O(d2-d1)) has dim d2-d1+1
        Ext^1 on P^1 for plain sheaves: dim H^1(O(d2-d1)) = 0 if d2 >= d1
        But for Higgs sheaves, the extension space is larger due to the
        Higgs field deformation: Ext^1_Higgs = Ext^1_Coh + Hom(E,F(K))
        where K = omega_{P^1} = O(-2).

    The Euler form gives: chi = r1*d2 - r2*d1 = d2 - d1 for rank 1.
    Virtual dim Ext^1 is the dimension of the extension space contributing
    to the CoHA multiplication.

    Returns the virtual dimension = -chi(alpha, beta) when chi < 0,
    or 0 if chi >= 0 (indicating Hom rather than Ext dominates).
    """
    chi = euler_form(alpha, beta)
    # For CY_2, the "virtual number of extensions" from alpha by beta is
    # max(0, -chi(alpha, beta)) in the generic/coprime case.
    return max(0, -chi)


def hall_product_coefficient(alpha: ChargeVector, beta: ChargeVector,
                              gamma: ChargeVector) -> Fraction:
    """Structure coefficient of the CoHA multiplication.

    In the CoHA of Higgs(P^1), the multiplication is:
        [M_alpha] * [M_beta] = sum_gamma c_{alpha,beta}^gamma [M_gamma]

    where c_{alpha,beta}^gamma counts (virtually) the number of short
    exact sequences 0 -> E_beta -> E_gamma -> E_alpha -> 0 in Higgs(P^1).

    By charge conservation: gamma = alpha + beta (in Z^2).
    The coefficient is then:
        c_{alpha,beta}^{alpha+beta} = chi(Gr(alpha; alpha+beta))
    where Gr is the "Hecke correspondence" / extension Grassmannian.

    For rank-1 to rank-1 (producing rank-2):
        alpha = (1, d1), beta = (1, d2), gamma = (2, d1+d2)
        c = 1 (every extension is unique up to scaling in rank 1)

    For more general ranks, the coefficient involves the Euler characteristic
    of the relevant Grassmannian of sub-Higgs-sheaves.

    Returns the structure coefficient as a Fraction.
    """
    r_a, d_a = alpha
    r_b, d_b = beta
    r_g, d_g = gamma

    # Charge conservation check
    if r_a + r_b != r_g or d_a + d_b != d_g:
        return Fraction(0)

    # Rank 1 x Rank 1 -> Rank 2
    if r_a == 1 and r_b == 1:
        # The extension Grassmannian is a point (1-dimensional Ext class
        # for each pair). The Euler characteristic of the correspondence is
        # determined by the Euler form.
        #
        # For Higgs sheaves on P^1, the number of extensions
        # 0 -> O(d2) + phi2 -> E -> O(d1) + phi1 -> 0
        # is parametrized by Ext^1_Higgs((O(d1),phi1), (O(d2),phi2)).
        #
        # The CoHA multiplication is commutative in the rank-1 sector
        # (it's the Cartan subalgebra). The coefficient is 1 for the
        # "shuffle product" interpretation.
        return Fraction(1)

    # Rank 1 x Rank r -> Rank (r+1): Hecke modification
    if r_a == 1 and r_b >= 2:
        # The Hecke correspondence at a line bundle is a projective bundle.
        # Its Euler characteristic depends on the specific geometry.
        # For generic stable beta, the coefficient is |chi(alpha, beta)| + 1
        # from the Grassmannian Gr(1, r+1) = P^r fiber.
        return Fraction(r_g)  # = r_b + 1

    # General: return the virtual count from the motivic formula
    # c_{alpha,beta}^gamma = chi(P^{ext_dim}) where ext_dim is determined
    # by the Euler form. This is a simplification; the full answer involves
    # the motivic Hall algebra.
    ext_dim = ext_euler_char(alpha, beta)
    if ext_dim >= 0:
        return Fraction(ext_dim + 1)  # chi(P^{ext_dim}) = ext_dim + 1
    return Fraction(1)


def coha_product_rank1(d1: int, d2: int) -> Dict[ChargeVector, Fraction]:
    """Multiply two rank-1 generators in the CoHA.

    [M(1,d1)] * [M(1,d2)] in the CoHA of Higgs(P^1).

    For rank 1, the multiplication is commutative (the Cartan subalgebra
    of the Yangian). The product lands in the rank-2 sector:
        [M(1,d1)] * [M(1,d2)] = [M(2, d1+d2)]

    with coefficient 1 (shuffle product).

    Returns dict mapping charge vectors to coefficients.
    """
    gamma = (2, d1 + d2)
    return {gamma: Fraction(1)}


