def kappa_cat_from_structure_sheaf() -> F:
    r"""kappa_cat from the holomorphic Euler characteristic of O_{P^2}.

    kappa_cat = chi(O_S) = sum_{i=0}^{dim S} (-1)^i h^i(O_S)

    For S = P^2:
      h^0(O_{P^2}) = 1   (global sections = constants)
      h^1(O_{P^2}) = 0   (P^2 is rational, H^1(O) = 0)
      h^2(O_{P^2}) = 0   (Serre duality: h^2(O) = h^0(K) = h^0(O(-3)) = 0)
      chi(O_{P^2}) = 1 - 0 + 0 = 1

    # VERIFIED: [DC] direct Hodge number computation;
    #           [LT] Hirzebruch-Riemann-Roch: chi(O_S) = (c_1^2 + c_2)/12
    #                = (9 + 3)/12 = 12/12 = 1.
    """
    return F(H0_O_P2 - H1_O_P2 + H2_O_P2)


def kappa_cat_from_hrr() -> F:
    r"""kappa_cat from the Hirzebruch-Riemann-Roch theorem.

    For a smooth projective surface S:
      chi(O_S) = (c_1(S)^2 + c_2(S)) / 12

    For P^2:
      c_1(P^2) = 3H,  c_1^2 = 9
      c_2(P^2) = 3     (= chi_top)
      chi(O_{P^2}) = (9 + 3) / 12 = 1

    # VERIFIED: [DC] (9 + 3)/12 = 1;
    #           [CF] matches kappa_cat_from_structure_sheaf.
    """
    return F(C1_SQUARED_P2 + C2_P2, 12)


def kappa_cat_from_todd_class() -> F:
    r"""kappa_cat from the Todd class integration.

    chi(O_S) = integral_S td(S)

    For P^2: td(P^2) = 1 + (3/2)H + H^2
      integral_{P^2} td = integral_{P^2} H^2 = 1
      (only the top-degree term contributes)

    Actually: td(P^2) = 1 + c_1/2 + (c_1^2 + c_2)/12
    Top-degree = (c_1^2 + c_2)/12 = (9 + 3)/12 = 1, integrated over [P^2].

    # VERIFIED: [DC] Todd class integration;
    #           [CF] matches kappa_cat_from_hrr.
    """
    # Todd class top-degree coefficient for surface
    todd_top = F(C1_SQUARED_P2 + C2_P2, 12)
    # Integration over the fundamental class [P^2]
    return todd_top


