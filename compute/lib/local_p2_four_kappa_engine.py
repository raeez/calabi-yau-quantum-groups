def kappa_fiber_from_intersection_form() -> F:
    r"""kappa_fiber from the intersection form on H_2(P^2, Z).

    The intersection form on H_2(P^2, Z) = Z is:
      Q: Z x Z -> Z,  Q(aH, bH) = ab * (H.H) = ab

    This is a rank-1 positive-definite form (signature (1,0)).

    kappa_fiber = rank(H_2(S, Z)) = 1

    The fiber kappa measures the complexity of the lattice polarization.
    For P^2 with rank-1 H_2, the lattice is as simple as possible.

    # VERIFIED: [DC] rank H_2(P^2, Z) = b_2(P^2) = 1;
    #           [LT] standard algebraic geometry.
    """
    return F(RANK_H2)


def kappa_fiber_from_picard_rank() -> F:
    r"""kappa_fiber from the Picard rank of P^2.

    For a smooth projective surface S:
      rho(S) = rank Pic(S) = rank H^{1,1}(S, Z) = b_2(S) - 2*h^{2,0}(S)

    For P^2: h^{2,0} = 0, b_2 = 1, so rho = 1.

    The Picard rank equals the rank of the intersection lattice,
    confirming kappa_fiber = 1.

    # VERIFIED: [DC] rho(P^2) = 1;
    #           [CF] matches kappa_fiber_from_intersection_form.
    """
    h20_P2 = 0  # P^2 is rational
    b2_P2 = BETTI_P2[2]  # = 1
    picard_rank = b2_P2 - 2 * h20_P2
    return F(picard_rank)


def kappa_fiber_from_fan() -> F:
    r"""kappa_fiber from the toric fan of P^2.

    The toric fan of P^2 has 3 rays in N = Z^2:
      v_0 = (1, 0),  v_1 = (0, 1),  v_2 = (-1, -1)

    The number of independent relations among rays:
      3 rays - 2 (rank of N) = 1

    This gives rank Pic(P^2) = 1, confirming kappa_fiber = 1.

    # VERIFIED: [DC] 3 - 2 = 1 from toric geometry;
    #           [CF] matches kappa_fiber_from_intersection_form.
    """
    n_rays = 3
    rank_N = 2
    return F(n_rays - rank_N)


