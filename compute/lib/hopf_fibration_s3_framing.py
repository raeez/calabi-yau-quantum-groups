    r"""Analysis of the BV compatibility obstruction Obs_BV.

    The BV obstruction is the HARD part of the S^3-framing programme.
    It asks: does the chain-level trivialization of the topological
    obstruction (via holomorphic CS) commute with the BV operator?

    For toric CY3: YES (torus equivariance).
    For compact CY3 with Cech homotopy: perturbatively YES
        (Thm cech-contracting-homotopy), non-perturbatively OPEN.

    THE STRUCTURE OF Obs_BV:

    The BV operator Delta = partial/partial Omega_3 acts on the
    cyclic bar complex CC_*(C). The holomorphic CS functional
    CS(dbar + A) = int_X Omega wedge tr(A dbar A + 2/3 A^3)
    provides a trivialization: delta_BV(CS) = int Omega F_A.

    The obstruction: CS is NOT E_2-equivariant (the holomorphic
    volume form Omega transforms with weight 1 under U(1) rotation).
    This breaks E_2 to E_1.

    But for the Hopf decomposition, we need only E_1 compatibility
    (the S^3-framing is an E_1 structure, not E_2). The question
    reduces to: does CS commute with the ORDERED product structure?

    For toric CY3: the torus action provides the ordering, and
    CS is equivariant.

    For compact CY3: the Cech homotopy provides a formal power
    series trivialization. Each term in the series is a well-defined
    Cech cochain. The convergence question: does the series of
    OPE coefficients produced by the HTT converge to holomorphic
    functions?

    The BV diagnostic is independent of the raw termwise A-infinity
    witness.  Convergence of the Cech-HTT series can close the analytic
    BV question only after the A-infinity carrier has been handled by
    strict formality, corrected TCFT data, or an HH^{-2} comparison.
    """
    geometry: str
    toric: bool
    obs_bv_perturbative: bool   # perturbative BV vanishes
    obs_bv_nonperturbative: bool  # non-perturbative BV vanishes
    convergence_proved: bool
    mechanism: str

    def is_resolved(self) -> bool:
        """Whether Obs_BV is fully resolved."""
        return self.obs_bv_perturbative and self.obs_bv_nonperturbative

    def is_perturbatively_resolved(self) -> bool:
        """Whether Obs_BV is resolved at the perturbative level."""
        return self.obs_bv_perturbative


