@dataclass
class ProductDecompositionK3E:
    r"""The product decomposition of the S^3-framing for K3 x E.

    For K3 x E = CY2 x CY1, the S^3-framing decomposes as:

        F^{(3)}_{K3 x E} = F^{(2)}_{K3} tensor B_E + correction

    where:
      - F^{(2)}_{K3}: CC_n(K3) -> CC_{n-2}(K3) is the S^2-framing
        of K3 (CY-A_2, PROVED)
      - B_E: CC_n(E) -> CC_{n+1}(E) is the Connes operator on E
        (the S^1-action, classical)
      - The correction comes from the Euler class of the Hopf bundle

    The tensor product acts on CC_*(K3 x E) = CC_*(K3) tensor CC_*(E).

    The key: F^{(2)}_{K3} is PROVED (CY-A_2), B_E is classical (Connes).
    The only remaining content is the correction term, which is
    TOPOLOGICAL (Euler class) and does not depend on the algebra.

    This means: for K3 x E, the S^3-framing obstruction reduces to
    the BV compatibility of the tensor product structure, which is
    the content of Kummer Step 5.

    DEGREE ACCOUNTING:
      F^{(2)}_{K3}: degree -1 on CC_*(K3)
      B_E: degree +1 on CC_*(E)
      F^{(2)} tensor B: degree -1+1 = 0 on CC_*(K3 x E)
      But F^{(3)} has degree -2.  So F^{(2)} tensor B is NOT F^{(3)}.

    The correct decomposition uses the full Connes hierarchy:
      F^{(3)}_{K3 x E} = sum_{i+j=3} B^{(i)}_{K3} tensor B^{(j)}_E

    where:
      B^{(0)}_{K3} tensor B^{(3)}_E: impossible (E is CY1, max level is 1)
      B^{(1)}_{K3} tensor B^{(2)}_E: impossible (E is CY1, max level is 1)
      B^{(2)}_{K3} tensor B^{(1)}_E: F^{(2)}_{K3} tensor B_E (degree -2: OK!)
      B^{(3)}_{K3} tensor B^{(0)}_E: impossible (K3 is CY2, max level is 2)

    So the ONLY contributing term is:
      F^{(3)}_{K3 x E} = F^{(2)}_{K3} tensor B_E

    Wait: check degrees. F^{(2)}_{K3}: CC_n -> CC_{n-1}, degree shift -1.
    B^{(1)}_E = B_E: CC_n -> CC_{n+1-1} = CC_n, degree shift 0.
    Actually B^{(k)} has degree shift 1-k. So B^{(1)} has shift 0.

    F^{(2)}_{K3} tensor B^{(1)}_E: total shift = -1 + 0 = -1.
    But F^{(3)} has shift 1-3 = -2.  Still wrong.

    Correction: for the PRODUCT CY3 = CY2 x CY1:
    The Kunneth formula for the cyclic bar complex gives:
      CC_*(K3 x E) ~ CC_*(K3) tensor CC_*(E)
    and the S^3-framing map on the product is:
      F^{(3)} = F^{(2)}_{K3} cap [E]
    where [E] is the fundamental class of E in HH_1(E).

    More precisely: the CY3 trace on K3 x E is:
      Tr_3 = Tr_{K3} tensor Tr_E: HH_2(K3) tensor HH_1(E) -> k tensor k -> k

    This gives F^{(3)} as the contraction using BOTH traces simultaneously.
    The degree shift: contracting 2 factors from K3 and 1 from E gives
    total contraction of 3, hence CC_n -> CC_{n-3}, shift -2.  Correct.
    """
    s2_framing_k3_proved: bool = True
    s1_action_e_classical: bool = True
    product_decomposition_valid: bool = True
    euler_class_contribution: Fraction = F(0)
    # The Euler class of the Hopf bundle contributes zero in the product case
    # because K3 x E is topologically S^2 x S^1 (NOT S^3) at the level of
    # the framing data.  The Hopf fibration correction vanishes for products.
    # This is the KEY SIMPLIFICATION for the K3 x E case.

    kummer_step5_status: str = "conjectural"

    def obstruction_reduces_to(self) -> str:
        return (
            "For K3 x E, the S^3-framing reduces to the proved S^2-framing "
            "of K3 (CY-A_2) combined with the classical Connes operator on E. "
            "The remaining content is Kummer Step 5: the excision argument "
            "for the orbifold resolution T^4/Z_2 x E. No S^3-framing "
            "obstruction per se; the obstruction is entirely in the "
            "BV compatibility of the product decomposition."
        )


