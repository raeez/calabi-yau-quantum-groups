# 2. THE THREE-COMPONENT OBSTRUCTION DECOMPOSITION
# =========================================================================

@dataclass
class ObstructionComponent:
    """A single component of the three-fold obstruction decomposition."""
    name: str
    value: Optional[Fraction]
    vanishes: bool
    mechanism: str
    status: str  # "proved", "conditional", "open"
    carrier: str = "chain"

    def __repr__(self) -> str:
        if self.vanishes:
            v = "0"
        elif self.value is None:
            v = "open"
        else:
            v = str(self.value)
        return f"{self.name} = {v} [{self.status}; {self.carrier}]"


@dataclass
class HopfObstructionDecomposition:
    r"""The three-component decomposition of the S^3-framing obstruction.

    Obs(C) = Obs_top(C) + Obs_Ainf(C) + Obs_BV(C)

    where:
      Obs_top  = topological obstruction (in pi_3(BSp) or pi_3(BU))
      Obs_Ainf = A-infinity compatibility obstruction ([m_3, F^{(2)}])
      Obs_BV   = BV compatibility obstruction (analytic)

    The decomposition is the chain-level refinement of the Hopf fibration:
      - Obs_top corresponds to the base obstruction (S^2-framing exists)
      - Obs_Ainf corresponds to the fiber obstruction (S^1-compatibility)
      - Obs_BV corresponds to the twist (Euler class correction)
    """
    geometry: str
    obs_top: ObstructionComponent
    obs_ainf: ObstructionComponent
    obs_bv: ObstructionComponent

    def total_vanishes(self) -> bool:
        """Whether the total obstruction vanishes."""
        return (self.obs_top.vanishes
                and self.obs_ainf.vanishes
                and self.obs_bv.vanishes)

    def summary(self) -> Dict[str, Any]:
        return {
            "geometry": self.geometry,
            "obs_top": repr(self.obs_top),
            "obs_ainf": repr(self.obs_ainf),
            "obs_bv": repr(self.obs_bv),
            "total_vanishes": self.total_vanishes(),
        }


