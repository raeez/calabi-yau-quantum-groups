    is_formal: bool
    cech_cover_size: int       # number of affine opens
    htt_terms: int             # number of terms in the HTT
    growth_type: str           # "polynomial", "Gevrey-1", "divergent"
    convergence_status: str    # "proved", "conditional", "open"

    def converges(self) -> bool:
        return self.convergence_status == "proved"


