@dataclass
class ConnesHierarchyElement:
    """An element of the Connes hierarchy B^{(k)} for CY_d.

    For CY_d, the Connes operator B: CC_n -> CC_{n+1} admits
    a refinement:
        B^{(k)}: CC_n -> CC_{n+1-k}  for k = 0, 1, ..., d

    with B^{(0)} = B and B^{(d)} = F (the full S^d-framing map).

    The hierarchy satisfies the nilpotence relation:
        sum_{i+j=d} B^{(i)} circ B^{(j)} = 0

    For d=3:
        B^{(0)} B^{(3)} + B^{(1)} B^{(2)} + B^{(2)} B^{(1)}
            + B^{(3)} B^{(0)} = 0
    i.e.:
        [B, F] = -[B^{(1)}, B^{(2)}]

    The commutator [B, F] is therefore EXACT (equal to -[B^{(1)}, B^{(2)}]).
    This is the chain-level content of the Hopf fibration decomposition.
    """
    level: int           # k in B^{(k)}
    degree_shift: int    # CC_n -> CC_{n + 1 - k}, so shift = 1 - k
    cy_dim: int          # d


@dataclass
class ConnesHierarchy:
    """The full Connes hierarchy B^{(0)}, B^{(1)}, ..., B^{(d)} for CY_d.

    For d=3, the hierarchy has 4 levels:
      B^{(0)} = B (Connes operator, degree +1)
      B^{(1)} (degree 0, from Omega^1 piece of the volume form)
      B^{(2)} (degree -1, the S^2-framing map for the CY2 subfactor)
      B^{(3)} = F (degree -2, the full S^3-framing map)

    The decomposition F = B^{(2)} circ B^{(1)} + correction
    is the operadic content of the Hopf fibration.
    """
    cy_dim: int
    levels: List[ConnesHierarchyElement]

    @classmethod
    def for_cy3(cls) -> "ConnesHierarchy":
        """Construct the Connes hierarchy for CY_3."""
        levels = [
            ConnesHierarchyElement(level=0, degree_shift=1, cy_dim=3),
            ConnesHierarchyElement(level=1, degree_shift=0, cy_dim=3),
            ConnesHierarchyElement(level=2, degree_shift=-1, cy_dim=3),
            ConnesHierarchyElement(level=3, degree_shift=-2, cy_dim=3),
        ]
        return cls(cy_dim=3, levels=levels)

    def nilpotence_relation_terms(self) -> List[Tuple[int, int]]:
        """Terms in the nilpotence relation sum_{i+j=d} B^{(i)} B^{(j)} = 0.

        Returns list of (i, j) pairs summing to d.
        """
        return [(i, self.cy_dim - i) for i in range(self.cy_dim + 1)]

    def bf_commutator_decomposition(self) -> Dict[str, Any]:
        """Decompose [B, F] using the nilpotence relation.

        For d=3:
            B^{(0)} B^{(3)} + B^{(1)} B^{(2)}
                + B^{(2)} B^{(1)} + B^{(3)} B^{(0)} = 0

        Rearranging:
            [B^{(0)}, B^{(3)}] = -[B^{(1)}, B^{(2)}]

        i.e. [B, F] = -[B^{(1)}, B^{(2)}]

        The RHS is computable from the intermediate hierarchy maps.
        """
        if self.cy_dim != 3:
            return {"error": "Only implemented for CY_3"}

        return {
            "lhs": "[B^{(0)}, B^{(3)}] = [B, F]",
            "rhs": "-[B^{(1)}, B^{(2)}]",
            "interpretation": (
                "The commutator of the Connes operator with the "
                "S^3-framing map is EXACT: it equals the negative "
                "commutator of the intermediate hierarchy maps. "
                "This is the chain-level content of the Hopf fibration "
                "decomposition: B^{(1)} is the S^1-fiber contribution, "
                "B^{(2)} is the S^2-base contribution, and their "
                "commutator is the twist from the Euler class."
            ),
            "euler_class_role": (
                "The commutator [B^{(1)}, B^{(2)}] is nonzero precisely "
                "because the Hopf fibration is nontrivial (Euler class = 1). "
                "For a trivial S^1-bundle over S^2 (which would give "
                "S^1 x S^2, not S^3), we would have [B^{(1)}, B^{(2)}] = 0 "
                "and therefore [B, F] = 0."
            ),
        }


