@dataclass(frozen=True)
class HopfFibrationData:
    r"""The Hopf fibration S^1 -> S^3 -> S^2 and its operadic content.

    The Hopf map eta: S^3 -> S^2 is the unique nontrivial element of
    pi_3(S^2) = Z.  Its Euler class e(eta) in H^2(S^2; Z) generates
    H^2(S^2; Z) = Z.

    At the operadic level:
      - S^1 corresponds to E_1 (associative, little intervals)
      - S^2 corresponds to E_2 (braided, little disks)
      - S^3 corresponds to E_3 (symmetric-braided at topological level)
      - The fibration S^1 -> S^3 -> S^2 corresponds to
        E_3 = E_1 tensor_{E_0} E_2 (Dunn additivity)

    The nontriviality of the Hopf fibration means the decomposition
    E_3 = E_1 tensor E_2 is NOT a direct product: the E_1 and E_2
    factors interact through the Euler class.
    """
    euler_class: int = 1  # generator of H^2(S^2; Z) = Z
    pi3_s2: int = 1       # pi_3(S^2) = Z, Hopf map is generator

    # Homotopy groups relevant to the framing obstruction
    pi2_sp: int = 0       # pi_2(Sp(2m)) = 0 for all m >= 1
    pi3_bsp: int = 0      # pi_3(BSp(2m)) = pi_2(Sp(2m)) = 0
    pi3_bu: int = 0       # pi_3(BU) = 0 (Bott periodicity, 3 is odd)

    # The Gysin sequence of the Hopf fibration:
    # ... -> H^{n-2}(S^2) -e-> H^n(S^2) -> H^n(S^3) -> H^{n-1}(S^2) -> ...
    # At n=2: H^0(S^2) -e-> H^2(S^2) -> H^2(S^3) -> H^1(S^2)
    #       : Z -(x1)-> Z -> 0 -> 0
    # So H^2(S^3) = 0, confirming pi_2(S^3) = 0.
    # At n=3: H^1(S^2) -e-> H^3(S^2) -> H^3(S^3) -> H^2(S^2)
    #       : 0 -> 0 -> Z -> Z
    # The connecting homomorphism H^3(S^3) -> H^2(S^2) is the Euler class.

    def topological_obstruction_vanishes(self) -> bool:
        """The topological S^3-framing obstruction vanishes."""
        return self.pi3_bsp == 0 and self.pi3_bu == 0

    def hopf_fibration_nontrivial(self) -> bool:
        """The Hopf fibration is nontrivial."""
        return self.euler_class != 0


