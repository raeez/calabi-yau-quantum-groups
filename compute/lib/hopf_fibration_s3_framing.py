def hopf_decomposition_c3() -> HopfObstructionDecomposition:
    r"""Hopf fibration decomposition for C^3.

    C^3 is the simplest CY3.  All three obstruction components vanish:
      - Obs_top = 0 (pi_3(BSp) = 0, universal)
      - Obs_Ainf = 0 (C^3 is formal: m_k = 0 for k >= 3)
      - Obs_BV = 0 (torus equivariance provides the BV trivialization)

    The S^3-framing is trivial (F = 0) because the 3-point function
    of the free boson vanishes.
    """
    return HopfObstructionDecomposition(
        geometry="C^3",
        obs_top=ObstructionComponent(
            name="Obs_top(C^3)",
            value=F(0),
            vanishes=True,
            mechanism="pi_3(BSp(2m)) = 0 for all m >= 1",
            status="proved",
        ),
        obs_ainf=ObstructionComponent(
            name="Obs_Ainf(C^3)",
            value=F(0),
            vanishes=True,
            mechanism=(
                "C^3 is formal (m_k = 0 for k >= 3). "
                "The commutator [m_3, B^{(2)}_term] = 0 trivially."
            ),
            status="proved",
        ),
        obs_bv=ObstructionComponent(
            name="Obs_BV(C^3)",
            value=F(0),
            vanishes=True,
            mechanism=(
                "T^3-equivariance of C^3 provides the BV trivialization. "
                "The holomorphic CS functional is torus-equivariant."
            ),
            status="proved",
        ),
    )


