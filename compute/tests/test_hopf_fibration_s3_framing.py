class TestConnesHierarchy:
    """Tests for the Connes hierarchy B^{(k)} for CY_3."""

    def test_cy3_hierarchy_levels(self):
        """CY_3 hierarchy has 4 levels: B^{(0)}, B^{(1)}, B^{(2)}, B^{(3)}.

        Path 1: General theory: CY_d has d+1 levels.
        Path 2: Explicit count for d=3: k = 0, 1, 2, 3.
        Path 3: Degree check: shifts are 1, 0, -1, -2.
        """
        ch = ConnesHierarchy.for_cy3()
        # VERIFIED [DC] count check [LT] standard theory
        assert len(ch.levels) == 4
        # VERIFIED [DC] CY dimension
        assert ch.cy_dim == 3

    def test_degree_shifts(self):
        """Degree shifts: B^{(k)} has shift 1-k.

        Path 1: B^{(0)} = B has shift +1 (Connes operator).
        Path 2: B^{(3)} = F has shift -2 (S^3-framing map).
        Path 3: General formula: shift = 1 - k.
        """
        ch = ConnesHierarchy.for_cy3()
        for level in ch.levels:
            # VERIFIED [DC] degree formula [DA] dimensional consistency
            assert level.degree_shift == 1 - level.level

    def test_nilpotence_relation_terms(self):
        """Nilpotence relation: sum_{i+j=3} B^{(i)} B^{(j)} = 0.

        Path 1: Direct enumeration of (i,j) pairs.
        Path 2: There are d+1 = 4 terms for d=3.
        Path 3: Pairs are (0,3), (1,2), (2,1), (3,0).
        """
        ch = ConnesHierarchy.for_cy3()
        terms = ch.nilpotence_relation_terms()
        # VERIFIED [DC] count check [LT] standard theory
        assert len(terms) == 4
        assert terms == [(0, 3), (1, 2), (2, 1), (3, 0)]

    def test_bf_commutator_decomposition(self):
        """[B, F] = -[B^{(1)}, B^{(2)}] (from nilpotence relation).

        Path 1: Rearranging sum_{i+j=3} B^{(i)} B^{(j)} = 0.
        Path 2: B^{(0)} B^{(3)} + B^{(3)} B^{(0)} = [B, F].
        Path 3: B^{(1)} B^{(2)} + B^{(2)} B^{(1)} = [B^{(1)}, B^{(2)}].
        """
        ch = ConnesHierarchy.for_cy3()
        decomp = ch.bf_commutator_decomposition()
        assert "lhs" in decomp
        assert "rhs" in decomp
        assert "[B, F]" in decomp["lhs"]
        assert "[B^{(1)}, B^{(2)}]" in decomp["rhs"]

    def test_euler_class_role(self):
        """The Euler class of the Hopf bundle controls [B^{(1)}, B^{(2)}].

        Path 1: The commutator [B^{(1)}, B^{(2)}] is nonzero precisely
                because the Hopf fibration is nontrivial.
        Path 2: For S^1 x S^2 (trivial bundle), [B^{(1)}, B^{(2)}] = 0.
        Path 3: The Euler class generates H^2(S^2;Z) = Z.
        """
        ch = ConnesHierarchy.for_cy3()
        decomp = ch.bf_commutator_decomposition()
        assert "Euler class" in decomp["euler_class_role"]


